import re

# ── 업체 이름 다듬기 ──────────────────────────────────────────
#   «주식회사 호남산업개발» · «호남산업개발 주식회사» → «호남산업개발»
#   ⚠️ 이름이 같다고 같은 회사가 아닙니다 — 같은 회사인지는 사업자번호로만 가립니다(bizno10).
CORP_NOISE = ["주식회사", "(주)", "㈜", "유한회사", "합자회사", "(유)", "(합)", "주)", "유)"]


def norm_corp(s):
    s = str(s)
    for t in CORP_NOISE:
        s = s.replace(t, "")
    return re.sub(r"\s+", "", s).strip()


# ── 사업자번호 ────────────────────────────────────────────────
#   숫자 10자리만 번호로 봅니다. 실수로 숫자로 읽힌 «7058800777.0» 도 살립니다.
def bizno10(v):
    s = str(v if v is not None else "").strip()
    s = re.sub(r"\.0+$", "", s)
    s = re.sub(r"[^0-9]", "", s)
    return s if len(s) == 10 else ""


# ── 지역(시도) ────────────────────────────────────────────────
REGIONS = ["서울", "부산", "대구", "인천", "광주", "대전", "울산", "세종", "경기",
           "강원", "충북", "충남", "전북", "전남", "경북", "경남", "제주"]
REGION_ALIAS = {
    "경기": ["경기"], "강원": ["강원"], "충북": ["충북", "충청북도"], "충남": ["충남", "충청남도"],
    "전북": ["전북", "전라북도"], "전남": ["전남", "전라남도"],
    "경북": ["경북", "경상북도"], "경남": ["경남", "경상남도"],
}
#   2026 전남 · 광주 통합 — 기관명이 «전남광주통합특별시 여수시» 꼴.
#   뒤 낱말이 광주 자치구면 광주, «…시 · …군» 이면 전남. 광역 기관(본청 · 교육청)은 공고명 단서로, 없으면 정하지 않음.
MERGED_SIDO = "전남광주통합특별시"
GWANGJU_GU = {"동구", "서구", "남구", "북구", "광산구", "광주청사"}


def region_of(inst, name=""):
    """발주기관(+공고명) → 시도 약칭 하나 · 못 정하면 ''"""
    s = str(inst or "").strip()
    if s.startswith(MERGED_SIDO):
        t = s[len(MERGED_SIDO):].split()
        h = t[0] if t else ""
        if h in GWANGJU_GU:
            return "광주"
        if h and (h[-1] in "시군" or h == "무안청사"):
            return "전남"
    blob = f"{s} {name}".replace(MERGED_SIDO, " ")
    for reg in REGIONS:
        if any(p in blob for p in REGION_ALIAS.get(reg, [reg])):
            return reg
    return ""
