import re

# ── 업체 이름 다듬기 ──────────────────────────────────────────
#   «주식회사 호남산업개발» · «호남산업개발 주식회사» → «호남산업개발»
#   ⚠️ 이름이 같다고 같은 회사가 아닙니다 — 같은 회사인지는 사업자번호로만 가립니다(bizno10).
CORP_NOISE = ["주식회사", "(주)", "㈜", "유한회사", "합자회사", "(유)", "(합)", "주)", "유)"]


def norm_corp(s):
    s = str(s)
    for t in CORP_NOISE:
        s = s.replace(t, "")
    return re.sub(r"\s+", "", s).strip()


# ── 사업자번호 ────────────────────────────────────────────────
#   숫자 10자리만 번호로 봅니다. 실수로 숫자로 읽힌 «7058800777.0» 도 살립니다.
def bizno10(v):
    s = str(v if v is not None else "").strip()
    s = re.sub(r"\.0+$", "", s)
    s = re.sub(r"[^0-9]", "", s)
    return s if len(s) == 10 else ""


# ── 지역(시도) ────────────────────────────────────────────────
REGIONS = ["서울", "부산", "대구", "인천", "광주", "대전", "울산", "세종", "경기",
           "강원", "충북", "충남", "전북", "전남", "경북", "경남", "제주"]
REGION_ALIAS = {
    "경기": ["경기"], "강원": ["강원"], "충북": ["충북", "충청북도"], "충남": ["충남", "충청남도"],
    "전북": ["전북", "전라북도"], "전남": ["전남", "전라남도"],
    "경북": ["경북", "경상북도"], "경남": ["경남", "경상남도"],
}
#   2026 전남 · 광주 통합 — 기관명이 «전남광주통합특별시 여수시» 꼴.
#   뒤 낱말이 광주 자치구면 광주, «…시 · …군» 이면 전남. 광역 기관(본청 · 교육청)은 공고명 단서로, 없으면 정하지 않음.
MERGED_SIDO = "전남광주통합특별시"
GWANGJU_GU = {"동구", "서구", "남구", "북구", "광산구", "광주청사"}


def region_of(inst, name=""):
    """발주기관(+공고명) → 시도 약칭 하나 · 못 정하면 ''"""
    s = str(inst or "").strip()
    if s.startswith(MERGED_SIDO):
        t = s[len(MERGED_SIDO):].split()
        h = t[0] if t else ""
        if h in GWANGJU_GU:
            return "광주"
        if h and (h[-1] in "시군" or h == "무안청사"):
            return "전남"
    blob = f"{s} {name}".replace(MERGED_SIDO, " ")
    for reg in REGIONS:
        if any(p in blob for p in REGION_ALIAS.get(reg, [reg])):
            return reg
    return ""


# ── ⚖ G582 난이도계수 — 추정가격 50억 이상 적격심사의 낙찰하한율 (2026-11-07) ──────────────
#   소장님 「나머지도 고쳐 줘」 뒤 G581 확인 중 찾음: 50억 이상 적격심사는 «자재 및 인력조달 가격의 적정성» 점수에
#   공사 난이도계수(1 · 0.95 · 0.9 · 0.85 · 0.8)를 곱해, 계수가 작으면 입찰가격에서 점수를 더 따야 하므로 낙찰하한율이 오릅니다.
#   나라장터 «기초금액조회» 에 난이도계수 · 낙찰하한율이 함께 나옵니다. 그런데 조달청 공고 목록(sucsfbidLwltRate)은
#   계수를 반영한 값이 올 때도, 기준 하한율(81.995 · 87.495)만 올 때도 있습니다:
#     11-07 마감 전 100억~300억 적격 17건 나라장터 대조 — 12건 같음 · 5건 다름(난이도 0.9 · 0.95 인데 목록 81.995 → 나라장터 83.395 · 82.695).
#     개찰 대조(R26BK01749022): 1순위 9,725,383,800원 = 83.395% 하한 바로 위 · 81.995% 였다면 9,608,224,560원(20등)이 1순위 → 83.395 로 개찰됨.
#   셈(행정안전부 «지방자치단체 입찰시 낙찰자 결정기준» 2025.7.1~ · 조달청 «시설공사 적격심사세부기준» 2026.1.30~ 같은 꼴):
#     100억~300억  자재·인력 14점 × 계수 · 입찰가격 30-{(90/100-(입찰가-A)/(예정가-A))×100} · 통과 92점 → 하한율 = 81.995 + 14×(1-계수)
#                  (1 → 81.995 · 0.95 → 82.695 · 0.9 → 83.395 · 0.85 → 84.095 · 0.8 → 84.795) — 나라장터 17건 모두 이 꼴
