#                  (1 → 87.495 · 0.9 → 87.995 · 0.8 → 88.495) — 목록 30일치 87.495 · 87.995 · 88.495 · 나라장터 대조 같음
#   ⚠️ 셈을 확인한 낙찰방법만 셈합니다(«…종합공사)» · PQ대상 · 재난복구 아님). PQ대상(나라장터 0.85 → 84.245 — 다른 배점)
#      · 재난복구 · 관리규정외 수기심사 · 전문 · 그 밖의 공사는 계수가 1 일 때만 목록 값을 쓰고, 계수가 1 보다 작은데
#      목록이 기준값이면 «셈 모름»(nk)으로 금액을 내지 않습니다(화면: 나라장터 하한율을 직접 넣으면 계산).
#   ⚠️ 계수를 아직 모르는데 목록이 기준값이면 «기다림»(dc) — 수집이 기초금액 개별조회로 계수를 받아 옵니다.
#   ⚠️ 목록이 기준값과 다르면(이미 계수 반영 · 11-07 대조 7건 모두 나라장터와 같음) 계수를 몰라도 그대로 씁니다.
#   ⚠️ 화면 web/src/lib/bidmath.js 하한율칸() 과 «같은 셈» 이어야 합니다(시험_난이도하한.py · .mjs 가 같은 표로 봄).
난이도_기준 = {"100": 81.995, "50": 87.495}


def _ff(v):
    try:
        x = float(v)
    except (TypeError, ValueError):
        return None
    return x if x == x else None


def 난이도셈(swin, est):
    """낙찰방법 글 · 추정가격 → (기준 하한율, 계수 1 줄 때 오르는 폭 %p 또는 None(셈 모름)) · 50억 아래 · 적격심사 아님 → None"""
    s = re.sub(r"\s+", "", str(swin or ""))
    if s and not s.startswith("적격심사"):
        return None
    재난 = "재난" in s
    pq = "PQ" in s.upper()
    종합 = "종합공사)" in s
    if "300억원미만100억원이상" in s:
        return (난이도_기준["100"], 14.0 if 종합 and not pq and not 재난 else None)
    if "100억원미만50억원이상" in s:
        return (난이도_기준["50"], 5.0 if 종합 and not pq and not 재난 else None)
    if "70억원미만50억원이상" in s:
        return (난이도_기준["50"], None)
    if "50억원미만" in s or "30억원미만" in s or "10억원미만" in s or "추정가격이2억원미만" in s or "추정가격2억원미만" in s:
        return None
    e = _ff(est) or 0
    if 1e10 <= e < 3e10:
        return (난이도_기준["100"], None)
    if 5e9 <= e < 1e10:
        return (난이도_기준["50"], None)
    return None


def 하한율칸(r):
    """⚖ G582 줄 하나 → (쓸 낙찰하한율, 공고 목록 값(바꿨을 때만 · 아니면 None), 막는 까닭 'dc' · 'nk' · None)
       하한율이 없거나 60~100 밖이면 그대로 돌려줍니다(화면 · 채점이 원래대로 거름)."""
    raw = r.get("llr")
    llr = _ff(raw)
    if llr is None or not (60 <= llr <= 100):
        return (raw, None, None)
    est = r.get("est") or ((_ff(r.get("base")) or 0) / 1.1)
    셈 = 난이도셈(r.get("swin"), est)
    if 셈 is None:
        return (llr, None, None)
    기준, 폭 = 셈
    dc = _ff(r.get("dc"))
    if dc is not None and not (0.5 <= dc <= 1.0):
        dc = None
    if 폭 is not None and dc is not None:
        v = round(기준 + 폭 * (1 - dc), 3)
        return (v, llr if abs(v - llr) > 0.0005 else None, None)
    if abs(llr - 기준) > 0.0005:
        return (llr, None, None)
    if dc is None:
        # 낙찰방법 글이 없는 줄(개찰 저장소 옛 줄)은 적격심사인지 몰라 막지 않습니다(전과 같음) — 계수가 오면 그때 봄
        return (llr, None, "dc" if str(r.get("swin") or "").strip() else None)
    if dc >= 0.9995:
        return (llr, None, None)
    return (llr, None, "nk")
