import { 세기 } from './lib/받은수.jsx'

export const 문의갈래 = ['설계변경', '안전관리계획서', '유해위험방지계획서', '내역서', '기성', '그 밖 서류']   // contact.html «서류 작성대행» 묶음과 같은 글(시험_잠금문의 가 대조)

export function 문의주소(도구, 갈래 = '그 밖 서류') {
  const s = 문의갈래.includes(갈래) ? 갈래 : '그 밖 서류'
  return `/contact?k=cn&s=${encodeURIComponent(s)}&t=${encodeURIComponent(String(도구 || '').slice(0, 40))}`
}

export default function 잠금문의({ 도구, 갈래, 셈 }) {
  return (
    <a className="btn primary sm" style={{ width: 'auto', margin: '0 2px' }} href={문의주소(도구, 갈래)}
      onClick={() => 세기(`|잠금문의|${셈 || 도구}`)}>📄 작성대행 · 견적 문의 ▸</a>
  )
}
