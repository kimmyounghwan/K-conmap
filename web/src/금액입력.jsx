import { useState } from 'react'
import { 금액수, 금액줄, 칸글읽기, 칸숫자 } from './lib/금액읽기.js'

export default function 금액입력({ value, onValue, 줄 = true, inputMode = 'numeric', onBlur, ...칸 }) {
  const n = 금액수(value)
  const [글, set글] = useState(null)            // 단위 · 점 · 띄어쓰기가 섞인 글을 칠 때만 { t, n }
  const 친글 = 글 && 글.n === n ? 글.t : null     // 바깥에서 값이 바뀌었으면 친 글은 버림
  const 바꿈 = (e) => {
    const t = e.target.value
    const r = 칸글읽기(t)
    set글(r.그대로 ? { t, n: r.수 } : null)
    onValue(r.수, r.숫자글)
  }
  const 벗어남 = (e) => {
    set글(null)                                   // 칸을 벗어나면 읽은 값의 쉼표 숫자로(못 읽었으면 빈 칸 — 예전처럼 · 다른 공고로 바꿀 때 묵은 글이 안 남게)
    if (onBlur) onBlur(e)
  }
  const 아래 = 줄 ? 금액줄(친글 != null ? 친글 : n, 친글 != null) : null
  return (
    <>
      <input {...칸} inputMode={inputMode} value={친글 != null ? 친글 : 칸숫자(value)} onChange={바꿈} onBlur={벗어남} />
      {아래 && <div className={'amt-read' + (아래.bad ? ' bad' : '')}>{아래.글}</div>}
    </>
  )
}
