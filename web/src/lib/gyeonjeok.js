/** 한글 금액 — 일금 ○○○원정 */
export function 한글금액(n) {
  const 숫 = ['', '일', '이', '삼', '사', '오', '육', '칠', '팔', '구']
  const 작 = ['', '십', '백', '천']
  const 큰 = ['', '만', '억', '조']
  let v = Math.round(Math.abs(n || 0))
  if (!v) return '영'
  const 조각 = []
  let i = 0
  while (v > 0) {
    const 네 = v % 10000
    if (네) {
      let s = ''
      String(네).padStart(4, '0').split('').forEach((c, j) => { const d = Number(c); if (d) s += 숫[d] + 작[3 - j] })
      조각.unshift(s + 큰[i])
    }
    v = Math.floor(v / 10000); i++
  }
  return (n < 0 ? '마이너스 ' : '') + 조각.join('')
}

