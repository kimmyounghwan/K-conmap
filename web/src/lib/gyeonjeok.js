const 수 = (v) => { const x = Number(String(v ?? '').replace(/[^\d.-]/g, '')); return Number.isFinite(x) ? x : 0 }

/** 내역 — 줄마다 재료비 · 노무비 · 경비 금액(수량 × 단가, 원 미만 버림) */
export function 내역셈(줄) {
  const 줄들 = []
  let 재 = 0, 노 = 0, 경 = 0
  for (const r of 줄 || []) {
    const q = 수(r.q)
    const am = 버림(q * 수(r.m)), al = 버림(q * 수(r.l)), ae = 버림(q * 수(r.e))
    const 빈줄 = !String(r.n || '').trim() && !q
    if (!빈줄) { 재 += am; 노 += al; 경 += ae }
    줄들.push({ ...r, 수량: q, 재금: am, 노금: al, 경금: ae, 합단가: 수(r.m) + 수(r.l) + 수(r.e), 합금: am + al + ae, 빈줄 })
  }
  /* 공종(g)별 소계 — 같은 이름끼리 */
  const 공종 = new Map()
  for (const r of 줄들) {
    if (r.빈줄) continue
    const k = String(r.g || '').trim() || '(공종 없음)'
    const o = 공종.get(k) || { 이름: k, 재: 0, 노: 0, 경: 0 }
    o.재 += r.재금; o.노 += r.노금; o.경 += r.경금
    공종.set(k, o)
  }
  return { 줄들, 재, 노, 경, 직접: 재 + 노 + 경, 공종: [...공종.values()] }
}

const 절사 = (v, u) => { const n = Math.max(1, Number(u) || 1); return Math.floor(v / n) * n }

/** 간단 견적 */
export function 간단셈(견) {
  const L = 내역셈(견.줄)
  const S = 견.간단 || {}
  const 덧 = (S.덧 || []).filter((d) => String(d.n || '').trim() || 수(d.v))
    .map((d) => ({ n: String(d.n || '').trim() || '(항목)', 금: d.pct ? 버림(L.직접 * 수(d.v) / 100) : 버림(수(d.v)), pct: !!d.pct, v: 수(d.v) }))
  const 덧합 = 덧.reduce((s, d) => s + d.금, 0)
  const 공사비 = L.직접 + 덧합
  const 일관 = 버림(공사비 * 수(S.일관) / 100)
  const 이윤 = 버림((공사비 + 일관) * 수(S.이윤) / 100)
  const 공급 = 공사비 + 일관 + 이윤
  const 부가 = S.부가 ? 버림(공급 * 0.1) : 0
  const 합계 = 공급 + 부가
  const 견적금액 = 절사(합계, S.절사)
  const 줄 = [
    { k: '재료비', 금: L.재, 근: '내역 재료비 합' },
    { k: '노무비', 금: L.노, 근: '내역 노무비 합' },
    { k: '경비', 금: L.경, 근: '내역 경비 합' },
    { k: '직접공사비 계', 금: L.직접, 계: true },
    ...덧.map((d) => ({ k: d.n, 금: d.금, 근: d.pct ? `직접공사비 × ${d.v}%` : '정액' })),
    { k: '일반관리비', 금: 일관, 근: `공사비 × ${수(S.일관)}%` },
    { k: '이윤', 금: 이윤, 근: `(공사비 + 일반관리비) × ${수(S.이윤)}%` },
    { k: '공급가액', 금: 공급, 계: true },
    ...(S.부가 ? [{ k: '부가가치세', 금: 부가, 근: '공급가액 × 10%' }] : []),
    { k: S.부가 ? '합계 (부가세 포함)' : '합계 (부가세 별도)', 금: 합계, 계: true },
  ]
  return { L, 줄, 공급, 부가, 합계, 견적금액, 절사분: 합계 - 견적금액, 부가포함: !!S.부가 }
}

