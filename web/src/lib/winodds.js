const NARROW_INST = /공사|공단|공제|진흥원|연구원/          // 창이 좁던 발주기관
const MED_INST = /대학|병원|의료원/
const PUBLIC_INST = /청$|부$|처$|국$|사업소|관리단|교육|학교/
const NARROW_WORK = /전기|통신|소방|정보/                   // 창이 좁던 공종
const WIDE_WORK = /조림|산림|숲|임도|농로|수리|배수|포장|도로/

export function winScore(r) {
  if (!r || !(r.base > 0)) return null
  let s = 0
  const est = (r.est > 0 ? r.est : r.base / 1.1)

  // ① 금액대 — 작을수록 창이 넓습니다 (1억 미만 0.055% ↔ 3~10억 0.006%)
  s += est < 1e8 ? 2 : est < 3e8 ? 1 : -1

  // ② 예가범위 — ±2% 공고는 사정률이 좁아 모두가 같은 자리에 몰립니다
  const w = (r.hi ?? 3) - (r.lo ?? -3)
  s += w >= 6 ? 1 : -2

  // ③ 발주기관
  const inst = String(r.inst || '')
  if (NARROW_INST.test(inst)) s -= 2
  else if (MED_INST.test(inst)) s -= 1
  else if (!PUBLIC_INST.test(inst)) s += 1        // 지자체

  // ④ 공종
  const nm = String(r.name || '')
  if (NARROW_WORK.test(nm)) s -= 2
  else if (WIDE_WORK.test(nm)) s += 1

  return s
}

