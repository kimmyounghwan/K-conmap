export const 공제칸 = [
  { k: 'it', 이름: '소득세' },
  { k: 'lt', 이름: '지방소득세' },
  { k: 'ei', 이름: '고용보험' },
  { k: 'np', 이름: '국민연금' },
  { k: 'hi', 이름: '건강보험' },
  { k: 'lc', 이름: '장기요양' },
]

/* 잠정 = 아직 확정 전이라 앞해 값을 쓴 칸
 *  2027: 국민연금 10%(근로자 5%) — 2026년부터 해마다 0.5%p씩 2033년 13% (보건복지부 2025-12-29 «내년부터 달라지는 국민연금»)
 *        건강보험 7.19% 동결 — 2026-09-08 건강보험정책심의위원회 «2027년도 건강보험료율 결정안»
 *        장기요양 — 2027년 요율 아직 발표 전 → 2026년 값(잠정)
 *        고용보험 — 고용노동부 2026-09-01 개편안 «근로자 0.9% → 1.0%» (시행 시기·확정 전) → 0.9%(잠정) */
const 요율표 = {
  2025: { np: 0.045, hi: 0.03545, lc: 0.9182 / 7.09, ei: 0.009 },
  2026: { np: 0.0475, hi: 0.03595, lc: 0.9448 / 7.19, ei: 0.009 },
  2027: { np: 0.05, hi: 0.03595, lc: 0.9448 / 7.19, ei: 0.009, 잠정: ['장기요양', '고용보험'] },
}
const 해들 = Object.keys(요율표).map(Number).sort((a, b) => a - b)

/** 그 달에 쓸 요율 — 없는 해는 가장 가까운 해 */
export function 요율(ym) {
  const y = Number(String(ym).slice(0, 4)) || 해들[해들.length - 1]
  let 쓸 = 해들[0]
  for (const h of 해들) if (h <= y) 쓸 = h
  return { 잠정: [], ...요율표[쓸], 해: 쓸, 없음: !요율표[y] }
}

/** 국민연금 기준소득월액 하한·상한 */
export function 연금상하한(ym) {
  if (ym >= '2026-07') return [410000, 6590000]
  if (ym >= '2025-07') return [400000, 6370000]
  return [390000, 6170000]
}

const 열원 = (x) => Math.floor((x + 1e-6) / 10) * 10   // 10원 미만 버림 (5,660,000 × 0.009 = 50,939.999… 같은 소수 오차는 바로잡음)

/**
 * 한 사람 한 달 공제
 * @param {string} ym  'YYYY-MM'
 * @param {number[]} 날돈  일한 날마다 받을 돈(공수 × 일급) — 0 인 날은 빼고
 * @param {string} 빼기  명부에서 늘 빼는 것 — 'P'(연금) 'H'(건강·요양) 'E'(고용) 'T'(소득세·지방세)
 * @param {{ap?:string, ex?:string}} 이달  그 달만 손으로 «넣기(ap)» · «빼기(ex)» — 'P' 'H' 'E'
 *   소장님: 「보험 대상이 되는 노무자 및 안되는 노무자 바로 확인 가능하면서 적용되게 해줘. 노무비 청구서에...」
 *   (예: 다른 현장까지 합쳐 8일이 넘으면 연금 «넣기» — 국민연금은 2025-07 부터 사업장 합산)
 */
export function 공제셈(ym, 날돈, 빼기 = '', 이달 = {}) {
  const R = 요율(ym)
  const ap = (이달 && 이달.ap) || '', ex = (이달 && 이달.ex) || ''
  const 일수 = 날돈.length
  const 보수 = 날돈.reduce((s, v) => s + v, 0)
  let it = 0
  if (!빼기.includes('T')) {
    for (const v of 날돈) it += Math.max(0, v - 150000) * 0.06 * 0.45
    it = 열원(it)
    if (it < 1000) it = 0
  }
  const lt = 열원(it * 0.1)
  /* 대상 가리기 — 이유를 글로 남깁니다(청구서에 그대로 보임) */
  const 가림 = (c, 규칙, 규칙글, 아님글) => {
    if (빼기.includes(c)) return { 대상: false, 이유: '명부에서 뺌', 손: false }
    if (ex.includes(c)) return { 대상: false, 이유: '이 달 뺌', 손: true }
    if (ap.includes(c)) return { 대상: true, 이유: '이 달 넣음', 손: true }
    return 규칙 ? { 대상: true, 이유: 규칙글, 손: false } : { 대상: false, 이유: 아님글, 손: false }
  }
  const 만 = Math.floor(보수 / 10000)
  const P = 가림('P', 일수 >= 8 || 보수 >= 2200000, 일수 >= 8 ? `${일수}일 ≥ 8일` : `${만.toLocaleString()}만 ≥ 220만`, `${일수}일·${만.toLocaleString()}만`)
  const H = 가림('H', 일수 >= 8, `${일수}일 ≥ 8일`, `${일수}일 < 8일`)
  const E = 가림('E', true, '일용 모두', '')
  const ei = E.대상 ? 열원(보수 * R.ei) : 0
  let np = 0
  if (P.대상) {
    const [lo, hi] = 연금상하한(ym)
    const 기준 = Math.min(hi, Math.max(lo, Math.floor(보수 / 1000) * 1000))
    np = 열원(기준 * R.np)
  }
  const hiF = H.대상 ? 열원(보수 * R.hi) : 0
  const lc = H.대상 ? 열원(hiF * R.lc) : 0
  return { 일수, 보수, it, lt, ei, np, hi: hiF, lc, 대상: { P, H, E }, 연금대상: P.대상, 건강대상: H.대상,
    요율해: R.해, 요율없음: R.없음, 잠정: R.잠정 }
}

/** 자동 값에 손으로 고친 값(o)을 덮어 합계·차인지급액까지 */
export function 공제합치기(자동, o) {
  const 최종 = {}
  let 합 = 0
  for (const c of 공제칸) {
    const v = o && o[c.k] != null ? Number(o[c.k]) || 0 : 자동[c.k]
    최종[c.k] = v
    합 += v
  }
  return { ...최종, 합, 차인: 자동.보수 - 합 }
}
