/* ── 날짜 ─────────────────────────────────────────────────── */
const 날꼴 = /^(\d{4})-(\d{2})-(\d{2})$/
export function 날읽기(s) {
  const m = 날꼴.exec(String(s || '').trim())
  if (!m) return null
  const t = Date.UTC(+m[1], +m[2] - 1, +m[3])
  const d = new Date(t)
  if (d.getUTCMonth() !== +m[2] - 1) return null   // 2월 30일 같은 것
  return t
}
export function 날글(t) {
  const d = new Date(t)
  return `${d.getUTCFullYear()}-${String(d.getUTCMonth() + 1).padStart(2, '0')}-${String(d.getUTCDate()).padStart(2, '0')}`
}
const 하루 = 86400000
export function 날더하기(s, n) { const t = 날읽기(s); return t == null ? '' : 날글(t + n * 하루) }
/** b − a (날 수). 둘 중 하나라도 없으면 null */
export function 날차(a, b) { const x = 날읽기(a), y = 날읽기(b); return x == null || y == null ? null : Math.round((y - x) / 하루) }
/** N년 뒤 같은 날 (2월 29일 → 없는 해는 2월 28일) */
export function 해더하기(s, n) {
  const t = 날읽기(s); if (t == null) return ''
  const d = new Date(t), y = d.getUTCFullYear() + n, m = d.getUTCMonth()
  const 끝 = new Date(Date.UTC(y, m + 1, 0)).getUTCDate()
  return 날글(Date.UTC(y, m, Math.min(d.getUTCDate(), 끝)))
}
const 요일 = ['일', '월', '화', '수', '목', '금', '토']
export function 요일글(s) { const t = 날읽기(s); return t == null ? '' : 요일[new Date(t).getUTCDay()] }

