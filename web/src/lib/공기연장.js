const 맞날 = (s) => /^\d{4}-\d{2}-\d{2}$/.test(String(s || ''))
const 날값 = (s) => { const [y, m, d] = s.split('-').map(Number); return Date.UTC(y, m - 1, d) }
const 날글 = (t) => new Date(t).toISOString().slice(0, 10)
/** s 로부터 n일(첫날 안 셈 — 민법 제157조) */
export function 날뒤(s, n) { return 맞날(s) ? 날글(날값(s) + n * 86400e3) : '' }
/** s 의 석 달 뒤 같은 날(그 달에 그 날이 없으면 그 달 말일 — 민법 제160조) — 폐기물관리법 «3개월 이상 연장» 셈 */
export function 석달뒤(s) {
  if (!맞날(s)) return ''
  const [y, m, d] = s.split('-').map(Number)
  const 끝 = new Date(Date.UTC(y, m - 1 + 3 + 1, 0)).getUTCDate()
  return 날글(Date.UTC(y, m - 1 + 3, Math.min(d, 끝)))
}
/** 연장 일수 — 늘린 준공기한 − 지금 준공기한 (같거나 앞이면 틀림) */
export function 연장일수(지금, 새것) {
  if (!맞날(지금) || !맞날(새것)) return null
  const n = Math.round((날값(새것) - 날값(지금)) / 86400e3)
  return n > 0 ? { 일: n } : { 틀림: true }
}

