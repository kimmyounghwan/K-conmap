/**
 * 📷 찍은 사진 건네기 (G322 · 2026-10-18) — 옆 «📷 +» 단추(찍기단추.jsx)에서 찍은 사진을 맵톡 글쓰기 · 사진→캐드로 넘깁니다.
 *   소장님: 「옆에 붙어 있는 + 표시가 사진 찍는 거거든 우리도 할 수 있어?」 「3번으로 해보자」(찍고 나서 고르기)
 * ■ 사진은 이 탭의 메모리에만 둡니다(어디에도 저장 · 전송하지 않음). 받는 화면이 한 번 꺼내 가면 지워집니다.
 * ■ 받는 화면이 이미 떠 있으면 «kcm-찍은사진» 사건으로 바로 알립니다(같은 화면이면 다시 그리지 않아도 받게).
 */
let 맡김 = null      /* { 파일: File, 곳: '맵톡' | '캐드', 때 } */

export const 사건이름 = 'kcm-찍은사진'

export function 맡기기(파일, 곳) {
  맡김 = { 파일, 곳, 때: Date.now() }
  try { window.dispatchEvent(new CustomEvent(사건이름, { detail: { 곳 } })) } catch (e) { /* 옛 브라우저 */ }
}

/** 이 곳(맵톡 · 캐드)에 맡긴 사진을 꺼냄 — 10분 넘은 것은 버림 */
export function 꺼내기(곳) {
  if (!맡김 || 맡김.곳 !== 곳) return null
  const x = 맡김
  맡김 = null
  if (Date.now() - x.때 > 10 * 60 * 1000) return null
  return x.파일
}
