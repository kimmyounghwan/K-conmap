/* ══════════════════════════════════════════════════════════════
   처방.js — 신청받아 드리는 PDF(업체 성적표 · 발주기관 보고서)의 «그래서 무엇부터» (2026-09-29)

   소장님: 「지금 사이트에 있는 방식으로 해줘 자가진단이든, 발주처 분석이든 … 신청을 받아서 PDF로 주는 자료가
            더 정밀하고 도움되어야 해」
   → 화면(누구나)은 지금처럼 요약 · 맛보기. 신청 PDF 는 숫자를 «다 보여 주는 것» 에서 한 걸음 더 —
     첫 장에 «📌 먼저 보실 것», 성적표 끝에 «그래서 무엇부터» 를 이 회사·이 기관 숫자로만 적습니다.

   ■ 원칙 (성적표종이.js 의 «그래서 무엇부터» 와 같음)
     · «이렇게 하면 딴다» 고 적지 않습니다 — 3년치 실측으로 금액을 어떻게 잡아도 1순위율은 3.5~4.4%에서 안 움직입니다.
       적는 것은 «지금 새고 있는 곳» 과 «숫자가 가리키는 쪽» 뿐입니다.
     · 숫자가 없는 조언은 한 줄도 넣지 않습니다. 건수가 적으면(아래 문턱) 말하지 않습니다.
   ■ 여기는 글만 만듭니다(그림판 없음) — node 로 시험: node tools/시험_처방.mjs
   각 항목 = { 열쇠, 글(*굵게* 표시 가능), 짧게(첫 장 한 줄) }
   ══════════════════════════════════════════════════════════════ */

const 몫 = (a, b) => (b ? Math.round(a / b * 1000) / 10 : 0)
const 쉼 = (n) => Number(n || 0).toLocaleString('ko-KR')
const 피 = (v, d = 3) => `${Number(v) >= 0 ? '+' : ''}${Number(v).toFixed(d)}%p`

/* ── 업체 성적표 — 3년치 순위(삼년요약) ─────────────────────── */
export function 삼년할것(s3) {
  if (!s3 || !s3.전체 || !(s3.전체.넣은 >= 5)) return []
  const t = s3.전체
  const 전체율 = 몫(t.일위, t.넣은)
  const out = []

  /* ① 하한 아래 — 하한율이 오른 뒤에 늘었으면 그것부터 */
  const 앞 = (s3.앞뒤 || []).find((x) => x.칸 === '하한율 오르기 전')
  const 뒤 = (s3.앞뒤 || []).find((x) => x.칸 === '하한율 오른 뒤')
  const 앞율 = 앞 ? 몫(앞.하한아래, 앞.넣은) : null
  const 뒤율 = 뒤 ? 몫(뒤.하한아래, 뒤.넣은) : null
  if (앞 && 뒤 && 앞.넣은 >= 10 && 뒤.넣은 >= 10 && 뒤.하한아래 >= 3 && 뒤율 >= 앞율 + 5) {
    out.push({
      열쇠: '하한',
      글: `하한율이 오른 뒤(${s3.cut || '2025년'} ~) *하한 아래로 떨어진 투찰이 ${앞율}% → ${뒤율}%* 로 늘었습니다(추정). ` +
          '오른 낙찰하한율(+2%p)이 금액 셈에 다 들어갔는지부터 확인하십시오 — 바로투찰 화면에 기초금액을 넣으면 하한 금액이 원 단위로 나옵니다.',
      짧게: `하한율 오른 뒤 하한 아래 ${앞율}% → ${뒤율}% — 하한 셈부터 확인`,
    })
  } else if (t.하한아래 >= 3 && 몫(t.하한아래, t.넣은) >= 10) {
    const 율 = 몫(t.하한아래, t.넣은)
    out.push({
      열쇠: '하한',
      글: `3년 동안 30위 안에 든 ${쉼(t.넣은)}건 중 *${쉼(t.하한아래)}건(${율}%)* 이 1순위보다 싸게 쓰고도 밀렸습니다(하한 아래 추정)` +
          (s3.아래깊이 != null ? ` — 가운데 *${Number(s3.아래깊이).toFixed(3)}%p* 아래였습니다.` : '.') +
          ' 등수에서 진 것이 아니라 심사에 못 올라간 자리입니다. *하한선 셈부터* 다시 맞추십시오.',
      짧게: `하한 아래로 떨어진 투찰 ${쉼(t.하한아래)}건(${율}%) — 하한 셈부터`,
    })
  }

  /* ② 참가 규모 — 1위가 나는 규모와 안 나는 규모 */
  /* 표본이 적으면(한 칸 10건 미만 · 1위 3건 미만) 우연과 가릴 수 없어 말하지 않습니다 */
  const 규모 = (s3.규모 || []).filter((x) => x.넣은 >= 10).map((x) => ({ ...x, 율: 몫(x.일위, x.넣은) }))
  if (규모.length >= 2) {
    const 좋 = [...규모].sort((a, b) => b.율 - a.율 || b.넣은 - a.넣은)[0]
    const 나쁨 = [...규모].sort((a, b) => a.율 - b.율 || b.넣은 - a.넣은)[0]
    if (좋.칸 !== 나쁨.칸 && 좋.일위 >= 3 && 좋.율 >= 나쁨.율 * 2 && 좋.율 - 나쁨.율 >= 3) {
      out.push({
        열쇠: '규모',
        글: `참가 *${좋.칸}* 개찰에서는 1위가 *${좋.율}%*(${쉼(좋.넣은)}건 중 ${쉼(좋.일위)}건), *${나쁨.칸}* 에서는 *${나쁨.율}%* 입니다. ` +
            `같은 금액 솜씨라면 *${좋.칸} 안팎으로 붙는 공고를 먼저* 고르십시오 — 첫 화면 «오늘 넣을 것» 이 공고마다 «예상 참가» 를 적어 드립니다.`,
        짧게: `참가 ${좋.칸} 공고에서 1위 ${좋.율}% (${나쁨.칸}은 ${나쁨.율}%) — 그런 공고부터`,
      })
    }
  }

  /* ③ 기관 — 잘 맞는 곳 · 많이 넣고도 1위가 없는 곳 */
  const 기관 = (s3.기관 || []).map((x) => ({ ...x, 율: 몫(x.일위, x.넣은) }))
  const 잘 = 기관.filter((x) => x.넣은 >= 5 && x.일위 >= 2 && x.율 >= Math.max(전체율 * 2, 전체율 + 5))
    .sort((a, b) => b.율 - a.율).slice(0, 2)
  if (잘.length) {
    out.push({
      열쇠: '기관잘',
      글: `*${잘.map((x) => `${x.칸}(${x.넣은}건 중 1위 ${x.일위})`).join(' · ')}* — 1위율이 평균(${전체율}%)의 두 배가 넘습니다. ` +
          '이 기관 공고는 *놓치지 마십시오* — 이 회사 금액 잡는 방식이 잘 맞는 곳입니다.',
      짧게: `잘 맞는 기관: ${잘.map((x) => x.칸).join(' · ')}`,
    })
  }
  const 헛 = 기관.filter((x) => x.넣은 >= 10 && x.일위 === 0).sort((a, b) => b.넣은 - a.넣은)[0]
  if (헛) {
    const 아래 = 헛.하한아래 ? ` 그중 ${쉼(헛.하한아래)}건은 하한 아래(추정)였습니다.` : ''
    out.push({
      열쇠: '기관헛',
      글: `*${헛.칸}* 에는 ${쉼(헛.넣은)}건을 넣어 30위 안에 들었지만 1위가 없습니다` +
          (헛.위차이 != null ? ` — 밀린 것은 가운데 1순위보다 *${피(헛.위차이)}* 위였습니다.` : '.') + 아래 +
          ' 그 기관의 낙찰 자리는 «발주기관 정밀 분석» 으로 따로 받아 보실 수 있습니다.',
      짧게: `${헛.칸}: ${쉼(헛.넣은)}건 넣고 1위 0 — 그 기관 자리 다시 보기`,
    })
  }

  /* ④ 겨냥 — 붙어서 졌나, 한 발 위에서 졌나 */
  const 겨 = new Map((s3.겨냥 || []).map(([k, v]) => [k, v]))
  const 붙음 = (겨.get('0.01%p 안') || 0) + (겨.get('0.01~0.05%p 위') || 0)
  const 진것 = [...겨.values()].reduce((a, v) => a + v, 0) - (겨.get('1순위보다 싸게(하한 아래 추정)') || 0)
  if (붙음 >= 3 && 몫(붙음, 진것) >= 20) {
    out.push({
      열쇠: '붙음',
      글: `1순위와 *0.05%p 안*에서 진 것이 *${쉼(붙음)}건*(하한 위에서 진 것의 ${몫(붙음, 진것)}%) 입니다. 금액을 더 깎아서 딸 자리가 아니라 ` +
          '*추첨(사정률)이 가른 자리*입니다 — 금액을 낮추기보다 *넣는 공고 수를 늘리는 쪽*이 숫자에 맞습니다.',
      짧게: `0.05%p 안에서 진 것 ${쉼(붙음)}건 — 깎기보다 넣는 수`,
    })
  } else if (t.위차이 != null && t.위차이 >= 0.3 && 진것 >= 10) {
    out.push({
      열쇠: '위',
      글: `하한 위에서 밀린 투찰은 가운데 1순위보다 *${피(t.위차이)}* 위였습니다 — 늘 한 발 위에서 쓰고 있습니다. ` +
          '기관마다 낙찰이 난 자리(아래 «기관마다» 표의 밀린 폭)를 보고 *자주 넣는 기관부터* 자리를 맞추십시오.',
      짧게: `밀린 투찰이 1순위보다 ${피(t.위차이)} 위 — 한 발 위에서 씀`,
    })
  }

  /* ⑤ 요즘 — 최근 두 분기가 그 앞과 다른가 */
  const 분 = s3.분기 || []
  if (분.length >= 4) {
    const 최근 = 분.slice(-2), 그앞 = 분.slice(0, -2)
    const 합 = (xs, k) => xs.reduce((a, x) => a + (x[k] || 0), 0)
    const 최n = 합(최근, '넣은'), 앞n = 합(그앞, '넣은')
    if (최n >= 10 && 앞n >= 10) {
      const 최율 = 몫(합(최근, '일위'), 최n), 앞율2 = 몫(합(그앞, '일위'), 앞n)
      if (Math.abs(최율 - 앞율2) >= 3 && (최율 >= 앞율2 * 1.5 || 최율 <= 앞율2 / 1.5)) {
        const 오름 = 최율 > 앞율2
        out.push({
          열쇠: '요즘',
          글: `최근 두 분기 1위율 *${최율}%* — 그 앞(${앞율2}%)보다 *${오름 ? '올랐습니다' : '내려갔습니다'}.* ` +
              (오름 ? '지금 쓰는 방식을 바꾸지 마십시오.' : '요즘 무엇이 달라졌는지(넣는 기관·규모·금액 정하는 방법) 아래 표에서 짚어 보십시오.'),
          짧게: `최근 두 분기 1위율 ${최율}% (그 앞 ${앞율2}%)`,
        })
      }
    }
  }
  return out.slice(0, 5)
}

/* ── 발주기관 보고서 ─────────────────────────────────────── */
export function 기관할것(d, M = {}, { 마감전수 = 0 } = {}) {
  if (!d) return []
  const w = d.w || {}, r = d.r || null, sj = d.sj || null
  const out = []
  const 뒤 = !w.mix && w.cut
  const 낙n = 뒤 ? (w.nn || 0) : (w.n || 0)

  if (낙n >= 20 && w.q1 != null && w.q3 != null) {
    out.push({
      열쇠: '자리',
      글: `낙찰의 절반이 *${Number(w.q1).toFixed(3)}~${Number(w.q3).toFixed(3)}%* 에서 났습니다(${뒤 ? '하한율 오른 뒤 ' : ''}${쉼(낙n)}건). ` +
          '이 폭보다 아래는 하한에 걸리기 쉽고, 위는 앞에 서는 곳이 많습니다 — 금액을 잡을 때 *이 폭을 먼저* 보십시오.',
      짧게: `낙찰 절반이 ${Number(w.q1).toFixed(3)}~${Number(w.q3).toFixed(3)}% 폭`,
    })
  }
  if (r && r.dq && r.dq.rows >= 30 && r.dq.share != null && M.dq != null && r.dq.share >= M.dq + 3) {
    out.push({
      열쇠: '하한',
      글: `이 기관 개찰에서는 참가자의 *${r.dq.share}%* 가 하한 아래로 떨어졌습니다(추정, 전국 ${M.dq}%). ` +
          '*하한 금액을 원 단위로 한 번 더* 확인하고 넣으십시오 — 여기서는 하한에 바짝 붙이다 떨어지는 곳이 많습니다.',
      짧게: `참가자 ${r.dq.share}%가 하한 아래(전국 ${M.dq}%) — 하한 확인`,
    })
  }
  if (r && r.gap && r.gap.n >= 10) {
    const c = 몫(r.gap.close, r.gap.n)
    if (c >= 50) {
      out.push({
        열쇠: '추첨',
        글: `1·2위가 *10건 중 ${Math.round(c / 10)}건* 꼴로 0.05%p 안에서 갈립니다 — 금액보다 *추첨(사정률)* 싸움입니다. ` +
            '금액을 더 다듬기보다 *이 기관 공고를 빠짐없이 넣는 것*이 확률에 맞습니다.',
        짧게: `0.05%p 안에서 갈린 개찰 ${c}% — 추첨 싸움, 빠짐없이 넣기`,
      })
    } else if (c <= 30 && r.gap.med != null) {
      out.push({
        열쇠: '금액',
        글: `1·2위가 가운데 *${Number(r.gap.med).toFixed(3)}%p* 벌어져 갈립니다(0.05%p 안은 ${c}%) — *금액을 어디에 거느냐가 가른* 기관입니다. ` +
            '«낙찰이 몰린 자리» 와 «금액대마다» 표를 보고 자리를 잡으십시오.',
        짧게: `1·2위 차 가운데 ${Number(r.gap.med).toFixed(3)}%p — 금액이 가르는 기관`,
      })
    }
  }
  if (r && r.np && r.np.med != null && M.np) {
    const 비 = r.np.med / M.np
    if (비 <= 0.7 || 비 >= 1.3) {
      out.push({
        열쇠: '참가',
        글: `개찰마다 보통 *${쉼(r.np.med)}곳*이 들어옵니다(전국 ${쉼(M.np)}곳) — ` +
            (비 <= 0.7 ? '*덜 붙는 기관*입니다. 면허가 맞으면 넣을 만한 자리입니다.'
              : '*많이 붙는 기관*입니다. 여기서는 금액을 다듬어도 확률이 잘 안 오릅니다 — 공고를 골라 넣으십시오.'),
        짧게: `참가 가운데 ${쉼(r.np.med)}곳(전국 ${쉼(M.np)}) — ${비 <= 0.7 ? '덜 붙는 기관' : '많이 붙는 기관'}`,
      })
    }
  }
  if (sj && sj.n >= 10 && M.p50 != null && Math.abs(sj.med - M.p50) >= 0.05) {
    const df = sj.med - M.p50
    out.push({
      열쇠: '사정률',
      글: `예정가격이 기초금액의 가운데 *${Number(sj.med).toFixed(3)}%* 로 나옵니다 — 전국보다 *${Math.abs(df).toFixed(3)}%p ${df > 0 ? '높게' : '낮게'}.* ` +
          '전국 평균으로 금액을 잡으면 이 기관에서는 그만큼 어긋납니다.',
      짧게: `사정률 가운데 ${Number(sj.med).toFixed(3)}% (전국보다 ${Math.abs(df).toFixed(3)}%p ${df > 0 ? '높음' : '낮음'})`,
    })
  }
  if ((w.mn || 0) >= 12 && (w.m || []).length === 12) {
    const 평균 = w.m.reduce((a, v) => a + v, 0) / 12
    const 많은달 = w.m.map((v, i) => [i + 1, v]).filter(([, v]) => v >= 평균 * 1.5).sort((a, b) => b[1] - a[1]).slice(0, 3)
    if (많은달.length && 평균 > 0) {
      out.push({
        열쇠: '달',
        글: `발주는 *${많은달.map(([m]) => `${m}월`).join(' · ')}* 에 몰립니다(한 해 평균, 다른 달의 1.5배 넘게). 그 전에 면허·실적 서류를 챙겨 두십시오.`,
        짧게: `발주가 몰리는 달: ${많은달.map(([m]) => `${m}월`).join(' · ')}`,
      })
    }
  }
  if (마감전수 > 0) {
    out.push({
      열쇠: '지금',
      글: `지금 마감 전 공고 *${쉼(마감전수)}건* — 뒤 «지금 마감 전» 칸에 권장 금액까지 적었습니다.`,
      짧게: `지금 마감 전 공고 ${쉼(마감전수)}건 — 뒤에 권장 금액`,
    })
  }
  return out.slice(0, 6)
}
