/**
 * 품목 한 줄의 등락 — [노무, 재료, 경비] 셋 따로(견본 4 시트 U~AH 칸 수식)
 *   D(등락률) = ROUNDDOWN((C − A) ÷ A, 4)
 *   E(등락폭) = 0 (B = 0) | C − B (C > B > A) | 0 (B ≥ C > A) | TRUNC(B × D) (그 밖)
 *   F(금액)   = TRUNC(E × 수량) · 변경(조정)단가 = INT(B + E)
 * @param {{수량:number, A:number[], B:number[], C:number[]}} 줄 A 입찰일(또는 직전 조정기준일) 단가 · B 계약단가 · C 조정기준일 단가
 */
export function 품목등락(줄) {
  const q = Number(줄.수량) || 0
  const D = [], E = [], F = [], 변경 = [], 경고 = []
  for (let i = 0; i < 3; i++) {
    const a = Number(줄.A?.[i]) || 0, b = Number(줄.B?.[i]) || 0, c = Number(줄.C?.[i]) || 0
    const d = a !== 0 ? 버림((c - a) / a, 4) : null
    let e
    if (b === 0) e = 0
    else if (c > b && b > a) e = c - b
    else if (b >= c && c > a) e = 0
    else if (d === null) { e = 0; 경고.push(i) }          /* A 가 0 인데 이 갈래로 오면 엑셀은 #VALUE! — 0 으로 두고 알림 */
    else e = 버림(b * d)
    D.push(d); E.push(e); F.push(버림(e * q)); 변경.push(b === 0 && d === null ? 0 : 아래(b + e))
  }
  return { 수량: q, D, E, F, 변경, 합: F[0] + F[1] + F[2], 경고 }
}

/* ═══════════════ 조정률 — 견본 «조정율» 시트 ═══════════════ */
/**
 * @param {object} I 비목별 조정율 적용대가(계약 − 빠른 − P/S)
 * @param {{노:number, 재:number, 경:number}} 등락 품목 등락 금액 합(F)
 * @param {object} 율 계약 요율(%) · 산안배수
 * @param {object} 요율 { 산재: {기준, 비교}, … } — 비면 계약요율 그대로(변동 없음)
 * @param {number} 바탕 조정률 나눌 수(조정율 적용대가 도급액)
 */
export function 조정률셈({ I, 등락, 율 = 기본원가율, 요율 = {}, 바탕 }) {
  const r = { ...기본원가율, ...율 }
  const t = (x) => 버림(x)
  /* 견본: rate = C × E ÷ D (C 계약 · D 기준시점 · E 비교시점) — 수식 차례 그대로 */
  const CED = (k) => {
    const C = Number(r[k]) || 0
    const D = Number(요율[k]?.기준) || C, E = Number(요율[k]?.비교) || D
    return { C, D, E, rate: D ? C * E / D : C }
  }
  const M = {}
  M.재료비 = 등락.재 || 0
  M.직노 = 등락.노 || 0
  M.산출경비 = 등락.경 || 0
  M.소계 = M.재료비 + M.직노 + M.산출경비
  M.간노 = t(M.직노 * r.간노 / 100)
  const 노바탕 = (I.직노 || 0) + (I.간노 || 0)
  let x = CED('산재'); M.산재 = t((M.직노 + M.간노) * x.C * x.E / x.D / 100 + (x.C * x.E / x.D - x.C) / 100 * 노바탕)
  x = CED('고용'); M.고용 = t((M.직노 + M.간노) * x.C * x.E / x.D / 100 + (x.C * x.E / x.D - x.C) / 100 * 노바탕)
  x = CED('건강'); M.건강 = t(M.직노 * x.C * x.E / x.D / 100 + (x.C * x.E / x.D - x.C) / 100 * (I.직노 || 0))
  x = CED('연금'); M.연금 = t(M.직노 * x.C * x.E / x.D / 100 + (x.C * x.E / x.D - x.C) / 100 * (I.직노 || 0))
  x = CED('노인'); M.노인 = t(M.건강 * x.C * x.E / x.D / 100 + (x.C * x.E / x.D - x.C) / 100 * (I.건강 || 0))
  x = CED('퇴직'); M.퇴직 = t(M.직노 * x.C * x.E / x.D / 100 + (x.C * x.E / x.D - x.C) / 100 * (I.직노 || 0))
  M.기계보증 = t(M.소계 * r.기계보증 / 100)
  x = CED('산안비'); M.산안비 = t(((M.재료비 + M.직노) * x.C * x.E / x.D / 100 + (x.C * x.E / x.D - x.C) / 100 * ((I.직노 || 0) + (I.재료비 || 0))) * (r.산안배수 || 1))
  M.환경 = t(M.소계 * r.환경 / 100)
  M.이행보증 = t(M.소계 * (r.이행보증 || 0) / 100)
  M.하도급보증 = t(M.소계 * r.하도급보증 / 100)
  M.기타경비 = t((M.재료비 + M.직노 + M.간노) * r.기타경비 / 100)
  M.순공사원가 = M.소계 + M.간노 + M.산재 + M.고용 + M.건강 + M.연금 + M.노인 + M.퇴직 + M.기계보증 + M.산안비 + M.환경 + M.이행보증 + M.하도급보증 + M.기타경비
  M.일관 = t(M.순공사원가 * r.일관 / 100)
  M.이윤 = t((M.순공사원가 + M.일관 - M.재료비) * r.이윤 / 100)
  M.공급가 = M.순공사원가 + M.일관 + M.이윤
  M.부가세 = t(M.공급가 * 분율(r.부가세))      /* 견본 TRUNC(M27*0.1) */
  const 합계 = 반올림(M.공급가 + M.부가세, -3)
  const 조정률 = 바탕 ? 버림(합계 / 바탕 * 100, 2) : 0
  const 변경율 = Object.fromEntries(요율변동키.map((k) => { const y = CED(k); return [k, { 계약: y.C, 기준: y.D, 비교: y.E, 변경: y.rate }] }))
  return { 등락: M, 합계, 바탕, 조정률, 변경율 }
}

/* ═══════════════ 선금 공제 — 견본 12_4 시트 ═══════════════ */
/**
 * 선금 공제 = ROUNDUP(금차분 적용대가 × 조정률 × 선금률, −3) · 선금률 = ROUND(선금 ÷ 금차분 계약금액, 4)
 *   감액(조정률 < 0)이면 공제하지 않습니다(선금 공제는 증액분에서 — 사이트 물가변동 계산기 G330 과 같게).
 */
export function 선금공제셈({ 금차계약 = 0, 금차제외 = 0, 선금 = 0, 조정률 = 0 } = {}) {
  const 적용 = (Number(금차계약) || 0) - (Number(금차제외) || 0)
  const 선금률 = 금차계약 ? 반올림((Number(선금) || 0) / 금차계약, 4) : 0
  const 공제 = 조정률 > 0 && 선금 > 0 ? 올림(적용 * (조정률 / 100) * 선금률, -3) : 0     /* 엑셀 ROUNDUP(③ × A × ⑤, −3) 과 같은 차례 */
  return { 금차계약: Number(금차계약) || 0, 금차제외: Number(금차제외) || 0, 적용, 선금: Number(선금) || 0, 선금률, 공제 }
}

/* ═══════════════ 날 ═══════════════ */
const 날수 = (s) => { const m = /^(\d{4})-(\d{1,2})-(\d{1,2})/.exec(String(s || '')); return m ? Date.UTC(+m[1], +m[2] - 1, +m[3]) / 86400000 : null }
/** 경과기간 — 견본 «1» 시트 꼴: 조정기준일 − 기준시점 − 1 (두 날은 빼고 셈) */
export function 경과일(기준, 조정기준일) {
  const a = 날수(기준), b = 날수(조정기준일)
  return a === null || b === null ? null : b - a - 1
}

/* ═══════════════ 한 벌 ═══════════════ */
/**
 * @param {object} 입력
 *   품목: [{ 공종, 규격, 단위, 머리?, 계약, 예정, 실행, PS, 기성, 사급?, A:[노,재,경], B:[노,재,경], C:[노,재,경] }]
 *   계약비목?: { 직재, 간재, … 도급액 } — 계약 원가계산서(없으면 품목 계약수량으로 사슬을 돌림)
 *   원가율 · 요율 · 계약일 · 직전조정일? · 입찰일 · 조정기준일 · 선금: { 금차계약, 금차제외, 선금, 지급일 } · 기타공제 · 기성금액?(받은 기성)
 */
export function ESC셈(입력 = {}) {
  const 율 = { ...기본원가율, ...(입력.원가율 || {}) }
  const 경고 = []
  const 갈래 = ['계약', '예정', '실행', '빠른', 'PS', '기성', '조정', '제외', '적용']
  const 직 = Object.fromEntries(갈래.map((g) => [g, { 직재: 0, 간재: 0, 직노: 0, 산출경비: 0 }]))
  const 줄들 = []
  let 등락 = { 노: 0, 재: 0, 경: 0 }
  for (const 원 of 입력.품목 || []) {
    if (원.머리) { 줄들.push({ ...원 }); continue }
    const n = (k) => Number(원[k]) || 0
    const q = { 계약: n('계약'), 예정: n('예정'), 실행: n('실행'), PS: n('PS'), 기성: n('기성') }
    q.빠른 = Math.max(q.예정, q.실행)                 /* Z = MAX(P, U) */
    q.조정 = q.계약 - q.빠른 - q.PS                  /* AJ = K − Z − AE (품목조정률 셈 수량) */
    q.제외 = Math.max(q.빠른, q.기성) + q.PS         /* AT = MAX(Z, AO) + AE */
    q.적용 = q.계약 - q.제외                         /* AY = K − AT */
    const B = [0, 1, 2].map((i) => Number(원.B?.[i]) || 0)
    for (const g of 갈래) {
      const 노 = 버림(q[g] * B[0]), 재 = 버림(q[g] * B[1]), 경 = 버림(q[g] * B[2])
      직[g].직노 += 노; 직[g].산출경비 += 경
      if (원.사급) 직[g].직재 += 재; else 직[g].간재 += 재
    }
    const 등 = 품목등락({ 수량: q.조정, A: 원.A, B, C: 원.C })
    등락 = { 노: 등락.노 + 등.F[0], 재: 등락.재 + 등.F[1], 경: 등락.경 + 등.F[2] }
    if (등.경고.length) 경고.push(`«${원.공종 || '이름 없음'}» 입찰일(A) 단가가 0 — 등락폭을 0 으로 두었습니다`)
    if (q.조정 < 0) 경고.push(`«${원.공종 || '이름 없음'}» 계약수량보다 예정 · 실행 · P/S 가 많습니다(조정 수량 ${Math.round(q.조정 * 10000) / 10000} — 견본도 그대로 셈)`)
    줄들.push({ ...원, B, 수: q, 등 })
  }
  const 계약 = 입력.계약비목 ? 계약비목맞춤(입력.계약비목) : 원가사슬(직.계약, 율, '천원버림')
  const 사슬 = (g, 끝) => 원가사슬(직[g], 율, 끝)
  const 예정 = 사슬('예정'), 실행 = 사슬('실행'), 빠른 = 사슬('빠른'), PS = 사슬('PS', '그대로'), 기성 = 사슬('기성'), 제외 = 사슬('제외')
  const 조정대가 = 비목빼기(계약, 빠른, PS)          /* 6 시트 AK = L − AA − AF (품목조정률 셈의 적용대가) */
  const 적용대가 = 비목빼기(계약, 제외)              /* 6 시트 AZ = L − AU (5 시트 ③ = ① − ②) */
  const 조 = 조정률셈({ I: 조정대가, 등락, 율, 요율: 입력.요율 || {}, 바탕: 조정대가.도급액 })
  const B = 계약.도급액, C = 제외.도급액, D = B - C
  const G = 버림(조.조정률 / 100 * D, -3)            /* 2 시트 F19 = TRUNC(A × D, −3) */
  const 선 = 선금공제셈({ ...(입력.선금 || {}), 조정률: 조.조정률 })
  const H = Number(입력.기타공제) || 0
  const 기준일 = 입력.직전조정일 || 입력.계약일
  const 경과 = 경과일(기준일, 입력.조정기준일)
  const 공정률 = (x) => (B ? x / B : 0)
  const 기성금액 = Number(입력.기성금액) || 0   /* 견본 2 시트 «조정신청일 이전 수령한 기성금액» — 넣으면 이 값으로 기성공정률 */
  return {
    율, 줄들, 직, 등락, 경고,
    비목: { 계약, 예정, 실행, 빠른, PS, 기성, 제외, 조정대가, 적용대가 },
    조정: 조,
    공정: { 예정: 공정률(예정.도급액), 실행: 공정률(실행.도급액), 기성: 공정률(기성금액 || 기성.도급액), 제외: 공정률(C), 기성금액: 기성금액 || 기성.도급액 },
    금액: { B, C, D, A: 조.조정률, G, F: 선.공제, H, 적용금액: G - 선.공제 - H },
    선금: { ...선, 지급일: 입력.선금?.지급일 || '' },
    날: { 입찰일: 입력.입찰일 || '', 계약일: 입력.계약일 || '', 직전조정일: 입력.직전조정일 || '', 기준일: 기준일 || '', 조정기준일: 입력.조정기준일 || '', 경과 },
    요건: { 경과90: 경과 !== null && 경과 >= 90, 률3: Math.abs(조.조정률) >= 3, 경계: 경과 !== null && Math.abs(경과 - 90) <= 3 },
  }
}

