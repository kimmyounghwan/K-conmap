/* ═══════════════ 끝수 — 엑셀과 같게 ═══════════════ */
const 정수가까이 = (t) => {
  const r = Math.round(t)
  return Math.abs(t - r) <= Math.max(1e-9, Math.abs(t) * 1e-12) ? r : null
}
/** TRUNC · ROUNDDOWN (0 쪽으로 버림) — d 가 빼기면 십 · 백 · 천 자리 */
export function 버림(x, d = 0) {
  if (!Number.isFinite(x)) return 0
  if (d < 0) { const k = 10 ** -d; const t = x / k; const r = 정수가까이(t); return (r !== null ? r : Math.trunc(t)) * k }
  const k = 10 ** d; const t = x * k; const r = 정수가까이(t)
  return (r !== null ? r : Math.trunc(t)) / k
}
/** ROUNDUP (0 에서 먼 쪽으로 올림) */
export function 올림(x, d = 0) {
  if (!Number.isFinite(x)) return 0
  const 위 = (t) => { const r = 정수가까이(t); return r !== null ? r : Math.sign(t) * Math.ceil(Math.abs(t)) }
  if (d < 0) { const k = 10 ** -d; return 위(x / k) * k }
  const k = 10 ** d; return 위(x * k) / k
}
/** ROUND (반올림 · 0.5 는 0 에서 먼 쪽) */
export function 반올림(x, d = 0) {
  if (!Number.isFinite(x)) return 0
  const 반 = (t) => {
    const a = Math.abs(t), fl = Math.floor(a), fr = a - fl
    const tol = Math.max(1e-9, a * 1e-12)
    const n = Math.abs(fr - 0.5) <= tol ? fl + 1 : fr > 0.5 ? fl + 1 : fl
    return Math.sign(t) * n
  }
  if (d < 0) { const k = 10 ** -d; return 반(x / k) * k }
  const k = 10 ** d; return 반(x * k) / k
}
/** INT (아래로) */
export const 아래 = (x) => { const r = 정수가까이(x); return r !== null ? r : Math.floor(x) }
/** «14.6%» 를 엑셀처럼 0.146 한 수로(14.6/100 의 소수 오차 없이) */
export const 분율 = (p) => Number((Number(p || 0) / 100).toPrecision(15))

