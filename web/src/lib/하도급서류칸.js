/* 표지(계약서) 칸 글 — 계약조건 조 번호를 같이 */
export function 표지글(값, k) {
  const v = 값[k] !== undefined && 값[k] !== null ? String(값[k]).trim() : ''
  if (!v) return ''
  if (k === '지급자재' && v !== '없음' && !/제12조/.test(v)) return v + ' — 계약조건 제12조'
  if (k === '연동' && !/제11조/.test(v)) return v + ' (계약조건 제11조)'
  return v
}
