/** 경력지수 = log N ÷ log 40 × 40 (N = 보정한 경력 년수 · 1년 미만은 1 · 40년 넘으면 40점) */
export function 경력점(년) {
  const n = Math.max(1, Number(년) || 0)
  return Math.min(40, (Math.log(n) / Math.log(40)) * 40)
}
/** 그 점수가 되려면 몇 년(보정한 경력) — 경력점의 거꾸로 */
export function 경력년(점) {
  if (!(점 > 0)) return 1
  if (점 >= 40) return 40
  return Math.pow(40, 점 / 40)
}

/** 교육지수 — 35시간마다 1점(건설정책 역량강화 교육은 2점) · 최근 3년 · 상한(확인.교육상한) */
export function 교육점(일반시간, 정책시간 = 0) {
  const p = Math.floor((Number(정책시간) || 0) / 35) * 2 + Math.floor((Number(일반시간) || 0) / 35)
  return Math.min(확인.교육상한, p)
}

