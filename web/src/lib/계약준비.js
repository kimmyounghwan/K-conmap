/** 인지세법 제3조①1 · 3호 — 도급 증서 기재금액별 세액(1천만원 이하는 없음) */
export const 인지세표 = [
  { 넘고: 10_000_000, 까지: 30_000_000, 세액: 20_000, 글: '1천만원 초과 3천만원 이하' },
  { 넘고: 30_000_000, 까지: 50_000_000, 세액: 40_000, 글: '3천만원 초과 5천만원 이하' },
  { 넘고: 50_000_000, 까지: 100_000_000, 세액: 70_000, 글: '5천만원 초과 1억원 이하' },
  { 넘고: 100_000_000, 까지: 1_000_000_000, 세액: 150_000, 글: '1억원 초과 10억원 이하' },
  { 넘고: 1_000_000_000, 까지: Infinity, 세액: 350_000, 글: '10억원 초과' },
]
export function 인지세(기재금액) {
  const v = Number(기재금액) || 0
  const r = 인지세표.find((x) => v > x.넘고 && v <= x.까지)
  return r ? r.세액 : 0
}
export function 인지세칸(기재금액) {
  const v = Number(기재금액) || 0
  return 인지세표.find((x) => v > x.넘고 && v <= x.까지) || null
}
/** 인지세법 시행령 제12조 — 증액 변경: (변경 전 + 증액) 세액 − 변경 전 세액 · 감액은 변경 없는 것으로 봄(0) */
export function 변경인지세(변경전, 변경후) {
  const a = Number(변경전) || 0, b = Number(변경후) || 0
  if (!(b > a)) return 0
  return Math.max(0, 인지세(b) - 인지세(a))
}

/**
 * 계약이행 보증 — 국가 시행령 제50조 · 제52조 / 지방 시행령 제51조 · 제53조
 *   입력: 발주(국가 · 지방) · 계약금액 · 장기(장기계속계약) · 총공사(제1차 계약 때 부기한 총공사금액) · 칠십미만(예정가격의 100분의 70 미만 낙찰) · 고시(경제위기 고시 기간)
 *   «100분의 10 이상» 이라 원 미만은 올림
 */
export function 이행보증(o = {}) {
  const 계약금액 = Number(o.계약금액) || 0
  const 총공사 = Number(o.총공사) || 0
  const 장기 = !!o.장기 && 총공사 > 0
  const 기준 = 장기 ? 총공사 : 계약금액
  const 보증율 = o.고시 ? 5 : 10
  const 이행율 = o.고시 ? (o.칠십미만 ? 30 : 20) : (o.칠십미만 ? 50 : 40)
  const 올림 = (n) => Math.ceil(n - 1e-6)
  /* 장기계속 공사이행보증서 기준 — 지방은 시행령 제51조⑧(총공사금액) · 국가 제52조는 «계약금액» 이라 따로 적지 않음 */
  const 이행기준 = 장기 ? (o.발주 === '지방' ? 총공사 : null) : 계약금액
  return {
    기준, 장기, 보증율, 이행율,
    보증금: 기준 > 0 ? 올림(기준 * 보증율 / 100) : 0,
    이행기준,
    이행보증금: 이행기준 > 0 ? 올림(이행기준 * 이행율 / 100) : null,
    면제될수: 계약금액 > 0 && 계약금액 <= 50_000_000,
  }
}

/** 보증서 날짜 — 국가 시행규칙 제55조①3나 · 지방 시행규칙 제53조①3나: 계약기간 개시일 ~ 종료일 이후 */
export function 보증기간(시작, 끝) {
  const 맞음 = (s) => /^\d{4}-\d{2}-\d{2}$/.test(String(s || ''))
  if (!맞음(시작) || !맞음(끝)) return null
  if (끝 < 시작) return { 틀림: true }
  return { 첫날: 시작, 끝날: 끝 }
}

