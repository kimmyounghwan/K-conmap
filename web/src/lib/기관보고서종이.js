/* 0.1 단위 칸 목록을 «가장 많은 칸 ±1%p» 로 잘라 두 줄을 맞춥니다 */
function 칸맞추기(ha, hb) {
  const sa = (ha || []).reduce((s, x) => s + x[1], 0) || 1
  const sb = (hb || []).reduce((s, x) => s + x[1], 0) || 1
  const ma = new Map((ha || []).map(([k, v]) => [Math.round(k * 10), v]))
  const mb = new Map((hb || []).map(([k, v]) => [Math.round(k * 10), v]))
  let 최다 = null, 최다수 = -1
  for (const [k, v] of ma) if (v > 최다수) { 최다 = k; 최다수 = v }
  if (최다 == null) return { bins: [], 밖a: 0, 밖b: 0 }
  const lo = 최다 - 12, hi = 최다 + 12         // 참가자는 위 꼬리가 깁니다(하한 위로 넉넉히 쓴 곳)
  const bins = []
  let 안a = 0, 안b = 0
  for (let k = lo; k <= hi; k++) {
    const a = ma.get(k) || 0, b = mb.get(k) || 0
    안a += a; 안b += b
    bins.push({ k: k / 10, a: a / sa * 100, b: hb && hb.length ? b / sb * 100 : null })
  }
  return { bins, 밖a: 100 - 안a / sa * 100, 밖b: hb && hb.length ? 100 - 안b / sb * 100 : null }
}

