/** 기관 이름 가리기 — «경상북도 안동시» → «경상북도 ○○시» */
export function 기관가리기(s) {
  const t = String(s || '').trim().split(/\s+/)
  if (!t[0]) return '○○기관'
  const 끝 = t[t.length - 1]
  const 꼬 = /[시군구]$/.test(끝) ? 끝.slice(-1) : /청$/.test(끝) ? '청' : '기관'
  const 앞 = t.length > 1 && /(도|특별시|광역시|특별자치시|특별자치도|통합특별시)$/.test(t[0]) ? t[0] + ' ' : ''
  return `${앞}○○${꼬}`
}

/* ── 세로 쌍막대 — 낙찰(파랑)과 참가자 전체(회색)를 한 눈금 위에 ─────────── */
