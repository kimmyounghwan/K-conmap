/**
 * 📋 G282 부재 일람표 — 도면에서 읽어 만든 배근표(공사.배근)를 «도면 일람표 꼴» 로 보여 주고 엑셀로 냄
 *   소장님 「내가 일람표 만들라고 했잖아」(2026-10-13) — 값은 만들어 셈에 썼지만 일람표 자체를 보여 주지 않았음.
 *   종류마다(기초 · 기둥 · 벽 · 보 · 슬래브 · 계단) 기호 · 크기 · 철근 · 근거(📄 도면 · 🤖 클로드가 만든 값과 까닭) · 3D 에 쓰인 수.
 *   화면(BIM 물량 «📋 부재 일람표» 칸)과 엑셀(«부재 일람표» 시트)이 이 한 곳을 같이 씀.
 */

export const 일람종류 = ['기초', '기둥', '벽', '보', '슬라브', '계단']
export const 일람이름 = { 기초: '기초', 기둥: '기둥', 벽: '벽', 보: '보', 슬라브: '슬래브', 계단: '계단' }

const 글 = (v) => (v === null || v === undefined ? '' : String(v).trim())
const 곱 = (a, b) => (글(a) && 글(b) ? 글(a) + ' × ' + 글(b) : 글(a) || 글(b))
const 둘 = (a, b) => (글(a) && 글(b) && 글(a) !== 글(b) ? 글(a) + ' / ' + 글(b) : 글(a) || 글(b))

/** 종류마다 칸 — [머리, 줄 → 값] */
const 칸들 = {
  보: [
    ['크기 B × D', (r) => 곱(r.폭, r.춤)],
    ['상부근', (r) => 글(r.상부)],
    ['하부근', (r) => 글(r.하부)],
    ['단부 상부 추가', (r) => 글(r.상부추가)],
    ['중앙 하부 추가', (r) => 글(r.하부추가)],
    ['늑근 단부 / 중앙', (r) => 둘(r.늑근단부, r.늑근중앙)],
    ['부근', (r) => 글(r.부근)],
  ],
  기둥: [
    ['크기', (r) => (+r.지름 > 0 ? '⌀' + 글(r.지름) : 곱(r.가로, r.세로))],
    ['주근', (r) => 글(r.주근)],
    ['대근 단부 / 중앙', (r) => 둘(r.대근단부, r.대근중앙)],
    ['대근 가닥(가로 × 세로)', (r) => (글(r.대근가로) || 글(r.대근세로) ? (글(r.대근가로) || '2') + ' × ' + (글(r.대근세로) || '2') : '')],
  ],
  벽: [
    ['두께', (r) => 글(r.두께)],
    ['수직근', (r) => 둘(r.수직, r.수직밖)],
    ['수평근', (r) => 둘(r.수평, r.수평밖)],
    ['배근', (r) => 글(r.배근)],
    ['단부 보강근', (r) => 글(r.단부보강)],
    ['추가 수직근', (r) => 글(r.추가수직)],
    ['벽 끝 U형', (r) => (/^U/i.test(글(r.단부U)) ? 'U' : '')],
  ],
  슬라브: [
    ['두께', (r) => 글(r.두께)],
    ['종류', (r) => 글(r.종류)],
    ['단변 하부', (r) => 글(r.단변하부)],
    ['단변 상부', (r) => 글(r.단변상부)],
    ['장변 하부', (r) => 글(r.장변하부)],
    ['장변 상부', (r) => 글(r.장변상부)],
  ],
  기초: [
    ['종류', (r) => 글(r.종류)],
    ['크기', (r) => 곱(r.가로, r.세로)],
    ['두께', (r) => 글(r.두께)],
    ['하부 가로 / 세로', (r) => 둘(r.하부가로, r.하부세로)],
    ['상부 가로 / 세로', (r) => 둘(r.상부가로, r.상부세로)],
    ['철근(m/㎡)', (r) => 글(r.단위철근)],
  ],
  계단: [
    ['두께', (r) => 글(r.두께)],
    ['주근', (r) => 둘(r.주근, r.상부주근)],
    ['배력근', (r) => 글(r.배력근)],
    ['참 주근 / 배력근', (r) => 둘(r.참주근, r.참배력근)],
    ['배근', (r) => 글(r.배근)],
    ['단 높이', (r) => 글(r.단높이)],
  ],
}

/** 기호 차례 — 층 머리(B1 · 1 · 2 · R · PH) 뒤 몸 · 숫자는 숫자 차례 */
const 차례 = (a, b) => String(a).localeCompare(String(b), 'ko', { numeric: true })

/**
 * @param {object} 배근 공사.배근 {보:[], 기둥:[], …}
 * @param {Array} 부재 3D 부재(모델.부재 — 표 · 기호) — 쓰인 수를 셈(없으면 비움)
 * @returns {{종류, 이름, 머리:string[], 줄:{기호, 칸:string[], 만든:string, 쓰임:number|null}[]}[]}
 */
export function 일람표만들기(배근, 부재 = null) {
  const 쓰임 = new Map()
  if (부재) for (const o of 부재) {
    if (o.겹침) continue
    const k = (o.표 === '옹벽' ? '벽' : o.표) + '|' + 글(o.기호)
    쓰임.set(k, (쓰임.get(k) || 0) + 1)
  }
  const out = []
  for (const 종 of 일람종류) {
    const rows = ((배근 || {})[종] || []).filter((r) => 글(r.기호))
    if (!rows.length) continue
    const 칸 = 칸들[종]
    const 줄 = rows.slice().sort((a, b) => 차례(a.기호, b.기호)).map((r) => ({
      기호: 글(r.기호),
      칸: 칸.map(([, f]) => f(r)),
      만든: 글(r.만든).replace(/^(클로드|건설맵):\s*/, ''),
      쓰임: 부재 ? (쓰임.get(종 + '|' + 글(r.기호)) || 0) : null,
    }))
    out.push({ 종류: 종, 이름: 일람이름[종], 머리: ['기호', ...칸.map(([h]) => h)], 줄 })
  }
  return out
}

/** 엑셀 시트 하나 — 종류마다 «■ 보 일람표» 머리 · 칸 이름 · 줄(근거 · 3D 쓰임) */
export function 일람표시트(표들, ST) {
  const rows = []
  let 넓 = 0
  for (const t of 표들) {
    if (rows.length) rows.push([])
    rows.push([{ v: '■ ' + t.이름 + ' 일람표', st: ST.HEAD }])
    rows.push([...t.머리, '3D 쓰임', '근거'].map((h) => ({ v: h, st: ST.HEAD })))
    for (const z of t.줄) rows.push([z.기호, ...z.칸, z.쓰임 === null ? '' : z.쓰임, z.만든 ? '🤖 건설맵이 만든 값 — ' + z.만든 : '📄 도면 일람표'])
    넓 = Math.max(넓, t.머리.length)
  }
  return {
    name: '부재 일람표',
    head: ['K-건설맵 부재 일람표 — 📄 도면에서 읽은 값 · 🤖 건설맵이 만든 값(까닭 적음 · 배근표에서 고칠 수 있음)'],
    rows,
    widths: [12, ...Array.from({ length: Math.max(넓 - 1, 0) }, () => 16), 9, 60],
  }
}
