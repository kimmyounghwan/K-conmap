      if (아래) { x.꼴 = '머리'; if (원가인가(x.이름)) x.원가성 = true; continue }
      const 이웃요약 = (y) => y && y.꼴 !== '합계' && 단위식(y.단위) && (y.수량 === null || y.수량 === 0 || y.수량 === 1) && !y.규격 && 번호인가(y.이름)
