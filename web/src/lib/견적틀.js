/* ══════════════════════════════════════════════════════════
   ② 줄마다 «공종 머리 / 품목 / 원가» 가리기 — 단가를 안 봄
   ══════════════════════════════════════════════════════════ */
/* 진짜 품목 꼴 — 단위가 «식» 이 아니고 수량이 있음(머리 · 요약 · 원가 줄은 거의 «식» 이거나 단위 빈칸) */
const 진품 = (x) => !!x.이름 && !!x.단위 && !단위식(x.단위) && x.단위 !== '%' && x.수량 !== null && x.수량 > 0
