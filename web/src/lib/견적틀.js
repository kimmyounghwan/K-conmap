const 겹치지않게 = (이름들) => {
  const 본 = new Map()
  return 이름들.map((n) => {
    const k = n.toLowerCase()
    const c = (본.get(k) || 0) + 1
    본.set(k, c)
    return c === 1 ? n : `${n.slice(0, 26)}(${c})`
  })
}

/** 고른 공종들 → 한 파일(공종마다 시트 · 둘 이상이면 맨 앞에 «공종 목록») */
export function 견적틀책(마디들, 표지 = {}, 옵션 = {}) {
  const 장들 = 마디들.map((m) => 견적틀장(m, 표지, 옵션))
  const 이름들 = 겹치지않게(장들.map((s) => s.이름))
  장들.forEach((s, i) => { s.이름 = 이름들[i] })
  const 모두 = 장들.length > 1 ? [목록장(마디들, 표지, 이름들), ...장들] : 장들
  return 격자책(모두)
}

/** 고른 공종들 → 공종마다 파일 하나씩 든 zip(업체마다 따로 보내기 좋게) */
export function 견적틀묶음(마디들, 표지 = {}, 옵션 = {}) {
  const f = {}
  const 이름들 = 겹치지않게(마디들.map((m) => 시트이름(m.글 || m.이름)))
  마디들.forEach((m, i) => {
    const 파일 = `${String(i + 1).padStart(2, '0')}_견적틀_${이름들[i].replace(/[\\/:*?"<>|\s]+/g, '_')}.xlsx`
    f[파일] = [격자책([견적틀장(m, 표지, 옵션)]), { level: 0 }]
  })
  return zipSync(f, { level: 0 })
}
