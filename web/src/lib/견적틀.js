    if (q01 && (x.단위 === '' || 단위식(x.단위)) && !요율(x.규격) && 관급머리.test(뗀이름(x.이름))) { x.꼴 = '머리'; x.관급머리 = true; x.옆아래 = !!(nx && nx.들 === x.들 && nx.꼴 === '?'); continue }
