/** 개찰이 시작되는 시각(한국시간). 실측 11,638건에서 이보다 이른 개찰은 0건. */
export const OPEN_FROM_HOUR = 9

/** 한국시간의 «시»와 «요일». 브라우저가 어느 시간대든 같은 답이 나오도록
 *  UTC 필드로 읽습니다 (getTimezoneOffset 은 기기 설정에 흔들립니다). */
export function kstParts(now = new Date()) {
  const d = new Date(now.getTime() + 9 * 3600000)
  return { h: d.getUTCHours(), day: d.getUTCDay() }   // day 0=일 6=토
}

/** 1순위(개찰) 목록 위에 붙일 한 줄. «어제 날짜가 정상인지» 를 시각으로 답합니다. */
export function firstNote(now = new Date()) {
  const { h, day } = kstParts(now)
  if (day === 0 || day === 6) return '주말에는 개찰이 없습니다'
  if (h < OPEN_FROM_HOUR) {
    const hh = String(OPEN_FROM_HOUR).padStart(2, '0')   // 「9시」보다 「09시」가 사이트 표기와 맞습니다
    return `오늘 개찰은 아직 시작 전입니다 — 개찰은 ${hh}시부터 열립니다`
  }
  return '개찰은 11시에 65%가 몰립니다'
}
