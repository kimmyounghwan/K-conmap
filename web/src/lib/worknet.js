/**
 * 워크넷 채용정보 검색 주소를 만든다.
 * @param {string} kw     찾을 낱말 (예: '철근')
 * @param {string} region '시군구,시도' 짝. 빈 값이면 전국.
 */
export function wnUrl(kw, region) {
  const q = new URLSearchParams({
    searchMode: 'Y',
    siteClcd: 'all',
    sortField: 'DATE',       // 최근 등록순
    sortOrderBy: 'DESC',
    resultCnt: '50',
    srcKeyword: kw,
    keyword: kw,
  })
  /* 고용형태(empTpGbcd)는 일부러 안 넣습니다 — 넣으면 상용직만 나와서
     건설 일용직이 통째로 빠집니다. 소장님들이 찾는 건 그쪽입니다. */
  if (region) q.set('region', region)
  return BASE + '?' + q.toString()
}
