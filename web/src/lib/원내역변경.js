/* 🩹 G131 — 긴 글이 칸 밖으로 안 나가게: «감» 꼴(칸 안 줄바꿈 · 선에서 한 칸 띄움) 칸의 글 길이로 줄 높이를 셈
 *   (엑셀 열 너비 1 ≈ 숫자 한 자 · 한글은 그 1.8 배 · 10pt 한 줄 ≈ 15pt) */
const 글폭 = (t) => { let w = 0; for (const ch of String(t ?? '')) w += /[\u1100-\u11ff\u2e80-\u9fff\uac00-\ud7af\uff00-\uffef]/.test(ch) ? 1.8 : 1; return w }
function 높이맞추기(줄들, 너비) {
  for (const r of 줄들) {
    if (!Array.isArray(r)) continue
    let n = 1
    r.forEach((c, j) => {
      if (!c || typeof c !== 'object' || !/감$/.test(c.s || '')) return
      const w = Math.max(4, (c.폭 || 너비[j] || 10) - 3)
      const 줄수 = String(c.v ?? '').split('\n').reduce((a, p) => a + Math.max(1, Math.ceil(글폭(p) / w)), 0)
      n = Math.max(n, 줄수)
    })
    if (n > 1) r.높이 = n * 15 + 3
  }
}

