/**
 * 🙋 건설맵 도우미 — 넣은 도면으로 «무슨 도면이 더 있어야 하는지» 알려 줌 (G391 · 2026-10-23)
 *
 * 소장님: 「무슨 도면이 필요하다고 알려주기도 해야 해..도우미 역할도 해줘야 해」 · 「건물을 세우기 위해서는 차례가 이렇게 되어야 한다는 설명 — 게임에서 뭘 하면 된다라고」
 *   (사이트 글은 «건설맵 도우미» — «클로드» 라고 안 씀)
 * ■ 바탕: 골조읽기 R(읽음 — 평면 · 높이 · 층고짐작 · 일람 · 셈 · 개수 · 정착표) · BIM 부재 · 도면에서모델 못옮김.
 * ■ 꼴: [{급: '꼭' | '있으면', 무엇, 글, 까닭}] — 급 차례(꼭 먼저) · 한 가지 까닭은 한 줄.
 */
const 층말 = (f) => (f === 'FT' ? '기초' : f === 'R' ? '지붕층' : f === 'PH' ? '옥탑층' : f === 'PR' ? '옥탑 지붕' : /^B\d+$/.test(f) ? '지하' + f.slice(1) + '층' : f + '층')
const 종류말 = { 기둥: '기둥', 보: '보', 슬라브: '슬라브', 벽: '벽', 기초: '기초', 계단: '계단' }

/**
 * @param {object} R    골조읽기(+ 플랜트다듬기) 결과
 * @param {object[]} 못옮김 도면에서모델 못옮김(없어도 됨)
 * @param {object} M 도면에서모델 결과 모델(없어도 됨) — 층마다 세운 부재가 있는지
 * @returns {{급: string, 무엇: string, 글: string, 까닭: string}[]}
 */
export function 필요한도면(R, 못옮김 = [], M = null) {
  const out = []
  const 넣 = (급, 무엇, 글, 까닭) => out.push({ 급, 무엇, 글, 까닭 })
  const 읽 = (R && R.읽음) || {}
  const 평면 = 읽.평면 || []
  const 층들 = ((R && R.공사 && R.공사.층) || []).map((f) => String(f.이름)).filter(Boolean)
  /* ① 평면 */
  if (!평면.length) {
    넣('꼭', '구조평면도', '구조평면도가 없습니다 — 기둥 · 보 · 벽 · 슬라브의 자리와 길이를 못 읽었습니다', '평면 = 자리 · 길이')
  } else {
    const 있는층 = new Set(평면.flatMap((p) => p.층 || []))
    const 세운층 = new Set([...((M && M.부재) || []).map((o) => o.층), ...(못옮김 || []).map((x) => x.층)])
    /* 맨 위 «층» 은 바로 아래층 지붕(보 · 슬라브)을 얹는 자리라 평면이 따로 없음(n층 = n층 기둥 · 벽 + 그 위 바닥) — 위로 부재가 없는 층은 안 물음 */
    const 맨위 = Math.max(...층들.map((f, i) => (세운층.has(f) || 있는층.has(f) ? i : -1)))
    const 빠진층 = 층들.filter((f, i) => !있는층.has(f) && !세운층.has(f) && i < 맨위)
    for (const f of 빠진층) {
      if (f === 'FT') 넣('꼭', '기초 평면도', '기초 평면도가 없습니다 — 기초 · 지중보를 못 세웠습니다', '기초 평면 = 기초 자리 · 지중보')
      else 넣('꼭', 층말(f) + ' 구조평면도', 층말(f) + ' 구조평면도가 없습니다 — ' + 층말(f) + ' 기둥 · 보 · 슬라브를 못 세웠습니다(같은 층이면 «층 복사»)', '평면 = 자리 · 길이')
    }
  }
  /* ② 일람 — 평면에 기호가 있는데 일람표에 없는 것 · 건설맵이 만든 일람 */
  const 일람밖 = new Map()
  for (const x of 못옮김 || []) if (/일람표에 없는 기호/.test(x.까닭 || '')) { const k = x.종류; if (!일람밖.has(k)) 일람밖.set(k, new Set()); 일람밖.get(k).add(x.기호) }
  for (const [종, s] of 일람밖) 넣('꼭', (종류말[종] || 종) + ' 일람표', (종류말[종] || 종) + ' 일람표에 없는 기호 ' + [...s].slice(0, 8).join(' · ') + (s.size > 8 ? ' …' : '') + ' — 그 기호가 있는 일람표 도면을 넣어 주세요', '일람표 = 크기 · 철근')
  const 만든 = ((R && R.경고) || []).find((w) => /건설맵이 만든 일람/.test(w))
  if (만든) { const m = 만든.match(/일람\s*(\d+)\s*가지\s*\(([^)]*)\)/); 넣('있으면', '일람표(만든 값)', '일람표에서 못 찾아 건설맵이 채운 기호 ' + (m ? m[1] + '가지(' + m[2] + ')' : '') + ' — 그 일람표가 있으면 넣어 주세요(지금은 비슷한 부재 · 흔한 값)', '일람표 = 크기 · 철근') }
  const 일 = 읽.일람 || {}
  if (일.표있음 === false) 넣('꼭', '부재 일람표', '부재 일람표(기둥 · 보 · 슬라브 · 벽 · 기초)를 찾지 못했습니다 — 크기 · 철근을 못 읽었습니다', '일람표 = 크기 · 철근')
  /* ③ 높이 */
  const 짐 = 읽.층고짐작 || []
  if (짐.length) 넣('꼭', '단면도 · 골구도', '단면도 · 골구도가 없어 ' + 짐.map((f) => 층말(String(f.층 || f))).join(' · ') + ' 층 높이를 짐작했습니다 — 단면도를 넣으면 정확해집니다', '단면 · 골구도 = 층 높이 · 레벨')
  else if (!읽.높이 || !Object.keys(읽.높이).length) 넣('꼭', '단면도 · 골구도', '층 높이(레벨)를 읽지 못했습니다 — 단면도 · 골구도를 넣어 주세요', '단면 · 골구도 = 층 높이 · 레벨')
  /* ④ 일반사항 */
  if (R && !R.정착표 && !((R.정착표들 || []).length)) 넣('있으면', '구조 일반사항', '구조 일반사항(정착 · 이음 길이표)이 없어 기준값(KDS)으로 셌습니다 — 일반사항 도면이 있으면 철근이 정확해집니다', '일반사항 = 정착 · 이음 · 피복')
  /* ⑤ 손으로 할 것 */
  const 까닭수 = (re) => (못옮김 || []).filter((x) => re.test(x.까닭 || '')).length
  const mat = 까닭수(/MAT|부정형 기초/)
  if (mat) 넣('있으면', '기초 상세', 'MAT · 부정형 기초 ' + mat + '곳은 모양을 못 읽어 손으로 — 기초 상세 · 단면이 있으면 두께 · 높이가 정확해집니다', '상세 = 두께 · 단차')
  /* 🟨 G392 건설맵이 도면 외곽선대로 먼저 세운 MAT · 부정형 기초 — 두께 · 철근 확인 */
  const 제안 = ((M && M.부재) || []).filter((o) => o.제안 && o.종류 === '기초')
  if (제안.length) {
    const 철빈 = 제안.filter((o) => /철근이 비었음/.test(o.제안)).length
    넣(철빈 ? '꼭' : '있으면', '기초 상세', '🟨 MAT · 부정형 기초 ' + 제안.length + '곳은 건설맵이 도면 외곽선대로 먼저 세웠습니다 — 두께' + (철빈 ? ' · 철근(' + 철빈 + '곳 비었음)' : '') + '을 보고 «✓ 이대로» 눌러 주세요 · 기초 상세(단면 · 배근)가 있으면 정확해집니다', '상세 = 두께 · 배근')
  }
  const 계 = 까닭수(/계단/)
  if (계) 넣('있으면', '계단 상세', '계단 ' + 계 + '곳은 손으로 — 계단 상세(단수 · 두께 · 배근)가 있으면 넣어 주세요', '상세 = 계단 단수 · 두께')
  const 비 = 까닭수(/비스듬/)
  if (비) 넣('있으면', '확대 평면 · 상세', '비스듬한 보 · 벽 ' + 비 + '곳은 손으로 — 확대평면도가 있으면 자리가 정확해집니다', '확대 평면 = 자리')
  const 겹 = 까닭수(/같은 자리/)
  if (겹) 넣('있으면', '확인', '같은 자리에 두 번 그려진 부재 ' + 겹 + '곳 — 도면을 확인해 주세요(한 번만 셈)', '확인')
  return out.sort((a, b) => (a.급 === b.급 ? 0 : a.급 === '꼭' ? -1 : 1))
}

/**
 * 🧭 길잡이 — 건물을 세우는 차례(게임의 «다음 할 일») · 끝낸 것은 ✓
 * @param {object} M 골조 모델 · @param {object} o {도면: 도면결과, 확인: Map(층 → 비율 0~1), 엑셀: boolean}
 * @returns {{번, 글, 끝: boolean, 지금: boolean, 할곳: string}[]}
 */
export function 길잡이(M, o = {}) {
  const 층 = (M && M.층) || []
  const 부 = (M && M.부재) || []
  const 있 = (f) => 부.some((x) => x.층 === f)
  const 단계 = []
  const 더 = (글, 끝, 할곳) => 단계.push({ 번: 단계.length + 1, 글, 끝: !!끝, 할곳 })
  더('도면 올리기 — 📐 도면 넣기에 구조도면을 모두', !!(M && M.도면에서) || 부.length > 0, '도면')
  더('일람표 · 일반사항 — 크기 · 철근 읽기', ['기둥', '보', '슬라브', '벽'].some((k) => ((M && M.배근 && M.배근[k]) || []).length > 0), '일람')
  for (const f of 층) {
    const 이름 = f.이름 === 'FT' ? '토공 · 기초' : /^B\d+$/.test(f.이름) ? '지하' + f.이름.slice(1) + '층' : f.이름 === 'R' ? '지붕층' : f.이름 === 'PH' ? '옥탑층' : f.이름 + '층'
    더(이름 + ' 세우기', 있(f.이름), '층:' + f.이름)
  }
  더('층 높이 — 단면 · 골구도로 확인', !!(o.도면 && !(o.도면.필요 || []).some((x) => /단면/.test(x.무엇))) || 층.every((f) => f.이름 === 'FT' || +f.층고 > 0), '통심')
  const 확 = o.확인 instanceof Map ? o.확인 : new Map()
  const 세운층 = 층.filter((f) => 있(f.이름))
  더('🚶 둘러보기 — 층마다 걸으며 빨간 곳 풀기', 세운층.length > 0 && 세운층.every((f) => (확.get(f.이름) || 0) >= 0.9), '둘러보기')
  더('📊 엑셀 산출서 받기', !!o.엑셀, '엑셀')
  const k = 단계.findIndex((s) => !s.끝)
  if (k >= 0) 단계[k].지금 = true
  return 단계
}
