const 정한말머리 = ['[후기·건의] ', '[K-건설맵] ']
const 앞말머리 = /^\s*(?:\[[^\]]*\]\s*)+/
const 낱자들 = /^[\u1100-\u11FF\u3131-\u318E\uA960-\uA97F\uD7B0-\uD7FF\uFFA0-\uFFDC]+$/u   /* 첫 · 가운데 · 끝소리 낱자 · 호환 자모(ㄱ ~ ㆎ) · 옛 낱자 · 반각 */

/** 이 글(제목 · 답글)이 한글 낱자만으로 되었나 — 말머리 · 띄어쓰기 · 문장부호 · 기호는 빼고 봄 */
export function 낱자만(글) {
  let s = String(글 ?? '')
  for (const m of 정한말머리) s = s.split(m).join('')
  s = s.replace(앞말머리, '').normalize('NFC').replace(/[^\p{L}\p{N}]/gu, '')
  return s.length > 0 && 낱자들.test(s)
}

