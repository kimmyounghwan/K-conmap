/* 기준이 될 수 없는 종류 */
export const 기준못됨 = new Set(['건축', '상세', '표', '횡단', '종단', '구조', '건물'])

/* 현황 도면 이름 — 현황도 · 현황평면도 · 대지현황도 · 지형도 (계획 · 철거는 아님) */
export function 현황이름(s) {
  const t = String(s || '').replace(/\s+/g, '')
  return /현황|지형/.test(t) && !/계획|철거|깨기/.test(t)
}

/**
 * 기준 차례(작을수록 먼저) — g: {종류, 성과표, 제목, 파일[]}
 * 0 측량성과표 · 1 이름에 GPS·측량 든 측량도면 · 2 측량도면 · 3 계획평면도 · 배치도 · 4 평면도 · 5 종평면 · 6 그 밖 · 9 기준 못 됨
 */
export function 기준차례(g) {
  const 이름 = `${g.제목 || ''} ${(g.파일 || []).join(' ')}`.replace(/\s+/g, '')
  if (g.성과표) return 0
  if (기준못됨.has(g.종류)) return 9
  if (g.종류 === '측량') return /GPS|측량/i.test(이름) ? 1 : 2
  if (g.종류 === '평면' && /계획평면|배치도/.test(이름)) return 3
  if (g.종류 === '평면') return 4
  if (g.종류 === '종평') return 5
  return 6
}
