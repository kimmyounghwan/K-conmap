/** 「2G1」 → ['2','G1'] · 「B1C2」 → ['B1','C2'] · 「RG1」 → ['R','G1'] · 층 표시 없으면 ['', 기호] */
export function 층떼기(기호) {
  const t = 글(기호).toUpperCase()
  const m = t.match(/^(FT|B\d+|\d+[A-Z]?(?=[A-Z])|\d+|R|PR|P\d*|FS|F)([A-Z].*)$/)
  if (!m) return ['', t]
  // 「2A」 가 중간층인지 기호 앞글자인지: 「2AG1」 처럼 뒤에 또 영문+숫자가 오면 중간층으로 봄
  return [m[1], m[2]]
}
/** 배근표 기호의 연속 표기 「1-RG1」「B2-B1C2」「1~3C1」 → {a, b, 기호} */
