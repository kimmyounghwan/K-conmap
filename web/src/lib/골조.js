const 글 = (x) => String(x ?? '').trim()
const 수 = (x, d = null) => {
  const t = 글(x).replace(/,/g, '')
  if (t === '') return d
  const v = Number(t)
  return Number.isFinite(v) ? v : d
}
/** mm → m 글자 (소수 셋째 자리까지, 끝 0 지움) */
function m(mm) {
  const v = Math.round(mm) / 1000
  let s = v.toFixed(3)
  s = s.replace(/0+$/, '').replace(/\.$/, '')
  return s === '-0' ? '0' : s
}
const 단위무게 = (d) => 철근표[d][1]
const 굵기 = (d) => 철근표[d][0]
const 갈고리mm = (기, d) => Math.max(기.갈고리 * 굵기(d), 75)

/** 엑셀 ROUND 와 같게 — 15자리로 다듬은 뒤 0.5 는 0 에서 먼 쪽으로 (4.4955 → 4.496) */
export function 엑셀반올림(v, 자리) {
  if (!Number.isFinite(v)) return v
  const t = Math.abs(Number(v.toPrecision(15)))
  const st = String(t)
  const r = st.includes('e') ? Math.round(t * Math.pow(10, 자리)) / Math.pow(10, 자리) : Number(Math.round(Number(st + 'e' + 자리)) + 'e-' + 자리)
  return v < 0 ? -r : r
}

/** 층 이름 맞추기: 「1F」「1층」「01」 → 「1」 · 「B1F」→「B1」 */
export function 층이름(s) {
  let t = 글(s).toUpperCase().replace(/층$/, '').replace(/F$/, '')
  if (/^0\d+$/.test(t)) t = String(+t)
  return t
}

