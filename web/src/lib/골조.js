export const 규격들 = Object.keys(철근표)

/** 「HD22」「SD22」「SHD22」「D22」「22」 → 「D22」 */
export function 규격(s) {
  const t = String(s ?? '').toUpperCase().replace(/\s/g, '')
  const m = t.match(/(\d{2})$/)
  if (!m) return ''
  const k = 'D' + m[1]
  return 철근표[k] ? k : ''
}
/** 끝의 길이 「L)3000」「L=3000」 떼기 → [나머지, 길이|null] */
function 길이떼기(t) {
  const m = t.match(/^(.*?)L[)=]?(\d+(?:\.\d+)?)$/)
  return m ? [m[1], +m[2]] : [t, null]
}
/** 「4-D22」「4-HD22」「4HD22」「4-D13 L)2000」 → {n:4, d:'D22', L?} */
export function 본수(s) {
  let t = String(s ?? '').toUpperCase().replace(/\s/g, '')
  if (!t) return null
  const [앞, L] = 길이떼기(t)
  t = 앞
  const m = t.match(/^(\d+)\s*[-×X*]?\s*[A-Z]*(\d{2})$/)
  if (!m) return null
  const d = 규격(m[2])
  if (!(d && +m[1] > 0)) return null
  return L ? { n: +m[1], d, L } : { n: +m[1], d }
}
/** 「D10@150」「HD10@150」「D10-150」 → {d:'D10', s:150}
 *  「D10+D13@200」(격배근) → {d:'D10', d2:'D13', s:200} · 「… L)600」 → L */
export function 간격(s) {
  let t = String(s ?? '').toUpperCase().replace(/\s/g, '')
  if (!t) return null
  const [앞, L] = 길이떼기(t)
  t = 앞
  let m = t.match(/^[A-Z]*(\d{2})\+[A-Z]*(\d{2})[@\-/](\d+(?:\.\d+)?)$/)
  if (m) {
    const d = 규격(m[1]), d2 = 규격(m[2])
    if (!(d && d2 && +m[3] > 0)) return null
    const o = { d, d2, s: +m[3] }
    if (L) o.L = L
    return o
  }
  m = t.match(/^[A-Z]*(\d{2})[@\-/](\d+(?:\.\d+)?)$/)
  if (!m) return null
  const d = 규격(m[1])
  if (!(d && +m[2] > 0)) return null
  return L ? { d, s: +m[2], L } : { d, s: +m[2] }
}
/**
 * 철근 칸 — 설명서의 넣는 꼴 5가지를 모두 읽습니다
 *   ① D10@200 L)3000  ② D10+D13@200 (격배근)  ③ 4-D13 L)2000  ④ 4-D13@200 L)…  ⑤ D10@1000x1000 L)600 (지지근)
 * @returns {{꼴, d, d2?, s?, s2?, n?, L?}|null}
 */
export function 철근칸(s) {
  let t = String(s ?? '').toUpperCase().replace(/\s/g, '')
  if (!t) return null
  const [앞, L] = 길이떼기(t)
  let m = 앞.match(/^[A-Z]*(\d{2})@(\d+(?:\.\d+)?)[X×*](\d+(?:\.\d+)?)$/)
  if (m && 규격(m[1])) return { 꼴: '지지근', d: 규격(m[1]), s: +m[2], s2: +m[3], L }
  m = 앞.match(/^(\d+)[-×X*]?[A-Z]*(\d{2})@(\d+(?:\.\d+)?)$/)
  if (m && 규격(m[2])) return { 꼴: '본수간격', n: +m[1], d: 규격(m[2]), s: +m[3], L }
  const g = 간격(s)
  if (g) return { 꼴: g.d2 ? '격배근' : '간격', ...g, L: g.L ?? L }
  const b = 본수(s)
  if (b) return { 꼴: '본수', ...b, L: b.L ?? L }
  return null
}

