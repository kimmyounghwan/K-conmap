/** 올림(10mm) */
const up10 = (x) => Math.ceil(x / 10 - 1e-9) * 10

/**
 * 정착·이음 기본값 — KDS 14 20 52 (콘크리트구조 정착 및 이음 설계기준)의 «기본식» 으로 셈합니다.
 *   인장 정착 l_d = 0.6·d_b·f_y /(λ·√f_ck)  (보정계수 1.0, 300mm 이상)
 *   상부 철근(그 아래 콘크리트 300mm 넘게 치는 수평철근) = 인장 정착 × 1.3
 *   압축 정착 = max(0.25·d_b·f_y /(λ·√f_ck), 0.043·d_b·f_y)  (200mm 이상)
 *   인장 이음(B급) = 1.3 × 인장 정착  (300mm 이상)
 *   압축 이음 = 0.072·f_y·d_b (f_y ≤ 400) · (0.13·f_y − 24)·d_b (f_y > 400)  (300mm 이상, f_ck < 21 이면 ×4/3)
 * ⚠️ 설계도면 «일반구조사항» 에 정착·이음 표가 있으면 그 값으로 고쳐 쓰십시오 — 그것이 맞습니다.
 */
export function 정착표(fck, fy, 경량 = 1) {
  const out = {}
  const rf = Math.sqrt(fck) * 경량
  for (const d of 규격들) {
    const db = 철근표[d][0]
    const ld = Math.max(0.6 * db * fy / rf, 300)
    const 압정 = Math.max(0.25 * db * fy / rf, 0.043 * db * fy, 200)
    let 압이 = fy <= 400 ? 0.072 * fy * db : (0.13 * fy - 24) * db
    if (fck < 21) 압이 *= 4 / 3
    out[d] = {
      인장정착: up10(ld),
      상부정착: up10(ld * 1.3),
      압축정착: up10(압정),
      인장이음: up10(Math.max(ld * 1.3, 300)),
      압축이음: up10(Math.max(압이, 300)),
    }
  }
  return out
}

