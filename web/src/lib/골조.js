/**
 * 옛 모양(공사.주자료 하나) → 새 모양(공사.동[…].주자료). 어느 쪽이 와도 새 모양으로 돌려줌(원본은 안 건드림)
 */
export function 정리(공사) {
  const P = { ...공사 }
  if (!Array.isArray(P.동) || !P.동.length) {
    P.동 = [{ ...새동(''), 주자료: { ...빈주자료(), ...(공사.주자료 || {}) } }]
  } else {
    P.동 = P.동.map((d) => ({ ...새동(''), ...d, 주자료: { ...빈주자료(), ...(d.주자료 || {}) } }))
  }
  delete P.주자료
  P.유닛 = Array.isArray(P.유닛) ? P.유닛 : []
  P.배근 = { 보: [], 기둥: [], 슬라브: [], 벽: [], 계단: [], 기초: [], 보강근: [], ...(P.배근 || {}) }
  return P
}

