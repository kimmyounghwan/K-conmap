/** 요약 표에 쓸 공종 — 맨 위 깊이가 하나뿐(공사 이름 하나)이면 한 칸 아래 깊이로 */
export function 요약공종(공종들) {
  if (!공종들.length) return []
  const 깊이들 = [...new Set(공종들.map((p) => p.깊이))].sort((a, b) => a - b)
  for (const d of 깊이들) {
    const 이것 = 공종들.filter((p) => p.깊이 === d)
    if (이것.length > 1 || d === 깊이들[깊이들.length - 1]) return 이것
  }
  return 공종들.filter((p) => p.깊이 === 깊이들[0])
}

