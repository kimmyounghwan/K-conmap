  let 시트들 = 기성시트들(읽은, 결과, 편집, 날짜)
  if (!xlsx) 시트들 = [내역시트(읽은.원읽은.모형, [0], { 제목: '내 역 서 (계 약)', 이름: '계약내역서' }), ...시트들]
  const 새 = 변경엑셀(시트들)
  const 이름들 = 시트들.map((s) => s.이름)
  if (!xlsx) return { 바이트: 새, 시트이름들: 이름들, 붙임: false }
  const 머리줄 = 시트들.map((s) => (s.머리 && s.머리.length ? [s.제목 ? 3 : 1, (s.제목 ? 2 : 0) + s.머리.length] : null))
