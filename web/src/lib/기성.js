/** kv 줄(이름 · 값 — 값은 B ~ 끝 칸 합침) */
function kv서식(제목, 줄들, 너비, 앞 = []) {
  const 폭 = 너비.length
  const 병합 = []
  const out = []
  let R = 3
  const 넣 = (row, 합) => { out.push(row); if (합) 병합.push(합.replace(/\{R\}/g, R)); R++ }
  for (const x of 앞) 넣(x.줄, x.합)
  for (const x of 줄들) {
    if (!x) { 넣([]); continue }
    if (x.표) { 넣(x.표.map((v) => ({ v, s: '머리' }))); for (const r of x.줄) 넣(r); continue }
    if (x.글) { 넣([{ v: x.글, s: x.s || '글' }], `A{R}:${열글(폭)}{R}`); continue }
    넣([{ v: x[0], s: '머리' }, { v: x[1] ?? '', s: x[2] || '글' }, ...Array.from({ length: 폭 - 2 }, () => ({ v: '', s: '글' }))], `B{R}:${열글(폭)}{R}`)
  }
  return { 제목, 너비, 머리: [], 병합, 줄: out, 세로: true }
}

