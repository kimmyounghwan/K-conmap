/** 품목마다 다음 회차에도 같은 열쇠 — 공종 경로 + 품명 · 규격 · 단위 + 같은 것이 여럿이면 차례 */
export function 품목열쇠들(모형) {
  const 쌓 = []
  const 본 = new Map()
  return 모형.줄.map((x) => {
    if (x.꼴 === '공종') {
      while (쌓.length && 쌓[쌓.length - 1].깊이 >= x.깊이) 쌓.pop()
      쌓.push(x)
      return null
    }
    if (x.꼴 !== '품목') return null
    const k = 쌓.map((y) => 글(y.이름)).join('>') + '#' + 열쇠(x)
    const n = (본.get(k) || 0) + 1
    본.set(k, n)
    return n > 1 ? k + '#' + n : k
  })
}

/** 공종 목록 — 화면의 «공종마다 %» 칸 · 범위(끝 줄 번호 · 품목들) · 별도 */
export function 공종목록(모형) {
  const 줄 = 모형.줄
  const out = []
  줄.forEach((x, i) => {
    if (x.꼴 !== '공종') return
    let 끝 = 줄.length - 1
    for (let j = i + 1; j < 줄.length; j++) if (줄[j].꼴 === '공종' && (줄[j].깊이 || 0) <= (x.깊이 || 0)) { 끝 = j - 1; break }
    const 품목들 = []
    for (let j = i + 1; j <= 끝; j++) if (줄[j].꼴 === '품목') 품목들.push(j)
    out.push({ i, 이름: x.이름, 번호: x.번호 || '', 깊이: x.깊이 || 0, 끝, 품목들, 별도: !!x.별도 })
  })
  return out
}

/** 줄마다 «별도 공종 아래인가» (관급자재처럼 순공사비 밖) */
function 별도아래(모형) {
  const 쌓 = []
  return 모형.줄.map((x) => {
    if (x.꼴 === '공종') {
      while (쌓.length && 쌓[쌓.length - 1].깊이 >= x.깊이) 쌓.pop()
      쌓.push(x)
      return 쌓.some((y) => y.별도)
    }
    return 쌓.some((y) => y.별도)
  })
}

/** 지난 기성 파일의 숨은 자료 시트(가장 큰 회차) → {회차, 차수, 기간, 원시트, 누계: Map} | null */
export function 지난자료(책) {
  const 이름들 = Object.keys(책).filter((n) => /^_기성자료\d+$/.test(n))
  if (!이름들.length) return null
  이름들.sort((a, b) => Number(b.slice(5)) - Number(a.slice(5)))
  const grid = 책[이름들[0]] || []
  let 몸 = ''
  for (const row of grid) if (row && 글(row[0]) === 'JSON') 몸 += String(row[1] ?? '')
  try {
    const j = JSON.parse(몸)
    if (!j || j.판 !== 자료판) return null
    return { 회차: j.회차 || 0, 차수: j.차수 || '', 기간: j.기간 || '', 원시트: j.원시트 || null, 원시트들: j.원시트들 || (j.원시트 ? [j.원시트] : null), 누계: new Map(j.누계 || []), 날짜: j.날짜 || '', 원파일: j.원파일 || '', 선금: j.선금 || '' }
  } catch { return null }
}

/* 내역 시트답지 않은 것(묶어 읽을 때 뺌) — 집계표 · 총괄표 · 원가 · 대비표 · 일위대가 · 단가 */
const 묶음아님 = /집계|총괄|요약|대비|원가|일위|단가|산출|표지|목차|갑지/

/** 내역 시트 여럿(건축 · 기계설비 · 전기 …)을 한 모형으로 — 시트마다 맨 위 공종 하나(깊이 0) 아래에 그 시트의 공종 · 품목 */
function 묶어읽기(책, 파일이름, 이름들) {
  if (!이름들 || 이름들.length <= 1) return 원읽기(책, 파일이름, 이름들 && 이름들[0])
  const 파 = 파일읽기(책, 파일이름)
  const ms = 파.시트들.filter((m) => 이름들.includes(m.시트))
  if (ms.length <= 1) return 원읽기(책, 파일이름, ms[0] && ms[0].시트)
  const 갈래 = ['재료비', '노무비', '경비', '합계'].filter((k) => ms.some((m) => m.갈래.includes(k)))
  const 줄 = []
  const 말 = []
  for (const m of ms) {
    const 끝 = m.상태.length - 1
    if (끝 > 0) 말.push({ 무게: '참고', 무엇: `«${m.시트}» 는 이미 ${m.꼴} 내역서입니다 — 마지막 상태(«${m.상태[끝]}»)를 계약으로 씁니다` })
    줄.push({ 꼴: '공종', 깊이: 0, 번호: '', 이름: m.시트, 규격: '', 원합: null, r: null })
    for (const x of m.줄) {
      if (x.꼴 === '계') continue
      줄.push(x.꼴 === '공종'
        ? { 꼴: '공종', 깊이: (x.깊이 || 0) + 1, 번호: x.번호, 이름: x.이름, 규격: x.규격 || '', 원합: x.원합 ? [x.원합[끝] || null] : null, r: x.r, ...(x.별도 ? { 별도: true } : {}) }
        : { 꼴: '품목', 번호: x.번호, 이름: (x.값[끝] && x.값[끝].이름) || x.이름, 규격: (x.값[끝] && x.값[끝].규격) || x.규격, 단위: x.단위, 값: [x.값[끝] || null], r: x.r })
    }
  }
  const 모형 = { 시트: ms.map((m) => m.시트).join(' + '), 상태: ['당초'], 갈래, 줄, 꼴: '1줄', 품목수: 줄.filter((x) => x.꼴 === '품목').length }
  const 합 = 모으기(모형).합[0]
  const 기준 = 갈래.includes('합계') ? '합계' : 갈래[0]
  const 원가 = 원가시트찾기(책)
  let 맞춘 = null
  if (원가) { 맞춘 = 원가맞추기(원가, 내역요약(모형, 0)); 말.push(...맞춘.말) }
  return { 파일이름, 시트들: 파.시트들.map((m) => m.시트), 고른: 모형.시트, 고른들: ms.map((m) => m.시트), 모형, 원가, 맞춘, 지문: [파일이름, 모형.시트, 모형.품목수, Math.round(합[기준] || 0)].join('|'), 말, 합: 합[기준] || 0 }
}

/** 원가계산서가 고른 내역과 맞나 — 재료 · 노무 · 경비 «나머지» 줄의 차이가 0.5 % 를 넘으면 안 맞음 */
function 원가맞음(r) {
  if (!r.원가 || !r.맞춘) return false
  const 맞음 = (m) => !m.셈.some((x) => x.꼴 === '나머지' && Math.abs(x.차이 || 0) > Math.max(1000, Math.abs(x.당초 || 0) * 0.005))
  /* 나열형 — 분야가 모두 이 내역 안에 있어야(«밖» 분야가 있으면 기성 원가 계약이 내역과 다름) */
  if (r.맞춘.분야) return r.맞춘.분야.every((f) => f.꼴 !== '밖' && 맞음(f.맞춘))
  return 맞음(r.맞춘)
}

/**
 * 계약 내역서(또는 지난 기성 파일) 읽기
 * @param 고를 내역 시트 이름들(없으면: 지난 자료 → 한 시트(가장 품목이 많은 내역) → 원가가 안 맞으면 내역 시트 모두 묶어 봄)
 * @returns {원읽은, 지난, 열쇠들, 공종들, 별도: [bool], 시트후보: [{시트, 품목수, 합, 고름}], 원가쓸, 말}
 */
export function 기성읽기(책, 파일이름, 고를 = null) {
  const 지난 = 지난자료(책)
  /* 우리가 붙인 시트(기성내역(n회) · 계약내역서 …)를 내역으로 잘못 고르지 않게 */
  const 우리것 = (n) => /^(기성내역|기성원가|부분기성|기성검산|기성검사원|기성청구서)\(\d+회\)$|^_기성자료\d+$/.test(n)
  const 깨끗 = Object.fromEntries(Object.entries(책).filter(([n]) => !우리것(n)))
  const 파 = 파일읽기(깨끗, 파일이름)
  const 있는 = new Set(파.시트들.map((m) => m.시트))
  let 이름들 = (고를 && 고를.filter((n) => 있는.has(n))) || null
  if ((!이름들 || !이름들.length) && 지난 && 지난.원시트들) 이름들 = 지난.원시트들.filter((n) => 있는.has(n))
  if (!이름들 || !이름들.length) 이름들 = [파.고른]
  let 원읽은 = 묶어읽기(깨끗, 파일이름, 이름들)
  const 말 = []
  /* 저절로: 고르지 않았는데 원가가 안 맞으면 — 내역 시트를 모두 묶어 봄(맞으면 그것으로) */
  if (!고를 && !(지난 && 지난.원시트들) && 원읽은.원가 && !원가맞음(원읽은)) {
    const 모두 = 파.시트들.filter((m) => !묶음아님.test(m.시트)).map((m) => m.시트)
    if (모두.length > 1) {
      const 시험 = 묶어읽기(깨끗, 파일이름, 모두)
      if (원가맞음(시험)) { 원읽은 = 시험; 이름들 = 모두; 말.push({ 무게: '참고', 무엇: `원가계산서가 내역 시트 ${모두.length}장(${모두.join(' · ')})을 합한 것과 맞아 모두 묶어 셉니다` }) }
    }
  }
  const 원가쓸 = 원가맞음(원읽은)
  if (원읽은.원가 && !원가쓸) {
    말.push({ 무게: '확인', 무엇: '원가계산서가 고른 내역 시트와 맞지 않습니다(재료비 · 노무비 · 경비 합이 다름) — 원가 기성은 빼고 순공사비로 셉니다. 원가계산서에 든 내역 시트를 모두 고르면 원가까지 셉니다' })
    말.push(...원읽은.말.filter((m) => m.무게 !== '확인'))
  } else 말.push(...원읽은.말)
  const 열쇠들 = 품목열쇠들(원읽은.모형)
  if (지난) {
    const 있 = new Set(열쇠들.filter(Boolean))
    const 못 = [...지난.누계.keys()].filter((k) => !있.has(k))
    if (못.length) 말.push({ 무게: '확인', 무엇: `지난 기성(${지난.회차}회)의 ${못.length}줄이 이번 내역서에 없습니다 — 그 줄의 전회 누계는 빠집니다` })
  }
  const 기준 = (m) => { const h = 모으기({ ...m, 상태: m.상태 }).합[m.상태.length - 1]; return h.합계 ?? ((h.재료비 || 0) + (h.노무비 || 0) + (h.경비 || 0)) }
  const 시트후보 = 파.시트들.map((m) => ({ 시트: m.시트, 품목수: m.품목수, 합: 기준(m), 고름: 이름들.includes(m.시트), 묶음아님: 묶음아님.test(m.시트) }))
  const 고른들 = 원읽은.고른들 || [원읽은.고른]
  return { 원읽은: { ...원읽은, 고른들 }, 지난, 열쇠들, 공종들: 공종목록(원읽은.모형), 별도: 별도아래(원읽은.모형), 시트후보, 원가쓸, 말 }
}

