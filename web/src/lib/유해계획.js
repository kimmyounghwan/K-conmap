/**
 * 고른 대상 → [{ 공사, 항들: [{ 대상, 호, 키, 글, 제목, 평가, 절차, 시설, 도면, 상세, 비고, 기타 }] }]
 * @param 대상들 ['건축', '굴착', …] · @param 끔 { 키: true } 뺄 작성대상 · @param 더 [[작업공사, 작업 이름]] 더 적을 작업
 */
export function 유해목록(대상들 = [], 끔 = {}, 더 = []) {
  const 묶 = new Map()
  const 넣 = (공사, 항) => { if (!묶.has(공사)) 묶.set(공사, []); 묶.get(공사).push(항) }
  const 본 = new Set()
  for (const 대키 of 유해대상차례.filter((k) => 대상들.includes(k))) {
    const t = 자.유해대상[대키]
    if (!t) continue
    for (const r of t.작성대상) {
      if (끔[r.키] || 본.has(r.키)) continue
      본.add(r.키)
      /* 다른 대상에 같은 작업공사 · 같은 작성대상 글이 있으면 한 항으로(예: 댐 · 굴착공사의 «굴착 및 발파 작업») */
      const 같은 = (묶.get(r.공사) || []).find((h) => h.글 === r.글)
      if (같은) { if (!같은.호들.includes(t.호)) 같은.호들.push(t.호); continue }
      넣(r.공사, { 대상: 대키, 호: t.호, 호들: [t.호], 대상이름: t.이름, ...r, 제목: 짧은제목[r.키] || r.글 })
    }
  }
  for (const r of 자.가설공통) {
    if (끔[r.키] || 본.has(r.키)) continue
    본.add(r.키)
    넣('가설공사', { 대상: 대상들[0] || '', 호: '', 대상이름: '', ...r, 공사: '가설공사', 제목: 짧은제목[r.키] || r.글, 기타: true })
  }
  for (const [공사, 이름] of 더 || []) {
    const 키 = '더' + 이름
    if (!글(이름) || 본.has(키)) continue
    본.add(키)
    넣(글(공사) || '가설공사', { 대상: 대상들[0] || '', 호: '', 대상이름: '', 키, 글: 이름, 제목: 이름, 평가: [], 공사: 글(공사) || '가설공사', 기타: true })
  }
  const 차례 = [...작업공사차례, ...[...묶.keys()].filter((k) => !작업공사차례.includes(k))]
  return 차례.filter((k) => 묶.has(k)).map((공사) => ({ 공사, 항들: 묶.get(공사) }))
}

