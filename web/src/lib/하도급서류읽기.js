const 사이 = (말) => [...말].map((ch) => ch.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('\\s*')
/** «라벨 : 값» — 라벨 글자 사이 빈칸 · 괄호 꼬리(«(법인명)» 등)를 봐줌 */
function 값찾기(글, 라벨들, { 줄만 = true, 꼴 = null } = {}) {
  const 줄들 = String(글 || '').split(/\r?\n/)
  for (const 라 of 라벨들) {
    const re = new RegExp('(?:^|\\s|[|│])' + 사이(라) + '(?:\\s*\\([^)]{0,12}\\))?\\s*[:：]?\\s*(.+)$')
    for (const 줄 of 줄들) {
      const m = re.exec(줄)
      if (!m) continue
      let v = m[1].trim()
      if (줄만) v = v.split(/\s{3,}|\t|│|\|/)[0].trim()
      if (꼴) { const k = 꼴.exec(v); if (!k) continue; v = k[1] || k[0] }
      if (v) return v
    }
  }
  return ''
}
const 날꼴 = /(\d{4})\s*[년.\-/]\s*(\d{1,2})\s*[월.\-/]\s*(\d{1,2})\s*일?/
export function 날로(t) {
  const m = 날꼴.exec(String(t || ''))
  return m ? m[1] + '년 ' + String(+m[2]).padStart(2, '0') + '월 ' + String(+m[3]).padStart(2, '0') + '일' : ''
}
