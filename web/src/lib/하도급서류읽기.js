/** 내역서(엑셀 격자)에서 공사명 — 원가계산서 · 내역서 위쪽 «공사명 : …» */
export function 내역공사명(책) {
  for (const grid of Object.values(책 || {})) {
    for (const row of (grid || []).slice(0, 12)) {
      const 글 = (row || []).map((x) => (x === null || x === undefined ? '' : String(x))).join('  ')
      const m = /공\s*사\s*명\s*[:：]?\s*(.+)/.exec(글)
      if (m && m[1].trim().length >= 3) return m[1].trim().replace(/\s{2,}.*$/, '').slice(0, 80)
    }
  }
  return ''
}
