  const 공사명 = 값찾기(글, ['계약건명', '공사명', '건명'])
  const 장소 = 값찾기(글, ['공사장소', '공사위치', '현장위치', '공사장 소재지', '현장'], { 줄만: false }).replace(/\s{2,}.*$/, '').trim()
  const 발주 = 값찾기(글, ['발주기관', '발주처', '발주자', '기관명'])
  const 금액글 = 값찾기(글, ['계약금액', '도급금액', '총 공사금액'], { 줄만: false })
  const 원 = 돈꼴.exec(금액글 || '')
  const 금액 = 원 ? Number(String(원[1] || 원[2] || 원[3]).replace(/,/g, '')) : null
  const 착공 = 날로(값찾기(글, ['착공일자', '착공년월일', '착공연월일', '착공일'], { 줄만: false }))
  const 준공 = 날로(값찾기(글, ['금차준공일자', '준공일자', '준공년월일', '준공연월일', '준공기한', '준공일'], { 줄만: false }))
