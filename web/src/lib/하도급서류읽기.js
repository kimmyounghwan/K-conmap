export function 종류알기(글, 이름 = '') {
  const t = String(글 || '').replace(/\s+/g, '')
  const n = String(이름 || '').replace(/\s+/g, '')
  if (/경력증명서|건설기술인경력|기술인경력/.test(t) || /경력/.test(n)) return '경력'
  if (/건설업등록(증|수첩)|건설사업자등록증/.test(t) || /등록(증|수첩)/.test(n) && /건설/.test(n)) return '등록증'
  if (/사업자등록증/.test(t) || /사업자/.test(n)) return '사업자'
  /* 원도급 계약서 — 「공사도급표준계약서」 · 전자계약 「공사계약서 · 공사변경계약서」(계약건명 · 계약상대자 · 착공일자) */
  const 계약표 = [/계약서/, /계약건명/, /계약상대자/, /계약금액/, /착공(일자|년월일|연월일)/, /준공(일자|기한|년월일|연월일)/, /계약(일반|특수)조건/].filter((re) => re.test(t)).length
  if (/(공사|변경|도급)\S{0,6}계약서/.test(t) || 계약표 >= 3 || /계약서/.test(n)) return '원계약서'
  if (/예금주|계좌번호|통장/.test(t) || /통장|계좌/.test(n)) return '통장'
  return '모름'
}

/* ── 사업자등록증 ── */
export function 사업자읽기(글) {
  const 번호 = 값찾기(글, ['등록번호', '사업자등록번호'], { 꼴: 사업자꼴 })
  let 상호 = 값찾기(글, ['법인명', '상호', '단체명'])
  상호 = 상호.replace(/^\(?단체명\)?\s*[:：]?\s*/, '').trim()
  const 대표 = 값찾기(글, ['대표자', '성명'], { 꼴: /^([가-힣]\s?[가-힣](?:\s?[가-힣]){0,3})/ })
  const 소재 = 값찾기(글, ['사업장소재지', '사업장 소재지', '본점소재지', '본점 소재지', '소재지'], { 줄만: false })
  const 개업 = 날로(값찾기(글, ['개업연월일', '개업년월일'], { 줄만: false }))
  return {
    번호: 사업자꼴.test(번호) ? 번호 : '', 상호: 상호.length >= 2 && 상호.length <= 40 ? 상호 : '', 대표: 대표 || '',
    소재: 소재.replace(/\s{2,}.*$/, '').trim().slice(0, 80), 개업,
  }
}
