  const 발급 = (/(\d{8}\s*-\s*[A-Z]\d{6,10})/.exec(t) || [])[1] || 값찾기(글, ['발급번호'], { 꼴: /([\w-]{8,})/ })
  const 성명 = 값찾기(글, ['성명'], { 꼴: /^([가-힣](?:\s?[가-힣]){1,4})/ })
