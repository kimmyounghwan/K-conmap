/** 날짜 글 → YYYY-MM-DD (2026.3.5 · 26/3/5 · 2026-03-05) · 연월만 있으면 YYYY-MM */
export function 날읽기(s) {
  const t = String(s || '').trim().replace(/[./년월]/g, '-').replace(/일/g, '').replace(/\s+/g, '').replace(/-+$/, '')
  let m = t.match(/^(\d{2,4})-(\d{1,2})-(\d{1,2})$/)
  if (m) return `${m[1].length === 2 ? '20' + m[1] : m[1]}-${두자(m[2])}-${두자(m[3])}`
  m = t.match(/^(\d{4})-(\d{1,2})$/)
  if (m) return `${m[1]}-${두자(m[2])}`
  m = t.match(/^(\d{4})(\d{2})(\d{2})$/)
  if (m) return `${m[1]}-${m[2]}-${m[3]}`
  return String(s || '').trim()
}
/** 엑셀에서 복사한 표(탭) → 줄 — 칸 차례는 위 «칸» 그대로 · 머리 줄은 건너뜀 */
export function 붙여읽기(종류, text) {
  const 정의 = 칸[종류] || []
  const out = []
  for (const line of String(text || '').split(/\r?\n/)) {
    if (!line.trim()) continue
    const c = line.split('\t').map((x) => x.trim())
    if (정의.some(([, 이름], i) => c[i] && c[i].replace(/\s/g, '') === 이름.replace(/\s/g, ''))) continue   // 머리 줄
    const r = { id: 새번호() }
    정의.forEach(([k, , , 꼴], i) => { const v = c[i] ?? ''; r[k] = 꼴 === 'num' ? (수(v) ? String(수(v)) : '') : 꼴 === 'date' ? 날읽기(v) : v })
    if (종류 === '실적') { r.st = r.e && r.e > 오늘() ? '시공중' : r.e ? '완료' : '시공중'; if (!r.k) r.k = '원도급' }
    if (정의.some(([k]) => String(r[k] || '').trim())) out.push(r)
  }
  return out
}

