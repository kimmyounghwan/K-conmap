/**
 * 🩺 넣은 돈이 «0 하나 더 · 덜» 같아 보이면 알림 — G513 (2026-11-02 소장님 「오늘 올린 거 점검 다시 해줘 … 이용자 입장에서」)
 *   점검에서: 휴업급여에 일당 1,800,000원(0 하나 더)을 넣어도 말없이 최고 금액으로 셈해 «맞는 결과» 처럼 보였음.
 *   셈은 그대로 하고, 칸 아래에 «확인하세요» 한 줄만 띄웁니다(판단기 · 계산기가 같이 씀).
 */
const 숫 = (v) => Number(String(v ?? '').replace(/[^\d]/g, '')) || 0
const 원 = (n) => n.toLocaleString('ko-KR')

/** 일당 — 100만 원 넘거나 3만 원 안 되면 */
export function 일당살핌(v) {
  const n = 숫(v)
  if (!n) return ''
  if (n > 1_000_000) return `일당 ${원(n)}원 — 100만 원이 넘습니다. 0을 하나 더 넣지 않았는지 보세요.`
  if (n < 30_000) return `일당 ${원(n)}원 — 3만 원이 안 됩니다. 0을 빠뜨리지 않았는지 보세요.`
  return ''
}

/** 시급 — 10만 원 넘거나 1,000원 안 되면 */
export function 시급살핌(v) {
  const n = 숫(v)
  if (!n) return ''
  if (n > 100_000) return `시급 ${원(n)}원 — 10만 원이 넘습니다. 일당이면 «일당» 을 고르세요.`
  if (n < 1_000) return `시급 ${원(n)}원 — 1,000원이 안 됩니다. 0을 빠뜨리지 않았는지 보세요.`
  return ''
}
