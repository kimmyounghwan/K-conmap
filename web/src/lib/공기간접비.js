/** 늘어난 기간 — 당초 준공일 다음 날 ~ 변경 준공일 { 일수, 시작, 끝 } · 날이 없거나 거꾸로면 { 일수: 0, 틀림 } */
export function 연장(당초, 변경) {
  const a = 날값(당초), b = 날값(변경)
  if (a == null || b == null) return { 일수: 0, 시작: '', 끝: '', 틀림: '' }
  if (b <= a) return { 일수: 0, 시작: '', 끝: '', 틀림: '변경 준공일이 당초 준공일보다 뒤여야 합니다' }
  return { 일수: Math.round((b - a) / 하루), 시작: 날글(a + 하루), 끝: 날글(b) }
}
/** 계약기간 일수(착공일 ~ 준공일 · 두 날 모두 셈) */
export function 기간일수(착공, 준공) {
  const a = 날값(착공), b = 날값(준공)
  return a == null || b == null || b < a ? 0 : Math.round((b - a) / 하루) + 1
}
/** 달력 개월 — 시작 ~ 끝(두 날 모두)을 달마다 «그 달에 든 날 ÷ 그 달 날 수» 로 더함(소수 둘째 자리 반올림) */
export function 달력개월(시작, 끝) {
  const a = 날값(시작), b = 날값(끝)
  if (a == null || b == null || b < a) return 0
  let 합 = 0, t = a
  while (t <= b) {
    const d = new Date(t), y = d.getUTCFullYear(), m = d.getUTCMonth()
    const 달끝 = Date.UTC(y, m + 1, 0), 달날 = new Date(달끝).getUTCDate()
    const 이달끝 = Math.min(달끝, b)
    합 += (Math.round((이달끝 - t) / 하루) + 1) / 달날
    t = 이달끝 + 하루
  }
  return Math.round(합 * 100) / 100
}

