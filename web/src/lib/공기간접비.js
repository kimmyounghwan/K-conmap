/**
 * 실비 산정
 * @returns {{ 연장, 개월, 사람:[{r, 인원, 월임금, 개월, 자동, 금액}], 간접노무비, 경비:[{r, 단가, 수량, 금액}], 직접경비,
 *   장비:[{r, 금액, 식}], 장비합, 승률:[{r, 율, 기준금액, 금액}], 승률합, 경비합, 일반관리비, 이윤, 공급가액, 부가세, 합계, 알림:[] }}
 */
export function 실비셈(st) {
  const 연 = 연장(st.당초, st.변경)
  const 개월 = 연.일수 ? 달력개월(연.시작, 연.끝) : 0
  const 알림 = []
  if (연.틀림) 알림.push(연.틀림)
  const 사람 = (st.사람 || []).map((r) => {
    const 인원 = Math.max(0, 수(r.인원)), 월임금 = 수(r.월임금)
    const 자동 = String(r.개월 ?? '').trim() === ''
    const 달 = 자동 ? 개월 : Math.max(0, 수(r.개월))
    return { r, 인원, 월임금, 개월: 달, 자동, 금액: 버림(인원 * 월임금 * 달) }
  })
  const 간접노무비 = 사람.reduce((a, x) => a + x.금액, 0)
  const 경비 = (st.경비 || []).map((r) => {
    const 단가 = 수(r.단가), 수량칸 = String(r.수량 ?? '').trim()
    const 수량 = 수량칸 === '' ? 1 : Math.max(0, 수(r.수량))
    return { r, 단가, 수량, 금액: 버림(단가 * 수량) }
  })
  const 직접경비 = 경비.reduce((a, x) => a + x.금액, 0)
  const 장비 = (st.장비 || []).map((r) => {
    if (r.꼴 === '임대') return { r, 금액: 버림(수(r.임대료)), 식: '유휴 기간 중 실제로 부담한 장비임대료' }
    const 가격 = 수(r.가격), 계수 = 계수읽기(r.계수), 연간 = 수(r.연간), 일 = 수(r.유휴일)
    const 금액 = 버림(가격 * 계수 * (연간 / 365) * 일 * 0.5)
    return { r, 금액, 가격, 계수, 연간, 일, 식: `(${원(가격)} × ${계수 ? 계수.toPrecision(4).replace(/\.?0+$/, '') : 0}) × (${원(연간)} ÷ 365) × ${원(일)}일 × 1/2` }
  })
  const 장비합 = 장비.reduce((a, x) => a + x.금액, 0)
  const 승률 = (st.승률 || []).map((r) => {
    const 율 = 수(r.율)
    const 기준금액 = r.기준 === '직접' ? 수(r.기준금액) : 간접노무비
    return { r, 율, 기준금액, 금액: 버림(기준금액 * 율 / 100) }
  })
  const 승률합 = 승률.reduce((a, x) => a + x.금액, 0)
  const 경비합 = 직접경비 + 장비합 + 승률합
  const 일율 = 수(st.일반), 이율 = 수(st.이윤)
  const 일반관리비 = 버림((간접노무비 + 경비합) * 일율 / 100)
  const 이윤 = 버림((간접노무비 + 경비합 + 일반관리비) * 이율 / 100)
  const 공급가액 = 간접노무비 + 경비합 + 일반관리비 + 이윤
  const 부가세 = 버림(공급가액 * 0.1)
  if (st.갈래 !== '지방' && 일율 > 일반관리비한도) 알림.push(`일반관리비율 ${일율}% — 국가계약법 시행규칙 제8조①(공사 ${일반관리비한도}%)보다 높습니다. 산출내역서의 율을 확인하세요.`)
  if (st.갈래 !== '지방' && 이율 > 이윤한도) 알림.push(`이윤율 ${이율}% — 시행규칙 제8조②(공사 ${이윤한도}%)보다 높습니다. 산출내역서의 율을 확인하세요.`)
  if (사람.some((x) => x.인원 > 0 && !x.월임금)) 알림.push('월 임금이 빈 직종이 있습니다(0원으로 셈).')
  if (사람.some((x) => !x.자동 && x.개월 > 개월 + 1e-9 && 개월 > 0)) 알림.push(`투입 개월이 늘어난 기간(${개월}개월)보다 긴 줄이 있습니다.`)
  return { 연장: 연, 개월, 사람, 간접노무비, 경비, 직접경비, 장비, 장비합, 승률, 승률합, 경비합, 일율, 이율, 일반관리비, 이윤, 공급가액, 부가세, 합계: 공급가액 + 부가세, 알림 }
}

