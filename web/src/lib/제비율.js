/* 표(data/jebiyul.json)는 부르는 쪽이 넣습니다(기준넣기) — 시험(node)에서도 같은 셈을 쓰려고(lib 은 json 을 바로 안 부름) */
let D = { 판: [], 규모: [], 기간: [], 일관규모: [], 일관: { 종합: [], 전문: [] }, 이윤: [], 국가유산: { 규모: [], 간노: [], 기타: [], 이윤규모: [], 이윤: [] } }
export function 기준넣기(d) { if (d && Array.isArray(d.판) && d.판.length) D = d }
export const 기준 = () => D
export const 종류들 = [
  { k: '토목', n: '토목', 표: '토목' },
  { k: '조경', n: '조경', 표: '토목' },
  { k: '산업설비(토목)', n: '산업·환경설비(토목 — 수처리시설 등)', 표: '토목' },
  { k: '건축', n: '건축', 표: '건축' },
  { k: '산업설비(건축)', n: '산업·환경설비(건축 — 지열 · 소각시설 등)', 표: '건축' },
  { k: '국가유산', n: '국가유산 수리', 표: '국가유산' },
]
export const 종류이름 = (k) => (종류들.find((x) => x.k === k) || {}).n || k

const 날꼴 = (s) => /^\d{4}-\d{2}-\d{2}$/.test(String(s || ''))
export const 오늘 = () => {
  const t = new Date(Date.now() + 9 * 3600e3)   // 한국 날짜
  return t.toISOString().slice(0, 10)
}

/** 공고일(YYYY-MM-DD) → 그날 맞는 판 · 앞 판 · 알림 */
export function 판고르기(날) {
  const 판 = D.판 || []
  const d = 날꼴(날) ? 날 : 오늘()
  let i = -1
  for (let j = 0; j < 판.length; j++) if (판[j].시작 <= d) i = j
  if (i < 0) return { 판: 판[0], 앞: null, 날: d, 알림: `${판[0].이름}보다 앞선 공고입니다 — 그때 기준은 여기 없습니다(가장 앞 판으로 보여 드림)` }
  /* 앞 판 = 간접노무비 · 기타경비가 다른 가장 가까운 앞 판(3. 13. 판은 1. 1. 판과 같아 건너뜀) */
  let 앞 = null
  for (let j = i - 1; j >= 0; j--) {
    if (JSON.stringify(판[j].간기) !== JSON.stringify(판[i].간기)) { 앞 = 판[j]; break }
  }
  return { 판: 판[i], 앞, 날: d, 알림: '' }
}

/** [이름, 아래(이상), 위(미만 · null=끝없음)] 표에서 값의 자리 */
export function 구간(표, v) {
  const x = Number(v)
  if (!isFinite(x) || x < 0) return -1
  for (let i = 0; i < 표.length; i++) {
    const [, lo, hi] = 표[i]
    if (x >= lo && (hi == null || x < hi)) return i
  }
  return -1
}

/** 공사기간(일) → 4칸 중 자리 (183일 이하 · 365일 이하 · 1095일 이하 · 그 넘음) */
export function 기간자리(일) {
  const n = Math.floor(Number(일))
  if (!isFinite(n) || n < 1) return -1
  return 구간(D.기간, n)
}

/** 착공 · 준공 날(YYYY-MM-DD) → 공사기간 일수(첫날 · 끝날 다 넣음) */
export function 일수(착공, 준공) {
  if (!날꼴(착공) || !날꼴(준공)) return 0
  const a = Date.parse(착공 + 'T00:00:00Z'), b = Date.parse(준공 + 'T00:00:00Z')
  return b >= a ? Math.round((b - a) / 86400000) + 1 : 0
}

const 소수 = (v) => (v == null ? null : Math.round(Number(v) * 1000) / 1000)

/**
 * 요율 찾기
 * @param {object} p { 날: 공고일, 종류: 종류들[].k, 업종: '종합' | '전문', 직접공사비, 추정가격, 공사일수 }
 * @returns {object} { 판, 앞판, 알림, 간노, 기타, 일관, 이윤, 자리: { 규모, 기간, 일관규모 }, 표: { 규모, 기간, 간노, 기타 }, 빠짐: [..] , 앞: { 간노, 기타 } }
 */
export function 찾기(p) {
  const q = p || {}
  const { 판, 앞, 알림 } = 판고르기(q.날)
  const 종 = 종류들.find((x) => x.k === q.종류) || 종류들[0]
  const 빠짐 = []
  const 직 = Number(q.직접공사비) || 0
  const 추 = Number(q.추정가격) || 0
  const 기간 = 기간자리(q.공사일수)
  if (!(직 > 0)) 빠짐.push('직접공사비')
  if (기간 < 0) 빠짐.push('공사기간')
  if (!(추 > 0)) 빠짐.push('추정가격')
  const out = { 판, 앞판: 앞, 알림, 종류: 종.k, 종류이름: 종.n, 업종: q.업종 === '전문' ? '전문' : '종합', 빠짐, 간노: null, 기타: null, 일관: null, 이윤: null, 자리: {}, 표: {}, 앞: {}, 메모: [] }

  if (종.표 === '국가유산') {
    const K = D.국가유산
    const g = 직 > 0 ? 구간(K.규모, 직) : -1
    out.표 = { 규모: K.규모, 기간: D.기간, 간노: K.간노, 기타: K.기타.map((v) => [v, v, v, v]) }
    out.자리 = { 규모: g, 기간: 기간 }
    if (g >= 0 && 기간 >= 0) out.간노 = 소수(K.간노[g][기간])
    if (g >= 0) out.기타 = 소수(K.기타[g])
    if (추 > 0) {
      const k = 구간(K.이윤규모, 추)
      out.자리.일관규모 = k
      out.이윤 = k >= 0 ? 소수(K.이윤[k]) : null
      out.일관 = 추 < 5_000_000_000 ? 소수(K.일관) : null
      if (out.일관 == null) out.메모.push('국가유산 수리 일반관리비는 원문 표에 «50억 미만» 줄에만 6% 가 있습니다 — 50억 이상은 발주처 기준을 따르십시오.')
    }
    out.메모.push('국가유산 수리 — 공사규모 구간이 다릅니다(5천만 · 1억 · 5억). 기타경비는 공사기간에 따라 바뀌지 않습니다(원문에서 규모마다 한 칸).')
    return out
  }

  const 간기 = 판.간기[종.k]
  const g = 직 > 0 ? 구간(D.규모, 직) : -1
  out.표 = { 규모: D.규모, 기간: D.기간, 간노: 간기.간노, 기타: 간기.기타 }
  out.자리 = { 규모: g, 기간: 기간 }
  if (g >= 0 && 기간 >= 0) {
    out.간노 = 소수(간기.간노[g][기간])
    out.기타 = 소수(간기.기타[g][기간])
    if (앞) {
      const a = 앞.간기[종.k]
      out.앞 = { 판: 앞, 간노: 소수(a.간노[g][기간]), 기타: 소수(a.기타[g][기간]) }
    }
  }
  if (추 > 0) {
    const k = 구간(D.일관규모, 추)
    out.자리.일관규모 = k
    if (k >= 0) {
      out.일관 = 소수(D.일관[out.업종][k])
      out.이윤 = 소수(D.이윤[k])
    }
  }
  return out
}

/** 그 판의 법정 요율(같은 원문 표) — 화면에 참고로 */
