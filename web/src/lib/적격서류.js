/** 'YYYY-MM-DD' → { y, m, d } (없는 날짜면 null) */
export function 날짜읽기(s) {
  const t = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(s || '').trim())
  if (!t) return null
  const y = +t[1], m = +t[2], d = +t[3]
  const x = new Date(Date.UTC(y, m - 1, d))
  if (x.getUTCFullYear() !== y || x.getUTCMonth() !== m - 1 || x.getUTCDate() !== d) return null
  if (y < 2000 || y > 2100) return null
  return { y, m, d }
}

/**
 * 실적인정기간 — 입찰공고일 · 작년 실적이 협회에서 확정됐는가
 *   작년확정 = true  → 협회 확정 (Y-3 · Y-2 · Y-1) + Y.1.1 ~ 공고일 (4년 미만)
 *   작년확정 = false → 협회 확정 (Y-4 · Y-3 · Y-2) + (Y-1).1.1 ~ 공고일 (4년 이상)
 */
export function 적격기간(공고일, 작년확정 = true) {
  const g = 날짜읽기(공고일)
  if (!g) return null
  const 마지막 = 작년확정 ? g.y - 1 : g.y - 2
  const 첫해 = 마지막 - 2
  const 끝 = `${g.y}.${g.m}.${g.d}`
  return {
    공고: 끝,
    확정해: [첫해, 첫해 + 1, 첫해 + 2],
    마지막확정: 마지막,
    덧시작: `${마지막 + 1}.1.1`,
    끝,
    전체: `${첫해}.1.1 ~ ${끝}`,
    넷이상: !작년확정,
  }
}

