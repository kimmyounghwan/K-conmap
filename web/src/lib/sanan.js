/** 대상액 하나 → 별표1 비율 · 기초액 · 금액 */
export function 별표1셈(대상액, 종류, 보건 = false) {
  const t = 종류찾기(종류)
  const v = Math.max(0, 수(대상액))
  if (보건) return { 금액: 버림(v * t.h / 100), 율: t.h, 기초: 0, 구간: '보건관리자 선임 대상', t, 대상액: v }
  if (v < 5 * 억) return { 금액: 버림(v * t.a / 100), 율: t.a, 기초: 0, 구간: '5억 원 미만', t, 대상액: v }
  if (v < 50 * 억) return { 금액: 버림(v * t.b / 100) + t.기초, 율: t.b, 기초: t.기초, 구간: '5억 원 이상 50억 원 미만', t, 대상액: v }
  return { 금액: 버림(v * t.c / 100), 율: t.c, 기초: 0, 구간: '50억 원 이상', t, 대상액: v }
}

/** 보건관리자 선임 대상인가 (시행령 별표5 건설업) — 토목공사업 공사는 1천억, 그 밖은 800억 · 상시 600명 이상 */
export function 보건대상(총공사금액, 토목업, 상시600) {
  const 기준 = 토목업 ? 1000 * 억 : 800 * 억
  return { 대상: !!상시600 || 수(총공사금액) >= 기준, 기준, 까닭: 상시600 ? '상시 근로자 600명 이상' : 수(총공사금액) >= 기준 ? `공사금액 ${토목업 ? '1천억' : '800억'} 원 이상` : '' }
}

/**
 * 계상 — 화면 입력 한 벌
 * @param {{종류, 방식:'detail'|'total', 재료, 노무, 총액, 관급, 토목업, 상시600, 보건손}} p
 *   재료 = 직접재료비 + 간접재료비 · 노무 = 직접노무비 · 총액 = 총공사금액 · 관급 = 발주자가 주는 재료비 · 완제품 가액
 *   보건손: '' 자동 · 'y' 대상 · 'n' 아님
 */
export function 계상(p) {
  const 재료 = 수(p.재료), 노무 = 수(p.노무), 총액 = 수(p.총액), 관급 = 수(p.관급)
  const 방식 = p.방식 === 'total' ? 'total' : 'detail'
  const 대상 = 방식 === 'total' ? 버림(총액 * 0.7) : 재료 + 노무
  const 토목업 = p.토목업 ?? (p.종류 === 'civil' || p.종류 === 'heavy')
  const 보 = 보건대상(총액, 토목업, p.상시600)
  const 보건 = p.보건손 === 'y' ? true : p.보건손 === 'n' ? false : 보.대상
  const 기본 = 별표1셈(대상, p.종류, 보건)
  let 결과 = 기본, 관급비교 = null
  if (관급 > 0) {
    const 넣고 = 별표1셈(대상 + 관급, p.종류, 보건)
    const 빼고 = 기본
    const 빼고12 = 버림(빼고.금액 * 1.2)
    const 넣고작다 = 넣고.금액 <= 빼고12
    관급비교 = { 넣고, 빼고, 빼고12, 고른: 넣고작다 ? '넣고' : '빼고12' }
    결과 = 넣고작다 ? 넣고 : { ...빼고, 금액: 빼고12, 구간: 빼고.구간 + ' · × 1.2' }
  }
  const 알림 = []
  if (총액 > 0 && 총액 < 2e7) 알림.push('총공사금액이 2천만 원 미만이면 이 고시가 적용되지 않습니다(제3조).')
  if (방식 === 'total') 알림.push('대상액을 모를 때만 총공사금액의 10분의 7 을 대상액으로 봅니다(제4조제1항제3호) — 원가계산서가 있으면 «재료비 · 직접노무비» 로 넣으십시오.')
  if (보건 && !보.대상) 알림.push('«보건관리자 선임 대상» 으로 직접 고르셨습니다.')
  if (총액 >= 4e7) 알림.push('공사금액 4천만 원 이상 — 실행예산에 산안비를 계상액 이상으로 따로 편성하고 사용내역서를 현장에 갖추어 두어야 합니다(제10조).')
  return {
    방식, 재료, 노무, 총액, 관급, 대상, 보건, 보건까닭: 보.까닭, 보건기준: 보.기준, 토목업,
    율: 결과.율, 기초: 결과.기초, 구간: 결과.구간, 금액: 결과.금액, t: 기본.t, 관급비교, 알림,
    총대비: 총액 > 0 ? 결과.금액 / 총액 : NaN,
  }
}

/** 별표1의3 설계변경 조정 — 변경 전 산안비 × 대상액 증감 비율 (도급계약서상 대상액) */
export function 설계변경(전산안비, 전대상, 후대상) {
  const a = 수(전산안비), b = 수(전대상), c = 수(후대상)
  if (!(a > 0) || !(b > 0) || !(c > 0)) return null      // 변경 후 대상액을 안 적었으면 셈하지 않음
  const 비율 = (c - b) / b
  const 증감 = a * 비율
  const 증감액 = 증감 >= 0 ? 버림(증감) : -버림(-증감)
  return { 비율, 증감액, 후: a + 증감액 }
}

/** 별표3 공사진척(기성 공정률)에 따른 최소 사용 비율 */
export function 사용기준(공정률) {
  const p = 수(공정률)
  if (p >= 90) return { 기준: 90, 글: '공정률 90% 이상 → 90% 이상 사용' }
  if (p >= 70) return { 기준: 70, 글: '공정률 70% 이상 90% 미만 → 70% 이상 사용' }
  if (p >= 50) return { 기준: 50, 글: '공정률 50% 이상 70% 미만 → 50% 이상 사용' }
  return { 기준: 0, 글: '공정률 50% 미만 — 별표3 기준 없음' }
}

