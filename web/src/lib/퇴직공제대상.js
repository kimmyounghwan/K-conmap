/**
 * 당연가입 판단
 *   입력: 종류(건설 · 전문) · 발주(국가 · 출자 · 재출자 · 민투 · 민간) · 금액(공사예정금액 — 장기계속은 연차별 계약이 아니라 «해당 공사의 예정금액»: 건설공사는 국가계약법 제21조 장기계속(건산법 시행령 제83조①1) · 전문 공사는 국가 · 지방계약법 장기계속(시행령 제6조1)) · 건축(건설 · 민간만)
 *   돌려줌: { 대상: true|false|null(금액 없음), 호, 까닭, 근거 }
 */
export function 가입판단(o = {}) {
  const 종 = o.종류 === '전문' ? '전문' : '건설'
  const 발 = 발주들.some((x) => x.k === o.발주) ? o.발주 : '국가'
  const 금액 = Number(o.금액) || 0
  const 법 = 종류들.find((x) => x.k === 종).법
  /* 금액과 관계없는 건축물 — 건설공사만(전문 공사에는 이 호가 없음) */
  if (종 === '건설') {
    const 축 = 건축들.find((x) => x.k === o.건축 && x.k)
    if (축) return { 대상: true, 호: 축.호, 까닭: `${축.이름} — 공사금액과 관계없이 대상`, 근거: `${법}${축.호}` }
  }
  if (!(금액 > 0)) return { 대상: null, 호: '', 까닭: '공사예정금액을 넣으면 판단합니다', 근거: 법 }
  const 공공호 = 종 === '건설'
    ? { 국가: '1', 출자: '2', 재출자: '2의2', 민투: '4' }
    : { 국가: '1', 출자: '2', 재출자: '2', 민투: '3' }
  const 오십호 = 종 === '건설' ? '7' : '4'
  if (발 !== '민간' && 금액 >= 억) {
    const 이름 = 발주들.find((x) => x.k === 발).이름
    return { 대상: true, 호: 공공호[발], 까닭: `${이름} 발주 · 공사예정금액 1억원 이상`, 근거: `${법}${공공호[발]}` }
  }
  if (금액 >= 50 * 억) return { 대상: true, 호: 오십호, 까닭: '공사예정금액 50억원 이상', 근거: `${법}${오십호}` }
  return {
    대상: false, 호: '',
    까닭: 발 === '민간' ? '민간 공사 · 공사예정금액 50억원 미만' : '공사예정금액 1억원 미만',
    근거: 법,
  }
}

/** 성립 신고 기한 — 사업시작일(착공)부터 14일 이내(건설근로자법 제10조의4①) · 첫날은 세지 않음(민법 제157조) */
export function 성립기한(착공) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(String(착공 || ''))) return ''
  const [y, m, d] = 착공.split('-').map(Number)
  const t = new Date(Date.UTC(y, m - 1, d + 14))
  return t.toISOString().slice(0, 10)
}

