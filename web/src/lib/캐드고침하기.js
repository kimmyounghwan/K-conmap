/**
 * 🛠 캐드 고치기 — 한 장 처리 순서 (일꾼 lib/캐드고침.worker.js · 시험 tools/시험_캐드고침.mjs 가 같이 씀) (2026-10-17)
 *
 *   읽기(바이트)  → 풀기 · 짝 · 나누기 · 진단
 *   고치기(바이트, 읽은, 설정)
 *     · 한글: '자동'(깨짐 의심일 때만) | '949'(CP949 로 다시 읽음) | '그대로'
 *     · 방식: '다시'(깨끗하게 다시 쓰기 — 판 바꾸기 · 글꼴) | '그대로'(짝을 하나도 안 버리고 글꼴 · 코드페이지만)
 *     · 판: 'AC1009' ~ 'AC1032' | '' (원래 판 — 다시 쓰기에서 원래 판이 R13 · R14 면 2000 으로)
 */
import * as K from './캐드고침.js'
import { 다시쓰기 } from './캐드다시쓰기.js'
import { 판목록 } from './캐드고침.js'

export function 읽기(bytes) {
  const u = bytes instanceof Uint8Array ? bytes : new Uint8Array(bytes)
  const P = K.풀기(u)
  const 짝 = K.짝들(P.글)
  const D = K.나누기(짝)
  if (!D.구역.length) throw Object.assign(new Error('DXF 구역(SECTION)을 찾지 못했습니다'), { kind: 'notdxf' })
  let 진 = K.진단(P, D)
  let 한글 = null
  if (P.깨짐 && P.깨짐.의심) {
    /* 한글이 깨진 도면 — 글꼴 이름(«제목» 이 «Á¦¸ñ» 로)과 한글 글 세기가 틀어짐 → 글꼴 · 글 안 글꼴 진단은 CP949 로 읽은 것으로.
       (2026-10-17 예시②: Standard(txt · 큰글꼴 없음)에 «축척» 이 있는데 깨진 채로는 한글이 안 보여 «?» 문제를 못 짚었음) */
    한글 = 한글로(u, { P, 진 })
    const 진2 = K.진단(한글.P, 한글.D)
    const 원 = 진.글꼴
    const 글꼴 = 진2.글꼴.map((f, i) => (원[i] && 원[i].키 !== f.키 ? { ...f, 원키: 원[i].키, 원이름: 원[i].이름 } : f))
    const 문제 = [...진.문제.filter((x) => x.고침 === '한글'), ...진2.문제.filter((x) => x.고침 === '글꼴' || x.고침 === '글안'), ...진.문제.filter((x) => !['한글', '글꼴', '글안'].includes(x.고침))]
    진 = { ...진, 글꼴, 글안글꼴: 진2.글안글꼴, 문제 }
  }
  return { P, 짝, D, 진, 한글 }
}

/* 한글을 그대로 둘 때(깨진 채로) — 화면에서 고른 글꼴(한글 이름)을 깨진 이름에 다시 붙임 */
function 깨진이름으로(글꼴, 진) {
  const 더 = { ...글꼴 }
  for (const f of 진.글꼴 || []) if (f.원키 && 글꼴[f.키] !== undefined) 더[f.원키] = 글꼴[f.키]
  return 더
}

/** 한글이 깨진 옛 판(코드페이지가 한글이 아님) — CP949 로 다시 읽음 */
function 한글로(bytes, R) {
  const 글 = new TextDecoder('euc-kr').decode(bytes instanceof Uint8Array ? bytes : new Uint8Array(bytes))
  const P = { ...R.P, 글, 인코딩: 'euc-kr', 코드페이지: 'ANSI_949', 깨짐: { ...R.P.깨짐, 고침: true } }
  const 짝 = K.짝들(글)
  return { P, 짝, D: K.나누기(짝), 진: R.진 }
}

const 판이름 = (v) => (판목록.find((x) => x.판 === v) || {}).이름 || K.판이름[v] || v

/**
 * @returns { 바이트: Uint8Array, 글: string, 판, 판이름, 인코딩, 알림: [{급, 글}], 셈 }
 */
export function 고치기(bytes, R, o = {}) {
  let 읽은 = R
  const 알림 = []
  const 한글 = o.한글 || '자동'
  if (한글 === '949' || (한글 === '자동' && R.P.깨짐 && R.P.깨짐.의심)) {
    읽은 = R.한글 || 한글로(bytes, R)
    알림.push({ 급: '안내', 글: `한글 깨짐 고침 — 글을 CP949(한글)로 다시 읽었습니다(코드페이지 ${R.P.코드페이지 || '없음'} → ANSI_949)` })
  }
  const 글꼴설정 = { 글꼴: 읽은 === R && R.한글 ? 깨진이름으로(o.글꼴 || {}, R.진) : o.글꼴 || {}, 모두: o.모두 || '', 글안: o.글안 || '그대로', 글안이름: o.글안이름, 빈글꼴: o.빈글꼴 !== false }
  if (o.방식 === '그대로') {
    const g = K.그대로고치기(읽은.짝, { ...글꼴설정, 한글: 읽은 !== R ? '949' : '' })
    const 판 = 읽은.P.판
    const 바이트 = K.그대로싸기(g.짝, 판, {})
    if (g.바꾼.글꼴) 알림.push({ 급: '안내', 글: `글꼴 바꿈 ${g.바꾼.글꼴}개` })
    if (g.바꾼.빈글꼴) 알림.push({ 급: '안내', 글: `이름 없는 TTF 글꼴 → 파일 이름 채움 ${g.바꾼.빈글꼴}개` })
    if (g.바꾼.모양이름) 알림.push({ 급: '안내', 글: `모양(SHX shape) 글꼴 기록 이름 비움 ${g.바꾼.모양이름}개 — 이름이 있으면 AutoCAD 가 도면을 못 엶` })
    if (g.바꾼.글안) 알림.push({ 급: '안내', 글: `글 안에 박힌 글꼴 ${g.바꾼.글안}곳 ${글꼴설정.글안 === '지움' ? '지움' : '바꿈'}` })
    return { 바이트, 글: null, 짝: g.짝, 판, 판이름: 판이름(판), 인코딩: 판 >= 'AC1021' ? 'utf-8' : 'euc-kr', 알림, 셈: { 바꿈: g.바꾼 } }
  }
  let 판 = o.판 || 읽은.P.판
  if (!판목록.some((x) => x.판 === 판)) 판 = 판 < 'AC1015' && 판 !== 'AC1009' ? 'AC1015' : 판 < 'AC1015' ? 'AC1009' : 'AC1032'
  const r = 다시쓰기(읽은.P, 읽은.D, { ...글꼴설정, 판 })
  return { 바이트: r.바이트(), 글: r.글, 판, 판이름: 판이름(판), 인코딩: r.인코딩, 알림: [...알림, ...r.알림], 셈: r.셈 }
}

