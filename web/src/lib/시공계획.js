/** 계상액을 항목 몫대로 천 원 단위로 나누되 합이 계상액과 꼭 같게(남는 원은 가장 큰 항목에) */
export function 몫나누기(총, 몫) {
  const 합몫 = 몫.reduce((s, v) => s + (+v || 0), 0) || 1
  const 값 = 몫.map((v) => Math.round(총 * (+v || 0) / 합몫 / 1000) * 1000)
  const 차 = 총 - 값.reduce((s, v) => s + v, 0)
  if (차 && 총 > 0) { let k = 0; 값.forEach((v, i) => { if (v > 값[k]) k = i }); 값[k] += 차 }
  return 값
}

