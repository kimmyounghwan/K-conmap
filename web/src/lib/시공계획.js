    const 합날 = 날들.reduce((s, v) => s + v, 0)
    if (!(합날 > 0)) return
    const 인합 = Object.values(조.인).reduce((s, v) => s + v, 0)
    /* 연인원: 노무비 ÷ 노임 · 노무비가 없으면 금액의 30% 를 노무비로 보고 · 금액도 없으면(공내역서) 작업조 × 가동일 */
    const 연인원 = r.무게만 ? 인합 * 합날 : r.노무비 > 0 ? r.노무비 / 노임 : r.금액 > 0 ? r.금액 * 0.3 / 노임 : 인합 * 합날
    for (const [이름, 몇] of Object.entries(조.인)) {
      const 몫 = 인합 > 0 ? 몇 / 인합 : 0
      날들.forEach((d, k) => 더(인, 이름, k, 연인원 * 몫 * d / 합날))
    }
    const 장비 = { ...조.장 }
    if (r.갈래 === '철거' && 설정.DWS) Object.assign(장비, { '절단기(D.W.S)': 1, '코어드릴': 1, '크레인(50t)': 1 })
