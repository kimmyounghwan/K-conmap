/** 목록 안 자리 — 다른 광고 줄(업체 광고 칸 · 쿠팡 목록 줄) 자리와 «거리» 장 넘게 떨어진 첫 자리(열한째 카드 다음부터 · 첫 화면을 광고로 채우지 않게)
 *  @param n 보이는 카드 수 · @param 다른 다른 광고가 붙는 카드 자리(0부터 · 그 카드 «다음» 에 붙음) · 없으면 -1 */
export function 애드핏목록자리(n, 다른 = [], 첫 = 10, 거리 = 3) {
  for (let p = 첫; p < n - 1; p++) {
    if (다른.every((q) => Math.abs(p - q) >= 거리)) return p
  }
  return -1
}

