/** 입.공종 → { 가설: { 있음, 비계, … }, … } — 빈 것은 없음 */
export function 공종정리(입공종 = {}) {
  const o = {}
  for (const k of 공종차례) {
    const v = 입공종[k]
    const 있 = v === true || (v && typeof v === 'object' && v.있음 !== false && (v.있음 === true || Object.values(v).some(Boolean)))
    o[k] = { 있음: !!있 }
    for (const [s] of 세부목록[k] || []) o[k][s] = !!(있 && v && typeof v === 'object' && v[s])
  }
  return o
}

