/* ══════════════════════════════════════════════════════════════
   인사.js — 👋 처음 오신 분께 «반갑습니다» · 다시 오신 분께 «오전 · 오후 · 저녁» 인사 (2026-09-29 → 09-30 하루 세 번)

   소장님(9/29): 「첫 방문자에게 반갑습니다라는 인사를 하고 재방문자에게는 다시 찾아줘서 고맙다라는 인사 가능해??」
   소장님(9/30): 「핸드폰은 인사가 뜨는데, 데스크탑에서는 안뜨는 거 같아 … 인사말은 오전, 오후, 저녁으로 해줘. 하루 3번....」
     → 데스크탑이 안 뜬 까닭(9/30 10:43 소장님 브라우저에서 확인): 쪽지는 뜹니다. 다만 ① «하루 한 번» 이라
        그날 아침에 이미 한 번 떴고(자동 점검이 같은 브라우저로 사이트를 연 것도 한 번으로 셈), ② 탭을 켜 둔 채로는
        «새 방문» 이 아니라서 다시 안 떴습니다. → 하루를 세 칸(오전 · 오후 · 저녁)으로 나눠 칸마다 한 번,
        탭을 켜 둔 채라도 칸이 바뀐 뒤 화면을 옮기면 뜨게 바꿈.

   ■ 셈은 이 브라우저 안에서만 합니다(localStorage 'kcm_visit') — 서버로 아무것도 보내지 않습니다.
       {n: 방문 횟수, first: 처음 온 때, last: 마지막으로 본 때, day: 마지막으로 인사한 날, slot: 마지막으로 인사한 «날 + 때»}
   ■ «방문» 한 번 = 30분 넘게 쉬었다가 다시 온 것(같은 탭을 계속 보는 동안은 한 번). 탭은 sessionStorage 로 압니다.
   ■ 인사: «처음» 한 번 · 그 뒤로는 때(오전 0~12시 · 오후 12~18시 · 저녁 18~24시)마다 한 번 — 하루 많아야 세 번.
   ■ ⚠️ 이 기능이 생기기 «전» 부터 다녀가신 분은 'kcm_visit' 이 없습니다. 그분들을 «처음» 으로 맞으면 거짓말이라,
       이 사이트가 이 브라우저에 적어 둔 것이 하나라도 있으면(보는 방법 봄 · 앱 띠 닫음 · 지나온 길 …) «다시» 로 봅니다.
       → 그 판단은 화면(인사.jsx)이 «사이트가 뜨기 전» 에 한 번 세 둔 저장 칸 수로 합니다(뜨고 나면 사이트가 스스로 적으므로).
   시험: node tools/시험_인사.mjs
   ══════════════════════════════════════════════════════════════ */
export const 열쇠 = 'kcm_visit'
export const 탭열쇠 = 'kcm_visit_s'
export const 쉼 = 30 * 60 * 1000            // 30분 넘게 쉬면 새 방문

const 두 = (n) => String(n).padStart(2, '0')
export const 날 = (ms) => { const d = new Date(ms); return `${d.getFullYear()}-${두(d.getMonth() + 1)}-${두(d.getDate())}` }
/** 하루 세 칸 — 오전(0~12시) · 오후(12~18시) · 저녁(18~24시). 시각은 그 브라우저의 시각 */
export const 때 = (ms) => { const h = new Date(ms).getHours(); return h < 12 ? '오전' : h < 18 ? '오후' : '저녁' }
export const 때칸 = (ms) => `${날(ms)} ${때(ms)}`

/**
 * 방문 한 번을 셉니다(사이트를 처음 띄울 때).
 *   옛      저장돼 있던 것(없으면 null)
 *   지금    ms
 *   탭중    이 탭이 이미 이 사이트를 보고 있었나(sessionStorage)
 *   전에옴  'kcm_visit' 은 없지만 이 사이트가 적어 둔 것이 있었나(이 기능 전부터 다녀가신 분)
 * 돌려주는 것: { 새: 저장할 것, 인사: '처음' | '다시' | null }
 */
export function 방문(옛, 지금, { 탭중 = false, 전에옴 = false } = {}) {
  const 오늘 = 날(지금)
  const 칸 = 때칸(지금)
  if (!옛 || !(옛.n >= 1)) {
    if (전에옴) return { 새: { n: 2, first: null, last: 지금, day: 오늘, slot: 칸 }, 인사: '다시' }
    return { 새: { n: 1, first: 지금, last: 지금, day: 오늘, slot: 칸 }, 인사: '처음' }
  }
  const 새방문 = !탭중 && (지금 - (Number(옛.last) || 0) >= 쉼)
  const 인사 = 옛.slot !== 칸 ? '다시' : null        // 옛 저장(하루 한 번 때)에는 slot 이 없어 한 번은 인사합니다
  return {
    새: { ...옛, n: 옛.n + (새방문 ? 1 : 0), last: 지금, day: 인사 ? 오늘 : 옛.day, slot: 인사 ? 칸 : 옛.slot },
    인사,
  }
}

/**
 * 화면을 옮길 때 — 탭을 켜 둔 채 때가 바뀌었으면(오전 → 오후) 한 번 인사합니다. 방문 수는 세지 않습니다.
 */
export function 옮김(옛, 지금) {
  if (!옛 || !(옛.n >= 1)) return { 새: 옛, 인사: null }
  const 칸 = 때칸(지금)
  const 인사 = 옛.slot && 옛.slot !== 칸 ? '다시' : null
  return { 새: { ...옛, last: 지금, day: 인사 ? 날(지금) : 옛.day, slot: 인사 ? 칸 : 옛.slot }, 인사 }
}

/** 검색 로봇·자동 브라우저에는 인사하지 않습니다 — 인사 글이 페이지 글로 읽히지 않게 */
export const 로봇 = (ua = '') => /bot|crawl|spider|slurp|headless|lighthouse|preview|facebookexternalhit|kakaotalk-scrap|yeti|daum/i.test(ua)

const 때글 = {
  오전: { 큰: '☀️ 좋은 아침입니다!', 작은: '다시 찾아 주셔서 고맙습니다 — 오늘도 안전한 현장 되십시오.' },
  오후: { 큰: '🌤️ 좋은 오후입니다!', 작은: '다시 찾아 주셔서 고맙습니다 — 남은 하루도 힘내십시오.' },
  저녁: { 큰: '🌙 편안한 저녁입니다!', 작은: '다시 찾아 주셔서 고맙습니다 — 오늘 하루 수고 많으셨습니다.' },
}
/** 띄울 글 — 처음은 늘 같고, 다시는 때마다 다릅니다 */
export function 인사글(종류, ms) {
  if (종류 === '처음') return { 큰: '👋 반갑습니다!', 작은: 'K-건설맵에 처음 오셨네요 — 회원가입 없이 바로 쓰실 수 있습니다.' }
  return 때글[때(ms)]
}
