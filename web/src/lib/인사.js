/* ══════════════════════════════════════════════════════════════
   인사.js — 👋 처음 오신 분께 «반갑습니다» · 🙏 다시 오신 분께 «다시 찾아 주셔서 고맙습니다» (2026-09-29)

   소장님: 「사이트 방문자들에게 인사를 할 수 있어. 첫 방문자에게 반갑습니다라는 인사를 하고
            재방문자에게는 다시 찾아줘서 고맙다라는 인사 가능해??」

   ■ 셈은 이 브라우저 안에서만 합니다(localStorage 'kcm_visit') — 서버로 아무것도 보내지 않습니다.
       {n: 방문 횟수, first: 처음 온 때, last: 마지막으로 본 때, day: 마지막으로 인사한 날}
   ■ «방문» 한 번 = 30분 넘게 쉬었다가 다시 온 것(같은 탭을 계속 보는 동안은 한 번). 탭은 sessionStorage 로 압니다.
   ■ 인사는 «처음» 한 번 · 그 뒤로는 «다시 오신 날» 하루에 한 번만 — 하루에 여러 번 드나드는 분께 매번 조르지 않게.
   ■ ⚠️ 이 기능이 생기기 «전» 부터 다녀가신 분은 'kcm_visit' 이 없습니다. 그분들을 «처음» 으로 맞으면 거짓말이라,
       이 사이트가 이 브라우저에 적어 둔 것이 하나라도 있으면(보는 방법 봄 · 앱 띠 닫음 · 지나온 길 …) «다시» 로 봅니다.
       → 그 판단은 화면(인사.jsx)이 «사이트가 뜨기 전» 에 한 번 세 둔 저장 칸 수로 합니다(뜨고 나면 사이트가 스스로 적으므로).
   시험: node tools/시험_인사.mjs
   ══════════════════════════════════════════════════════════════ */
export const 열쇠 = 'kcm_visit'
export const 탭열쇠 = 'kcm_visit_s'
export const 쉼 = 30 * 60 * 1000            // 30분 넘게 쉬면 새 방문

const 두 = (n) => String(n).padStart(2, '0')
export const 날 = (ms) => { const d = new Date(ms); return `${d.getFullYear()}-${두(d.getMonth() + 1)}-${두(d.getDate())}` }

/**
 * 방문 한 번을 셉니다.
 *   옛      저장돼 있던 것(없으면 null)
 *   지금    ms
 *   탭중    이 탭이 이미 이 사이트를 보고 있었나(sessionStorage)
 *   전에옴  'kcm_visit' 은 없지만 이 사이트가 적어 둔 것이 있었나(이 기능 전부터 다녀가신 분)
 * 돌려주는 것: { 새: 저장할 것, 인사: '처음' | '다시' | null }
 */
export function 방문(옛, 지금, { 탭중 = false, 전에옴 = false } = {}) {
  const 오늘 = 날(지금)
  if (!옛 || !(옛.n >= 1)) {
    if (전에옴) return { 새: { n: 2, first: null, last: 지금, day: 오늘 }, 인사: '다시' }
    return { 새: { n: 1, first: 지금, last: 지금, day: 오늘 }, 인사: '처음' }
  }
  const 새방문 = !탭중 && (지금 - (Number(옛.last) || 0) >= 쉼)
  const 인사 = 새방문 && 옛.day !== 오늘 ? '다시' : null
  return { 새: { ...옛, n: 옛.n + (새방문 ? 1 : 0), last: 지금, day: 인사 ? 오늘 : 옛.day }, 인사 }
}

/** 검색 로봇·자동 브라우저에는 인사하지 않습니다 — 인사 글이 페이지 글로 읽히지 않게 */
