/** 한국 날짜 «YYYY-MM-DD» */
export const 한국날 = (t = Date.now()) => new Date(t + 9 * 3600e3).toISOString().slice(0, 10)

/** 지금 이 자리에 나올 수 있는 광고들 — 기간 안 · «심의필요» 인데 심의 글이 없는 것은 뺌 */
export function 자리후보(자리, 오늘 = 한국날(), 목록 = 광고들) {
  return 목록.filter((a) => (a.자리 || []).includes(자리)
    && (!a.부터 || a.부터 <= 오늘) && (!a.까지 || 오늘 <= a.까지)
    && !(a.심의필요 && !String(a.심의 || '').trim()))
}

/** 이 자리에 한 장 — 이 자리에 고정(고정: true · 고정자리)이 있으면 늘 그것 · 아니면 여럿 중 고르게(고르기 = 0 이상 1 미만) */
export function 자리광고(자리, 오늘 = 한국날(), 고르기 = Math.random, 목록 = 광고들) {
  const 후보 = 자리후보(자리, 오늘, 목록)
  if (!후보.length) return null
  const 고정 = 후보.find((a) => a.고정 === true || (a.고정자리 || []).includes(자리))
  if (고정) return 고정
  return 후보[Math.min(후보.length - 1, Math.floor(고르기() * 후보.length))]
}

