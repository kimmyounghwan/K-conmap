/* ── 숫자 읽기 — 원(정수) · 백분율(소수 넷째 자리까지 → × 10,000 정수) ── */
export function 원읽기(v) {
  const s = String(v ?? '').replace(/[,\s원]/g, '')
  if (!/^\d+(\.\d+)?$/.test(s)) return null
  return BigInt(s.split('.')[0])
}
export function 백읽기(v) {
  const s = String(v ?? '').replace(/[,\s%]/g, '')
  if (!/^\d+(\.\d+)?$/.test(s) && !/^\.\d+$/.test(s)) return null
  const [정, 소 = ''] = s.split('.')
  return BigInt(정 || '0') * 10000n + BigInt((소 + '0000').slice(0, 4))   /* 넷째 자리 아래는 버림(입력은 보통 둘째 자리) */
}
