/** 입찰가격 — 평점(만분) · 반올림한 비율(만분율 정수 q: 88.75% → 8875) */
export function 입찰가격점(b, 입찰, 예정, A) {
  const 입 = 원읽기(입찰), 예 = 원읽기(예정), a = 원읽기(A) ?? 0n
  if (입 == null || 예 == null || 예 <= a || 입 <= a) return null
  const n = 입 - a, d = 예 - a
  const q = (2n * n * 10000n + d) / (2n * d)       /* 소수점 다섯째 자리에서 반올림 → 1만분율 */
  const 넘음 = 입 > 예
  let 점
  if (!넘음 && n * 10000n >= d * BigInt(b.고정선)) 점 = b.고정점 * 만      /* 다. 91.25 · 90.25 이상(예정가격 − A 이하) */
  else {
    const 차 = q > 9000n ? q - 9000n : 9000n - q
    점 = b.가격 * 만 - b.k * Number(차) * 100
  }
  점 = Math.max(2 * 만, 점)                                        /* 라. 최저평점 2점 */
  return { 점, q: Number(q), 넘음, 날비율: Number((n * 1000000n) / d) / 10000 }
}

/** 이 수행능력으로 95점을 넘는 가장 낮은 입찰가격(원) — 없으면 null */
export function 최저입찰(b, 수행점, 예정, A, 감점 = 0) {
  const 예 = 원읽기(예정), a = 원읽기(A) ?? 0n
  if (예 == null || 예 <= a) return null
  const 필요 = 통과점수 * 만 - 수행점 + 감점     /* 입찰가격 점수가 이만큼(만분) */
  if (필요 > b.가격 * 만) return null
  if (필요 <= 2 * 만) return { 원: a + 1n, q: 0 }
  /* 점 = 가격만 − k × |9000 − q| × 100 ≥ 필요 → q ≥ 9000 − (가격만 − 필요) / (k × 100) */
  const 여유 = Math.floor((b.가격 * 만 - 필요) / (b.k * 100))
  const q = 9000 - 여유
  const d = 예 - a
  /* 날 비율이 (q − 0.5)/10000 이상이면 반올림해 q → n ≥ d × (2q − 1) / 20000 (올림) */
  const 분자 = d * BigInt(2 * q - 1)
  const n = (분자 + 19999n) / 20000n
  return { 원: a + n, q }
}

/** 한 번에 — 화면이 쓰는 것 */
export function 셈(입력) {
  const b = 구간(입력.추정)
  if (!b || b.밖) return { b }
  const 시 = 시공경험(b, 입력)
  const 경 = 경영상태(b, 입력)
  const 종합 = 입력.종류 !== '전문'
  /* 가점 — 특별신인도(+1 · 배점한도 안) · 접근성 */
  let 특 = 0
  const 사 = 사고표[입력.사고] || 0
  if (b.별표 === 4) 특 = 사
  else 특 = Math.min(만, (입력.특신 ? 만 : 0) + 사)
  let 접 = 0
  const 접근대상 = b.별표 === 7 || b.별표 === 6 || (b.별표 === 5 && 원읽기(입력.추정) < 500000000n)
  if (입력.접근 && 접근대상) 접 = b.별표 === 6 && 종합 ? 2000 : 만
  const 다됨 = 시.점 != null && 경.점 != null
  const 바탕 = (시.점 || 0) + (경.점 || 0)
  const 수행 = Math.min(b.수행, 바탕 + 특 + 접)
  const 가 = 입찰가격점(b, 입력.입찰, 입력.예정, 입력.A)
  const 감 = Math.round(Math.max(0, Math.min(15, Number(String(입력.감점 || '0').replace(/[^0-9.]/g, '')) || 0)) * 만)
  const 합 = 다됨 && 가 ? 수행 + 가.점 - 감 : null
  const 최저 = 다됨 ? 최저입찰(b, 수행, 입력.예정, 입력.A, 감) : null
  return {
    b, 시, 경, 특, 접, 접근대상, 수행, 수행만점: b.수행, 바탕, 가, 감, 합, 다됨,
    통과: 합 != null ? 합 >= 통과점수 * 만 : null,
    차: 합 != null ? 합 - 통과점수 * 만 : null,
    최저,
    못닿음: 다됨 ? 수행 + b.가격 * 만 - 감 < 통과점수 * 만 : null,   /* 입찰가격이 만점이어도 95점이 안 됨 */
  }
}
