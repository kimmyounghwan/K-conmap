/** 한국 오늘의 달(1~12) */
export const 이번월 = (오늘 = 한국오늘()) => Number(String(오늘).slice(5, 7))

/** 열두 달 — [{ 월, 항목: [{ k, 짧게, 무엇, 시행, 다음, 주소 }] }] */
export function 달력() {
  const 줄 = (x) => ({ k: x.k, 짧게: 달표[x.k].짧게, 무엇: x.무엇, 시행: 달표[x.k].시행, 다음: x.다음, 주소: x.주소 })
  return Array.from({ length: 12 }, (_, i) => ({ 월: i + 1, 항목: 점검표.filter((x) => 달표[x.k] && 달표[x.k].달.includes(i + 1)).map(줄) }))
}
/** 이번 달 볼 것 — 그 달이 «바뀌는 달» 인 것 + 이미 «다음 확인» 이 지난 것(밀린 것) */
export function 이번달볼것(오늘 = 한국오늘()) {
  const 월 = 이번월(오늘)
  const 볼 = 점검표.filter((x) => (달표[x.k] && 달표[x.k].달.includes(월)) || x.다음 <= 오늘)
  return 볼.map((x) => ({ k: x.k, 짧게: (달표[x.k] || {}).짧게 || x.무엇, 무엇: x.무엇, 다음: x.다음, 밀림: x.다음 <= 오늘, 주소: x.주소, 근거: x.근거 }))
}
/** 다음에 볼 달 — 이번 달 뒤로 «바뀌는 달» 이 처음 오는 달(이번 달은 빼고 · 열두 달을 돌아 찾음) → { 월, 항목 } | null */
export function 다음볼달(오늘 = 한국오늘()) {
  const 월 = 이번월(오늘), 열두 = 달력()
  for (let i = 1; i <= 12; i++) { const m = 열두[(월 - 1 + i) % 12]; if (m.항목.length) return m }
  return null
}
