/** 지연손해금 — 원금 × 율 × 날 수 ÷ 365. 날 수 = 지급기일 다음 날부터 계산일까지(둘 다 넣어 셈). 원 미만 버림 */
export function 지연손해금({ 원금 = 0, 지급기일 = '', 계산일 = '', 율 = 0 } = {}) {
  const 날 = 날차(지급기일, 계산일)
  const p = +원금 || 0, r = +율 || 0
  if (날 == null || 날 <= 0 || !(p > 0) || !(r > 0)) return { 날: 날 != null && 날 > 0 ? 날 : 0, 금액: 0 }
  return { 날, 금액: Math.floor(p * r / 100 * 날 / 365) }
}

