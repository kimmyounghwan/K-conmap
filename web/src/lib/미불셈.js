const 숫 = ['', '일', '이', '삼', '사', '오', '육', '칠', '팔', '구']
const 작은 = ['', '십', '백', '천']
const 큰 = ['', '만', '억', '조']
/** 50,000,000 → 「오천만」 */
export function 한글금액(n) {
  let v = Math.floor(+n || 0)
  if (!(v > 0)) return '영'
  let out = '', i = 0
  while (v > 0) {
    const 네 = v % 10000
    if (네) {
      let s = ''
      String(네).padStart(4, '0').split('').forEach((c, j) => { const d = +c; if (d) s += 숫[d] + 작은[3 - j] })
      out = s + 큰[i] + out
    }
    v = Math.floor(v / 10000); i++
  }
  return out
}
