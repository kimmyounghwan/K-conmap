/* ── 조사 — 받침이 있으면 은·과·이·을·으로 ────────────────────── */
function 받침(w) {
  const c = String(w || '').trim().slice(-1)
  const n = c.charCodeAt(0)
  if (n >= 0xac00 && n <= 0xd7a3) return (n - 0xac00) % 28 !== 0
  return /[013678]$/.test(c)   // 숫자: 일·삼·육·칠·팔·영(0)·십 …
}
