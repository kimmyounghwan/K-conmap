/** N달 뒤 같은 날(없는 날이면 그달 말일) */
export function 월더하기(s, n) {
  const t = 날읽기(s); if (t == null) return ''
  const d = new Date(t)
  const y0 = d.getUTCFullYear(), m0 = d.getUTCMonth() + n
  const y = y0 + Math.floor(m0 / 12), m = ((m0 % 12) + 12) % 12
  const 끝 = new Date(Date.UTC(y, m + 1, 0)).getUTCDate()
  const x = new Date(Date.UTC(y, m, Math.min(d.getUTCDate(), 끝)))
  return `${x.getUTCFullYear()}-${String(x.getUTCMonth() + 1).padStart(2, '0')}-${String(x.getUTCDate()).padStart(2, '0')}`
}

