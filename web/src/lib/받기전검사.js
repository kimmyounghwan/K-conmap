/**
 * 📋 받기 전 검사 — 적산 엑셀을 받기 전에 한 번 더 셈해 보고 받음 (G442 · 2026-10-28)
 *   소장님 2026-10-25: 「엑셀로 다운받을 때는 시험을 한 번 더 … 도면 물량이 나와서 바로 다운 받는 게 아니라
 *   한 번 더 시험을 거치고 다운받게」 · 「못 통과하면 … 알려주고 받게 해야지」 · 엑셀 안은 수식 없이 숫자만
 *   (화면에는 그 말을 적지 않음 — 「이건 기재하지마」).
 *
 * 차례: 시트들 → writeWorkbook → 값만으로(수식 칸을 셈판 값으로) → 그 파일을 다시 읽어서 검사
 *   ① 셈 오류 칸 0 ② 이상한 값(#DIV/0! · NaN · ∞) 0 ③ 시트마다 «합계» 줄 = 그 위 줄들의 합
 *   ④ 맞댈 값(화면 · 3D 합) = 엑셀 값 — 부르는 쪽이 [{이름, 시트, 줄, 열, 값, 오차}] 로 줌
 *     줄 = 첫 칸 글(«합계» · 노선 이름 …) · 열 = 1행 머리 글(«콘크리트(㎥)» …) · 시트 = 이름 또는 /정규식/
 * 통과하면 맨 앞에 «검사 결과» 시트를 붙여 숫자만 담긴 파일을 돌려줌 · 못 통과해도 파일은 만들어 둠(«알고 받기»).
 */
import { writeWorkbook } from './qtoxlsx.js'
import { 값만으로 } from './엑셀쓰기.js'
import { 엑셀읽기, 주소풀기, 칸이름 } from './엑셀읽기.js'

const 수 = (x) => {
  if (!x) return null
  const v = x.v
  if (typeof v === 'number') return Number.isFinite(v) ? v : null
  if (x.t === 'n' || x.t == null) { const n = Number(v); return v !== '' && v != null && Number.isFinite(n) ? n : null }
  return null
}
const 글 = (x) => (x && x.v != null ? String(x.v) : '')
const 쉼 = (v, d = 2) => Number(v).toLocaleString('ko-KR', { maximumFractionDigits: d, minimumFractionDigits: d })

/** 읽은 시트 → { 이름, 칸(Map), 끝행, 끝열, 머리: {글 → 열번호}, 줄찾기(첫칸글) → 행번호[] } */
function 시트판(s) {
  let 끝행 = 0, 끝열 = 0
  for (const ref of s.칸.keys()) { const p = 주소풀기(ref); if (p) { if (p.r > 끝행) 끝행 = p.r; if (p.c > 끝열) 끝열 = p.c } }
  const 머리 = new Map()
  for (let c = 1; c <= 끝열; c++) { const t = 글(s.칸.get(칸이름(1, c))).trim(); if (t && !머리.has(t)) 머리.set(t, c) }
  const 값 = (r, c) => s.칸.get(칸이름(r, c))
  return { 이름: s.이름, 칸: s.칸, 끝행, 끝열, 머리, 값 }
}

/**
 * @param sheets writeWorkbook 시트들(수식 칸 {f} 그대로 둬도 됨)
 * @param 맞댈 [{ 이름, 시트: '이름' | RegExp, 줄: '첫 칸 글', 열: '머리 글', 값: 화면 값, 오차: 0.01, 단위: '㎥', 자리: 2, 줄합: 첫 칸이 «줄» 인 줄을 모두 더함 }]
 * @param 옵 { 합계말: ['합계'], 합계안봄: /시트 이름/ — 합계를 안 볼 시트(도면에서 읽은 표) }
 * @returns { 통과, 줄: [{ 됨, 글 }], 바이트(검사 결과 시트 붙인 파일) }
 */
export function 받기전검사(sheets, 맞댈 = [], 옵 = {}) {
  try { return 검사본(sheets, 맞댈, 옵) } catch (e) {
    /* 📋 G444 검사가 멈춰도 받을 길은 남김 — 왜 멈췄는지 알리고 «알고 받기» 는 검사 없이 만든 파일 */
    let 바이트 = null
    try { 바이트 = writeWorkbook(sheets) } catch (e2) { /* 파일도 못 만듦 */ }
    return { 통과: false, 줄: [{ 됨: false, 글: '받기 전 검사를 하다 멈췄습니다 — ' + String((e && e.message) || e).slice(0, 160) + (바이트 ? ' · «알고 받기» 를 누르면 검사 없이 만든 파일을 받습니다' : ' · 파일도 만들지 못했습니다') }], 바이트 }
  }
}
function 검사본(sheets, 맞댈, 옵) {
  const 합계말 = 옵.합계말 || ['합계']
  const 원 = writeWorkbook(sheets)
  const 값판 = 값만으로(원)
  const 책 = 엑셀읽기(값판.바이트)
  const 판들 = 책.시트들.map(시트판)
  const 줄 = []
  /* ① 셈 오류 */
  줄.push({ 됨: 값판.오류 === 0, 글: 값판.오류 === 0 ? `셈 칸 ${값판.바꾼.toLocaleString('ko-KR')}곳을 다시 셈 — 셈 오류 0` : `셈 오류 칸 ${값판.오류}곳(셈하지 못함)` })
  /* ② 이상한 값 */
  const 이상 = []
  for (const 판 of 판들) for (const [ref, x] of 판.칸) { const t = 글(x); if (/^#(DIV\/0!|REF!|VALUE!|NAME\?|NUM!|N\/A|NULL!)/.test(t) || /^(NaN|-?Infinity)$/.test(t)) 이상.push(판.이름 + '!' + ref + ' «' + t + '»') }
  줄.push({ 됨: !이상.length, 글: 이상.length ? `이상한 값 ${이상.length}칸 — ${이상.slice(0, 4).join(' · ')}${이상.length > 4 ? ' …' : ''}` : '이상한 값(#DIV/0! · NaN · ∞) 0칸' })
  /* ③ 합계 줄 = 위 줄들의 합(시트마다 · 수가 든 열만) */
  let 합본 = 0
  const 합틀 = []
  for (const 판 of 판들) {
    if (옵.합계안봄 && 옵.합계안봄.test(판.이름)) continue        // 📋 G444 도면에서 읽은 표(«표 …»)의 합계는 도면 것 — 우리 셈이 아님
    for (let r = 2; r <= 판.끝행; r++) {
      if (!합계말.includes(글(판.값(r, 1)).trim())) continue
      for (let c = 2; c <= 판.끝열; c++) {
        const t = 수(판.값(r, c)); if (t === null) continue
        let s = 0, n = 0
        for (let rr = 2; rr < r; rr++) { const v = 수(판.값(rr, c)); if (v !== null) { s += v; n++ } }
        if (!n) continue
        합본++
        const 오 = Math.max(0.011 + n * 0.00005, Math.abs(t) * 1e-6)     // 줄마다 넷째 자리 반올림 몫까지
        if (Math.abs(s - t) > 오) 합틀.push(`${판.이름} ${칸이름(1, c).replace(/\d+$/, '')}열(${글(판.값(1, c)) || '—'}) 합계 ${쉼(t, 3)} ≠ 위 줄 합 ${쉼(s, 3)}`)
      }
    }
  }
  if (합본) 줄.push({ 됨: !합틀.length, 글: 합틀.length ? `합계가 위 줄 합과 다름 ${합틀.length}곳 — ${합틀.slice(0, 3).join(' · ')}${합틀.length > 3 ? ' …' : ''}` : `시트마다 «합계» = 위 줄들의 합(${합본}칸)` })
  /* ④ 맞댈 값 = 엑셀 값 */
  for (const m of 맞댈) {
    const 판 = 판들.find((p) => (m.시트 instanceof RegExp ? m.시트.test(p.이름) : p.이름 === m.시트))
    if (m.여럿) {
      /* 📋 G444 시트 줄 여럿 = 셈 결과(줄마다 앞 칸들 [항목, 규격, 단위] · [번호]) — 한 줄로 · 다른 것만 적음 */
      if (!판) { 줄.push({ 됨: false, 글: `${m.이름} — 시트 «${m.시트 instanceof RegExp ? m.시트.source : m.시트}» 가 엑셀에 없음` }); continue }
      const c = 판.머리.get(m.열)
      const 칸수 = Math.max(1, ...m.여럿.map((x) => x.줄.length))
      const 열쇠 = (a) => a.map((v) => String(v ?? '').trim()).join('\u0001')
      const 자리표 = new Map()
      for (let rr = 2; rr <= 판.끝행; rr++) { const k = 열쇠(Array.from({ length: 칸수 }, (_, j) => 글(판.값(rr, j + 1)))); if (!자리표.has(k)) 자리표.set(k, rr) }
      const 틀 = [], 못 = []
      for (const x of m.여럿) {
        const 키 = [...x.줄, ...Array(칸수 - x.줄.length).fill('')]
        const r = 자리표.get(열쇠(키)) || 0
        const 이름 = x.줄.filter((z) => z !== '' && z != null).join(' ')
        const 엑 = r && c ? 수(판.값(r, c)) : null
        if (엑 === null) { 못.push(이름); continue }
        if (Math.abs(엑 - x.값) > (x.오차 ?? m.오차 ?? 0.011)) 틀.push(`${이름} 엑셀 ${쉼(엑, 3)} ≠ 화면 ${쉼(x.값, 3)}`)
      }
      줄.push({ 됨: !틀.length && !못.length, 글: 틀.length || 못.length ? `${m.이름} — 다름 ${틀.length} · 못 찾음 ${못.length}: ${[...틀, ...못.map((z) => z + ' 줄 없음')].slice(0, 4).join(' · ')}${틀.length + 못.length > 4 ? ' …' : ''}` : `${m.이름} — ${m.여럿.length.toLocaleString('ko-KR')}줄 모두 화면 셈과 같음` })
      continue
    }
    const 자리 = m.자리 ?? 2, 단위 = m.단위 || ''
    if (!판) { 줄.push({ 됨: false, 글: `${m.이름} — 시트 «${m.시트}» 가 엑셀에 없음` }); continue }
    const c = 판.머리.get(m.열)
    let 엑 = null
    if (m.줄합) {
      /* 첫 칸이 m.줄 인 줄을 모두 더함(구조물 부분별 → 그 구조물 합) */
      let s = 0, n = 0
      for (let rr = 2; rr <= 판.끝행; rr++) if (글(판.값(rr, 1)).trim() === m.줄) { const v = c ? 수(판.값(rr, c)) : null; if (v !== null) { s += v; n++ } }
      엑 = n ? s : null
    } else {
      let r = 0
      for (let rr = 2; rr <= 판.끝행; rr++) if (글(판.값(rr, 1)).trim() === m.줄 || 글(판.값(rr, 2)).trim() === m.줄) { r = rr; if (글(판.값(rr, 1)).trim() === m.줄) break }
      엑 = r && c ? 수(판.값(r, c)) : null
    }
    if (엑 === null) { 줄.push({ 됨: false, 글: `${m.이름} — 엑셀 «${판.이름}» 에서 «${m.줄}» 줄 · «${m.열}» 칸을 못 찾음` }); continue }
    const 오차 = m.오차 ?? 0.011
    const 됨 = Math.abs(엑 - m.값) <= 오차
    줄.push({ 됨, 글: `${m.이름} — 엑셀 ${쉼(엑, 자리)} ${단위}${됨 ? ' = ' : ' ≠ '}화면 ${쉼(m.값, 자리)} ${단위}` })
  }
  const 통과 = 줄.every((x) => x.됨)
  /* «검사 결과» 시트를 맨 앞에 붙여 다시 — 숫자만 */
  const 결과시트 = { name: '검사 결과', head: ['', '검사', '결과'], rows: [...줄.map((x, i) => [i + 1, x.글, x.됨 ? '통과' : '못 통과']), ['', 통과 ? '모두 통과' : `못 통과 ${줄.filter((x) => !x.됨).length}가지 — 알고 받음`, '']], widths: [5, 110, 10] }
  const 끝 = 값만으로(writeWorkbook([결과시트, ...sheets]))
  return { 통과, 줄, 바이트: 끝.바이트 }
}

/* ── 맞댈 값 만들기 — 화면(셈 결과)과 엑셀 칸 ── */
/** 🏢 골조(모델셈 S) — «부재별» 합계 = 화면 합 · «집계» 콘크리트 · 거푸집 · 철근 줄 합 = 화면 합 */
export function 골조맞댈(S) {
  if (!S || !S.합) return []
  const n = (S.부재별 && S.부재별.size) || 0
  const 오 = 0.011 + n * 0.00005           // 줄마다 넷째 자리에서 반올림한 몫
  const 합 = S.합
  return [
    { 이름: '🏢 골조 콘크리트(부재별 합계)', 시트: '부재별', 줄: '합계', 열: '콘크리트(㎥)', 값: 합.콘크리트, 단위: '㎥', 자리: 3, 오차: 오 },
    { 이름: '🏢 골조 거푸집(부재별 합계)', 시트: '부재별', 줄: '합계', 열: '거푸집(㎡)', 값: 합.거푸집, 단위: '㎡', 자리: 2, 오차: 오 * 10 },
    { 이름: '🏢 골조 철근(부재별 합계)', 시트: '부재별', 줄: '합계', 열: '철근(ton)', 값: 합.철근 / 1000, 단위: 't', 자리: 4, 오차: 0.0006 + n * 0.00005 },
    { 이름: '🏢 골조 콘크리트(집계 — 버림 포함)', 시트: '집계', 줄: '콘크리트', 열: '산출수량', 값: 합.콘크리트 + (합.버림 || 0), 단위: '㎥', 자리: 3, 줄합: true },
    { 이름: '🏢 골조 거푸집(집계)', 시트: '집계', 줄: '거푸집', 열: '산출수량', 값: 합.거푸집, 단위: '㎡', 자리: 2, 줄합: true },
    { 이름: '🏢 골조 철근(집계)', 시트: '집계', 줄: '철근', 열: '산출수량', 값: 합.철근 / 1000, 단위: 't', 자리: 4, 줄합: true, 오차: 0.0006 },
  ]
}
/** 🛣 토목(토목모델 결과 · 함께합) — 집계 합계 = 화면 «물량 합» · 노선마다 평균단면 합계 = 집계 · 구조물 부분별 합 = 집계 */
export function 토목맞댈(토, 함께, 옵 = {}) {
  if (!토 || !함께 || !함께.토목) return []
  const 건 = 함께.건물 || { 콘크리트: 0, 거푸집: 0 }
  const 줄 = [
    { 이름: '🛣 토목 콘크리트(집계 합계)', 시트: '토목 집계', 줄: '합계', 열: '콘크리트(㎥)', 값: 함께.토목.콘크리트 + 건.콘크리트, 단위: '㎥' },
    { 이름: '🛣 토목 거푸집(집계 합계)', 시트: '토목 집계', 줄: '합계', 열: '거푸집(㎡)', 값: 함께.토목.거푸집 + 건.거푸집, 단위: '㎡', 자리: 1, 오차: 0.06 },
    { 이름: '🛣 터파기(집계 합계)', 시트: '토목 집계', 줄: '합계', 열: '터파기(㎥)', 값: 함께.토목.터파기, 단위: '㎥', 자리: 1, 오차: 0.06 },
    { 이름: '🛣 되메우기(집계 합계)', 시트: '토목 집계', 줄: '합계', 열: '되메우기(㎥)', 값: 함께.토목.되메우기, 단위: '㎥', 자리: 1, 오차: 0.06 },
  ]
  const 이름틀 = (s) => new RegExp('^평균단면 ' + String(s).replace(/[\[\]:*?/\\]/g, ' ').replace(/\s+/g, ' ').trim().slice(0, 22).replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))
  for (const n of 토.노선들 || []) {
    줄.push({ 이름: '평균단면 «' + n.이름 + '» 콘크리트 = 집계', 시트: 이름틀(n.이름), 줄: '합계', 열: '콘크리트(㎥)', 값: (n.합 && n.합.콘크리트) || 0, 단위: '㎥', 오차: 0.02 })
  }
  if (옵.함께시트 && 함께.합) {
    줄.push({ 이름: '🏢 + 🛣 함께 합 콘크리트', 시트: '함께 합', 줄: '합계', 열: '콘크리트(㎥)', 값: 함께.합.콘크리트, 단위: '㎥' })
    if (함께.골조) 줄.push({ 이름: '🏢 + 🛣 함께 합 철근', 시트: '함께 합', 줄: '합계', 열: '철근(ton)', 값: 함께.합.철근, 단위: 't', 자리: 3, 오차: 0.0006 })
  }
  for (const q of 토.구조물들 || []) {
    줄.push({ 이름: '구조물 «' + q.이름 + '» 부분별 합 = 집계', 시트: '구조물(부분별)', 줄: q.이름, 열: '콘크리트(㎥)', 값: q.합.콘크리트, 단위: '㎥', 줄합: true, 오차: 0.011 + (q.ids || []).length * 0.00005 })
  }
  return 줄
}

/** 📋 G444 «집계» 시트(골조 · 마감 엑셀) 줄마다 = 셈 결과 집계 — 합: [{항목|재료, 규격, 단위, 산출|수량}] · 열 = 수량 칸 머리 · 줄은 [항목, 규격, 단위] 로 찾음 */
export function 집계맞댈(합, 열 = '산출수량', 이름 = '«집계» 시트 = 화면 집계', 시트 = '집계') {
  const 여럿 = (합 || []).map((x) => ({ 줄: [x.항목 ?? x.재료 ?? '', x.규격 ?? '', x.단위 ?? ''], 값: +(x.산출 ?? x.수량) })).filter((x) => Number.isFinite(x.값))
  return 여럿.length ? [{ 이름, 시트, 열, 여럿 }] : []
}
/** 📋 G444 도면 물량 자동 «산출서» 줄마다 수량 = 화면 줄 수량(번호로 찾음 · 엑셀은 셋째 자리 반올림) */
export function 산출서맞댈(줄들, 토공들 = [], 시트 = '산출서', 이름 = '«산출서» 줄마다 수량 = 화면') {
  /* 토공 줄 = 토공 시트 합계(구간마다 셋째 자리 반올림 → 합) · 화면은 반올림 없이 더함 → 구간 수만큼 0.0005 */
  const 토공오차 = (x) => (x.토공 && 토공들[x.토공.t] ? (토공들[x.토공.t].점 || []).length * 0.0005 : 0)
  const 여럿 = (줄들 || []).map((x, i) => ({ 줄: [String(i + 1)], 값: +x.수량, 오차: 0.0011 + 토공오차(x) })).filter((x) => Number.isFinite(x.값))
  return 여럿.length ? [{ 이름, 시트, 열: '수량', 여럿 }] : []
}
/** 📋 G444 내역서에 물량 넣은 파일(소장님 내역서 그대로 · 수량 칸만 바꿈) — 다시 열어 넣은 칸마다 = 화면 값인지
 *   소장님 내역서의 식(금액 = 수량 × 단가 …)은 소장님 것이라 그대로 둠(숫자로 바꾸지 않음) · 넣은 칸 = { 시트, 줄(1부터), 칸(0부터), 값 }
 */
export function 넣은칸검사(바이트, 됨 = []) {
  const 줄 = []
  let 책 = null
  try { 책 = 엑셀읽기(바이트) } catch (e) { 책 = null }
  줄.push({ 됨: !!책, 글: 책 ? `만든 파일을 다시 열어 봄 — 시트 ${책.시트들.length}장` : '만든 파일을 다시 열지 못했습니다' })
  if (책) {
    const 다름 = []
    for (const x of 됨) {
      const 시 = 책.시트들.find((t) => String(t.이름).trim() === String(x.시트).trim())
      const 엑 = 시 ? 수(시.칸.get(칸이름(x.줄, x.칸 + 1))) : null
      if (엑 === null || Math.abs(엑 - x.값) > 0.0005) 다름.push(`${x.시트} ${칸이름(x.줄, x.칸 + 1)} ${x.품명 || ''} ${엑 === null ? '빈 칸' : 쉼(엑, 3)} ≠ 화면 ${쉼(x.값, 3)}`)
    }
    줄.push({ 됨: !다름.length, 글: 다름.length ? `넣은 칸이 화면과 다름 ${다름.length}곳 — ${다름.slice(0, 3).join(' · ')}${다름.length > 3 ? ' …' : ''}` : `넣은 수량 칸 ${됨.length.toLocaleString('ko-KR')}곳 모두 화면 값과 같음` })
  }
  return { 통과: 줄.every((x) => x.됨), 줄, 바이트 }
}
