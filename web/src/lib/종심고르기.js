/** 🛠 G815 확률 막대(통.h — 0.5%p 칸 비율)에서 «가장 많이 나온 1%p»(붙은 두 칸 합이 가장 큰 곳) → { 아래, 위, 몫 } · 막대가 없으면 null */
export function 많이나온곳(통) {
  const h = 통 && 통.h
  if (!h || !Array.isArray(h.p) || !h.p.length) return null
  const w = Number(h.w) || 0.5, s = Number(h.s) || 0
  let best = null
  for (let i = 0; i < h.p.length; i++) {
    const 몫 = (h.p[i] || 0) + (h.p[i + 1] || 0)
    if (!best || 몫 > best.몫 + 1e-9) best = { 아래: s + i * w, 위: s + (i + Math.min(2, h.p.length - i)) * w, 몫 }
  }
  return best
}

