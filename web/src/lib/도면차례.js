/* 부재 일람표 안 차례 — 기둥 → 보 → 슬래브 → 벽 → 지하외벽 */
const 일람안 = (t) => (/기둥|COL/i.test(t) ? 1 : /보|BEAM|GIRDER/i.test(t) ? 2 : /슬래브|슬라브|SLAB/i.test(t) ? 3 : /지하외벽|외벽/i.test(t) ? 5 : /벽|WALL/i.test(t) ? 4 : 6)

