/* 앞의 도면 번호(«S-202 » · «A-000 » · «08. » · «3-2.» · «1.»)를 떼고 띄어쓰기를 붙임 — «S-202 1층» 이 «2021층» 이 되지 않게 */
const 번호떼기 = (s) => String(s || '').replace(/\.(dwg|dxf|pdf)$/i, '').replace(/^\s*[A-Za-z]{1,3}\s*(?:-\s*\d+|\d{3,})(?:\s*[-~]\s*\d+)?[\s._)]+/, '').replace(/^\s*\d+(?:-\d+)?\s*[.)]\s*/, '')
const 붙 = (s) => 번호떼기(s).replace(/\s+/g, '')

/* 토목 말 — 하나라도 있으면 토목 (건축 말보다 먼저 봄 · «배수펌프장 일반도» 는 토목 구조물) */
const 토목말 = /계획평면|파일배치|말뚝|상수도|이설|급수|오수|우수|배수|노선|측점|종평면|종단면|횡단면|횡단|유수지|호안|관로|관추진|반력벽|측량|GPS|성과표|가도|가물막이|가체절|흙막이|토공|사업계획|철거계획|격점|수문|양수|펌프장|BOX|박스|암거|옹벽|하천|제방|맨홀|하수|도로|포장|교량/i
/* 건축 말 */
const 건축말 = /층|구조평면|평면도|일람표|일람|기초|창호|입면|배치도|면적|개요|일반사항|계단|코어|데크|철골|SRC|지붕|옥탑|PH|단면도|골조|주심도|마감|ROOF|FOOTING|FOUNDATION|BEAM/i

/** 이름 → 층 순(기초 −100 · 지하 n → −n · n층 → n · 지붕 900 · 옥탑 950 · 모르면 null) */
export function 층순(이름) {
  const t = 붙(이름).toUpperCase()
  if (/옥탑지붕|PHR|옥탑층?지붕/.test(t)) return 960
  if (/옥탑|PH\d*층?|(^|[^A-Z])PH($|[^A-Z])/.test(t)) return 950
  if (/지붕|ROOF|(^|[^A-Z0-9])R층|(^|[^A-Z])RF($|[^A-Z])/.test(t)) return 900
  if (/기초|FOOTING|FOUNDATION|(^|[^A-Z])FT($|[^A-Z])|MAT/.test(t)) return -100
  let m = t.match(/(지하|B)(\d+)(층|F)?/)
  if (m) return -Number(m[2])
  m = t.match(/(\d+)(?:~|-|∼)(\d+)층/)                                   // «2~5층»(기준층) — 맨 아래 층으로
  if (m) return Number(m[1])
  m = t.match(/(?:지상)?(\d+)(층|F)(?![A-Z])/)
  if (m) return Number(m[1])
  return null
}

/** 이름 → 노선 번호(«3호 배수로» → 3) — 없으면 null */
const 노선번호 = (이름) => { const m = 붙(이름).match(/(\d+)호/); return m ? Number(m[1]) : null }

