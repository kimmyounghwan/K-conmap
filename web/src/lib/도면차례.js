/**
 * 도면 이름(제목 또는 파일 이름) → { 무리: '건축' | '토목' | '모름', 차례(1 ~ 14 · 모르면 99), 갈래, 층(층순) , 노선(번호), 안(같은 차례 안 순서) }
 */
export function 도면차례(이름, 무리강제 = null) {
  const t = 붙(이름)
  const 토 = 토목말.test(t), 건 = 건축말.test(t)
  if (!토 && !건 && /목록|목차|표지|간지|INDEX/i.test(t)) return { 무리: '공통', 차례: 1, 갈래: '표지 · 목록', 층: null, 노선: null, 안: 0 }
  const 무리 = 토 ? '토목' : 건 ? '건축' : 무리강제 || '모름'
  if (무리 === '토목') {
    for (const [차례, 갈래, re] of 토목차례) if (re.test(t)) return { 무리, 차례, 갈래, 층: null, 노선: 노선번호(t), 안: 0 }
    return { 무리, 차례: 99, 갈래: '그 밖', 층: null, 노선: 노선번호(t), 안: 0 }
  }
  if (무리 === '건축') {
    const 층 = 층순(t)
    for (const [차례, 갈래, re] of 건축차례) {
      if (!re.test(t)) continue
      if (차례 === 8) {                                                    // 층 평면 — 지하는 ⑦ · 지붕 · 옥탑은 ⑨
        const c = 층 !== null && 층 < 0 && 층 > -100 ? 7 : 층 !== null && 층 >= 900 ? 9 : 8
        return { 무리, 차례: c, 갈래: c === 7 ? '지하층 평면' : c === 9 ? '지붕 · 옥탑 평면' : '층 평면', 층, 노선: null, 안: 0 }
      }
      return { 무리, 차례, 갈래, 층, 노선: null, 안: 차례 === 10 ? 일람안(t) : 0 }
    }
    return { 무리, 차례: 99, 갈래: '그 밖', 층, 노선: null, 안: 0 }
  }
  return { 무리, 차례: 99, 갈래: '모름', 층: null, 노선: null, 안: 0 }
}

/** 목록을 보는 차례로 — 건축 먼저(골조), 토목, 모름 · 같은 차례 안은 층(아래 → 위) · 노선 번호 · 일람 안 차례 · 이름 */
export function 차례정렬(목록, 이름꺼내 = (x) => x) {
  const 무리순 = { 공통: -1, 건축: 0, 토목: 1, 모름: 2 }
  /* 무리 말이 없는 도면(«난간상세도» · «XREF_PLAN»)은 같이 넣은 도면의 많은 쪽 무리로 */
  const 먼저 = 목록.map((x) => 도면차례(이름꺼내(x)))
  const 셈 = { 건축: 먼저.filter((c) => c.무리 === '건축').length, 토목: 먼저.filter((c) => c.무리 === '토목').length }
  const 많은 = 셈.건축 || 셈.토목 ? (셈.토목 > 셈.건축 ? '토목' : '건축') : null
  const 쌍 = 목록.map((x, i) => ({ x, 이름: String(이름꺼내(x) || ''), c: 먼저[i].무리 === '모름' && 많은 ? 도면차례(이름꺼내(x), 많은) : 먼저[i] }))
  쌍.sort((a, b) => (무리순[a.c.무리] - 무리순[b.c.무리]) || (a.c.차례 - b.c.차례) || ((a.c.층 ?? 0) - (b.c.층 ?? 0)) || ((a.c.노선 ?? 0) - (b.c.노선 ?? 0)) || (a.c.안 - b.c.안) || a.이름.localeCompare(b.이름, 'ko'))
  return 쌍.map((q) => q.x)
}
