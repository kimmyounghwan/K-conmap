/**
 * 🧮 셈 방법 (🏭 G295 — 2026-10-15) — 플랜트식 토목 기초 도면(골조자동 _플랜트 줄)의 셈 기준
 *   📐 도면 그대로(기본) · 📑 내역서처럼(지중보 · 기초를 바닥판 윗면까지 — lib/골조.js 기준값 «내역식» 둘 다 켬)
 *   화면: 셈방법칸.jsx (BIM 물량 · 적산 자동)
 */
export const 셈방법글 = {
  도면: '바닥판과 지중보 · 기초가 겹치는 곳은 한 번만 셉니다.',
  내역식: '지중보 · 기초를 바닥판 윗면까지 셉니다(공내역서 셈).',
}

/** 공사(골조 셈 입력)에 셈 방법을 입힘 — «내역식» 이면 거푸집 · 콘크리트 둘 다 */
export function 셈방법입히기(공사, 방법) {
  if (!공사 || 방법 !== '내역식') return 공사
  return { ...공사, 기준: { ...(공사.기준 || {}), 내역식: { 거푸집: true, 콘크리트: true } } }
}

/* ── 🤖 저절로 고르기 — 내역서를 넣으면 내역서의 철근 콘크리트(㎥) · 거푸집(㎡) 수량과 더 가까운 셈 방법 ── */
const 글 = (v) => String(v ?? '')
const 콘줄 = (n) => /M3|㎥|m3/i.test(글(n.단위)) && /레미콘|콘크리트|CONC/i.test(글(n.품명)) && !/무근|버림|양생|CHIPPING|치핑|접착|마감|시험/i.test(글(n.품명) + 글(n.규격))
const 틀줄 = (n) => /M2|㎡|m2/i.test(글(n.단위)) && /거푸집|형틀|유로폼/.test(글(n.품명))
/** 내역서 한 권에 건물 · 공종이 여럿이면(두 건물 × 토목 · 건축 공내역) 전체 합계로는 못 견줌 —
 *  이어진 줄 덩이(합판거푸집 3회 · 4회 · 6회처럼 붙은 줄은 더함)마다 견줌 · 전체 합계도 한 덩이 */
export function 내역덩이(줄, 조건) {
  const 들 = []
  let s = 0, 켬 = false
  for (const n of 줄 || []) {
    const v = +n.수량
    if (조건(n) && Number.isFinite(v) && v > 0) { s += v; 켬 = true } else if (켬) { 들.push(s); s = 0; 켬 = false }
  }
  if (켬) 들.push(s)
  if (들.length > 1) 들.push(들.reduce((a, v) => a + v, 0))
  return 들
}
/**
 * @param 줄 내역 줄들 [{품명, 규격, 단위, 수량}] · @param 도면S · 내역S 골조 셈 결과(셈방법 «도면» · «내역식») · @param 버림 버림 콘크리트 규격(빼고 견줌)
 * @returns {방법: '도면'|'내역식', 까닭}
 */
export function 셈방법고르기(줄, 도면S, 내역S, 버림) {
  if (!줄 || !줄.length || !도면S || !내역S) return { 방법: '도면', 까닭: '' }
  const 콘들 = 내역덩이(줄, 콘줄), 틀들 = 내역덩이(줄, 틀줄)
  if (!콘들.length && !틀들.length) return { 방법: '도면', 까닭: '내역서에 콘크리트 · 거푸집 줄이 없어 도면 그대로 셉니다.' }
  const 가깝 = (v, 들) => (v > 0 && 들.length ? Math.min(...들.map((d) => Math.abs(Math.log(v / d)))) : 0)
  const 점 = (S) => {
    const 합 = (S.집계 && S.집계.합) || []
    const 콘 = 합.filter((h) => h.항목 === '콘크리트' && h.규격 !== 버림).reduce((a, h) => a + h.산출, 0)
    const 틀 = 합.filter((h) => h.항목 === '거푸집').reduce((a, h) => a + h.산출, 0)
    return 가깝(콘, 콘들) + 가깝(틀, 틀들)
  }
  return { 방법: 점(내역S) < 점(도면S) ? '내역식' : '도면', 까닭: '내역서와 더 가까워 골랐습니다.' }
}
