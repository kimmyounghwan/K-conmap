            닫기(다음날(마지막), `${달글(ym)} ${n}일 < 8일 → 그 달 최종근로일(${짧은날(마지막)}) 다음날 상실`)
            H.과정.push(`② ${달글(ym)}(첫 근로일 다음 달) ${n}일 — 8일 미만이라 ${달글(ym)} 최종근로일 ${짧은날(마지막)} 다음날 ${짧은날(다음날(마지막))} 상실`)
