/* 🎂 나이 — 생년월일(주민번호 앞 6자리 또는 8자리) · 뒷자리는 받지 않습니다 */
/** '610315' · '19610315' · '1961-03-15' · '1961.3.15' → '1961-03-15' (틀리면 '') · 6자리는 올해보다 뒤면 1900년대 */
export function 생일풀기(s, 올해 = new Date().getFullYear()) {
  const raw = String(s || '').trim()
  let y, m, d
  const 점 = raw.match(/^(\d{4})[.\-/ ]\s*(\d{1,2})[.\-/ ]\s*(\d{1,2})\.?$/)
  const t = raw.replace(/[^\d]/g, '')
  if (점) { y = +점[1]; m = +점[2]; d = +점[3] }
  else if (t.length === 6) { const yy = +t.slice(0, 2); y = 2000 + yy > 올해 ? 1900 + yy : 2000 + yy; m = +t.slice(2, 4); d = +t.slice(4, 6) }
  else if (t.length === 8) { y = +t.slice(0, 4); m = +t.slice(4, 6); d = +t.slice(6, 8) }
  else return ''
  const dt = new Date(y, m - 1, d)
  if (y < 1900 || y > 올해 || dt.getFullYear() !== y || dt.getMonth() !== m - 1 || dt.getDate() !== d) return ''
  return 날글(dt)
}
