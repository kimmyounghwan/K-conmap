import { 쉬는날, 다음날, 기한미루기, 공휴일표, 요일, 남은날, 한국오늘 } from './해마다.js'

const 날꼴 = /^\d{4}-\d{2}-\d{2}$/
export const 날맞음 = (s) => {
  if (!날꼴.test(String(s || ''))) return false
  const [y, m, d] = s.split('-').map(Number)
  const t = new Date(Date.UTC(y, m - 1, d))
  return t.getUTCFullYear() === y && t.getUTCMonth() === m - 1 && t.getUTCDate() === d
}
const 표있음 = (ds) => !!공휴일표[Number(ds.slice(0, 4))]

export const 근거 = {
  국가기성: '국가계약법 시행령 제58조 ③ · ④ · 공사계약일반조건 제39조 ②',
  국가준공: '국가계약법 시행령 제58조 ① · ⑥ · 공사계약일반조건 제40조 ②',
  지방기성: '지방계약법 시행령 제67조 ① · ③ · ④',
  지방준공: '지방계약법 시행령 제67조 ①',
  민법: '민법 제157조 · 제161조',
  이자: '공사계약일반조건 제41조 ①',
}

/** 시작한 날 다음 날부터 토 · 일 · 공휴일을 빼고 n 번째 날 — {날, 센[], 뺀[], 모름} */
export function 일하는날셈(시작, n = 5) {
  const 센 = [], 뺀 = []
  let d = 시작, 모름 = !표있음(시작)
  for (let i = 0; 센.length < n && i < 60; i++) {
    d = 다음날(d)
    if (!표있음(d)) 모름 = true
    if (쉬는날(d)) 뺀.push(d)
    else 센.push(d)
  }
  return { 날: 센[n - 1], 센, 뺀, 모름 }
}

/** 시작한 날 다음 날부터 달력으로 n 번째 날 — 그 날이 토 · 일 · 공휴일이면 다음 일하는 날(민법 제161조) — {날, 원래, 밀림, 센[], 뺀[], 모름} */
export function 달력셈(시작, n = 5) {
  const 센 = []
  let d = 시작
  for (let i = 0; i < n; i++) { d = 다음날(d); 센.push(d) }
  const k = 기한미루기(d)
  const 뺀 = []
  for (let x = d; x !== k.날; x = 다음날(x)) 뺀.push(x)
  return { 날: k.날, 원래: d, 밀림: k.밀림, 센, 뺀, 모름: k.모름 || !표있음(시작) || !표있음(k.날) }
}

/**
 * 지급 기한
 * @param {{무엇: '기성'|'준공', 발주: '국가'|'지방', 검사일?: string, 청구일?: string, 오늘?: string}} o
 *   기성: 검사일(검사 완료일) 꼭 · 청구일은 검사 완료 «뒤» 에 청구했을 때만 시작이 바뀜
 *   준공: 청구일(준공검사 합격 뒤 대가 지급 청구서를 낸 날) 꼭
 */
export function 대금기한(o = {}) {
  const 무엇 = o.무엇 === '준공' ? '준공' : '기성'
  const 발주 = o.발주 === '지방' ? '지방' : '국가'
  const 검사 = 날맞음(o.검사일) ? o.검사일 : ''
  const 청구 = 날맞음(o.청구일) ? o.청구일 : ''
  const 오늘 = 날맞음(o.오늘) ? o.오늘 : 한국오늘()
  const 알림 = []
  if (무엇 === '기성' && !검사) return { 무엇, 발주, 오류: '검사 완료일을 넣으세요.' }
  if (무엇 === '준공' && !청구) return { 무엇, 발주, 오류: '대가 지급 청구서를 낸 날을 넣으세요(준공검사에 합격한 뒤).' }
  let 시작, 시작말
  if (무엇 === '기성') {
    if (청구 && 청구 > 검사) { 시작 = 청구; 시작말 = '검사 완료일 뒤에 청구 → 청구를 받은 날부터' }
    else { 시작 = 검사; 시작말 = 청구 ? '검사 완료일까지 청구 → 검사 완료일부터' : '검사 완료일부터' }
  } else {
    시작 = 청구; 시작말 = '청구를 받은 날부터'
    if (검사 && 청구 < 검사) 알림.push('청구한 날이 준공검사 날보다 앞섭니다 — 준공대가는 검사에 합격한 뒤 청구합니다(공사계약일반조건 제40조 ①). 검사 뒤 다시 낸 날을 넣으세요.')
  }
  const 토공빼고 = 발주 === '지방' || 무엇 === '준공'
  const 셈 = 토공빼고 ? 일하는날셈(시작, 5) : 달력셈(시작, 5)
  const 참고 = 토공빼고 ? null : 일하는날셈(시작, 5)
  const 참고기한 = 참고 && 참고.날 !== 셈.날 ? 참고.날 : null
  const 모름 = 셈.모름 || (참고 ? 참고.모름 : false)
  if (모름) 알림.push('공휴일 표가 없는 해가 걸려 있습니다(2026 · 2027 년만 있음) — 그 해 공휴일은 따로 확인하세요.')
  const 근거들 = 발주 === '국가'
    ? (무엇 === '기성' ? [근거.국가기성, 근거.민법] : [근거.국가준공])
    : (무엇 === '기성' ? [근거.지방기성] : [근거.지방준공])
  return {
    무엇, 발주, 시작, 시작말, 기한: 셈.날, 요일: 요일(셈.날),
    셈법: 토공빼고 ? '토공빼고' : '달력', 센: 셈.센, 뺀: 셈.뺀, 원래: 셈.원래 || null, 밀림: !!셈.밀림,
    참고기한, 참고요일: 참고기한 ? 요일(참고기한) : '', 남은: 남은날(셈.날, 오늘), 오늘, 모름, 알림, 근거: 근거들,
  }
}

/** 날 글 — 2026-11-09 → 11월 9일(월) · 해가 다르면 2027년 1월 4일(월) */
export function 날말(ds, 오늘 = 한국오늘()) {
  if (!날맞음(ds)) return ''
  const [y, m, d] = ds.split('-').map(Number)
  return `${String(y) !== 오늘.slice(0, 4) ? y + '년 ' : ''}${m}월 ${d}일(${요일(ds)})`
}
