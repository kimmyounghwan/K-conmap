export const 판정글 = { 맞음: '✓ 맞음', 비슷: '△ 비슷', 다름: '✗ 다름', 없음: '— 건설맵에 아직 없음', 부분: '◇ 부분 물량(견주지 않음)' }
/** «내역 대조»(공종 · 갈래마다 · 차이 · 율은 식) + «내역 품목 판정»(줄마다) */
export function 내역대조시트(결과, 나무, ST) {
  const 판글 = 판정글
  const rows = 결과.단위들.map((d, i) => {
    const R = i + 2
    return [d.길.join(' > ') || d.공종, 갈래이름[d.갈래], 갈래단위[d.갈래], { v: +d.내역.toFixed(3), st: ST.QTY }, { v: +d.건설맵.toFixed(3), st: ST.QTY },
      { f: `ROUND(E${R}-D${R},3)`, st: ST.QTY }, { f: `IF(D${R}=0,"",ROUND((E${R}-D${R})/ABS(D${R})*100,2))`, st: ST.QTY },
      판글[d.판정], d.묶음.map((b) => `${b.이름} ${b.값.toFixed(1)}`).join(' · '), d.품목.map((pi) => 나무.품목[pi].행 + '행').join(', '), d.까닭.join(' · ')]
  })
  const 품 = 결과.품목줄.map((r) => {
    const p = r.품목
    const q = p.수량[결과.상태번]
    return [p.행, p.이름, p.규격, p.단위, q === null || q === undefined ? '' : { v: q, st: ST.QTY }, r.갈래 ? 갈래이름[r.갈래] : '', 판글[r.판정 || '없음'], r.까닭 || '']
  })
  /* 📤 G401 변경 수량 제안 — 견준 공종 · 갈래(✓ · △ · ✗)의 내역 품목마다 «건설맵 ÷ 내역 합» 비율로 나눈 변경 수량(설계변경 작업대 · 2줄 내역서로 옮겨 씀)
       부분 상태(기시행 · 차수 · 잔공사)에선 만들지 않음 · 철근은 가공 · 조립 줄을 같은 비율로 */
  const 단위로 = new Map(결과.단위들.map((d) => [d.키, d]))
  const 제안 = []
  if (!결과.부분) for (const r of 결과.품목줄) {
    const d = r.단위 && 단위로.get(r.단위), p = r.품목, q = p.수량[결과.상태번]
    if (!d || !['맞음', '비슷', '다름'].includes(d.판정) || !(d.내역 > 0) || !(q > 0)) continue
    const 비 = d.건설맵 / d.내역, R = 제안.length + 2
    제안.push([p.행, d.길.join(' > ') || d.공종, p.이름, p.규격, p.단위, { v: q, st: ST.QTY }, { v: +(q * 비).toFixed(3), st: ST.QTY },
      { f: `ROUND(G${R}-F${R},3)`, st: ST.QTY }, { f: `IF(F${R}=0,"",ROUND((G${R}-F${R})/ABS(F${R})*100,2))`, st: ST.QTY }, 판글[d.판정],
      `${갈래이름[d.갈래]} — 공종 내역 합 ${+d.내역.toFixed(3)} → 건설맵 ${+d.건설맵.toFixed(3)}(× ${비.toFixed(4)})${d.사람값 ? ' · ✋ 사람이 고친 값' : ''} · 건설맵 묶음: ${d.묶음.map((b) => b.이름).join(' · ')}`])
  }
  return [
    { name: '내역 대조', head: ['공종', '갈래', '단위', `내역(${결과.상태})`, '건설맵', '차이(건설맵−내역)', '차이율(%)', '판정', '건설맵 묶음', '내역 줄', '근거 · 까닭'], rows, widths: [40, 12, 6, 13, 13, 14, 10, 16, 40, 18, 70], freeze: 1 },
    { name: '내역 품목 판정', head: ['내역 줄', '품명', '규격', '단위', `수량(${결과.상태})`, '갈래', '판정', '까닭'], rows: 품, widths: [8, 28, 22, 6, 12, 12, 18, 70], freeze: 1 },
    ...(제안.length ? [{ name: '변경 수량 제안', head: ['내역 줄', '공종', '품명', '규격', '단위', `당초(${결과.상태})`, '변경 제안(건설맵)', '증감', '증감율(%)', '판정', '근거 — 공종 · 갈래의 건설맵 ÷ 내역 합 비율로 나눔(설계변경 작업대에 옮겨 쓰기 · 확인 후)'], rows: 제안, widths: [8, 36, 26, 20, 6, 13, 15, 12, 10, 14, 90], freeze: 1 }] : []),
  ]
}
