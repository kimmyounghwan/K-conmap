/* 🗂 G380 (2026-10-23) — 같은 파일에 «심사 전» 시트와 심사 뒤 시트가 함께 있을 때 심사 전 시트는 고르지 않습니다.
 *   「토목-내역서(심사전)」 · 「토목-내역서」 — 실측: 설계내역서 한 부 · 두 시트를 다 켜 노무비가 원가계산서의 7.2배, 작업대는 품목이 더 많은 심사 전 시트를 골랐음.
 *   심사 뒤 짝(이름에서 «심사전» 을 뗀 시트)이 있을 때만 뺍니다 — 짝이 없으면 그대로 둡니다. 80% 비율 · 설계변경 작업대가 함께 씁니다. */
const 심사전 = /[\s_\-]*[(（[]?\s*(원가)?심사\s*전\s*[)）\]]?/g
export const 심사전인가 = (이름) => /심사\s*전/.test(String(이름 || ''))
/** 이름들 → 뺄 이름 Set(심사 뒤 짝이 있는 심사 전 시트) */
export function 옛판빼기(이름들) {
  const 있음 = new Set(이름들.map((t) => String(t || '').replace(/\s+/g, '')))
  const 뺄 = new Set()
  for (const t of 이름들) {
    if (!심사전인가(t)) continue
    const 짝 = String(t).replace(심사전, '').replace(/\s+/g, '')
    if (짝 && 있음.has(짝)) 뺄.add(t)
  }
  return 뺄
}
