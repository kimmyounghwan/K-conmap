import { 날더하기, 다음날, 해값, 최저임금표, 보상기준표, 통상근로계수표, 짧은날, 긴날 } from './해마다.js'
import { 생일풀기, 만나이 } from './ilyong4.js'

const 날꼴 = /^(\d{4})-(0[1-9]|1[0-2])-(0[1-9]|[12]\d|3[01])$/
const 말일 = (ym) => new Date(Number(ym.slice(0, 4)), Number(ym.slice(5, 7)), 0).getDate()
export const 날맞나 = (ds) => typeof ds === 'string' && 날꼴.test(ds) && Number(ds.slice(8, 10)) <= 말일(ds.slice(0, 7))
const 날수 = (ds) => Date.UTC(Number(ds.slice(0, 4)), Number(ds.slice(5, 7)) - 1, Number(ds.slice(8, 10))) / 86400e3
export const 날차 = (a, b) => Math.round(날수(b) - 날수(a))
const 원 = (n) => Math.floor(Number(n) || 0).toLocaleString('ko-KR')
/** n년 뒤 같은 날(2.29. → 2.28.) */
export function 해더하기(ds, n) {
  const y = Number(ds.slice(0, 4)) + n, md = ds.slice(5)
  const d = `${y}-${md}`
  return 날맞나(d) ? d : `${y}-02-28`
}

/** 고령 비율 — 별표 1 (61 ~ 65세 이후) */
export const 고령비 = {
  칠십: { 61: 66 / 70, 62: 62 / 70, 63: 58 / 70, 64: 54 / 70, 65: 50 / 70 },
  구십: { 61: 86 / 90, 62: 82 / 90, 63: 78 / 90, 64: 74 / 90, 65: 70 / 90 },
}
const 비율 = (표, 나) => 표[Math.min(65, 나)]

/** 그해 기준 — 최고 · 최저 보상기준 금액 · 최저임금액 */
export function 기준(해) {
  const b = 해값(보상기준표, 해), m = 해값(최저임금표, 해)
  return { 최고: b.최고, 최저: b.최저, 최저임금액: m.시급 * 8, 잠정: b.잠정 || m.잠정, 기준해: b.해 }
}

/**
 * 하루 휴업급여 — 평균임금 p(원) · 그해 기준 g · 나이 나(없으면 감액 없음) · 유예(61세 이후 일하다 다쳐 2년 안)
 * → { 액, 꼴: '70'|'90'|'최저임금'|'80', 줄: [까닭 …], 감액 }
 */
export function 하루액(p, g, 나 = null, 유예 = false) {
  const 평 = Math.min(p, g.최고)
  const 줄 = []
  if (p > g.최고) 줄.push(`평균임금 ${원(p)}원이 최고 보상기준 금액(${원(g.최고)}원)을 넘어 ${원(g.최고)}원으로 셈(제36조⑦)`)
  const 칠 = 평 * 0.7, 선 = g.최저 * 0.8
  let 액, 꼴
  if (칠 > 선) { 액 = 칠; 꼴 = '70'; 줄.push(`평균임금 ${원(평)}원 × 70% = ${원(칠)}원(제52조)`) }
  else {
    const 구 = 평 * 0.9
    if (구 > 선) { 액 = 선; 꼴 = '80'; 줄.push(`70%(${원(칠)}원)가 최저 보상기준 금액의 80%(${원(선)}원) 이하 → 90%(${원(구)}원)가 그보다 많아 ${원(선)}원(제54조① 단서)`) }
    else if (구 < g.최저임금액) { 액 = g.최저임금액; 꼴 = '최저임금'; 줄.push(`70%(${원(칠)}원)가 최저 보상기준 금액의 80%(${원(선)}원) 이하 → 90%(${원(구)}원)가 최저임금액(${원(g.최저임금액)}원)보다 적어 최저임금액(제54조②)`) }
    else { 액 = 구; 꼴 = '90'; 줄.push(`70%(${원(칠)}원)가 최저 보상기준 금액의 80%(${원(선)}원) 이하 → 평균임금 × 90% = ${원(구)}원(제54조①)`) }
  }
  let 감액 = null
  if (나 !== null && 나 >= 61) {
    if (유예) 줄.push(`${나}세 — 61세 이후 일하다 다쳐 요양 시작일부터 2년은 감액하지 않음(제55조 단서 · 시행령 제51조)`)
    else {
      const 셋째 = 선 * 비율(고령비.구십, 나)
      const 칠분 = Math.round(비율(고령비.칠십, 나) * 70), 구분 = Math.round(비율(고령비.구십, 나) * 90)
      if (꼴 === '70') {
        const a = 액 * 비율(고령비.칠십, 나)
        if (a < 셋째) { 감액 = `${나}세 감액 — ${원(액)}원 × ${칠분}/70 = ${원(a)}원이 최저 보상기준 금액 × 80/100 × ${구분}/90(${원(셋째)}원)보다 적어 ${원(셋째)}원(별표 1 제1호 단서)`; 액 = 셋째 }
        else { 감액 = `${나}세 감액 — ${원(액)}원 × ${칠분}/70 = ${원(a)}원(별표 1 제1호)`; 액 = a }
      } else if (꼴 === '80') { 감액 = `${나}세 감액 — 최저 보상기준 금액 × 80/100 × ${구분}/90 = ${원(셋째)}원(별표 1 제3호)`; 액 = 셋째 }
      else { const a = 액 * 비율(고령비.구십, 나); 감액 = `${나}세 감액 — ${원(액)}원 × ${구분}/90 = ${원(a)}원(별표 1 제2호)`; 액 = a }
      줄.push(감액)
    }
  }
  return { 액: Math.floor(액 + 1e-6), 꼴, 줄, 감액, 평균: 평 }
}

/**
 * 셈 — 입력 i: 일당 · 직접(true 면 평균임금을 직접) · 평균 · 처음(쉰 첫날 = 요양 시작) · 끝(쉰 끝날) · 다친날(없으면 처음) · 생일('610315' 꼴 · 선택)
 * → { 빈 | 일수, 셋날, 평균, 구간: [{부터, 까지, 일, 액, 줄}], 총, 잠정, 증감(1년 지난 날 · 없으면 ''), 상병(2년 지난 날), 나이글 }
 */
export function 휴업셈(i) {
  const 처음 = 날맞나(i && i.처음) ? i.처음 : null, 끝 = 날맞나(i && i.끝) ? i.끝 : null
  if (!처음 || !끝 || 끝 < 처음) return { 빈: true, 까닭: !처음 ? '쉰 첫날을 넣으세요' : !끝 ? '쉰 끝날을 넣으세요' : '끝날이 첫날보다 앞입니다' }
  const 수 = (v) => Math.max(0, Math.floor(Number(String(v ?? '').replace(/[^\d.]/g, '')) || 0))
  const 다친날 = 날맞나(i.다친날) && i.다친날 <= 처음 ? i.다친날 : 처음
  const 계수 = 해값(통상근로계수표, Number(다친날.slice(0, 4))).계수
  const 평균 = i.직접 ? 수(i.평균) : Math.floor(수(i.일당) * 계수)
  if (!평균) return { 빈: true, 까닭: i.직접 ? '평균임금을 넣으세요' : '일당을 넣으세요' }
  const 일수 = 날차(처음, 끝) + 1
  const 생일 = 생일풀기(i.생일 || '')
  const 다친나이 = 생일 ? 만나이(생일, 다친날) : null
  const 유예끝 = 다친나이 !== null && 다친나이 >= 61 ? 날더하기(해더하기(처음, 2), -1) : null   // 요양 시작일부터 2년(시행령 제51조) — 시작일을 넣어 2년 되는 날의 전날까지
  const 구간 = []
  let 총 = 0, 잠정 = false
  for (let d = 처음; d <= 끝; d = 다음날(d)) {
    const g = 기준(Number(d.slice(0, 4)))
    if (g.잠정) 잠정 = true
    const 나 = 생일 ? 만나이(생일, d) : null
    const 유예 = !!(유예끝 && d <= 유예끝)
    const r = 하루액(평균, g, 나, 유예)
    총 += r.액
    const 끝구간 = 구간[구간.length - 1]
    if (끝구간 && 끝구간.액 === r.액 && 끝구간.열쇠 === r.줄.join('|')) { 끝구간.까지 = d; 끝구간.일++ }
    else 구간.push({ 부터: d, 까지: d, 일: 1, 액: r.액, 줄: r.줄, 꼴: r.꼴, 열쇠: r.줄.join('|') })
  }
  const 셋날 = 일수 <= 3
  // 오래 쉴 때(올리기 전 검토 2026-11-02) — 제36조③ 다친 날부터 1년이 지나면 평균임금을 해마다 증감(이 셈은 증감 전)
  //   · 제66조 요양 시작 2년이 지난 뒤 중증요양상태면 휴업급여 대신 상병보상연금 — 둘 다 화면에 알림만
  const 증감날 = 해더하기(다친날, 1), 상병날 = 해더하기(처음, 2)
  return {
    일수, 셋날, 평균, 계수, 직접: !!i.직접, 다친날, 구간, 총: 셋날 ? 0 : 총, 셈총: 총, 잠정,
    증감: 끝 >= 증감날 ? 증감날 : '', 상병: 끝 >= 상병날 ? 상병날 : '',
    나이글: 생일 ? `다친 날 ${다친나이}세${유예끝 ? ` — 61세 이후 일하다 다쳐 ${긴날(유예끝)}까지 감액 없음` : ''}` : '',
  }
}

