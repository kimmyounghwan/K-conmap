/**
 * 📏 단위 보기 (2026-09-27)
 * 소장님: 「정렬이 제대로 안돼있어. 그리고 단위 표시가 되어야 하지 않을까? 철근이면 톤...레미콘이면 루베로..」
 *   → 화면에서는 m3 → ㎥(루베), m2 → ㎡(헤베), ton → 톤 으로 보이고, 수량 옆에도 단위를 붙입니다.
 *   ⚠️ 엑셀(양식)의 단위 칸은 그대로 둡니다 — 내역서 대조(단위풀기)와 발주처 양식이 그 글자를 씁니다.
 */
const 표 = {
  m3: '㎥', 'm³': '㎥', M3: '㎥', '㎥': '㎥', 루베: '㎥',
  m2: '㎡', 'm²': '㎡', M2: '㎡', '㎡': '㎡', 헤베: '㎡',
  ton: '톤', TON: '톤', Ton: '톤', t: '톤', T: '톤', 톤: '톤',
  ea: '개', EA: '개',
}
const 말 = { '㎥': '루베', '㎡': '헤베' }
/** 'm3' → '㎥' */
export function 단위보기(u) { const s = String(u ?? '').trim(); return 표[s] || s }
/** 'm3' → '㎥(루베)' — 단위 칸에 */
export function 단위풀이(u) { const b = 단위보기(u); return 말[b] ? `${b}(${말[b]})` : b }
