const 버림 = (x) => Math.floor(Math.round(x * 1e6) / 1e6)
const 수 = (v) => { const n = Number(String(v ?? '').replace(/[^0-9.\-]/g, '')); return Number.isFinite(n) ? n : 0 }

/** 총액을 지분(%)대로 원 미만 버림으로 나누고, 남는 원은 끝전 구성원에게 — [금액…] (합 = 총액) */
export function 지분나누기(총액, 지분들, 끝전 = 0) {
  const T = Math.round(수(총액))
  const 몫 = 지분들.map((p) => 버림((T * 수(p)) / 100))
  const 남 = T - 몫.reduce((a, b) => a + b, 0)
  const k = 끝전 >= 0 && 끝전 < 몫.length ? 끝전 : 0
  if (몫.length) 몫[k] += 남
  return 몫
}

/**
 * 이번 회 나누기
 * @param {{계약: number, 금회: number, 방식: '지분'|'직접', 준공: boolean, 끝전: number,
 *          구성원: {이름?: string, 지분: number, 선금?: number, 전회?: number, 전회정산?: number, 직접?: number}[]}} o
 */
export function 회차나누기(o = {}) {
  const 구성원 = (o.구성원 || []).filter((x) => x && (수(x.지분) > 0 || 수(x.직접) > 0 || 수(x.전회) > 0))
  const 계약 = Math.round(수(o.계약)), 금회총 = Math.round(수(o.금회))
  const 끝전 = Number.isInteger(o.끝전) ? o.끝전 : 0
  const 알림 = []
  const 지분합 = Math.round(구성원.reduce((a, x) => a + 수(x.지분), 0) * 1e6) / 1e6
  if (!구성원.length) return { 오류: '구성원 지분율을 넣으세요.', 줄: [], 알림 }
  if (Math.abs(지분합 - 100) > 1e-6) 알림.push(`지분율 합이 ${지분합}% 입니다 — 100% 가 되어야 합니다(공동수급협정서의 출자비율).`)
  if (!(계약 > 0)) return { 오류: '계약금액(공동수급체 전체)을 넣으세요.', 줄: [], 알림, 지분합 }
  const 몫들 = 지분나누기(계약, 구성원.map((x) => x.지분), 끝전)
  const 전회들 = 구성원.map((x) => Math.round(수(x.전회)))
  let 금회들
  if (o.준공) 금회들 = 몫들.map((m, i) => m - 전회들[i])
  else if (o.방식 === '직접') 금회들 = 구성원.map((x) => Math.round(수(x.직접)))
  else 금회들 = 지분나누기(금회총, 구성원.map((x) => x.지분), 끝전)
  const 줄 = 구성원.map((x, i) => {
    const 몫 = 몫들[i], 전회 = 전회들[i], 금회 = 금회들[i], 누계 = 전회 + 금회
    const 선금 = Math.round(수(x.선금)), 전회정산 = Math.round(수(x.전회정산))
    let 정산 = 0
    if (선금 > 0 && 몫 > 0) {
      const 누계정산 = o.준공 ? 선금 : Math.min(선금, 버림((선금 * 누계) / 몫))
      정산 = Math.max(0, Math.min(선금 - 전회정산, 누계정산 - 전회정산))
    }
    return { 이름: x.이름 || '', 지분: 수(x.지분), 몫, 전회, 금회, 누계, 잔여: 몫 - 누계, 율: 몫 > 0 ? 누계 / 몫 : 0, 선금, 전회정산, 정산, 정산누계: 전회정산 + 정산, 지급: 금회 - 정산 }
  })
  const 합 = (k) => 줄.reduce((a, x) => a + x[k], 0)
  const 금회합 = 합('금회')
  if (!o.준공 && o.방식 === '직접' && 금회총 > 0 && 금회합 !== 금회총) 알림.push(`구성원별로 적은 금회 합(${금회합.toLocaleString('ko-KR')}원)이 금회 기성(${금회총.toLocaleString('ko-KR')}원)과 ${(금회합 - 금회총).toLocaleString('ko-KR')}원 다릅니다.`)
  for (const x of 줄) {
    if (x.잔여 < 0) 알림.push(`${x.이름 || '구성원'} 누계가 제 몫(계약금액 × 지분율)보다 ${(-x.잔여).toLocaleString('ko-KR')}원 많습니다 — 준공 때 출자비율과 같아야 합니다(공동계약운용요령 제11조 ③).`)
    if (x.금회 < 0) 알림.push(`${x.이름 || '구성원'} 금회가 음수입니다 — 전회 누계가 몫을 넘었습니다.`)
  }
  if (o.준공) for (const x of 줄) if (x.누계 !== x.몫) 알림.push(`${x.이름 || '구성원'} 준공 누계가 몫과 다릅니다.`)
  const 총 = { 몫: 합('몫'), 전회: 합('전회'), 금회: 금회합, 누계: 합('누계'), 잔여: 합('잔여'), 선금: 합('선금'), 정산: 합('정산'), 지급: 합('지급') }
  return { 줄, 총, 알림, 지분합, 계약, 금회총: o.준공 ? 금회합 : (o.방식 === '직접' ? 금회합 : 금회총) }
}
