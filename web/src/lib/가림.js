/* 🙈 연락처 가림 — 2026-09-29 (사랑방 글을 검색에 내면서)
 *
 * 사랑방 글을 «글마다 한 장» 으로 구워 검색에 냅니다(qnapages.py · prerender.py).
 * 구운 글에서 전화번호 · 메일 주소를 가리는데, 화면(React)이 그 자리를 덮어 원글을 보이면
 * 크롤러와 사람이 보는 글이 달라집니다(클로킹). 그래서 화면도 **같은 규칙** 으로 가립니다.
 * ⚠️ qnapages.py 의 _전화 · _메일 과 **글자 하나까지 같게** 둡니다. 한쪽만 고치면 둘이 달라집니다.
 * ⚠️ 뒤돌아보기((?<!…))를 쓰지 않습니다 — 옛 아이폰 사파리(16.4 전)는 그 한 줄 때문에 화면이 통째로 멈춥니다.
 */
const 전화 = /(^|[^0-9])((?:\+82[\s.\-]*|0)1[016789][\s.\-)]*\d{3,4}[\s.\-]*\d{4}|0\d{1,2}[\s.\-)]+\d{3,4}[\s.\-]+\d{4}|0\d{1,2}\d{7,8})(?![0-9])/g
const 메일 = /[A-Za-z0-9._%+\-]+@[A-Za-z0-9\-]+(?:\.[A-Za-z0-9\-]+)+/g

export function 가림(s) {
  return String(s == null ? '' : s)
    .replace(메일, '(메일 주소 가림)')
    .replace(전화, (_m, 앞) => 앞 + '(전화번호 가림)')
}
