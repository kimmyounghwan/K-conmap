/** 한글 낱자 → 초성(한글 아닌 글자는 그대로) */
export function 초성(s) {
  let o = ''
  for (const ch of String(s || '')) {
    const c = ch.charCodeAt(0)
    o += c >= 0xac00 && c <= 0xd7a3 ? 초성표[Math.floor((c - 0xac00) / 588)] : ch
  }
  return o
}

