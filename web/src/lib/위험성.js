/** 관리기간 글 — 서식 «20.00.00~00.00.(0일간)» 모양 */
export function 기간글(a, b) {
  if (!a) return ''
  const [y1, m1, d1] = a.split('-')
  if (!b) return `${y1.slice(2)}.${m1}.${d1}~`
  const [, m2, d2] = b.split('-')
  const 일 = Math.round((new Date(b) - new Date(a)) / 86400000) + 1
  return `${y1.slice(2)}.${m1}.${d1}~${m2}.${d2}.(${일}일간)`
}
