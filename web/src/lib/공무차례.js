export const 모든도구 = 단계들.flatMap((s) => s.도구.map((t) => ({ ...t, 단계: s.k })))
export const 했음열쇠 = (id) => 'gm:' + id

/** 현장의 ✓ — 단계마다 { k, 한, 다 } · 모두 { 한, 다 } (현장이 없으면 0) */
export function 진행(현장) {
  const 셋 = new Set((현장 && Array.isArray(현장.했음)) ? 현장.했음 : [])
  const 단계 = 단계들.map((s) => ({ k: s.k, 한: s.도구.filter((t) => 셋.has(했음열쇠(t.id))).length, 다: s.도구.length }))
  return { 단계, 한: 단계.reduce((a, x) => a + x.한, 0), 다: 모든도구.length }
}

/** 지금 할 단계 — 착공 전이면 ①, 공사 중이면 ②, 준공 30일 안 · 지났으면 ③ (날이 없으면 ①) */
export function 지금단계(현장, 오늘) {
  if (!현장 || !현장.착공 || !오늘) return '착공'
  if (오늘 < 현장.착공) return '착공'
  if (현장.준공) {
    const 준 = Date.parse(현장.준공 + 'T00:00:00Z'), 오 = Date.parse(오늘 + 'T00:00:00Z')
    if (Number.isFinite(준) && Number.isFinite(오) && 준 - 오 <= 30 * 864e5) return '준공'
  }
  return '공사'
}
