/**
 * 🧮 셈 방법 고르기 (🏭 G295 — 2026-10-15)
 *   소장님 「최대한 이용자가 편하게 사용하게 해줘 · 초등학생도 이용할 수 있게.. 쉽게」
 *   플랜트식 토목 기초 도면(바닥판 · 지중보 · 기초)일 때만 보입니다 — 단추 둘(셋)과 한 줄 설명.
 *   · 📐 도면 그대로 — 겹치는 곳은 한 번만 셉니다(표준 산출 기준 · 기본)
 *   · 📑 내역서처럼 — 지중보 · 기초를 바닥판 윗면까지 셉니다(보 · 기초를 먼저 치고 바닥을 나중에 치는 순서 · 공내역서와 견줄 때)
 *   · 🤖 저절로 — 내역서를 넣으면 내역서 합계와 더 가까운 쪽(적산 자동 화면만)
 *   셈은 lib/골조.js 기준값 «내역식» { 거푸집, 콘크리트 } 를 켜고 끕니다.
 */
import { 셈방법글 } from './lib/셈방법.js'
export { 셈방법입히기 } from './lib/셈방법.js'

export default function 셈방법칸({ 값, 바꾸기, 저절로 = false, 고른 = '', 까닭 = '' }) {
  const 단추 = [...(저절로 ? [['저절로', '🤖 저절로']] : []), ['도면', '📐 도면 그대로'], ['내역식', '📑 내역서처럼']]
  const 지금 = 값 === '저절로' ? 고른 || '도면' : 값
  return (
    <div className="sem-box" role="group" aria-label="셈 방법">
      <div className="sem-top">
        <b>🧮 셈 방법</b>
        <span className="sem-btns">
          {단추.map(([k, 글]) => (
            <button key={k} type="button" className={'btn line sm' + (값 === k ? ' on' : '')} aria-pressed={값 === k} onClick={() => 바꾸기(k)}>{글}</button>
          ))}
        </span>
      </div>
      <div className="muted sem-say">
        {값 === '저절로' && <>지금 <b>{지금 === '내역식' ? '📑 내역서처럼' : '📐 도면 그대로'}</b> — {까닭 || '내역서를 넣으면 더 가까운 쪽을 고릅니다.'} </>}
        {셈방법글[지금]}
      </div>
    </div>
  )
}
