/**
 * 🎓 G625 건설기술인 등급 셈(web/src/lib/등급셈.js) 시험 — node tools/시험_등급셈.mjs
 *   ① 경력지수 표(교육원 자료: 1년 0 · 2년 7.516072988 · 10년 24.96785402 · 20년 32.48392701 · 30년 36.88054786 · 40년 40) — 소수 6자리까지
 *   ② 등급 경계(설계 · 시공 75 · 65 · 55 · 35 / 건설사업관리 80 · 70 · 60 · 40) — 경계 바로 위 · 아래
 *   ③ 자격 · 학력 · 대학원 가점(만점 20) · 교육(35시간 1점 · 정책 2점 · 상한) · 보정 계수 · 감점 · 다음 등급까지 경력 몇 년
 *   ④ 손셈 다섯 사람(따로 적은 셈과 같음)
 *   ⑤ 원문(법제처 고시 [별표 3] · 11-09 크롬으로 쪽마다 읽음) — 자격 «기타 10»(0점 칸 없음) · 산업안전지도사 30 · 이공계 다른 직무 15
 *      · 일한 분야가 다르면 초급까지(승급 없음) · 감점 3 · 2 · 1(최대 3 · 한 등급까지) · 교육 5점 이내
 */
import * as G from '../web/src/lib/등급셈.js'

let bad = 0, n = 0
const ok = (이름, c, got) => { n++; if (!c) bad++; console.log((c ? '  ✓ ' : '  ✗ ') + 이름 + (c || got === undefined ? '' : ' = ' + JSON.stringify(got).slice(0, 300))) }
const 같다 = (a, b, e = 1e-6) => Math.abs(a - b) < e

/* ① */
for (const [년, 점] of [[0, 0], [0.5, 0], [1, 0], [2, 7.516072988], [10, 24.96785402], [20, 32.48392701], [30, 36.88054786], [40, 40], [55, 40]]) {
  ok(`경력 ${년}년 → ${점}점`, 같다(G.경력점(년), 점), G.경력점(년))
}
ok('경력년(경력점(x)) = x (2 · 7.5 · 13 · 33.3년)', [2, 7.5, 13, 33.3].every((x) => 같다(G.경력년(G.경력점(x)), x, 1e-9)))

/* ② 경계 */
const 셈 = (o) => G.등급셈({ 갈래: 'sg', 자격: 'eng', 학력: 'ba', 대학원: '없음', 경력: [], 일반교육: 0, 정책교육: 0, 감점: 0, ...o })
const 년for = (점) => G.경력년(점)   /* 그 경력점이 되는 년수 */
for (const [목표, 이름] of [[75, '특급'], [65, '고급'], [55, '중급']]) {
  const 위 = 셈({ 경력: [{ 년: 년for(목표 - 50 + 0.001), 책임: 'g' }] })
  const 아래 = 셈({ 경력: [{ 년: 년for(목표 - 50 - 0.01), 책임: 'g' }] })
  ok(`설계 · 시공 ${목표}점 바로 위 → ${이름} · 바로 아래 → 한 등급 낮음`, 위.등급 === 이름 && 아래.등급 !== 이름, [위.합, 위.등급, 아래.합, 아래.등급])
}
ok('기사 · 학사 · 경력 없음 = 50 → 초급(35 이상)', 셈({}).합 === 50 && 셈({}).등급 === '초급', 셈({}))
const cm = G.등급셈({ 갈래: 'cm', 자격: 'eng', 학력: 'ba', 경력: [{ 년: 년for(10.01), 책임: 'cmres' }].map((c) => ({ ...c, 년: c.년 / 1.1 })) })
ok('건설사업관리 — 60점 넘으면 중급(설계 · 시공 경계와 다름)', cm.합 >= 60 && cm.합 < 70 && cm.등급 === '중급', cm)
ok('건설사업관리 39점 → 등급 밖(초급 40부터)', G.등급셈({ 갈래: 'cm', 자격: 'craft', 학력: 'hs', 경력: [] }).등급 === '등급 밖')

/* ③ */
ok('자격: 기술사 · 건축사 40 · 기사 · 기능장 · 산업안전지도사 30 · 산업기사 20 · 기능사 15 · 기타 10', ['pe', 'eng', 'ieng', 'craft', 'etc'].map((k) => 셈({ 자격: k }).자격).join() === '40,30,20,15,10'
   && /건축사/.test(G.자격들[0].이름) && /산업안전지도사/.test(G.자격들[1].이름))
ok('자격 — 0점 칸 없음(자격 없는 사람도 «기타 10») · 모르는 값도 10', !G.자격들.some((x) => x.점 === 0) && 셈({ 자격: 'none' }).자격 === 10 && /자격 없음/.test(G.자격들[G.자격들.length - 1].이름))
ok('학력: 학사 20 · 3년제 19 · 2년제 18 · 고교 15 · 이공계 다른 직무 15 · 지정과정 12 · 그 밖 10', ['ba', 'as3', 'as2', 'hs', 'sci', 'edu', 'etc'].map((k) => 셈({ 학력: k }).학력).join() === '20,19,18,15,15,12,10')
ok('대학원 가점 — 학사 + 박사도 20(만점) · 2년제 + 석사 19.5', 셈({ 학력: 'ba', 대학원: '박사' }).학력 === 20 && 셈({ 학력: 'as2', 대학원: '석사' }).학력 === 19.5)
ok('교육 — 34시간 0 · 35시간 1 · 정책 35시간 2 · 많이 들어도 상한', G.교육점(34) === 0 && G.교육점(35) === 1 && G.교육점(0, 35) === 2 && G.교육점(500, 500) === G.확인.교육상한)
ok('보정 계수 — 현장대리인 10년(설계 · 시공 ×1.3) = 13년', 셈({ 경력: [{ 년: 10, 책임: 'site' }] }).보정년 === 13)
ok('보정 계수 — 같은 10년도 건설사업관리 갈래에서는 ×1.04', G.등급셈({ 갈래: 'cm', 자격: 'eng', 학력: 'ba', 경력: [{ 년: 10, 책임: 'site' }] }).보정년 === 10.4)
ok('경력 여러 줄 더함(현장대리인 5 · 참여 3 → 9.5년)', 셈({ 경력: [{ 년: 5, 책임: 'site' }, { 년: 3, 책임: 'g' }] }).보정년 === 9.5)
ok('감점 빼기(3점)', 셈({ 감점: 3 }).합 === 47)
const 다 = 셈({ 경력: [{ 년: 3, 책임: 'g' }] })
const 더 = 셈({ 경력: [{ 년: 3 + 다.다음.경력더년, 책임: 'g' }] })
ok('다음 등급까지 경력 몇 년 — 그만큼 더하면 다음 등급', 다.다음 && 다.다음.등급 === '고급' && 더.등급 === '고급', [다, 더.합])

/* ④ 손셈 — 경력점 = log10(N)/log10(40)×40 */
const L = (x) => Math.log10(Math.max(1, x)) / Math.log10(40) * 40
const 사람 = [
  ['토목기사 · 4년제 · 현장 참여 3년', { 자격: 'eng', 학력: 'ba', 경력: [{ 년: 3, 책임: 'g' }] }, 30 + 20 + L(3), '중급'],
  ['건축기사 · 2년제 · 현장대리인 6년 · 교육 70시간', { 자격: 'eng', 학력: 'as2', 경력: [{ 년: 6, 책임: 'site' }], 일반교육: 70 }, 30 + 18 + L(7.8) + 2, '고급'],
  ['토목시공기술사 · 4년제 · 참여 8년', { 자격: 'pe', 학력: 'ba', 경력: [{ 년: 8, 책임: 'g' }] }, 40 + 20 + L(8), '특급'],
  ['산업기사 · 고교 · 참여 2년', { 자격: 'ieng', 학력: 'hs', 경력: [{ 년: 2, 책임: 'g' }] }, 20 + 15 + L(2), '초급'],
  ['자격 없음 · 비전공 · 참여 1년', { 자격: 'etc', 학력: 'etc', 경력: [{ 년: 1, 책임: 'g' }] }, 10 + 10 + 0, '등급 밖'],
]
for (const [이름, 입, 손, 등] of 사람) {
  const r = 셈(입)
  ok(`${이름} → ${Math.round(손 * 100) / 100}점 ${등}`, 같다(r.합, Math.round(손 * 100) / 100, 0.011) && r.등급 === 등, r)
}

/* ⑤ 원문 규칙 */
ok('원문 확인 표시 · 교육 상한 5(이수한 날부터 3년)', G.확인.원문 === true && G.확인.교육상한 === 5 && /^2026-11-/.test(G.확인.날))
const 특 = 셈({ 자격: 'pe', 경력: [{ 년: 8, 책임: 'g' }] })
const 특다 = 셈({ 자격: 'pe', 경력: [{ 년: 8, 책임: 'g' }], 다른분야: true })
ok('일한 분야가 다르면 — 같은 점수라도 초급까지 · «다음 등급» 없음(승급 없음)', 특.등급 === '특급' && 특다.등급 === '초급' && 특다.다음 === null && 특다.합 === 특.합, [특.등급, 특다.등급, 특다.다음])
const 밖다 = 셈({ 자격: 'etc', 학력: 'etc', 경력: [{ 년: 1, 책임: 'g' }], 다른분야: true })
ok('일한 분야가 달라도 35점 아래면 등급 밖 · 다음은 초급', 밖다.등급 === '등급 밖' && 밖다.다음 && 밖다.다음.등급 === '초급', 밖다)
const cm다 = G.등급셈({ 갈래: 'cm', 자격: 'etc', 학력: 'sci', 경력: [{ 년: 3, 책임: 'cmres' }], 다른분야: true })
ok('건설사업관리 다른 분야 — 40점 아래면 등급 밖(초급 경계 40)', cm다.합 < 40 && cm다.등급 === '등급 밖', cm다)
ok('감점 — 값은 0 ~ 3(9를 넣어도 3) · 고른 칸 넷', 셈({ 감점: 9 }).감점 === 3 && G.감점들.map((x) => x.k).join() === '0,1,2,3')
const 감전 = 셈({ 자격: 'pe', 경력: [{ 년: 년for(36.5 - 20 + 0), 책임: 'g' }] })
const 감후 = 셈({ 자격: 'pe', 경력: [{ 년: 년for(36.5 - 20 + 0), 책임: 'g' }], 감점: 3 })
ok('감점 3 — 76.5 특급 → 73.5 고급(한 등급)', 감전.등급 === '특급' && 감후.등급 === '고급' && Math.abs(감전.합 - 감후.합 - 3) < 0.011, [감전.합, 감전.등급, 감후.합, 감후.등급])

console.log(`\n${bad ? '❌' : '✅'} 시험_등급셈 ${n - bad}/${n}`)
process.exit(bad ? 1 : 0)
