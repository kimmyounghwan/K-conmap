import { 개찰자리, 분위of, 사정률분위, 실격률어림, 복기, 성향, 공고값 } from '../web/src/lib/개찰복기.js'
import { 내성적 } from '../web/src/lib/넣은금액.js'
import { limitAmount } from '../web/src/lib/bidmath.js'

let 통과 = 0, 실패 = 0
const 확인 = (이름, 참, 더 = '') => { if (참) { 통과++; console.log('  ✔', 이름) } else { 실패++; console.log('  ✘', 이름, typeof 더 === 'string' ? 더 : JSON.stringify(더)) } }
const p50 = 99.896
/* 참가 68곳 · A값 있음 · ±3% */
const r = { amt: 164986700, rate: 90.346, base: 181320000, aval: 10707640, ayn: 'Y', llr: 89.745, lo: -3, hi: 3, np: 68, enp: 67, pc: 0, amts: [164986700, 165198000, 165245000, 165339600, 165432000], nrank: 68, rq: [[1, 164986700], [2, 165198000], [3, 165245000], [5, 165432000], [10, 176068000]] }

/* 참가 2곳 — 1순위가 하한보다 꽤 위(1순위 자리가 넓음) */
const r2 = { amt: 146278000, rate: 93.913, base: 155615000, aval: 7277751, ayn: 'Y', llr: 89.745, lo: -3, hi: 3, np: 2, enp: 14, pc: 0, amts: [146278000, 146370000], nrank: 2, rq: [[1, 146278000], [2, 146370000]] }

console.log('① 분위')
{
  const v = 공고값(r)
  확인('σ(±3%) ≈ 0.768', Math.abs(v.sd - 0.7676) < 0.001, v.sd)
  const 자 = 개찰자리(r, p50)
  확인('사정률 = 예정 ÷ 기초', Math.abs(자.sj - (164986700 / 0.90346 / 181320000 * 100)) < 0.001, 자)
  /* 실제 사정률에서의 하한 금액 → 그 금액의 분위 = 사정률 분위(같은 뜻) */
  const 하한 = limitAmount(r.base, 자.sj, r.llr, r.aval, 0)
  const q하한 = 분위of({ base: r.base, llr: r.llr, A: r.aval, amt: 하한, p50, sd: v.sd })
  확인('하한 금액의 분위 = 사정률 분위(실격선)', Math.abs(q하한 - 사정률분위(자.sj, p50, v.sd)) < 0.2, [q하한, 자.실격선])
  확인('1순위 금액 분위 ≥ 실격선', 자.일순끝 >= 자.실격선, 자)
  확인('실격률어림 — 실측표와 같고 25 아래는 100−분위', Math.round(실격률어림(50)) === 50 && Math.round(실격률어림(95)) === 4 && Math.round(실격률어림(10)) === 90 && Math.abs(실격률어림(75) - 25.05) < 0.1, [실격률어림(50), 실격률어림(95), 실격률어림(10), 실격률어림(75)])
}

console.log('② 1순위 자리 = 내성적과 같은 판정')
{
  const 자 = 개찰자리(r, p50), v = 공고값(r)
  확인('참가 68곳 공고 — 1순위가 하한에 붙음(자리 폭 0.1분위 안)', 자.폭 < 0.1, 자)
  /* 참가 2곳 — 하한과 1순위 사이 금액 */
  const 자2 = 개찰자리(r2, p50), v2 = 공고값(r2)
  const 하한2 = limitAmount(r2.base, 자2.sj, r2.llr, r2.aval, 0)
  const 안 = Math.round((하한2 + r2.amt) / 2)
  const 성안 = 내성적(r2, 안, r2.amts)
  const q안 = 분위of({ base: r2.base, llr: r2.llr, A: r2.aval, amt: 안, p50, sd: v2.sd })
  확인('참가 2곳 — 하한과 1순위 사이 금액 → 내성적 1순위 · 분위가 1순위 자리 안', 성안.상태 === '일순' && q안 >= 자2.실격선 - 0.1 && q안 <= 자2.일순끝 + 0.1 && 자2.폭 > 1, [성안.상태, q안, 자2])
  const 위 = r.amt + 300000
  const 성위 = 내성적(r, 위, r.amts)
  확인('높은 금액 → 통과(밀림) · 분위가 1순위 자리보다 높음', 성위.상태 === '통과' && 분위of({ base: r.base, llr: r.llr, A: r.aval, amt: 위, p50, sd: v.sd }) > 자.일순끝, 성위.상태)
  const 아래 = limitAmount(r.base, 자.sj, r.llr, r.aval, 0) - 50000
  const 성아래 = 내성적(r, 아래, r.amts)
  확인('하한보다 낮은 금액 → 실격 · 분위가 실격선보다 낮음', 성아래.상태 === '실격' && 분위of({ base: r.base, llr: r.llr, A: r.aval, amt: 아래, p50, sd: v.sd }) < 자.실격선, 성아래.상태)
}

console.log('③ 복기 글')
{
  const 글들 = {}
  const 하한2 = limitAmount(r2.base, 개찰자리(r2, p50).sj, r2.llr, r2.aval, 0)
  for (const [이름, 금액, rr] of [['실격', limitAmount(r.base, 개찰자리(r, p50).sj, r.llr, r.aval, 0) - 50000, r], ['밀림', r.amt + 300000, r], ['일순', Math.round((하한2 + r2.amt) / 2), r2]]) {
    const 성 = 내성적(rr, 금액, rr.amts)
    const b = 복기(성, rr, 금액, p50, { med: 99.7, n: 8 })
    글들[이름] = b
    확인(`${이름} — 줄 넷(사정률 · 자리 · 참가 · 배움)`, b && b.줄들.map((x) => x.k).join(',') === '사정률,자리,참가,배움', b && b.줄들.map((x) => x.k))
    const 모두 = b.줄들.map((x) => x.글).join(' ')
    확인(`${이름} — «분위를 내리면 더 이긴다» 같은 말 없음 · 기관 평소 · 예상 참가 있음`, !/내리면 더 (이|딸)/.test(모두) && /이 기관 평소/.test(모두) && /예상 (67|14)곳/.test(모두), 모두.slice(0, 300))
    console.log('     ', 모두.slice(0, 260))
  }
  확인('실격 글에 «권장(75분위) 쪽으로»', /권장\(75분위\)/.test(글들.실격.줄들[3].글))
  확인('밀림 글에 «참가 수가 더 크게»', /참가 수가 더 크게/.test(글들.밀림.줄들[3].글))
  확인('일순 글에 «1순위 자리 안»', /1순위 자리 안/.test(글들.일순.줄들[3].글))
  확인('모름(하한율을 모름)이면 복기 없음', 복기({ 상태: '모름' }, r, 1, p50) === null)
  확인('예가범위 ±2% 는 σ 가 더 작음(같은 금액이라도 분위가 다름)', 공고값({ ...r, lo: -2, hi: 2 }).sd < 공고값(r).sd)
}

console.log('④ 성향')
{
  확인('3건 미만이면 없음', 성향([{ o: { s: '실격', q: 30 } }, { o: { s: '통과', q: 80 } }]) === null)
  const 낮 = 성향([{ o: { s: '실격', q: 30 } }, { o: { s: '실격', q: 35 } }, { o: { s: '통과', q: 40 } }, { o: { s: '일순', q: 38 } }, { o: { s: '모름' } }, { o: null }])
  확인('낮은 자리 — 평균 35.8 · 실격 2 · 일순 1 · 밀림 1 · 권장 쪽으로', 낮 && 낮.n === 4 && 낮.평균 === 35.8 && 낮.실격 === 2 && 낮.일순 === 1 && 낮.밀림 === 1 && /권장\(75분위\)/.test(낮.말), 낮)
  const 높 = 성향([{ o: { s: '통과', q: 92 } }, { o: { s: '통과', q: 90 } }, { o: { s: '통과', q: 95 } }])
  확인('높은 자리 — 참가가 적은 공고', 높 && /높은 자리/.test(높.말) && /참가가 적은 공고/.test(높.말), 높)
}

console.log(실패 ? `✘ ${실패} 틀림 · ${통과} 맞음` : `✔ 모두 맞음(${통과})`)
process.exit(실패 ? 1 : 0)
