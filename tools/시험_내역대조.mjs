let bad = 0
const ok = (이름, c, got) => { if (!c) bad++; console.log((c ? '  ✓ ' : '  ✗ ') + 이름 + (got !== undefined ? ' = ' + JSON.stringify(got) : '')) }
const 같다 = (a, b, t = 1e-6) => Math.abs(a - b) <= t
const 읽기 = (p) => { const b = fs.readFileSync(new URL(p, import.meta.url)); return 도면읽기(decodeBytes(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength))) }

console.log('① 이름으로 뜻')
ok('기호: WD1·AW-2·C1·MH-3 예, X1·D13·STA1·R300 아니오', ['WD1', 'AW-2', 'C1', 'MH-3'].every(기호인가) && !['X1', 'D13', 'STA1', 'R300', '2700'].some(기호인가))
ok('실 이름: 사무실·화장실·거실 예, 1층 평면도·실내재료마감표 아니오', ['사무실', '화장실', '거실'].every((s) => 실이름인가(s)) && !['1층평면도', '실내재료마감표', '2700'].some((s) => 실이름인가(s)))
ok('레이어: C-측구 → 측구(길이) · A-DIM → 주석 · PAVE-ASCON → 아스콘 포장(면적)', 레이어뜻('C-측구').품명 === '측구' && 레이어뜻('A-DIM').주석 && 레이어뜻('PAVE-ASCON').종 === '면적')
ok('블록: 집수정 → 집수정·빗물받이 · 방위표 → 주석', 블록뜻('집수정').품명 === '집수정·빗물받이' && 블록뜻('방위표').주석)
ok('단위: ton → kg×1000 · ㎡ → m2 · 개소 → 개', 단위풀기('ton').배 === 1000 && 단위풀기('㎡').무리 === 'm2' && 단위풀기('개소').무리 === '개')

console.log('② 도면 전부 (가상 예시 도면 둘)')
const 도면 = []
for (const [p, 이름] of [['../web/public/jeoksan/토목_예시.dxf', '토목_예시.dxf'], ['../web/public/jeoksan/마감_예시.dxf', '마감_예시.dxf']]) {
  const M = 읽기(p)
  const u = 단위배율(M.units, M.box)
  const 표들 = 자.표찾기(M)
  const 철 = 자.철근모으기(표들)
  const m = new Map(); for (const x of 철.줄) m.set(x.d, (m.get(x.d) || 0) + x.kg)
  for (const [d, kg] of m) 도면.push({ key: 이름 + ':철:' + d, 구분: '철근', 품명: '철근', 규격: d, 단위: 'kg', 수량: kg, 근거: '철근 재료표', 도면: 이름 })
  for (const x of 자.수량모으기(표들).줄) 도면.push({ key: 이름 + ':량:' + x.품명 + x.규격, 구분: '수량표', 품명: x.품명, 규격: x.규격, 단위: x.단위, 수량: x.수량, 근거: '수량표', 도면: 이름 })
  for (const g of 자.노선묶기(자.측점찾기(M))) {
    const s = 자.본측점고르기(g); const 네모 = 자.본네모짐작(M, s, g.점.filter((q) => Math.abs(q.x - s.x) < 3 * s.h))
    const 본 = 자.본만들기(M, s, 네모, g.점); const r = 자.평균단면(자.본읽기(M, 본, g.점), 본.칸)
    본.칸.forEach((c, j) => { if (c.쓰기) 도면.push({ key: 이름 + ':토:' + j, 구분: '토공', 품명: c.이름, 규격: '', 단위: c.단위 === 'm' ? 'm²' : 'm³', 수량: r.합[j], 근거: '평균단면', 도면: 이름 }) })
  }
  const R = 모두(M, { k: u.k, 표들 })
  for (const x of R.항목) if (x.켬) 도면.push({ ...x, key: 이름 + ':' + x.key, 도면: 이름 })
  if (이름 === '마감_예시.dxf') {
    ok('실 3개 (사무실 48 · 회의실 30 · 화장실 9 m²)', R.실.length === 3 && 같다(R.실.reduce((s, r) => s + r.면적, 0), 87), R.실.map((r) => r.이름 + ' ' + r.면적))
    ok('창호일람표 수량 = 평면 기호 수 (WD1 2 · WD2 1 · AW1 3 · AW2 1)', R.창호.every((w) => !w.다름) && R.창호.length === 4, R.창호.map((w) => w.기호 + ' ' + w.도면 + '/' + w.표수))
    const 벽 = R.항목.find((x) => x.품명 === '벽 마감 W2')
    ok('화장실 벽 W2 = 12×2.4 − WD2 0.8×2.1 − AW2 0.6×0.6 = 26.76', 벽 && 같다(벽.수량, 26.76), 벽 && 벽.수량)
    const 바 = R.항목.find((x) => x.품명 === '바닥 마감 F1')
    ok('바닥 F1 = 48 + 30 = 78', 바 && 같다(바.수량, 78))
  } else {
    ok('측구 레이어 160 m · 집수정 블록 4 · 가로등 3', 같다(R.항목.find((x) => x.품명 === '측구').수량, 160) && R.항목.find((x) => /집수정/.test(x.품명)).수량 === 4 && R.항목.find((x) => /가로등/.test(x.품명)).수량 === 3)
  }
}
ok('도면 물량 줄 (철근 3 · 수량표 4 · 토공 7 · 레이어 2 · 블록 2 · 창호 4 · 실 1 · 마감 7)', 도면.length === 30, 도면.length)

console.log('③ 내역 대조 (가상 내역서 24줄)')
const 내 = 내역읽기(fs.readFileSync(new URL('../web/public/jeoksan/내역_예시.xlsx', import.meta.url)), '내역_예시.xlsx')
ok('내역서 시트: 내역서 켬 · 일위대가 끔 · 24줄', 내.줄.length === 24 && 내.시트들.find((s) => s.시트 === '일위대가')?.켬 === false, 내.말)
const R = 대조(도면, 내.줄)
const 판 = (품명) => { const r = R.줄.find((x) => x.내역.품명 === 품명 && (x.내역.규격 || '') !== undefined); return r }
const 찾 = (품명, 규격 = '') => R.줄.find((x) => x.내역.품명 === 품명 && x.내역.규격 === 규격)
ok('이형철근 D13 0.049 ton ↔ 도면 48.755 kg → 같음', 찾('이형철근', 'SD400 D13').판정 === '같음' && 찾('이형철근', 'SD400 D13').도면.규격 === 'D13', [찾('이형철근', 'SD400 D13').도면수량, 찾('이형철근', 'SD400 D13').판정])
ok('이형철근 D16 0.075 → 도면 0.08112 → 도면이 많음 (+8.2%)', 찾('이형철근', 'SD400 D16').판정 === '도면이 많음' && 같다(찾('이형철근', 'SD400 D16').율, 8.16, 0.01), 찾('이형철근', 'SD400 D16').율)
ok('레미콘 18.4 = 수량표 18.4', 찾('레미콘', '25-24-150').판정 === '같음')
ok('합판거푸집 60 ↔ 거푸집 64.8 → 도면이 많음', 찾('합판거푸집', '3회').판정 === '도면이 많음' && 같다(찾('합판거푸집', '3회').차이, 4.8, 1e-9))
ok('PE 이중벽관 D300 ↔ 수량표(레이어 관로 64.6 이 아니라)', 찾('PE 이중벽관', 'D300').도면.구분 === '수량표')
ok('토사 깎기 589 = 토공 토사 589 · 노상 쌓기 150 ↔ 139 도면이 적음', 찾('토사 깎기').판정 === '같음' && 찾('노상 쌓기').판정 === '도면이 적음')
ok('L형 측구 150 ↔ 측구 레이어 160 · 빗물받이 4 = 집수정 블록 4 · 가로등 설치 4 ↔ 3', 찾('L형 측구').도면.품명 === '측구' && 찾('빗물받이').판정 === '같음' && 찾('가로등 설치').판정 === '도면이 적음')
ok('교통안전표지판 → 도면에서 못 찾음', 찾('교통안전표지판').판정 === '도면에서 못 찾음')
ok('마감: 바닥 F1 78 같음 · 벽 W1 130 ↔ 123.12 도면이 적음 · 창호 AW1 3 같음', 찾('바닥 마감(F1) 비닐타일').판정 === '같음' && 찾('벽 마감(W1) 수성페인트').판정 === '도면이 적음' && 찾('창호 AW1 알루미늄창', '1800×1500').판정 === '같음')
ok('셈: 같음 16 · 다름 7 · 못 찾음 1', R.셈.같음 === 16 && R.셈.다름 === 7 && R.셈.없음 === 1, R.셈)
ok('내역에 없는 도면 물량: 관로 레이어 · 실 면적 · F2·C2·W2 · WD2·AW2 …', R.남은도면.some((d) => d.품명 === '관로') && R.남은도면.some((d) => d.품명 === '바닥 마감 F2'), R.남은도면.map((d) => d.품명))
const R2 = 대조(도면, 내.줄, { [찾('교통안전표지판').내역.id]: 도면.find((d) => /가로등/.test(d.품명)).key })
ok('사람이 짝을 바꾸면 그 짝으로', R2.줄.find((x) => x.내역.품명 === '교통안전표지판').도면 !== null)
