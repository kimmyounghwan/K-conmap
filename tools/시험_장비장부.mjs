import { 줄금액, 청구액, 유류받음, 거래처현황, 기사현황, 달마다, 청구서, 한글돈, 달끝날, 예시장부, 원, 수 } from '../web/src/lib/장비장부.js'

let ok = 0, bad = 0
const eq = (got, want, what) => {
  const g = JSON.stringify(got), w = JSON.stringify(want)
  if (g === w) { ok++; console.log('  ✓', what) } else { bad++; console.log('  ✗', what, '— 나온 값', g, '· 바란 값', w) }
}

console.log('1) 한 줄')
eq(줄금액(7.5, 90000), 675000, '7.5시간 × 9만 = 67만5천')
eq(줄금액('8', '70,000'), 560000, '글자·쉼표도 숫자로')
eq(수('1,234.5원'), 1234.5, '수() — 쉼표·글자 빼기')
eq(원(1234567.4), '1,234,567', '원() — 반올림 · 쉼표')
eq(청구액({ amt: 100, oil: 30, ok: 'C' }), 130, '내가 청구하는 유류 → 임대료에 더함')
eq(청구액({ amt: 100, oil: 30, ok: 'G' }), 100, '원청이 대 준 유류 → 임대료에 안 더함')
eq(유류받음({ amt: 100, oil: 30, ok: 'G' }), 30, '원청이 대 준 유류 → 받은 돈으로 셈')
eq(유류받음({ amt: 100, oil: 30, ok: 'C' }), 0, '청구 유류는 받은 돈 아님')
eq([달끝날('2026-02'), 달끝날('2028-02'), 달끝날('2026-09')], ['2026-02-28', '2028-02-29', '2026-09-30'], '달 끝날(윤년)')

console.log('2) 거래처 · 기사 · 달마다')
const 자료 = {
  drivers: { d1: { n: '가기사', e: '굴삭기', u: 90000, ud: 600000 }, d2: { n: '나기사', e: '덤프', u: 60000 } },
  clients: { c1: { n: '가건설', s: '가현장' }, c2: { n: '나토건' }, c3: { n: '안쓴곳' } },
  rows: {
    r1: { d: '2026-08-05', dr: 'd1', cl: 'c1', q: 8, un: '시간', u: 90000, amt: 720000, oil: 100000, ok: 'G' },
    r2: { d: '2026-08-20', dr: 'd1', cl: 'c1', q: 1, un: '일', u: 600000, amt: 600000 },
    r3: { d: '2026-09-02', dr: 'd2', cl: 'c2', q: 5, un: '시간', u: 60000, amt: 300000, oil: 50000, ok: 'C' },
    r4: { d: '2026-09-03', dr: 'd1', cl: 'c1', q: 4, un: '시간', u: 90000, amt: 360000 },
    r5: { d: '2026-09-04', cl: 'gone', cn: '지운곳', q: 1, un: '회', u: 10000, amt: 10000 },
  },
  pay: { p1: { d: '2026-08-31', cl: 'c1', amt: 1000000, dr: 'd1' }, p2: { d: '2026-09-10', cl: 'c2', amt: 350000 } },
  cost: { k1: { d: '2026-08-15', t: '오일', amt: 200000, dr: 'd1' }, k2: { d: '2026-09-01', t: '타이어', amt: 50000 } },
}
const 거 = 거래처현황(자료)
const g1 = 거.줄.find((e) => e.id === 'c1')
eq([g1.임대, g1.유류, g1.수금, g1.받음, g1.미수], [1680000, 100000, 1000000, 1100000, 580000], '가건설 — 임대 168만 · 원청 유류 10만 · 수금 100만 → 미수 58만')
const g2 = 거.줄.find((e) => e.id === 'c2')
eq([g2.임대, g2.받음, g2.미수], [350000, 350000, 0], '나토건 — 청구 유류 5만까지 35만, 다 받음')
eq(거.줄.find((e) => e.id === 'gone').이름, '지운곳', '지운 거래처는 적어 둔 이름으로')
eq(!!거.줄.find((e) => e.id === 'c3'), true, '안 쓴 거래처도 줄은 있음(0원)')
eq(거.줄[0].id, 'c1', '미수 큰 곳이 위')
eq(거.합.미수, 590000, '합계 미수 59만(지운곳 1만 포함)')
eq(Math.round(g1.비율 * 1000), Math.round(1680000 / 2040000 * 1000), '비율 = 거래처 임대 ÷ 전체')
const 구 = 거래처현황(자료, { from: '2026-09-01', to: '2026-09-30' })
eq(구.줄.find((e) => e.id === 'c1').임대, 360000, '기간(9월)만')
const 기 = 기사현황(자료)
const k1 = 기.find((e) => e.id === 'd1')
eq([k1.시간, k1.일, k1.임대, k1.수금, k1.경비], [12, 1, 1680000, 1000000, 200000], '가기사 — 12시간 · 1일 · 임대 168만 · 수금 100만 · 경비 20만')
eq(기.find((e) => e.id === '-').경비, 50000, '기사 없는 경비는 «기사 없음» 줄')
const 달 = 달마다(자료)
eq(달.map((e) => e.ym), ['2026-08', '2026-09'], '달 차례(오래된 달부터)')
eq([달[0].임대, 달[0].받음, 달[0].경비, 달[0].남음], [1320000, 1100000, 200000, 1120000], '8월 — 임대 132만 · 받음 110만 · 경비 20만 · 남음 112만')

