  ok('«방범셔터설치» 는 실 이름이 아님', !실.some((r) => /방범|셔터/.test(r.이름)))
  ok('사무실 설계 면적 글 77.42 · 벽 중심 ±1 %', 사 && 사.도면면적 === 77.42 && 가까(사.중심면적, 77.42, 0.78), 사 && [사.도면면적, 사.중심면적])
