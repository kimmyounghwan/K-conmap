  const 층 = (e) => M.layers[M.E.ly[e]].name
  let 벽 = 0, 입면 = 0, 위생 = 0, 면적 = 0
  for (let e = 0; e < 막.length; e++) { if (!막[e]) continue; const n = 층(e); if (n === 'A-WALL') 벽++; if (n === 'ELE-8') 입면++; if (n === 'TOIL') 위생++; if (n === 'AREA') 면적++ }
  ok('벽 선은 막음 · 입면(ELE-8) · 위생기구 · 면적 선은 안 막음', 벽 > 20 && 입면 === 0 && 위생 === 0 && 면적 === 0, { 벽, 입면, 위생, 면적 })
  const 토 = 막는토막(M, 막)
