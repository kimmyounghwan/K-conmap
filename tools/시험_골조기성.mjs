/**
 * 📆 G463 골조 모델 기성 — 회차마다 끝난 칸(층 × 구간) → 기성 내역 · 엑셀 시트 (lib/골조모델.js 기성셈 · 기성시트)
 *   node tools/시험_골조기성.mjs   (가상 예시 모델 — 실제 현장 아님)
 */
import { 작업예시모델, 예시모델, 모델셈, 정돈, 구간물량, 구간몫, 기성칸물량, 기성회차더하기, 기성회차빼기, 기성칸바꾸기, 기성고치기, 기성셈, 기성시트, 기성상태, 모델시트 } from '../web/src/lib/골조모델.js'
import { ST } from '../web/src/lib/qtoxlsx.js'
import { 받기전검사 } from '../web/src/lib/받기전검사.js'

let bad = 0
const ok = (이름, c, got) => { if (!c) bad++; console.log((c ? '  ✓ ' : '  ✗ ') + 이름 + (got !== undefined && !c ? ' = ' + JSON.stringify(got).slice(0, 600) : '')) }
const 가까 = (a, b, t = 1e-6) => Number.isFinite(a) && Number.isFinite(b) && Math.abs(a - b) <= t
const 갈래 = ['콘크리트', '거푸집', '철근']

console.log('① 칸 물량 — 칸 합 + 자리 없음 = 모델 전체 · 구간물량과 같음')
let M = 작업예시모델()
const S = 모델셈(M)
const Q = 기성칸물량(M, S)
ok('칸 6개(FT · 1 · 2 층 × A팀 · B팀 — 예시는 구간 밖 부재 없음)', Q.칸.size === 6 && [...Q.칸.keys()].every((k) => /^(FT|1|2)\|z[12]$/.test(k)), [...Q.칸.keys()])
for (const k of 갈래) ok(k + ' — 칸 합 + 자리 없음 = 전체', 가까(Q.칸합[k] + Q.없음[k], S.합[k], 1e-6), [Q.칸합[k], Q.없음[k], S.합[k]])
const Z = 구간물량(M, S)
ok('구간물량(층별)과 칸 물량이 같음(A팀 1층 콘크리트)', 가까(Z.줄[0].층별.get('1').콘크리트, Q.칸.get('1|z1').합.콘크리트, 1e-9), [Z.줄[0].층별.get('1'), Q.칸.get('1|z1').합])
ok('구간몫 — 구간 네모 밖 부재는 0', [...S.G.기.values()].some((g) => 구간몫(g, M.구간[0]) === 0))

console.log('② 회차 · 칸 고르기')
M = 기성회차더하기(M, '2026-10-15')
ok('새 회차 1회(날짜 · 고른 회차)', M.기성.회차.length === 1 && M.기성.회차[0].날짜 === '2026-10-15' && M.기성.고른 === 1)
M = 기성칸바꾸기(M, 1, ['FT|z1', 'FT|z2'])
M = 기성회차더하기(M, '2026-10-30')
const 앞 = M
M = 기성칸바꾸기(M, 2, ['FT|z1'])
ok('앞 회차(1회)에 든 칸은 2회에서 눌러도 그대로', M === 앞)
M = 기성칸바꾸기(M, 2, ['1|z1', '1|z2'])
ok('2회 — 1층 두 칸', M.기성.회차[1].칸.join() === '1|z1,1|z2')
M = 기성칸바꾸기(M, 2, ['1|z2'])
ok('다시 누르면 뺌(1층 B팀)', M.기성.회차[1].칸.join() === '1|z1')
M = 기성칸바꾸기(M, 2, ['1|z1', '1|z2'])
ok('층 모두 — 하나라도 없으면 모두 넣음', M.기성.회차[1].칸.sort().join() === '1|z1,1|z2')
ok('상태 — FT = 1회 · 1층 = 2회', 기성상태(M).get('FT|z1') === 1 && 기성상태(M).get('1|z2') === 2 && !기성상태(M).has('2|z1'))

console.log('③ 기성 내역 — 금회 · 전회 · 누계 · 잔여')
const B = 기성셈(M, S)
const 칸합 = (keys, k) => keys.reduce((a, x) => a + Q.칸.get(x).합[k], 0)
for (const k of 갈래) {
  const 배 = k === '철근' ? 0.001 : 1
  const h = B.합[k]
  ok(k + ' 금회 = 1층 칸 합 · 전회 = FT 칸 합 · 누계 = 전회 + 금회', 가까(h.금회, 칸합(['1|z1', '1|z2'], k) * 배, 1e-6) && 가까(h.전회, 칸합(['FT|z1', 'FT|z2'], k) * 배, 1e-6) && 가까(h.누계, h.전회 + h.금회, 1e-9), h)
  ok(k + ' 잔여 = 전체 − 누계 · 전체 = 모델 합', 가까(h.잔여, h.전체 - h.누계, 1e-6) && 가까(h.전체, S.합[k] * 배, 1e-6), h)
}
ok('1회를 고르면 — 금회 = FT · 전회 0', 가까(기성셈(M, S, 1).합.콘크리트.금회, 칸합(['FT|z1', 'FT|z2'], '콘크리트'), 1e-6) && 기성셈(M, S, 1).합.콘크리트.전회 === 0)
ok('철근 «자리 없음»(보강 덧줄 — 칸에 안 듦) 줄', B.줄.some((r) => r.갈래 === '철근' && r.자리없음 && 가까(r.전체, Q.없음.철근 / 1000, 1e-9)))

console.log('④ 단가 · 금액 · 갈래 고르기')
M = 기성고치기(M, { 단가: { 콘크리트: 90000, 거푸집: 25000, 철근: 1200000 } })
const B2 = 기성셈(M, S)
ok('줄 금액 = 수량 × 단가(원 미만 버림)', B2.줄.filter((r) => !r.자리없음).every((r) => r.금회금액 === Math.floor(r.금회 * r.단가 + 1e-6) && r.누계금액 === Math.floor(r.누계 * r.단가 + 1e-6)))
ok('합계 금액 = 줄 금액 합', B2.금액.금회 === B2.줄.reduce((a, r) => a + r.금회금액, 0) && B2.금액.누계 === B2.줄.reduce((a, r) => a + r.누계금액, 0))
const M거 = 기성고치기(M, { 갈래: ['거푸집'] })
const B3 = 기성셈(M거, S)
ok('거푸집만 고르면 거푸집 줄만(형틀팀 기성)', B3.줄.length > 0 && B3.줄.every((r) => r.갈래 === '거푸집') && Object.keys(B3.합).join() === '거푸집')

console.log('⑤ 정돈(저장 · 파일) · 회차 빼기')
const M2 = 정돈(JSON.parse(JSON.stringify(M)))
ok('저장했다 열어도 기성 그대로', JSON.stringify(M2.기성) === JSON.stringify(M.기성), M2.기성)
const M3 = 정돈(JSON.parse(JSON.stringify(기성고치기(작업예시모델(), { 갈래: ['철근'] }))))
ok('회차 없이 갈래만 바꿔도 남음', M3.기성 && M3.기성.갈래.join() === '철근', M3.기성)
ok('기본 그대로면 기성 칸 없음(예전 모델 그대로)', !정돈(작업예시모델()).기성)
const M4 = 기성회차빼기(M)
ok('끝 회차 빼기 — 1회만 남고 고른 = 1', M4.기성.회차.length === 1 && M4.기성.고른 === 1)

console.log('⑥ 엑셀 시트 · 받기 전 검사')
const 시 = 기성시트(M, S, ST)
ok('시트 셋 — 기성내역(2회) · 기성칸(층×구간) · 기성회차', 시.map((x) => x.name).join() === '기성내역(2회),기성칸(층×구간),기성회차', 시.map((x) => x.name))
const 모 = 모델시트(M, S, ST)
ok('모델 엑셀에도 기성 시트(모델 시트 앞)', 모.findIndex((x) => /^기성내역/.test(x.name)) >= 0 && 모.findIndex((x) => /^기성내역/.test(x.name)) < 모.findIndex((x) => x.name === '모델'))
const 검 = 받기전검사(시, [{ 이름: '금회 금액', 시트: /^기성내역/, 줄: '합계', 열: '금회 금액(원)', 값: B2.금액.금회, 오차: 1 }, { 이름: '칸 콘크리트', 시트: /^기성칸/, 줄: '합계', 열: '콘크리트(㎥)', 값: Q.칸합.콘크리트, 오차: 0.02 }])
ok('받기 전 검사 통과(합계 = 위 줄 합 · 화면 값 = 엑셀)', 검.통과, 검.줄.filter((x) => !x.됨))
ok('회차가 없으면 기성 시트 없음', 기성시트(작업예시모델(), S, ST).length === 0)

console.log('⑦ 구간 없는 모델 — 층 전체가 한 칸')
const E = 예시모델()
const SE = 모델셈(E)
const QE = 기성칸물량(E, SE)
ok('칸 = 층마다 «밖»(층 전체)', [...QE.칸.keys()].every((k) => /\|밖$/.test(k)) && [...QE.칸.values()].every((c) => c.구간이름 === '층 전체'), [...QE.칸.keys()])
let E2 = 기성칸바꾸기(기성회차더하기(E, '2026-10-30'), 1, [...QE.칸.keys()])
ok('모두 고르면 누계 = 전체(자리 없음 빼고) · 진도 100 %', 가까(기성셈(E2, SE).합.콘크리트.누계, QE.칸합.콘크리트, 1e-6) && 가까(기성셈(E2, SE).줄.filter((r) => r.갈래 === '콘크리트' && !r.자리없음).reduce((a, r) => a + r.율, 0) / 기성셈(E2, SE).줄.filter((r) => r.갈래 === '콘크리트' && !r.자리없음).length, 1, 1e-9))

console.log(bad ? `\n✗ ${bad}건 틀림` : '\n✓ 모두 맞음')
process.exit(bad ? 1 : 0)
