/**
 * 🧭 블록 옹벽 단면 시험 (G251 — 2026-10-12)
 *   node tools/시험_블록옹벽.mjs
 * 소장님 현장 E 1호 배수로: 공장 제품 블록(«제품» 층)과 그 뒤 뒷채움 잡석 띠를 콘크리트로 세어 1,043 m 에 4,229 ㎥(내역 배수로 호안 무근 895 ㎥).
 *   지어낸 단면 — 터파기(사다리꼴) 왼쪽에 블록 10단(«제품» 층) · 그 뒤 0.3 m 뒷채움 띠 · 블록 밑 기초 콘크리트 0.8 × 0.5 (모두 «0» 층 선)
 *   → 콘크리트 = 기초 0.4 ㎡ 만 · 블록 · 뒷채움은 콘크리트 아님 · «블럭기초» 층은 콘크리트
 */
import { 단면면적 } from '../web/src/lib/토공3d.js'

let bad = 0
const ok = (이름, c, got) => { if (!c) bad++; console.log((c ? '  ✓ ' : '  ✗ ') + 이름 + (got !== undefined ? ' = ' + JSON.stringify(got) : '')) }
const 네모 = (x0, y0, x1, y1) => [[x0, y0, x1, y0], [x1, y0, x1, y1], [x1, y1, x0, y1], [x0, y1, x0, y0]]

function 단면(블록층, 기초층) {
  const 조각 = new Map()
  조각.set('GROUND', [[-12, 0, 12, 0]])
  const 영 = []
  /* 터파기 사다리꼴 */
  영.push([-6, 0, -4, -3.5], [-4, -3.5, 4, -3.5], [4, -3.5, 6, 0])
  /* 뒷채움 띠(블록 뒤 0.3 m · 기초 위 ~ 지반) — 블록 뒷면 선 x = -3.5 ~ -2.3(기울기) · 바깥 선 0.3 m 뒤 */
  영.push([-3.5, -3.0, -2.3, 0], [-3.8, -3.0, -2.6, 0], [-3.8, -3.0, -3.5, -3.0])
  조각.set('0', 영)
  /* 기초 0.8 × 0.5 (블록 밑) */
  조각.set(기초층, 네모(-3.6, -3.5, -2.8, -3.0))
  /* 블록 10단 — 0.5 × 0.3, 한 단마다 0.12 m 씩 뒤로 */
  const 블 = []
  for (let n = 0; n < 10; n++) { const x0 = -3.45 + n * 0.12, y0 = -3.0 + n * 0.3; 블.push(...네모(x0, y0, x0 + 0.5, y0 + 0.3)) }
  조각.set(블록층, 블)
  return 단면면적(조각, (ly) => ly === 'GROUND', (y) => y, 1, 0)
}

console.log('■ 블록 옹벽 단면')
{
  const a = 단면('제품', '블럭기초')
  ok('콘크리트 = 기초 0.8 × 0.5 = 0.4 ㎡ (블록 · 뒷채움 띠는 콘크리트 아님)', !!a && Math.abs(a.콘크리트 - 0.4) < 0.05, a && +a.콘크리트.toFixed(3))
  ok('거푸집 = 기초 옆면 정도(블록 · 뒷채움 테두리 아님) — 2 m 아래', !!a && a.거푸집 < 2, a && +a.거푸집.toFixed(2))
  ok('구조물(흙 대신) 에는 블록도 듦 — 콘크리트보다 큼', !!a && a.구조물 > a.콘크리트 + 1, a && +a.구조물.toFixed(2))
  const b = 단면('콘크리트벽', '블럭기초')
  ok('같은 모양을 «콘크리트벽» 층으로 그리면 블록 단도 콘크리트(예전 그대로)', !!b && b.콘크리트 > 1.2, b && +b.콘크리트.toFixed(3))
}
console.log(bad ? `✗ ${bad} 곳 틀림` : '✓ 모두 통과')
process.exit(bad ? 1 : 0)
