/**
 * 🧪 G808 «🏛 종심제 계산» 카드 셈 — lib/종심고르기.js (node · 파이썬 종심예측.py 와 대 봄 · 인터넷 안 씀)
 *   ① 금액대 · 기관 첫 낱말 · 묶음 열쇠 = 종심예측.py(같은 줄 다섯으로 대 봄)
 *   ② 묶음고르기 — 표본 넉넉한 가장 좁은 묶음 · 표본 적음은 건너뜀 · 없으면 전체 · 자료 없으면 null
 *   ③ 점수보기 — 가운데(50분위) · 끝(10 · 90분위 중 낮은 쪽) · 기대(열아홉 점 평균) = 종심가격점수 손셈 · 예정 어림(y50)
 *   ④ 세줄 — 가운데 = 기대 점수 가장 높은 금액(촘촘히 다시 찾아도 더 높은 곳 없음) · 낮게 ≤ 가운데 ≤ 높게 · 천 원 아래 버림
 *   ⑤ 순공사하한(제13조③ — 예정 100억 미만만) · 동점글(88%)
 *   돌리기: node tools/시험_종심고르기.mjs
 */
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { 금액대, 기관첫, 묶음열쇠들, 묶음고르기, 점수보기, 세줄, 예정어림, 순공사하한, 동점글, 점들 } from '../web/src/lib/종심고르기.js'
import { 종심가격점수 } from '../web/src/lib/종심셈.js'

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
let n = 0, bad = 0
const ok = (이름, c, got) => { n++; if (!c) bad++; console.log((c ? '  ✓ ' : '  ✗ ') + 이름 + (c || got === undefined ? '' : ' = ' + JSON.stringify(got).slice(0, 400))) }

console.log('① 파이썬(종심예측.py)과 같은 열쇠')
const 보기줄 = [
  ['간이형', '조달청 가상지방조달청', 15e9, '토목공사업'], ['일반', '가상공단 본사', 35e9, '건축공사업'], ['지방종평', '가상도', 70e9, ''],
  ['고난도', '', 120e9, '토목건축공사업'], ['종심', '가상시청', 0, '전기공사업'],
]
const py = JSON.parse(execFileSync('python3', ['-c', `
import sys, json
sys.path.insert(0, ${JSON.stringify(ROOT)})
import 종심예측 as P
rows = ${JSON.stringify(보기줄)}
out = []
for k, i, e, m in rows:
    r = {"kind": k, "inst": P.기관(i), "band": P.금액대(e), "main": m}
    out.append([P.열쇠글(t) for t in P.열쇠들(r)])
print(json.dumps(out, ensure_ascii=False))
`], { encoding: 'utf8' }))
const js = 보기줄.map(([k, i, e, m]) => 묶음열쇠들(k, i, e, m))
ok('묶음 열쇠 다섯 줄 = 파이썬', JSON.stringify(js) === JSON.stringify(py), { js, py })
ok('금액대 · 기관 첫 낱말', 금액대(15e9) === 0 && 금액대(3e10) === 1 && 금액대(7e10) === 2 && 금액대(2e11) === 3 && 금액대(0) === -1 && 기관첫('조달청 가상') === '조달청' && 기관첫('') === '')

console.log('② 묶음고르기')
const d = (중) => 점들.map((p) => +(중 - 2 + (p / 100) * 4).toFixed(3))      // 가운데 ± 2%p 고르게
const 통 = (중, n_, 적음 = false) => ({ n: n_, q10: +(중 - 1.6).toFixed(3), q50: 중, q90: +(중 + 1.6).toFixed(3), y50: 100.3, d: d(중), 표본적음: 적음 })
const 판 = { 보임: true, 묶음: { '전체': 통(87, 300), '간이형': 통(87.5, 200), '간이형|조달청': 통(87.8, 120), '간이형|조달청|0': 통(88, 60), '간이형|조달청|0|토목공사업': 통(88.2, 12, true) } }
const g1 = 묶음고르기(판, '간이형', '조달청 가상지방조달청', 15e9, '토목공사업')
ok('토목 묶음은 표본 적음 → 건너뛰고 간이형|조달청|0', g1 && g1.열쇠 === '간이형|조달청|0' && g1.q50 === 88, g1)
const g2 = 묶음고르기(판, '일반', '가상공단', 35e9, '건축공사업')
ok('🩹 G809 갈래 자료 없음(일반) → null(전체로 안 넓힘)', g2 === null, g2)
const 판2 = { ...판, 묶음: { ...판.묶음, '지방종평': 통(93.5, 6, true) } }
const g3 = 묶음고르기(판2, '지방종평', '가상시', 7e10, '')
ok('갈래 표본 적음(지방종평 6건) → 그 갈래 · 표본적음(예상 안 냄)', g3 && g3.열쇠 === '지방종평' && g3.표본적음 === true && g3.n === 6, g3)
ok('자료 없음 · 묶음 빔 → null', 묶음고르기(null, '간이형') === null && 묶음고르기({ 묶음: {} }, '간이형') === null)

console.log('③ 점수보기')
const base = 12_000_000_000
const t = 통(88, 100)
const T = 10_550_000_000
const s = 점수보기(T, t, base, 60)
const Y = Math.floor(base * 100.3 / 100)
const 손 = (p) => 종심가격점수(T, Math.floor(base * p / 100), Y, 60)
const 손기대 = Math.round((t.d.reduce((a, p) => a + 손(p), 0) / t.d.length) * 1000) / 1000
ok('예정 어림 = 기초 × 100.3%', 예정어림(t, base) === Y && s.예정 === Y, [예정어림(t, base), Y])
ok('가운데 · 끝 · 기대 = 종심가격점수 손셈', s.가운데 === 손(88) && s.최저 === Math.min(손(86.4), 손(89.6)) && s.기대 === 손기대, [s, 손(88), 손기대])
ok('율 = 금액 ÷ 기초 × 100', Math.abs(s.율 - (T * 100) / base) < 1e-9)
ok('금액 · 기초 없음 → null', 점수보기(0, t, base, 60) === null && 점수보기(T, t, 0, 60) === null && 점수보기(T, null, base, 60) === null)

console.log('④ 세줄')
const 줄 = 세줄(t, base, 60)
const 가 = 줄.find((x) => x.이름 === '가운데'), 낮 = 줄.find((x) => x.이름 === '조금 낮게'), 높 = 줄.find((x) => x.이름 === '조금 높게')
ok('세 줄 · 낮게 < 가운데 < 높게 · 천 원 아래 버림', 줄.length === 3 && 낮.T < 가.T && 가.T < 높.T && [낮, 가, 높].every((x) => x.T % 1000 === 0), 줄.map((x) => [x.이름, x.T]))
let 더 = 0
for (let p = 84; p <= 92; p += 0.001) { const v = 점수보기(Math.floor(base * p / 100 / 1000) * 1000, t, base, 60); if (v.기대 > 가.기대 + 1e-9) 더++ }
ok('가운데 = 기대 점수가 가장 높은 금액(0.001%p 로 다시 찾아도 더 높은 곳 없음)', 더 === 0, 더)
ok('가운데 기대 ≥ 낮게 · 높게 기대 · 점수 0 ~ 60', 가.기대 >= 낮.기대 && 가.기대 >= 높.기대 && 줄.every((x) => x.기대 > 0 && x.기대 <= 60), 줄.map((x) => x.기대))
ok('자료 없음 → 빈 줄', 세줄(null, base, 60).length === 0 && 세줄(t, 0, 60).length === 0)

console.log('⑤ 순공사하한 · 동점글')
ok('예정 100억 미만 — ⌈⌈순공사원가 × 예정 ÷ 기초⌉ × 0.98⌉', 순공사하한(8_000_000_000, 9_900_000_000, 10_000_000_000) === Math.ceil(Math.ceil(8_000_000_000 * 9_900_000_000 / 10_000_000_000) * 0.98))
ok('예정 100억 이상 · 순공사원가 모름 → 0', 순공사하한(8e9, 1e10, 1e10) === 0 && 순공사하한(0, 9e9, 1e10) === 0)
ok('동점글(예규 제13조②) — 균형 ÷ 예정 88% 이상이면 «입찰금액이 낮은 쪽» · 아니면 «균형가격에 더 가까운 쪽» · 앞 차례(수행능력 + 사회적책임) 함께', /입찰금액이 낮은 쪽/.test(동점글({ q50: 88.5, y50: 100 })) && /균형가격에 더 가까운 쪽/.test(동점글({ q50: 87, y50: 100 })) && /공사수행능력 \+ 사회적책임/.test(동점글({ q50: 87, y50: 100 })) && 동점글(null) === '')

console.log(`\n${bad ? '✗' : '✓'} 시험_종심고르기 ${n - bad}/${n}`)
if (bad) process.exit(1)
