def _rw(p, cells, h=None):
    """신고서 줄 — «둘째 이름표 칸이 하나» 인 22칸으로 적은 줄을 23칸(둘째 칸이 1.6 · 3.8 둘)으로 옮겨 적음.
    둘째 칸(2)을 덮는 칸은 한 칸 더 넓힘(합 너비 그대로) · 온 줄(PC1)은 그대로 · 세로 병합으로 찬 칸은 건너뜀(fb.row 와 같게)."""
    r, c, out = p.r, 1, []
    for spec in cells:
        span = spec[0]
        while (r, c) in p.occ:
            c += 1
        if span < PC1 and ((c == 1 and span >= 2) or c == 2):
            span += 1
        out.append((span,) + tuple(spec[1:]))
        c += span
    return p.row(out, h=h)


