def _n(v):
    return v if isinstance(v, (int, float)) and not isinstance(v, bool) else 0


def _len(v):
    return 0 if v is None or v == "" else len(str(v))


def _rd10(x):
    """엑셀 ROUNDDOWN(x,-1) — 0 쪽으로 10원 미만 버림"""
    import math
    return math.floor(x / 10 + 1e-9) * 10 if x >= 0 else -math.floor(-x / 10 + 1e-9) * 10


def _ymd(d):
    return f"{d.year}. {d.month}. {d.day}."


