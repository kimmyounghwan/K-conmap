    today = datetime.date.today()
    if endd == "":
        h["기한"] = ""
    elif endd < today:
        h["기한"] = f"⚠ 존치기간이 {_ymd(endd)} 에 끝났습니다 — 철거하거나 바로 구청 건축과에 문의"
    elif endd - datetime.timedelta(days=7) < today:
        h["기한"] = "⚠ 연장신고 기한(만료 7일 전)이 지났습니다 — 바로 구청 건축과에 문의"
    else:
        h["기한"] = f"존치기간 끝 {_ymd(endd)} — 오늘부터 {(endd - today).days:,}일 남음 · 늘려야 하면 만료 7일 전까지 연장신고"
    return {"판정": a, "신고서": b, "신고안내": c, "배치도": {}, "대지사용승낙서": s, "확인": h}
