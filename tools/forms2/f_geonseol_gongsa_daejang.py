def _isnum(v):
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def _n(v):
    return v if _isnum(v) else 0


def _d(v):
    if isinstance(v, datetime.datetime):
        return v.date()
    return v if isinstance(v, datetime.date) else None


def _ymd(d):
    return f"{d.year}. {d.month}. {d.day}."


def _y(d):
    return YOIL[(d.weekday() + 1) % 7]


def _shift(d):
    return d + datetime.timedelta(days=2 if d.weekday() == 5 else 1 if d.weekday() == 6 else 0)


def _rd2(x):
    """엑셀 TEXT(ROUNDDOWN(x,2),"0.00")"""
    q = Decimal(repr(x)).quantize(Decimal("0.01"), rounding=ROUND_DOWN)
    return f"{q:.2f}"


def _won(v):
    return f"{int(Decimal(repr(v)).quantize(Decimal('1'), rounding=ROUND_HALF_UP)):,}"


def _rate(dgt):
    return 50 if dgt < 300000000 else 30 if dgt < 1000000000 else 20 if dgt < 3000000000 else 10


def expect(pages):
    a_in, b1, b2 = pages["셈"], pages["1쪽"], pages["2쪽"]
    a, o1, o2 = {}, {}, {}
    T = datetime.timedelta
    dgt = _n(b1.get("계약금액"))
    gyd = _d(b1.get("계약일"))
    if dgt == 0:
        a["통보"] = "" if (not a_in.get("공사유형") and not a_in.get("도급방법")) else TB_NEED
    else:
        a["통보"] = TB_Y if dgt >= 100000000 else TB_N
    if dgt < 100000000:
        a["기한"] = ""
    elif not gyd:
        a["기한"] = GH_NEED
    else:
        due = _shift(gyd + T(days=30))
        a["기한"] = f"{GH_A}{_ymd(gyd)}{GH_B}{_ymd(due)}({_y(due)}){GH_C}"
    tot, jno, exr = _n(b1.get("총노무비#1")), _n(b1.get("직접노무비#1")), b1.get("예외사유#1")
    if dgt == 0:
        a["직접"] = ""
    elif dgt >= 7000000000:
        a["직접"] = JS_NO
    else:
        rt = _rate(dgt)
        s = f"{JS_A}{_won(dgt)}{JS_B}{rt}{JS_C}"
        if exr not in (None, ""):
            s += JS_EX
        elif tot == 0 or jno == 0:
            s += JS_NEED
        elif jno * 100 >= rt * tot:
            s += JS_OK + _rd2(jno * 100 / tot) + "%"
        else:
            s += JS_LOW + _rd2(jno * 100 / tot) + JS_LOW2
        a["직접"] = s
    dgm = a_in.get("도급방법")
    up = sum(_n(b1.get(f"업체금액#{j}")) for j in (1, 2, 3))
    if not dgm or dgt == 0:
        a["업체합"] = ""
    elif dgm == DG[0]:
        a["업체합"] = GD_ONE
    elif up == dgt:
        a["업체합"] = GD_OK
    else:
        a["업체합"] = f"{GD_DIFF_A}{_won(up)}{GD_DIFF_B}"
    for s in (1, 2):
        pa, pb = _n(b2.get(f"하도부분금액#{s}")), _n(b2.get(f"하도계약금액#{s}"))
        nm = b2.get(f"하도상호#{s}") or ""
        if pa == 0 or pb == 0:
            a[f"하도확인#{s}"] = ""
            o2[f"하도급률#{s}"] = "%"
        else:
            r = _rd2(pb * 100 / pa)
            a[f"하도확인#{s}"] = f"{HR_A}{nm} {r}" + (HR_OK if pb * 100 >= HR_MIN * pa else HR_LOW)
            o2[f"하도급률#{s}"] = f"{r}%"
        cd = _d(b2.get(f"체결일#{s}"))
        if not cd:
            a[f"하도기한#{s}"] = ""
        else:
            hd = _shift(cd + T(days=30))
            a[f"하도기한#{s}"] = f"{nm}{HG_A}{_ymd(cd)}{HG_B}{_ymd(hd)}({_y(hd)}){HG_C}"
    for k in range(1, 5):
        rd, jd = _d(b2.get(f"수령일#{k}")), _d(b2.get(f"지급일#{k}"))
        if not (rd and jd):
            a[f"지급#{k}"] = ""
            continue
        base = rd
        if k == 1:
            c1 = _d(b2.get("체결일#1"))
            if c1 and c1 > rd:
                base = c1
        dd = _shift(base + T(days=15))
        lab = f"{k}. {GUBUN2[k - 1]}" + (JG_A1 if k == 1 else JG_A)
        a[f"지급#{k}"] = f"{lab}{_ymd(base)}{JG_B}{_ymd(dd)}({_y(dd)}){JG_C}{_ymd(jd)}" + (JG_OK if jd <= dd else JG_LATE)
    srs, sjs = 0, 0
    for k in range(1, 5):
        su = sum(_n(b2.get(f"{n}#{k}")) for n in ("현금", "어음", "기타"))
        sj = sum(_n(b2.get(f"{n}#{k}")) for n in ("지현금", "지어음", "지기타"))
        o2[f"수령계#{k}"] = su if su else ""
        o2[f"지급계#{k}"] = sj if sj else ""
        srs += su
        sjs += sj
    a["대금"] = "" if (srs == 0 and sjs == 0) else f"{DG_TOT_A}{_won(srs)}{DG_TOT_B}{_won(sjs)}원"
    if not b1.get("공사명") and dgt == 0 and not dgm:
        a["빈칸"] = ""
    else:
        miss = [n for n, fn in BIN_PY if fn(a_in, b1)]
        a["빈칸"] = BIN_OK if not miss else (BIN_A + " · ".join(miss))[:len(BIN_A) + 300]
    o1["유형표시"] = _box_py(a_in.get("공사유형"), YH, "    ")
    o1["발주표시"] = _box_py(a_in.get("발주구분"), BJ, "  ")
    o1["공제표시"] = _box_py(a_in.get("공제가입"), GJ, "  ")
    o1["도급표시"] = (("[√] " if dgm == DG[0] else "[   ] ") + "단독도급  " + ("[√] " if (dgm or "")[:4] == "공동도급" else "[   ] ") + "공동도급("
                     + "  ".join(("[√] " if dgm == x else "[   ] ") + x[7:] for x in DG[1:]) + ")")
    o1["성질표시"] = _box_py(a_in.get("계약성질"), GS, "  ")
    o1["입찰표시"] = _box_py(a_in.get("입찰방법"), IB, "  ")
    o1["계약표시"] = _box_py(a_in.get("계약방법"), GB, "  ")
    return {"셈": a, "1쪽": o1, "2쪽": o2}


