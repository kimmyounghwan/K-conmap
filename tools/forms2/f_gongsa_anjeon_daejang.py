def _n(v):
    return v if isinstance(v, (int, float)) and not isinstance(v, bool) else 0


def _ymd(d):
    return f"{d.year}. {d.month}. {d.day}."


def _edate(d, m):
    """엑셀 EDATE — 달을 더하고 말일은 그 달 끝으로"""
    import calendar
    y, mo = divmod(d.month - 1 + m, 12)
    y += d.year
    mo += 1
    return D(y, mo, min(d.day, calendar.monthrange(y, mo)[1]))


def _won(v):
    if v < 100000000:
        return ""
    e, man = int(v // 100000000), int(v // 10000) % 10000
    return f"{e:,}억" + (f" {man:,}만" if man > 0 else "") + " 원"


def expect(pages):
    pj, gy, hw = pages["판정"], pages["사업개요"], pages["확인"]
    a = {}
    tot, sep, ind, bun = pj.get("총공사금액"), pj.get("나뉜총액"), pj.get("개별금액"), pj.get("분리발주")
    a["총금액말"] = _won(tot) if _n(tot) else ""
    a["나뉜말"] = "개별 금액으로 봄(고시 제3조 ②)" if sep == "예" else ""
    if not _n(tot) and not _n(ind):
        r = ""
    else:
        if sep == "예":
            r = "⚠ 개별 공사금액을 적으세요" if not _n(ind) else ("✓ 작성 대상 — 개별 공사금액 50억 원 이상(고시 제3조 ②)" if ind >= 5000000000 else "대상 아님 — 개별 공사금액 50억 원 미만(고시 제3조 ②)")
        else:
            r = "⚠ 총공사금액을 적으세요" if not _n(tot) else ("✓ 작성 대상 — 총공사금액 50억 원 이상(시행령 제55조)" if tot >= 5000000000 else "대상 아님 — 총공사금액 50억 원 미만(시행령 제55조)")
        r += " · 나눈 공사마다 각각 씀(통합해 써도 됨 · 고시 제4조)" if bun == "예" else ""
    a["대상판정"] = r
    st, en = pj.get("착공일"), pj.get("준공일")
    if not st:
        a["제출기한"] = ""
    elif en and en < st:
        a["제출기한"] = "⚠ 준공이 착공보다 앞섭니다"
    else:
        dd = st - datetime.timedelta(days=1)
        a["제출기한"] = f"착공 전날 {_ymd(dd)}({'월화수목금토일'[dd.weekday()]})까지 발주자에게 제출"
    days = []
    for k in range(1, N_CHK + 1):
        if not st:
            v, msg = "", ""
        else:
            prev, day = _edate(st, 3 * (k - 1)), _edate(st, 3 * k)
            if en and prev >= en:
                v = ""
            elif en and day > en:
                v = en
            else:
                v = day
            if not v:
                msg = ""
            elif en and v == en and day > en:
                msg = "3개월 안에 끝남 — 준공 전에 확인" if k == 1 else "준공 전에 마지막 확인"
            else:
                msg = f"착공 뒤 {3 * k}개월 되는 날"
        a[f"확인날#{k}"] = v
        a[f"확인말#{k}"] = msg
        days.append(v)
    b = {}
    if gy.get("공사금액") is None or (isinstance(gy.get("공사금액"), str) and gy.get("공사금액", "").startswith("=")):
        b["공사금액"] = tot if _n(tot) else ""
    if gy.get("공사기간표시") is None or (isinstance(gy.get("공사기간표시"), str) and gy.get("공사기간표시", "").startswith("=")):
        b["공사기간표시"] = f"{_ymd(st)} ~ {_ymd(en)}" if (st and en) else ""
    h = {"확판정": r, "확기한": a["제출기한"]}
    today = datetime.date.today()
    if not st:
        h["오늘제출"] = ""
    elif today <= st - datetime.timedelta(days=1):
        h["오늘제출"] = f"제출 기한까지 {((st - datetime.timedelta(days=1)) - today).days:,}일 남음"
    elif today < st:
        h["오늘제출"] = ""
    else:
        h["오늘제출"] = "⚠ 착공 전날이 지났습니다 — 냈는지 확인 · 안 냈으면 바로"
    nx = next((d for d in days if d and d >= today), None)
    if not st:
        h["다음확인"] = ""
    elif nx is None:
        h["다음확인"] = "준공 — 이행 확인 끝" if (en and en < today) else "⚠ 확인 날짜를 셀 수 없음(준공일 · 착공일 확인)"
    else:
        h["다음확인"] = f"{_ymd(nx)} 전에 1회 이상 — 오늘부터 {(nx - today).days:,}일"
    vals = [hw.get(f"제출#{i}") for i in range(1, len(SUB) + 1)]
    m = len(SUB)
    o = sum(1 for v in vals if v == "○")
    x = sum(1 for v in vals if v == "×")
    na = sum(1 for v in vals if v == "해당 없음")
    h["제출요약"] = "" if o + x + na == 0 else (f"✓ {m}가지 모두 확인 — 제출" if o + na == m else f"⚠ 남은 것 {m - o - na}가지")
    return {"판정": a, "사업개요": b, "확인": h}
