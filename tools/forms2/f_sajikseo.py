def _end_after(a, months):
    """a(그날 0시부터 셈 · 그날 포함)부터 months 달이 끝나는 날 — 해당일 전날 · 해당일이 없으면 그 달 말일(민법 제160조 ② ③) · 엑셀 식"""
    e = f"EDATE({a},{months})"
    return f"IF(DAY({e})<DAY({a}),{e},{e}-1)"


