# ── 파이썬으로 따로 셈 ──────────────────────────────────────────────────
def _d(v):
    return v if isinstance(v, datetime.date) else None


def _s(v):
    return "" if v is None else str(v)


def _ymd(x):
    return f"{x.year}. {x.month}. {x.day}."


def end_after(a, months):
    x = _ed(a, months)
    return x if x.day < a.day else x - datetime.timedelta(days=1)


def _num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return 0.0


def expect(pages):
    a, b = {}, {}
    j, k = pages["사직"], dict(pages["일정"])
    # 수식 기본 칸(빈 서식 · 작성 예시에 값이 없을 때) — 첫 장 값을 그대로 받음
    v = k.get("통고일")
    if isinstance(v, str) and v.startswith("="):
        k["통고일"] = j.get("제출일")
    s, d = _d(j.get("입사일")), _d(j.get("퇴직일"))
    if not s or not d:
        a["근속"] = ""
    elif d < s:
        a["근속"] = "⚠ 퇴직일이 입사일보다 앞섬"
    else:
        a["근속"] = f"{_ymd(s)} ~ {_ymd(d)}  ·  {dur(s, d)}"
    a["본문"] = (BODY0 if not d else f"위 본인은 위와 같은 사유로 {d.year}년 {d.month}월 {d.day}일 자로 사직하고자 하오니 허락하여 주시기 바랍니다.")
    a["제출인"] = _s(j.get("성명"))
    a["귀하"] = "                         대표이사 귀하" if not j.get("상호") else f"{j.get('상호')}  대표이사 귀하"
    nm, sh, bu = _s(j.get("성명")), _s(j.get("상호")), _s(j.get("부서"))
    b["누구"] = "" if not nm else nm + ("" if not sh else " · " + sh) + ("" if not bu else " · " + bu)
    b["k근속"] = a["근속"]
    y1 = end_after(s, 12) if s else None
    b["일년날"] = y1 or ""
    if not s or not d or d < s:
        b["퇴직금"] = ""
    elif d >= y1:
        b["퇴직금"] = "✓ 1년 이상 — 퇴직금 대상(4주 평균 1주 15시간 이상일 때)"
    else:
        b["퇴직금"] = f"⚠ 1년에 {(y1 - d).days}일 모자람 — 그날까지 근무해야 퇴직금 대상"
    b["지급기한"] = (d + datetime.timedelta(days=14)) if d else ""
    t = _d(k.get("통고일"))
    pay = _s(k.get("급여"))
    d0 = _num(k.get("기간시작"))
    d0 = 1 if d0 == 0 else min(28, max(1, int(d0)))
    if not t:
        b["민법끝"] = b["민법풀이"] = b["효력끝"] = b["효력말"] = ""
    else:
        if pay[:2] == "월급":
            ps = D(t.year, t.month, d0) if t.day >= d0 else _ed(D(t.year, t.month, d0), -1)
            mend = _ed(ps, 2) - datetime.timedelta(days=1)
            b["민법풀이"] = f"③ 월급 — 사직서 낸 날이 든 임금 기간(매달 {d0}일 시작)의 다음 한 기간이 끝나는 날"
        else:
            mend = end_after(t + datetime.timedelta(days=1), 1)
            b["민법풀이"] = "② 사직서 낸 다음 날부터 1개월이 끝나는 날"
        b["민법끝"] = mend
        ce = _d(k.get("계약끝"))
        eff = min(mend, ce) if (_s(k.get("계약")) == TERM[1] and ce) else mend
        b["효력끝"] = eff
        if not d:
            b["효력말"] = "이 날이 지나야 퇴직 효력이 생깁니다"
        elif d >= eff:
            b["효력말"] = f"✓ 사직서의 퇴직일({_ymd(d)})에 퇴직 — 민법 기간 안"
        else:
            b["효력말"] = f"⚠ 이 날까지 근로 의무 — 사직서의 퇴직일보다 {(eff - d).days}일 늦음"
    b["증명기한"] = end_after(d + datetime.timedelta(days=1), 36) if d else ""
    return {"사직": a, "일정": b}
