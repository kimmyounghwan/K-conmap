def expect(inp):
    vals = [inp.get(f"결과#{k}") for k in range(1, 200) if f"결과#{k}" in inp]
    filled = [v for v in vals if isinstance(v, str) and v != ""]
    n = len(filled)
    if n == 0:
        return {"집계": ""}
    a, b, c = filled.count("적정"), filled.count("부적정"), filled.count("해당없음")
    s = f"점검 {항목수}항목 · 적정 {a} · 부적정 {b} · 해당없음 {c}"
    if n - a - b - c > 0:
        s += f" · 그 밖의 글 {n - a - b - c}"
    if 항목수 - n > 0:
        s += f" · 안 적음 {항목수 - n}"
    return {"집계": s}
