def _ga_f():
    """가설구조물 판정 수식"""
    parts = []
    for i, gname in enumerate(GS):
        if i == len(GS) - 1:
            parts.append((_is("가설구조물", gname), f'"{GA_ETC}"'))
            continue
        ok = f'"{GA_OK}{G_HO[i][:3]}{G_HO[i][3:]}"'
        if G_MIN[i] is None:
            parts.append((_is("가설구조물", gname), ok))
        else:
            parts.append((_is("가설구조물", gname), f'IF({H}=0,"{GA_HN}{H_TXT[i]}",IF({H}<{G_MIN[i]},"{GA_LOW}{H_TXT[i]}",{ok}))'))
    body = '""'
    for cond, val in reversed(parts):
        body = f'IF({cond},{val},{body})'
    return f'=IF({_is("구분", GB[1])},"{GA_NA}",{body})'


