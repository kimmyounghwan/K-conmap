def _amount(p, lab, key, exv):
    L = {"kind": "label"}
    p.row([(1, lab, L), (2, I(key, ex=exv, fmt=WON)),
           (2, F(key + "한글", f"=IF(N({{{key}}})=0,\"\",{{{key}}})", fmt="hangul", align="left", size=9.5))], h=28)


def _period(p, key, s, e):
    L = {"kind": "label"}
    p.row([(1, "계약기간", L), (1, I(key + "시작", ex=s, fmt="ymd", align="center")),
           (1, I(key + "끝", ex=e, fmt=END, align="center")),
           (2, F(key + "일수", f"=IF(OR(N({{{key}시작}})=0,N({{{key}끝}})=0),\"\",{{{key}끝}}-{{{key}시작}}+1)", fmt=DAYS,
                 align="center"))], h=26)


