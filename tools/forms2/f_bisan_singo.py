# ── 파이썬으로 따로 셈 ──────────────────────────────────────────────────
def _n(v):
    return v if isinstance(v, (int, float)) and not isinstance(v, bool) else 0


def _r2(v):
    """엑셀처럼 소수 둘째 자리에서 반올림(0.5 는 올림 — 파이썬 기본은 짝수 쪽)"""
    return Decimal(str(v)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)


def _fmt_num(v):
    """엑셀 TEXT(x,"#,##0.##") 과 같게(정수는 «2,400»)"""
    return f"{_r2(v):,.2f}".rstrip("0").rstrip(".")


def _f2(v):
    """TEXT(x,"0.0#") — 5.625 → «5.63» (엑셀 · 사이트 셈과 같게)"""
    s = f"{_r2(v):.2f}"
    return s[:-1] if s.endswith("0") else s


def _f1(v):
    """TEXT(x,"0.#") 꼴은 안 씀 — 수를 그대로 글로(엑셀 & 와 같게)"""
    return str(int(v)) if float(v).is_integer() else str(v)


def _ymd(d):
    return f"{d.year}. {d.month}. {d.day}."


def _given(d, k):
    """적은 값 — 수식 기본값('=…')은 «안 적음» 으로 봄"""
    v = d.get(k)
    return None if (isinstance(v, str) and v.startswith("=")) else v


def _j(parts):
    return " · ".join(t for c, t in parts if c)


