def _nt(ref):
    """수를 글로 — 정수면 «2,400» · 소수면 «2,400.5» (엑셀 TEXT 의 «2,400.» 꼴을 피함)"""
    return f'IF({ref}=INT({ref}),TEXT({ref},"#,##0"),TEXT({ref},"#,##0.##"))'


def _join(parts):
    """« · 가 · 나» 를 이어 붙인 뒤 앞의 « · » 를 떼는 꼴 — parts: (조건식, 글식) 목록"""
    return "MID(" + "&".join(f'IF({c}," · "&{t},"")' for c, t in parts) + ",4,999)"


