def expect(inp):
    dsum = sum(inp.get(f"직접금액#{i}") or 0 for i in range(1, N + 1))
    ssum = sum(inp.get(f"하도급금액#{i}") or 0 for i in range(1, N + 1))
    tot = inp["총노무비"]
    g = inp["도급금액"]
    duty = 0.5 if g < 3e8 else 0.3 if g < 1e9 else 0.2 if g < 3e9 else 0.1 if g < 7e9 else "대상 아님"
    ratio = dsum / tot
    return {
        "직접합": dsum, "하도급합": ssum, "총노무비한글": tot, "날짜경고": "",
        "경고": "" if abs(dsum + ssum - tot) < 1 else "?",
        "의무비율": duty, "직접비율": ratio, "판정": "충족" if ratio >= duty else "부족",
        "서명": f'{inp["수급인상호"]} {inp["수급인대표"]}', "수신": f'{inp["발주자대표"]} 귀하',
    }
