YOIL = "월화수목금토일"


def _ymd(d):
    return f"{d.year}. {d.month}. {d.day}."


_end = 끝날      # 기간셈.끝날 — 조문 그대로 따로 셈(엑셀 식을 베끼지 않음)


def expect(pages):
    s, sg = pages["셈"], pages["신청서"]
    a = {}
    hs, gj, hd, cy = s.get("허가신고"), s.get("공장"), s.get("허가일"), s.get("착공예정")
    yrs = 1 if hs == HS[1] else (3 if gj == "예" else 2)
    if not hs or not hd:
        a["기한"] = a["한도"] = a["오늘"] = ""
        a["확인"] = "" if not hs else NEED_D
        due = ext = None
    else:
        due = _end(hd, 12 * yrs)
        ext = _end(due, 12)
        law = ("신고일부터 1년(법 제14조제5항)" if hs == HS[1] else
               ("허가를 받은 날부터 3년 — 공장 승인(법 제11조제7항제1호)" if gj == "예" else "허가를 받은 날부터 2년(법 제11조제7항제1호)"))
        a["기한"] = f"{_ymd(due)}({YOIL[due.weekday()]})까지 — {law}"
        a["한도"] = f"{_ymd(ext)}({YOIL[ext.weekday()]})까지 — 1년의 범위(정당한 사유가 있다고 인정되면 · 허가권자가 정함)"
        if not cy:
            a["확인"] = NEED_C
        elif cy <= due:
            a["확인"] = IN_OK
        elif cy <= ext:
            a["확인"] = EXT_OK
        else:
            a["확인"] = EXT_NG
        today = datetime.date.today()
        if due < today:
            a["오늘"] = PAST_A + _ymd(due) + (PAST_B_S if hs == HS[1] else PAST_B_H)
        elif due == today:
            a["오늘"] = TODAY_END
        else:
            a["오늘"] = f"지금 착수 기한까지 오늘부터 {(due - today).days:,}일 남음 — 그 안에 착수하거나 이 신청서를 냅니다"
    a["사유"] = "" if not hs else (SAYU_OK if sg.get("연기사유") else SAYU_NO)
    a["다음"] = "" if not hs else NEXT
    b = {"허가일표시": "년          월          일" if not hd else f"{hd.year}년  {hd.month}월  {hd.day}일",
         "착공표시": "년          월          일" if not cy else f"{cy.year}년  {cy.month}월  {cy.day}일"}
    return {"셈": a, "신청서": b}
