def _ymd(x):
    return f"{x.year}. {x.month}. {x.day}."


def expect(pages):
    gi = pages[BI]
    z = {lg: {} for lg in pages}
    st, en = gi["착공일"], gi["준공일"]
    days = (en - st).days + 1
    tot = (gi.get("도급") or 0) + (gi.get("관급") or 0)
    sub = gi.get("작성일") or st
    z[BI] = {"합계": tot or "", "공사일수": days, "작성표시": sub}
    src = dict(gi)
    src.update({"합계": tot, "작성표시": sub, "공사일수": days})
    ct = gi["계약일"]
    special = {"@인수문장": f"{ct.year}년 {ct.month}월 {ct.day}일자로 계약 체결한 «{gi['공사명']}» 현장을 위와 같이 인수함.",
               "@감독": f"직 {gi.get('감독직급') or ''}    성명 {gi.get('감독성명') or ''}   (인)" if (gi.get("감독직급") or gi.get("감독성명")) else "직                성명                    (인)",
               "@감리": f"성명 {gi['감리원']}   (인)" if gi.get("감리원") else "성명                    (인)",
               "@대리문장": f"      상기자를 {ct.year}년 {ct.month}월 {ct.day}일자 계약한 «{gi['공사명']}» 의 현장대리인으로 선임하고 본인에게 부여된 현장 내의 책임을 대행하도록 "
                        f"하였기에 현장대리인 선임계를 제출합니다.",
               "@위치": "공사위치 : " + gi["장소"] if gi.get("장소") else "공사위치 :",
               "@배치기간": f"{_ymd(st)} ~\n{_ymd(en)}"}
    for (lg, key), (s, num) in COPIES.items():
        if s.startswith("@"):
            v = special[s]
        else:
            v = src.get(s)
            v = (v if v else "") if num else (v if v not in (None, "") else "")
        z[lg][key] = v
    # 현장인수증
    a = pages["현장인수증"]
    s_ = 0
    for i in range(1, NINS + 1):
        q, u = a.get(f"수량#{i}"), a.get(f"단가#{i}")
        v = round(q * u) if (q and u) else ""
        z["현장인수증"][f"금액#{i}"] = v
        s_ += v or 0
    z["현장인수증"]["공종계"] = s_ or ""
    z["현장인수증"]["간접"] = "" if (not s_ or not gi.get("도급")) else gi["도급"] - s_
    # 점검표
    c = pages["안전관리계획서"]
    ok = sum(1 for i in range(1, 11) if c.get(f"양호#{i}"))
    bad = sum(1 for i in range(1, 11) if c.get(f"불량#{i}"))
    z["안전관리계획서"]["점검결과"] = "" if ok + bad == 0 else (f"양호 {ok} · 불량 {bad}" + (f" · 빈칸 {10 - ok - bad}" if ok + bad < 10 else "")
                                                         + "  →  " + ("불량 항목 조치 후 작업" if bad else "작업 가능"))
