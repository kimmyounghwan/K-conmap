    ep = [e.get(f"환계획#{i}") or 0 for i in range(1, len(E_ITEMS) + 1)]
    ET = sum(ep)
    ez["환총계"] = ET or ""
    for i in range(1, len(E_ITEMS) + 1):
        ez[f"환비율#{i}"] = ep[i - 1] / ET if (ep[i - 1] and ET) else ""
    ez["환비율계"] = 1 if ET else ""
    ez["환차이"] = "" if (not ET or not ecap) else ET - ecap
    # 공정표 · 인력 · 장비
    gz = z["예정공정표"]
    u = pages["예정공정표"].get("칸단위") or 0
