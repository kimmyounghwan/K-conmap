def _nt(ref):
    """수를 글로 — 정수면 «2,400» · 소수면 «2,400.5» (엑셀 TEXT 의 «2,400.» 꼴을 피함)"""
    return f'IF({ref}=INT({ref}),TEXT({ref},"#,##0"),TEXT({ref},"#,##0.##"))'


