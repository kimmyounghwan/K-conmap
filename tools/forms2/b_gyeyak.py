def _haja_end(a, n):
    import datetime as _d
    try:
        b = _d.date(a.year + n, a.month, a.day)
    except ValueError:                      # 2월 29일 → 엑셀 DATE 처럼 3월 1일로 넘어감
        b = _d.date(a.year + n, 3, 1)
    return b - _d.timedelta(days=1)


