def expect(pages):
    cv = pages["표지"]
    g = pages["공사개요"]
    e = {"공사명표시": cv["공사명"],
         "목적글": f"    본 계획서는 「{cv['공사명']}」 중 토공 및 가시설({cv['공법']}) 설치에 대하여 다음 세 가지를 목적으로 합니다."}
    tot = 0
    for i in range(1, len(MAT) + 1):
        w, ln, n = g.get(f"단위중량#{i}"), g.get(f"길이#{i}"), g.get(f"본수#{i}")
        if w and ln and n:
            q = round(w * ln * n / 1000 + 1e-9, 2)
            e[f"수량#{i}"] = q
            tot += q
        else:
            e[f"수량#{i}"] = ""
    e["강재합계"] = tot
    t = pages["투입계획"]
    x = {}
    se = si = 0
    for i in range(1, 9):
        a, b = t.get(f"장일#{i}"), t.get(f"장일수#{i}")
        x[f"장누계#{i}"] = a * b if a and b else ""
        se += a * b if a and b else 0
        a, b = t.get(f"인일#{i}"), t.get(f"인일수#{i}")
        x[f"인누계#{i}"] = a * b if a and b else ""
        si += a * b if a and b else 0
    x.update({"합장비": se, "합인": si})
    k = pages["계측"]
    y = {}
    for i in range(1, 6):
        b, m = k.get(f"기준#{i}"), k.get(f"실측#{i}")
        if b and m:
            f = b / m
            y[f"F#{i}"] = f
            y[f"판정#{i}"] = "위험" if f < k["하한"] else ("안전" if f > k["상한"] else "주의")
        else:
            y[f"F#{i}"] = y[f"판정#{i}"] = ""
    den = k["기둥간격"] * 1000 / k["침하차"]
    y["침하비"] = den
    y["침하판정"] = "위험" if den <= k["위험분모"] else ("주의" if den < k["안전분모"] else "안전")
    s = pages["공정표"]
    z = {"눈금글": f"착수 후  (한 칸 = {s['눈금']}일)"}
    st, nn = s["착공일"], s["눈금"]
    for j in range(NB):
        z[f"s{j + 1}"] = st + datetime.timedelta(days=j * nn)
        z[f"e{j + 1}"] = st + datetime.timedelta(days=(j + 1) * nn - 1)
    a0, a1 = [], []
    for i in range(1, 9):
        b, c = s.get(f"착수#{i}"), s.get(f"완료#{i}")
        if b and c:
            z[f"일수#{i}"] = "⚠ 날짜" if c < b else (c - b).days + 1
            a0.append(b); a1.append(c)
        else:
            z[f"일수#{i}"] = ""
    z["총공기"] = (max(a1) - min(a0)).days + 1
    return {"공사개요": e, "투입계획": x, "계측": y, "공정표": z}
