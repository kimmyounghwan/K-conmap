def _vl(p, r, *cols, bottom=()):
    """연결선 — 칸의 왼쪽 테두리로 세로줄, 아래 테두리로 가로줄을 그립니다."""
    cs = set(cols) | set(bottom)
    for c in cs:
        p.ws.cell(row=r, column=c).border = Border(left=LINE if c in cols else None, bottom=LINE if c in bottom else None)


