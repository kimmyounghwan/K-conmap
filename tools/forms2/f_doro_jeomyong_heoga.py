def _num(key, items):
    """{key} 가 items 의 몇째인가(없으면 0) — 겹친 IF"""
    s = "0"
    for n, t in reversed(list(enumerate(items, 1))):
        s = f'IF({{{key}}}="{t}",{n},{s})'
    return s


