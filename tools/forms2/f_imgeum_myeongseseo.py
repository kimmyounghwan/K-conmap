def _n(v):
    if v is None or isinstance(v, str):
        try:
            return float(v)
        except (TypeError, ValueError):
            return 0.0
    if isinstance(v, (datetime.date,)):
        return 0.0
    return float(v)


def _r0(x):
    """엑셀 ROUND(x,0) — 0.5 는 0 에서 먼 쪽"""
    return math.floor(abs(x) + 0.5) * (1 if x >= 0 else -1)


def _int6(x):
    """엑셀 INT(ROUND(x,6))"""
    return math.floor(round(x, 6))


def _ten_py(x):
    return math.floor((x + 0.000001) / 10) * 10


def _wn(x):
    return f"{int(x):,}" if float(x).is_integer() else f"{x:,.0f}"


def _num_txt(x):
    """엑셀이 숫자를 글로 이을 때의 꼴(12 · 1.5 · 2)"""
    x = float(x)
    return str(int(x)) if x.is_integer() else repr(x).rstrip("0").rstrip(".")


def expect(inp):
    """한 장 서식 — run.py 는 작성 예시 칸 값(inputs)을 바로 줌 · 장면시험 show 는 {"명세서": inputs} 로 줌 → 둘 다 받음 · 돌려주는 것은 이름 → 값"""
    a = {}
    v = dict(inp["명세서"]) if isinstance(inp.get("명세서"), dict) else dict(inp)

    def dflt(key, fn):
        """수식이 기본값인 칸(비우면 저절로) — 셈한 값을 넣고 대조에도 넣음(4대보험 · 통상시급 같은 칸이 검사에서 빠지지 않게)"""
        if isinstance(v.get(key), str) and v[key].startswith("="):
            v[key] = fn()
            a[key] = v[key]

    yy = _n(v.get("귀속연"))
    y = 2026 if yy == 0 else yy
    ym = 202612 if yy == 0 else yy * 100 + (12 if _n(v.get("귀속월")) == 0 else _n(v.get("귀속월")))
    small = str(v.get("규모") or "")[:1] == "4"
    dflt("통상임금", lambda: _n(v.get("기본급")))
    dflt("시급", lambda: 0 if _n(v.get("소정시간")) == 0 else _r0(_n(v.get("통상임금")) / _n(v.get("소정시간"))))
    sh = _n(v.get("시급"))
    x1, x2, x3, x4 = (1, 0, 1, 1) if small else (1.5, 0.5, 1.5, 2)
    oh, nh, h8, hx = _n(v.get("연장시간")), _n(v.get("야간시간")), _n(v.get("휴일8")), _n(v.get("휴일초"))
    a["연장"] = _int6(sh * oh * x1)
    a["연장법"] = "" if oh == 0 else f"통상시급 {_wn(sh)}원 × {_num_txt(oh)}시간 × {_num_txt(x1)}"
    a["야간"] = _int6(sh * nh * x2)
    a["야간법"] = "" if nh == 0 else (f"상시 4명 이하 — 가산 없음({_num_txt(nh)}시간)" if small else f"통상시급 {_wn(sh)}원 × {_num_txt(nh)}시간 × 0.5")
    a["휴일"] = _int6(sh * (h8 * x3 + hx * x4))
    a["휴일법"] = "" if h8 + hx == 0 else (f"통상시급 {_wn(sh)}원 × ({_num_txt(h8)}시간 × {_num_txt(x3)}" + ("" if hx == 0 else f" + {_num_txt(hx)}시간 × {_num_txt(x4)}") + ")")
    a["식대비"] = min(_n(v.get("식대")), NONTAX)
    a["자가비"] = min(_n(v.get("자가운전")), NONTAX)
    a["그밖비"] = _n(v.get("비과세"))
    a["지급합계"] = (_n(v.get("기본급")) + a["연장"] + a["야간"] + a["휴일"] + _n(v.get("수당1")) + _n(v.get("수당2")) + _n(v.get("상여금"))
                 + _n(v.get("식대")) + _n(v.get("자가운전")) + _n(v.get("비과세")))
    a["비과세합계"] = a["식대비"] + a["자가비"] + a["그밖비"]
    a["과세합계"] = a["지급합계"] - a["비과세합계"]
    dflt("기준보수", lambda: a["과세합계"])
    dflt("하한", lambda: 410000 if ym >= 202607 else (400000 if ym >= 202507 else 390000))
    dflt("상한", lambda: 6590000 if ym >= 202607 else (6370000 if ym >= 202507 else 6170000))
    dflt("연금율", lambda: 0.05 if y >= 2027 else (0.0475 if y >= 2026 else 0.045))
    dflt("건강율", lambda: 0.03595 if y >= 2026 else 0.03545)
    dflt("요양비", lambda: 0.9448 / 7.19 if y >= 2026 else 0.9182 / 7.09)
    base = _n(v.get("기준보수"))
    pen = min(_n(v.get("상한")), max(_n(v.get("하한")), math.floor(base / 1000) * 1000))
    dflt("연금", lambda: 0 if base == 0 else _ten_py(pen * _n(v.get("연금율"))))
    dflt("건강", lambda: _ten_py(base * _n(v.get("건강율"))))
    dflt("요양", lambda: _ten_py(_n(v.get("건강")) * _n(v.get("요양비"))))
    dflt("고용", lambda: _ten_py(base * _n(v.get("고용율"))))
    dflt("지방세", lambda: _ten_py(_n(v.get("소득세")) * 0.1))
    a["연금법"] = "" if base == 0 else f"기준소득월액 {_wn(pen)}원(천원 미만 버림 · 하한 ~ 상한) × {_n(v.get('연금율')) * 100:.2f}%"
    a["건강법"] = "" if base == 0 else f"보수 {_wn(base)}원 × {_n(v.get('건강율')) * 100:.3f}%"
    a["요양법"] = "" if _n(v.get("건강")) == 0 else f"건강보험료 × {_n(v.get('요양비')) * 100:.2f}%(장기요양보험료율 ÷ 건강보험료율)"
    a["고용법"] = "" if base == 0 else f"보수 {_wn(base)}원 × {_n(v.get('고용율')) * 100:.1f}%"
    a["공제합계"] = sum(_n(v.get(k)) for k in ("연금", "건강", "요양", "고용", "소득세", "지방세", "공제1", "공제2"))
    a["실지급"] = a["지급합계"] - a["공제합계"]
    a["실지급한글"] = a["실지급"]
    a["상호줄"] = "" if not v.get("상호") else str(v.get("상호"))
    return a
