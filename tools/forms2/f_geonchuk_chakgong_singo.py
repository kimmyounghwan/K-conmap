def _n(v):
    return v if isinstance(v, (int, float)) and not isinstance(v, bool) else 0


def _ymd(d):
    return f"{d.year}. {d.month}. {d.day}."


def _edate(d, months):
    import calendar
    y, m = divmod(d.month - 1 + months, 12)
    y += d.year
    m += 1
    return D(y, m, min(d.day, calendar.monthrange(y, m)[1]))


