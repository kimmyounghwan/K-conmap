def prow(p, gx, items, h):
    """items = [(x1, x2, 내용[, 모양])…] — 세로 병합으로 찬 칸은 fb.row 가 건너뜀 · 칸 자리가 원문 x 와 맞는지 확인"""
    r = p.r
    cells = []
    c = 1
    for it in items:
        a, b = gx.cols(it[0], it[1])
        assert b >= a, (p.name, r, it[:2])
        while (r, c) in p.occ:
            c += 1
        assert c == a, f"[{p.name}] {r}행 칸 자리 {c} ≠ {a} (x {it[0]})"
        cells.append((b - a + 1,) + tuple(it[2:]))
        c = b + 1
    return p.row(cells, h=h)


def _bd(p, r1, r2, c1, c2, top=True, bot=True, left=True, right=True):
    """(r1~r2, c1~c2) 를 한 칸처럼 — 바깥선만(안쪽 선 지움)"""
    from openpyxl.styles import Border
    from fb import LINE
    for r in range(r1, r2 + 1):
        for c in range(c1, c2 + 1):
            p.ws.cell(row=r, column=c).border = Border(left=LINE if (left and c == c1) else None, right=LINE if (right and c == c2) else None,
                                                       top=LINE if (top and r == r1) else None, bottom=LINE if (bot and r == r2) else None)


def _close(p, r):
    """표 안 «free» 칸 줄에 위 · 아래 선 — 줄 끝 칸은 오른선도"""
    from openpyxl.styles import Border
    from fb import LINE
    for c in range(1, p.pc + 1):
        bd = p.ws.cell(row=r, column=c).border
        if any(getattr(bd, k) is not None and getattr(bd, k).style for k in ("left", "right", "top", "bottom")):
            continue
        p.ws.cell(row=r, column=c).border = Border(top=LINE, bottom=LINE, right=LINE if c == p.pc else None)


