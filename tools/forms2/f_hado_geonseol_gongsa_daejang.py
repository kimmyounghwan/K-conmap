def _e(d, ex, k):
    return d.get(k) if ex else None


def _ymdf(ref):
    return f'YEAR({ref})&". "&MONTH({ref})&". "&DAY({ref})&"."'


def _yo(ref):
    return f'CHOOSE(WEEKDAY({ref}),"일","월","화","수","목","금","토")'


def _due(x):
    """x(날짜 식) — 토요일이면 +2 · 일요일이면 +1(민법 제161조 · 공휴일은 글로만)"""
    return f"(({x})+IF(WEEKDAY({x})=7,2,IF(WEEKDAY({x})=1,1,0)))"


def _box_f(ref, opts, sep="  "):
    return "=" + ('&"' + sep + '"&').join(f'IF({ref}="{o}","[√] ","[   ] ")&"{o}"' for o in opts)


def _box_py(v, opts, sep="  "):
    return sep.join(("[√] " if v == o else "[   ] ") + o for o in opts)


