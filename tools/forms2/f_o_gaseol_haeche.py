def expect(pages):
    cv, gy, gj, sh, an = pages["표지"], pages["개요"], pages["공정표"], pages["수행계획"], pages["안전환경"]
    e = {"공사명표시": cv["공사명"] + "  ［ 흙막이 가시설 해체공사 ］", "시공사표시": cv["회사"], "공사일수": (gy["준공일"] - gy["착공일"]).days + 1,
         "인원계": sum(gy.get(f"인원#{i}") or 0 for i in range(1, 7)) or ""}
    w = round(sh["부재길이"] * sh["단위중량"] / 1000, 2)
    u = (w + (sh.get("부가") or 0)) / sh["정격"]
    s = {"부재중량": w, "사용률": u, "양중판정": "정격 총하중 이내" if u <= 1 else "⚠ 정격 총하중 초과 — 장비 · 반경 다시 검토"}
    acc = 0
    for i in range(1, 7):
        v = sh.get(f"높이#{i}")
        if v:
            acc += v
            s[f"누계#{i}"] = acc
        else:
            s[f"누계#{i}"] = ""
    s["높이계"] = acc or ""
    diff = abs(acc - gy["굴착깊이"])
    s["높이대조"] = "✓ 굴착 깊이와 같음" if diff < 0.005 else f"굴착 깊이와 {diff:.2f} m 차이"
    a = {}
    for i in range(1, 4):
        n_, v = an.get(f"소음#{i}"), an.get(f"진동#{i}")
        if not n_ and not v:
            a[f"환경판정#{i}"] = ""
        elif (n_ or 0) > an["소음기준"]:
            a[f"환경판정#{i}"] = "⚠ 소음 기준 초과"
        elif (v or 0) > an["진동기준"]:
            a[f"환경판정#{i}"] = "⚠ 진동 기준 초과"
        elif (n_ or 0) > an["소음목표"] or (v or 0) > an["진동목표"]:
            a[f"환경판정#{i}"] = "기준 이내 · 목표 초과"
        else:
            a[f"환경판정#{i}"] = "목표 이내"
    return {"표지": {}, "개요": e, "공정표": g.exp_gongjeong(gj, gy["착공일"], 10), "수행계획": s, "안전환경": a}
