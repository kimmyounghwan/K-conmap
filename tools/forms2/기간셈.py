"""기간셈 — «날부터 N달(해)» 끝날 (민법 제157조 · 제160조 ② · ③) · 2026-11-17 G738 착공연기신청서에서 만듦

  ■ 왜 EDATE 하나로는 안 되나
    · EDATE(날+1, N) − 1 → 기산일이 2월 29일(윤년 2월 28일 허가)이고 끝 해가 평년이면 하루 이른 2월 27일 ✗
      (제160조③ «최종의 월에 해당일이 없는 때에는 그 월의 말일로 만료» = 2월 28일)
    · EDATE(날, N)      → 평년 2월 28일 허가 · 끝 해가 윤년(예: 2026-02-28 → 2년)이면 2월 28일 ✗
      (제160조② 기산일 3월 1일에 해당한 날의 전날 = 2월 29일)
  ■ 쓰는 법(생성기)
    from 기간셈 import 끝날식, 끝날
    · 엑셀 칸 : F("기한", "=" + 끝날식("{허가일}", "24"))   — d 는 첫날(그날은 빼고 셈 · 제157조 본문)
    · expect  : 끝날(허가일, 24)                            — 조문대로 따로 셈(엑셀 식을 베끼지 않음 — 베끼면 시험이 못 잡음)
  ■ 그날 0시부터 시작하는 기간(근로 시작 · 입사일 — 제157조 단서)은 하루 앞당긴 날을 넣음: 끝날식("({입사일}-1)", n)
  ■ 끝날이 토요일 · 공휴일이면 다음 날(제161조)은 셈하지 않음 — 서식마다 글로만 알림(공휴일이 해마다 바뀜).
  ■ 시험: tools/시험_기간끝날.py — 2020 ~ 2032 모든 날 × 1 · 2 · 3 · 6 · 12 · 24 · 36 · 48달을 조문 셈과 대조 +
    생성기에 EDATE 가 새로 들어오면 멈춤(날부터 N달 끝날이면 이 모듈로 · 다른 뜻이면 그 시험의 이미_있음 에 까닭과 함께)
"""
import calendar
import datetime


def 끝날식(d, n):
    """엑셀 식 — d(첫날 · 그날은 빼고)부터 n 달이 끝나는 날 = MAX(EDATE(d,n), EDATE(d+1,n)−1) (제160조 ② · ③ 둘 다 맞음)"""
    return f"MAX(EDATE({d},{n}),EDATE({d}+1,{n})-1)"


def 끝날(d, months):
    """파이썬 — 조문 그대로: 기산일 a = d + 1(제157조) → 마지막 달에서 a 에 해당한 날의 전날(제160조②) · 그 달에 그날이 없으면 그 달 말일(③)"""
    a = d + datetime.timedelta(days=1)
    y, m = divmod(a.month - 1 + months, 12)
    y += a.year
    m += 1
    last = calendar.monthrange(y, m)[1]
    if a.day > last:
        return datetime.date(y, m, last)
    return datetime.date(y, m, a.day) - datetime.timedelta(days=1)
