def expect(pages):
    cv, b, ck, bu = pages["표지"], pages["본문"], pages["점검표"], pages["환경보전비"]
    out = {"표지": {}}
    e = {"공사명표시": cv["공사명"], "수급사표시": cv["회사"], "공기": f"({(b['준공'] - b['착공']).days + 1}일)", "금액한글": b["공사금액"]}
    for k in ("연장", "인접", "백m"):
        v = [b.get(f"{k}#{i}") for i in range(1, 7) if b.get(f"{k}#{i}") is not None]
        e[f"{k}계"] = sum(v) if v else ""
    out["본문"] = e
    res = [ck.get(f"결과#{k}") for k in range(1, sum(len(x[2]) for x in CHK) + 1)]
    n = len(res)
    filled = [r for r in res if r not in (None, "")]
    good = sum(1 for r in filled if r == "○")
    nums = [r for r in filled if isinstance(r, (int, float))]
    out["점검표"] = {"점검요약": f"양호(○) {good}항목 · 부적합 {len(nums)}항목 {sum(nums)}건 · 빈칸 {n - len(filled)}항목" if filled else ""}
    e = {}
    amts = {}
    tot = 0
    for i in range(1, NDET + 1):
        q, u = bu.get(f"수량#{i}"), bu.get(f"단가#{i}")
        v = round(q * u) if (q and u) else ""
        e[f"금액#{i}"] = v
        if v != "":
            tot += v
            j = bu.get(f"번호#{i}")
            amts[j] = amts.get(j, 0) + v
    e["세부계"] = tot or ""
    s = sum(amts.values())
    for j in range(1, 9):
        e[f"총괄#{j}"] = amts.get(j) or ""
        e[f"비율#{j}"] = (amts[j] / s) if amts.get(j) else ""
    e["총괄계"] = s or ""
    e["비율계"] = 1 if s else ""
    c = bu["계상액"]
    e["계상대조"] = ("" if not s else (f"⚠ 사용계획이 계상액보다 {s - c}원 많습니다." if s > c else f"※ 계상액 대비 {round(s / c * 100, 1):g}% 계획"))
    out["환경보전비"] = e
    out["신고증명서"] = {}
    return out
