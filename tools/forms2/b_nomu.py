    e.update({"소계": s, "부가가치세": v, "정산합계": s + v})
    for k in ("가동일수", "가동시간", "대기시간", "임대료", "유류"):
        e[f"합:{k}"] = sum(v for _, v in col(inp, k))
    e["합:합계"] = s
    return e


