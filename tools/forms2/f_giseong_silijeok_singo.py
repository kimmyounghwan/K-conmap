def _n(v):
    return v if isinstance(v, (int, float)) and not isinstance(v, bool) else 0


def _digs(a, any_=None):
    a = _n(a)
    if (any_ if any_ is not None else a) == 0:
        return [""] * 7
    s = str(int(a // 1000000)) if any_ is None else str(int(a))
    return ["" if k <= 7 - len(s) else s[k - 7 + len(s) - 1] for k in range(1, 8)]


