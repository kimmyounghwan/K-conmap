def cnt(key, good="양호", bad="불량"):
    """점검 결과 세기 — 표 아래 한 줄"""
    return (f'=IF(COUNTA({{{key}[]}})=0,"","{good} "&COUNTIF({{{key}[]}},"{good}")&" · {bad} "&COUNTIF({{{key}[]}},"{bad}")'
            f'&" · 빈칸 "&COUNTBLANK({{{key}[]}}))')


def exp_cnt(inp, key, n, good="양호", bad="불량"):
    v = [inp.get(f"{key}#{i}") for i in range(1, n + 1)]
    return f"{good} {sum(1 for x in v if x == good)} · {bad} {sum(1 for x in v if x == bad)} · 빈칸 {sum(1 for x in v if not x)}"


