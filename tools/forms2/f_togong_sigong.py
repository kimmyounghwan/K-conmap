def _num(v):
    return v if isinstance(v, (int, float)) and not isinstance(v, bool) else 0


def _fs(v):
    """엑셀 «&» 로 숫자를 글에 붙일 때 모양(1.2 → "1.2", 3900 → "3900")"""
    if isinstance(v, float) and v.is_integer():
        v = int(v)
    return ("%.10f" % v).rstrip("0").rstrip(".") if isinstance(v, float) else str(v)


def _cnt(vals, what):
    return sum(1 for v in vals if v == what)


def _summary(vals, n, done, left):
    a, x, na = _cnt(vals, "○"), _cnt(vals, "×"), _cnt(vals, "해당 없음")
    if a + x + na == 0:
        return ""
    return done if a + na == n else f"{left}{n - a - na}가지"


