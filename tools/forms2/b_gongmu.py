# ── 기성대가 청구서 ────────────────────────────────────────────
def _cheonggu(total, prev, adv_rate, deduct=0):
    now = total - prev
    adv = tr(now, adv_rate) if adv_rate else 0
    vat = now - rnd(dm(now) / dm("1.1"))
    tot = now - adv - deduct
    return now, adv, vat, tot


