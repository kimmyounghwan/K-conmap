def _n(v):
    return v if isinstance(v, (int, float)) and not isinstance(v, bool) else 0


def _ed(d, m):
    y = d.year + (d.month - 1 + m) // 12
    mo = (d.month - 1 + m) % 12 + 1
    return D(y, mo, min(d.day, calendar.monthrange(y, mo)[1]))


def _ymd(d):
    return f"{d.year}. {d.month}. {d.day}."


def _d(v):
    """날짜 칸 — 빈 서식 자리글(«년 월 일»)이나 빈칸은 None(엑셀 N() = 0 과 같게)"""
    return v if isinstance(v, datetime.date) else None


def _num(x):
    """엑셀 «&» 로 이은 수 — 정수면 정수 글"""
    return str(int(x)) if float(x) == int(x) else repr(float(x)).rstrip("0").rstrip(".")


DAY1 = datetime.timedelta(days=1)


def _arise(s, k):
    e = _ed(s, k)
    return e + DAY1 if e.day < s.day else e


def _end1(a):
    e = _ed(a, 12)
    return e if e.day < a.day else e - DAY1


