def 합친부피(상자들):
    xs = sorted({v for b in 상자들 for v in (b[0], b[3])})
    ys = sorted({v for b in 상자들 for v in (b[1], b[4])})
    zs = sorted({v for b in 상자들 for v in (b[2], b[5])})
    합 = 0.0
    for i in range(len(xs) - 1):
        cx = (xs[i] + xs[i + 1]) / 2
        bx = [b for b in 상자들 if b[0] < cx < b[3]]
        if not bx:
            continue
        for j in range(len(ys) - 1):
            cy = (ys[j] + ys[j + 1]) / 2
            by = [b for b in bx if b[1] < cy < b[4]]
            if not by:
                continue
            for k in range(len(zs) - 1):
                cz = (zs[k] + zs[k + 1]) / 2
                if any(b[2] < cz < b[5] for b in by):
                    합 += (xs[i + 1] - xs[i]) * (ys[j + 1] - ys[j]) * (zs[k + 1] - zs[k])
    return 합 / 1e9


def 네모밖넓이(기둥, 판):
    """기둥 네모 중 슬라브 판(네모) 밖 넓이 mm²"""
    x0, y0, x1, y1 = 기둥
    a0, b0, a1, b1 = 판
    안 = max(0, min(x1, a1) - max(x0, a0)) * max(0, min(y1, b1) - max(y0, b0))
    return (x1 - x0) * (y1 - y0) - 안


