/* 🧭 G132 도면 물량 자동 — 외부참조 끼우기 · 한 번만 세기 · 위치도(축소 사본) 빼기 · 단위 짐작 · 종단 L= · 횡단 수량표 시험
     node tools/시험_외부참조.mjs
   도면은 모두 지어낸 것(tools/외부참조_예시.py → tools/시험자료/xref_*.dxf · 종단_예시.dxf · 횡단_예시.dxf).
   실제 하수도 도면(DWG 7장 + 외부참조 32MB)으로는 클라우드 작업 공간에서 맞춰 봤습니다:
     오수계획평면도에 끼운 «#계획오수라인» 2,943.844 m = ezdxf + shapely 로 따로 자른 값과 같음 · 도면 6장에 겹쳐도 한 번
     종단 «관로 구간» L= 72곳 2,880 m = 관경별 합 = 공법별 합 = 횡단 수량표 노선 14개 연장 2,880 m · 횡단 평균단면법 = ezdxf 로 따로 셈한 값과 같음 */
import { readFileSync } from 'fs'
import { 도면읽기, 단위배율 } from '../web/src/lib/골조도면.js'
import { 참조붙이기, 참조모음, 경계를B로, 부르는참조, 참조키 } from '../web/src/lib/외부참조.js'
import { 모두, 레이어뜻 } from '../web/src/lib/도면전부.js'
import { 세기 } from '../web/src/lib/도면자동.js'
import { 구간표읽기, 속성단면 } from '../web/src/lib/단면표.js'

let ok = 0, bad = 0
const 같음 = (got, want, what, tol = 1e-6) => {
  const g = typeof got === 'number' ? Math.abs(got - want) <= tol : JSON.stringify(got) === JSON.stringify(want)
  if (g) { ok++; console.log('  ✓', what) } else { bad++; console.log('  ✗', what, '— 나온 값', JSON.stringify(got), '· 바란 값', JSON.stringify(want)) }
}
const 참 = (c, what, 더 = '') => 같음(!!c, true, what + (더 ? ' (' + 더 + ')' : ''))
const 읽 = (n) => 도면읽기(readFileSync(new URL('./시험자료/' + n, import.meta.url), 'utf8'))
const 층길이 = (S, 이름) => { const a = S.층.find((x) => x.이름 === 이름); return a ? a.길이m : 0 }

console.log('1) 외부참조 · XCLIP 읽기')
const 바탕 = 읽('xref_바탕.dxf'), 평1 = 읽('xref_평면1.dxf'), 평2 = 읽('xref_평면2.dxf')
같음(평1.참조.length, 2, '평면1 — 외부참조 넣은 자리 2')
참(평1.참조.every((r) => r.경계 && r.경계.length === 4), 'XCLIP 경계(네모 4점) 읽음')
같음(참조키(평1.참조[0].길), 'xref_바탕', '참조 이름 = 경로 · 확장자 뺀 파일 이름')
같음(부르는참조(평1).map((r) => r.키), ['xref_바탕'], '부르는 참조(위치도 빼고) 1가지')
const 단 = 단위배율(평1.units, 평1.box, 평1.ox, 평1.oy)
같음([평1.units, 단.k], [4, 1000], '파일 머리는 mm 인데 TM 좌표 · 작은 너비 → m 로 짐작')
같음(단위배율(4, [0, 0, 60000, 40000], 5000, 3000).k, 1, 'mm 로 그린 건물(원점 근처 · 너비 수만) → mm 그대로')
const 사본 = [...평1.E.sc].filter((v) => v < 0.5).length
참(사본 >= 2, '귀퉁이 위치도(0.1배 붙여넣기 블록) 도형의 배율 0.1 기록', String(사본))

console.log('2) 끼워 넣기 — 잘린 대로 길이')
const k = 1000
const 혼자 = 세기(평1, { k })
같음(층길이(혼자, '#계획오수라인'), 0, '끼우기 전 — 위치도(0.1배)의 계획오수는 물량에서 뺌')
참(혼자.뺀사본 >= 2, '뺀 축소 사본 수를 알려 줌', String(혼자.뺀사본))
const 끼운 = 참조붙이기(평1, 바탕, 'xref_바탕')
같음(끼운.붙은, 2, '두 자리에 끼움')
const S1 = 세기(끼운.모델, { k })
같음(층길이(S1, 'xref_바탕|#계획오수라인'), 200, '계획오수 300 m 중 XCLIP 0~100 · 100~200 → 200 m')
같음(층길이(S1, 'xref_바탕|-L형측구'), 200, '현황 측구도 잘린 만큼 200 m')
const 블 = S1.블록.find((b) => b.이름 === '맨홀')
같음(블 && 블.수, 2, '맨홀 블록 — 잘린 범위(0~200) 안 2개')
const 전1 = 모두(끼운.모델, { k, 참조뺌: true })
참(!전1.항목.some((x) => /\|/.test(x.key)), '끼운 도면에서는 외부참조 줄을 따로 안 셈(원본 쪽에서 한 번)')

console.log('3) 외부참조 «한 번만» — 도면 둘이 50 m 겹쳐 보여 줌')
const 경계들 = [...평1.참조, ...평2.참조].map((r) => 경계를B로(r, 바탕))
const 모음 = 참조모음(바탕, 경계들, 1, 'xref_바탕')
const 전 = 모두(모음, { k })
const 오수 = 전.항목.find((x) => x.key === '층길이:xref_바탕|#계획오수라인')
같음(오수 && 오수.수량, 250, '평면1(0~200) ∪ 평면2(150~250) = 250 m (겹친 50 m 한 번)')
참(오수 && 오수.켬, '«#계획» 레이어는 외부참조여도 켬')
const 측구 = 전.항목.find((x) => x.key === '층길이:xref_바탕|-L형측구')
참(측구 && !측구.켬, '바탕도 현황 측구는 처음엔 꺼 둠', 측구 && 측구.근거)
const 대문 = 전.항목.find((x) => x.key === '블록:대문')
참(대문 && 대문.수량 === 2 && !대문.켬, '현황 블록(대문) 2개 · 꺼 둠')

console.log('4) 레이어 뜻 — 점 시설 · 현황 · 외부참조')
참(레이어뜻('오수맨홀').주석 && 레이어뜻('오수맨홀').점시설, '«오수맨홀» 레이어 선은 오수관로 길이로 안 셈(점 시설)')
같음(레이어뜻('#계획오수라인').품명, '오수관로', '«#계획오수라인» = 오수관로')
참(레이어뜻('기존 측구').현황, '«기존» = 현황')
참(레이어뜻('xref-A|-L형측구').참조 && !레이어뜻('xref-A|#계획오수라인').참조, '외부참조 레이어 — 계획 이름만 켬')

console.log('5) 종단 — «이름 / L=» 띠 (엇갈린 짧은 구간 포함)')
const 종 = 읽('종단_예시.dxf')
const 띠 = Object.fromEntries(구간표읽기(종).map((g) => [g.품명, [g.수량, g.개수]]))
같음(띠['D200(오수관)'], [60, 1], 'D200 60 m')
같음(띠['D300(오수관)'], [40, 1], 'D300 40 m')
같음(띠['관로 구간(맨홀~맨홀)'], [100, 3], '맨홀 구간 3곳 100 m (엇갈린 «1 LINE-003 / L=15» 도 짝)')
같음(띠['OPEN CUT(토사)'], [100, 1], '공법 OPEN CUT(토사) 100 m')
const 종줄 = 모두(종, { k: 1, 단면: true }).항목
const 합계줄 = 종줄.find((x) => x.key === '구간:관로 구간(맨홀~맨홀)')
참(합계줄 && !합계줄.켬, '관경별 줄이 있으면 «관로 구간» 합계 줄은 꺼 둠(겹쳐 세지 않게)')

console.log('6) 횡단 — 수량표 블록 속성 · 평균단면법')
const 횡 = 읽('횡단_예시.dxf')
const t = 속성단면(횡)[0]
같음([t.블록, t.단면수, t.노선수, t.간격, t.길이], ['SEC-TABL', 7, 2, 20, 60], '단면 7 · 노선 2(0+0 에서 새로) · NO 20 m · 연장 60 m')
const 값 = Object.fromEntries(t.항목.map((x) => [x.품명, [x.단위, Math.round(x.수량 * 1000) / 1000]]))
같음(값['터파기(육상)'], ['m³', 125], '터파기 125 m³ ((2+3)/2×20 + (3+4)/2×10 + (전)→(후) 0 + 2×10 + 1×20)')
같음(값['모래부설'], ['m³', 26], '모래부설 26 m³')
같음(값.ASP, ['m²', 56], 'ASP = 폭(m) × 연장 → 56 m²')
참(!값['지반고'], '지반고(높이)는 물량에서 뺌')

console.log(`\n${ok} 통과 · ${bad} 실패`)
process.exit(bad ? 1 : 0)
