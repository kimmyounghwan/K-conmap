# -*- coding: utf-8 -*-
"""🧪 G221 (2026-10-09) 참가가능지역 · 시 · 군 근거 — 지역 판정이 다시 «전국» 으로 새지 않게 잠급니다.

  소장님: 「87건이나 된다고 이상한데 ㅎㅎㅎ」
  왜: 지역 제한을 rgnb(지역제한 판단기준)로만 봤는데 그 칸은 수의계약에만 와서, 경기 · 경북 지역 제한
      «제한경쟁» 공고가 넣을 수 있는 공고로 셈해졌습니다(87건 → 실제 10건 안팎).
  ① rgn_keys — 참가가능지역 글 → «시도» · «시도 시군» 열쇠
  ② 수집 — 참가가능지역을 잘리지 않은 열쇠(rgk)로 남기는가 · bidindex 에 rgs 칸이 있는가
  ③ 근거 — 본사 주소 · 시 · 군 제한 공고에 넣은 기록 → 시 · 군 근거(s) · 제한경쟁 공고(rgnb 빈 칸)도 지역 근거로
  돌리기: python tools/시험_참가지역.py   (올리기 bat 이 올리기 전에 돌립니다 — 틀리면 멈춤)
"""
import io
import os
import re
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

틀림 = []
셈 = [0]


def 봄(이름, 참, 덧=""):
    셈[0] += 1
    print(("✓ " if 참 else "✗ ") + 이름 + (f" — {덧}" if 덧 else ""))
    if not 참:
        틀림.append(이름)


try:
    import collect as C
except ImportError as e:      # requests 등이 없는 PC — 클라우드 · 깃허브에서 돎
    C = None
    print(f"  (collect 는 패키지가 없어 건너뜀 — {e})")

if C is not None:
    K = C.rgn_keys
    # ① 열쇠
    봄("① 시도 전체", K("인천광역시") == ["인천"], str(K("인천광역시")))
    봄("① 통합특별시 군", K("전남광주통합특별시 장흥군") == ["전남 장흥군"], str(K("전남광주통합특별시 장흥군")))
    봄("① 통합특별시 구 → 광주", K("전남광주통합특별시 광산구") == ["광주 광산구"])
    봄("① 통합특별시만 → 전남 · 광주 둘 다", K("전남광주통합특별시") == ["전남", "광주"], str(K("전남광주통합특별시")))
    봄("① 여럿 · 겹침 없음", K("경상북도 의성군, 경상북도 의성군, 경상북도 군위군") == ["경북 의성군", "경북 군위군"])
    봄("① 시 아래 구는 시까지", K("경기도 수원시 장안구") == ["경기 수원시"])
    봄("① 세종 · 옛 이름", (K("세종특별자치시"), K("전라남도 여수시"), K("강원도 춘천시")) == (["세종"], ["전남 여수시"], ["강원 춘천시"]))
    봄("① 못 읽는 조각 → ?", K("어딘가 이상한 곳") == ["?"])
    봄("① 빈 값 → 빈 목록", K("") == [] and K(None) == [])
    # 낙찰업체 주소 → 시 · 군
    봄("① 주소 첫 조각 → «전남 여수시»", K("전남광주통합특별시 여수시 시청로 1, 2층".split(",")[0])[:1] == ["전남 여수시"])

    # ② 수집 — 잘리지 않은 열쇠 · bidindex 칸
    names = [f"전남광주통합특별시 {x}" for x in "목포시 여수시 순천시 나주시 광양시 담양군 곡성군 구례군 고흥군 보성군 화순군 장흥군 강진군 해남군 영암군 무안군".split()]
    st = {"con": {"N1": {"no": "N1"}, "N2": {"no": "N2", "rgn": "옛 글", "rgk": ["전남"]}}}
    C.put_rgn([st], {"N1": names, "N2": ["인천광역시"]})
    봄("② 화면 글(rgn)은 12곳까지 · 판정 열쇠(rgk)는 16곳 전부", len(st["con"]["N1"]["rgn"].split(", ")) == 12 and len(st["con"]["N1"]["rgk"]) == 16
       and "전남 무안군" in st["con"]["N1"]["rgk"], f'{len(st["con"]["N1"]["rgk"])}곳')
    봄("② 이미 있는 값은 안 덮음", st["con"]["N2"]["rgn"] == "옛 글" and st["con"]["N2"]["rgk"] == ["전남"])
    src = io.open(os.path.join(ROOT, "collect.py"), encoding="utf-8").read()
    i = src.index('"f": ["no", "name"')
    f = re.findall(r'"([a-z]+)"', src[src.index("[", i):src.index("]", src.index("[", i))])
    봄("② bidindex 맨 뒤 칸 «rgs»(참가가능지역 열쇠)", f[-1] == "rgs", f[-3:].__repr__())
    봄("② bidindex 줄에 rgk 또는 rgn 열쇠를 실음", 'r.get("rgk") or rgn_keys(r.get("rgn"))' in src)

    # ③ 근거
    first = {"con": {
        # 경기 지역 제한 «제한경쟁»(rgnb 빈 칸) 에 넣음 → 경기 근거
        "A": {"dt": "20261001", "corps": [["갑건설", "", "", "1111111111"]], "bno": "", "adr": ""},
        # 장흥군 하나로 좁힌 수의계약에 넣음 → «전남 장흥군» 근거
        "B": {"dt": "20261002", "corps": [["을건설", "", "", "2222222222"]], "bno": "", "adr": ""},
        # 낙찰 — 본사 주소 여수
        "D": {"dt": "20261003", "corps": [], "bno": "3333333333", "win": "병건설",
              "adr": "전남광주통합특별시 여수시 시청로 1, 2층"},
        # 못 읽는 조각이 섞인 참가지역 → 지역 근거 안 붙임
        "E": {"dt": "20261004", "corps": [["정건설", "", "", "4444444444"]], "bno": "", "adr": ""},
    }}
    live = {"con": {
        "A": {"lic": ["토목공사업/0001"], "rgnb": "", "mthd": "제한경쟁", "rgn": "경기도"},
        "B": {"lic": ["토목공사업/0001"], "rgnb": "본사또는참여지사소재지", "mthd": "수의계약",
              "rgn": "전남광주통합특별시 장흥군", "rgk": ["전남 장흥군"]},
        "E": {"lic": ["토목공사업/0001"], "rgn": "경기도, 엉뚱한곳"},
    }}
    ev, _ = C.partner_evidence(first, live)
    봄("③ 제한경쟁(판단기준 빈 칸)의 참가지역도 지역 근거", ev.get("1111111111", {}).get("r") == {"경기": "20261001"},
       str(ev.get("1111111111", {}).get("r")))
    봄("③ 시 · 군 하나로 좁힌 공고 → 시 · 군 근거 + 시도 근거",
       ev.get("2222222222", {}).get("s") == {"전남 장흥군": "20261002"} and ev["2222222222"]["r"] == {"전남": "20261002"})
    봄("③ 낙찰 본사 주소 → «전남 여수시» · 전남", ev.get("3333333333", {}).get("s") == {"전남 여수시": "20261003"}
       and ev["3333333333"]["r"] == {"전남": "20261003"}, str(ev.get("3333333333")))
    봄("③ 못 읽는 조각이 섞이면 지역 근거 안 붙임(짐작 안 함)", ev.get("4444444444", {}).get("r") == {} and ev["4444444444"]["s"] == {})
    with tempfile.TemporaryDirectory() as d:
        led = os.path.join(d, "partners.json")
        C.save_json(led, {"v": 1, "c": {"3333333333": {"n": "병건설", "l": {"0001": "20261001"}, "r": {"전남": "20261001"}}}, "ln": {}})
        C.export_partners(first, live, out_dir=os.path.join(d, "p"), ledger_path=led, log=lambda *a: None)
        v = C.load_json(led, {})
        봄("③ 옛 장부(s 없음)에 시 · 군 근거를 붙여 쌓음", v["c"]["3333333333"].get("s") == {"전남 여수시": "20261003"}
           and v["c"]["2222222222"].get("s") == {"전남 장흥군": "20261002"}, str(v["c"]["3333333333"]))

print(f"\n{셈[0]}개 중 틀림 {len(틀림)}")
sys.exit(1 if 틀림 else 0)
