    def 그리기(self):
        덩 = []
        for (a, b, t) in self.벽들:
            덩.append(LineString([a, b]).buffer(t / 2, cap_style=3, join_style=2))
        벽 = unary_union(덩)
        뚫 = []
        for (w, s0, s1, 종, 쪽, 경첩) in self.구멍:
            a, b, t = self.벽들[w]
            dx, dy = b[0] - a[0], b[1] - a[1]
            L = math.hypot(dx, dy)
            ux, uy = dx / L, dy / L
            nx, ny = -uy, ux
            p0 = (a[0] + ux * s0, a[1] + uy * s0)
            p1 = (a[0] + ux * s1, a[1] + uy * s1)
            h = t / 2 + 1
            뚫.append(Polygon([(p0[0] + nx * h, p0[1] + ny * h), (p1[0] + nx * h, p1[1] + ny * h), (p1[0] - nx * h, p1[1] - ny * h), (p0[0] - nx * h, p0[1] - ny * h)]))
            m = t / 2
            if 종 == '창':
                for o in (-m, -25, 25, m):
                    self.선((p0[0] + nx * o, p0[1] + ny * o), (p1[0] + nx * o, p1[1] + ny * o), 'A-WIN')
            elif 종 == '문':
                W = s1 - s0
                # 경첩 — 열리는 쪽 벽 면 · 닫힌 문짝은 그 면을 따라 W
                hx, hy = (p0 if 경첩 == 0 else p1)
                ex, ey = (p1 if 경첩 == 0 else p0)
                hx, hy = hx + nx * m * 쪽, hy + ny * m * 쪽
                ex, ey = ex + nx * m * 쪽, ey + ny * m * 쪽
                ox, oy = hx + nx * W * 쪽, hy + ny * W * 쪽          # 열린 문짝 끝
                self.선((hx, hy), (ox, oy), 'A-DOOR')
                a_닫 = math.degrees(math.atan2(ey - hy, ex - hx))
                a_열 = math.degrees(math.atan2(oy - hy, ox - hx))
                # 호 — 반시계로 닫힘 → 열림 (90°)
                d = (a_열 - a_닫) % 360
                if d <= 180:
                    self.msp.add_arc((hx, hy), W, a_닫, a_열, dxfattribs={'layer': 'A-DOOR'})
                else:
                    self.msp.add_arc((hx, hy), W, a_열, a_닫, dxfattribs={'layer': 'A-DOOR'})
            elif 종 == '미닫이':
                for o in (-30, 30):
                    self.선((p0[0] + nx * o, p0[1] + ny * o), (p1[0] + nx * o, p1[1] + ny * o), 'A-DOOR')
        벽 = 벽.difference(unary_union(뚫)) if 뚫 else 벽
