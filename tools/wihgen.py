def 머리(ws, r, 끝, 제목, 아래제목, 칸들):
    """왼쪽 칸 + 가운데 제목 + 오른쪽 결재/점검 — 원본 그대로"""
    # 🔑 결재·점검 상자는 «폭 34칸 고정» 입니다. 제목 칸이 남는 만큼 넓어집니다.
    #    (칸수마다 비례로 나누면 서식마다 결재란 폭이 달라집니다 — 원본은 다 같습니다)
    왼라벨, 왼값, 오른 = 10, 22, 34
    가운데 = 끝 - (왼라벨 + 왼값 + 오른)
    ㄱ = 왼라벨 + 왼값 + 가운데 + 1               # 결재 시작 칸
    몇 = len(칸들)
    for i, (이름, 값) in enumerate(칸들):
        글(ws, r + i, 1, 왼라벨, " " + 이름, pt=9.5, 높=22)
        글(ws, r + i, 왼라벨 + 1, 왼라벨 + 왼값, " " + 값, pt=9.5, 맞="left")
    글(ws, r, 왼라벨 + 왼값 + 1, 왼라벨 + 왼값 + 가운데,
       제목 + (("\n" + 아래제목) if 아래제목 else ""), 굵=True, pt=16, 행=몇)
    # ── 결재 / 점검
    폭공사, 폭안전, 폭소장, 폭감독, 폭라벨 = 6, 6, 8, 6, 4
    c = ㄱ
    글(ws, r, c, c + 폭라벨 - 1, "결\n재", pt=9, 행=2); c += 폭라벨
    for 이름, w in (("공 사", 폭공사), ("안 전", 폭안전), ("현장소장", 폭소장)):
        글(ws, r, c, c + w - 1, 이름, pt=9, 높=18)
        글(ws, r + 1, c, c + w - 1, "", 높=30)
        c += w
    글(ws, r, c, c + 폭라벨 - 1, "점\n검", pt=9, 행=2); c += 폭라벨
    글(ws, r, c, c + 폭감독 - 1, "공사감독", pt=9)
    글(ws, r + 1, c, c + 폭감독 - 1, "")
    # "/" 줄
    c = ㄱ
    글(ws, r + 2, c, c + 폭라벨 - 1, "", 높=18); c += 폭라벨
    for w in (폭공사, 폭안전, 폭소장):
        글(ws, r + 2, c, c + w - 1, "/", pt=9); c += w
    글(ws, r + 2, c, c + 폭라벨 - 1, ""); c += 폭라벨
    글(ws, r + 2, c, c + 폭감독 - 1, "/", pt=9)
    if 몇 == 3:
        글(ws, r + 3, 1, 왼라벨 + 왼값 + 가운데, "", 테=False, 높=6)
    return r + max(몇, 3) + 1


