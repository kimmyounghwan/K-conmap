def 글(ws, r, c1, c2, t="", *, 굵=False, pt=10, 칠=None, 맞="center", 높=None,
       색=None, 테=True, 행=1):
    if c2 > c1 or 행 > 1:
        ws.merge_cells(start_row=r, start_column=c1, end_row=r + 행 - 1, end_column=c2)
    cell = ws.cell(r, c1, t)
    cell.font = Font(name=KF, size=pt, bold=굵, color=색)
    cell.alignment = {"center": 중앙, "left": 왼쪽, "lefttop": 왼위}[맞]
    if 칠:
        cell.fill = 칠
    if 테:
        for rr in range(r, r + 행):
            for cc in range(c1, c2 + 1):
                ws.cell(rr, cc).border = 칸선
    if 높:
        for rr in range(r, r + 행):
            ws.row_dimensions[rr].height = 높
    return cell


def 쪽(ws, 칸수, 가로=True):
    for c in range(1, 칸수 + 1):
        ws.column_dimensions[열(c)].width = 단위
    ws.page_setup.orientation = "landscape" if 가로 else "portrait"
    ws.page_setup.paperSize = 9
    ws.page_setup.fitToWidth = 1
    ws.page_setup.fitToHeight = 0
    ws.sheet_properties.pageSetUpPr.fitToPage = True
    ws.page_margins.left = ws.page_margins.right = 0.25
    ws.page_margins.top = ws.page_margins.bottom = 0.35


def 줄높이(글들, 폭칸, 최소=26, 한줄=14.5):
    """openpyxl 은 자동 행높이가 없습니다. 한글 한 자를 «두 칸» 으로 보고 줄 수를 셉니다.
       (formsgen.py 에서 1.35 를 곱했다가 글자가 잘렸던 그 자리입니다 — 8절 참조)"""
    최대 = 1
    for 글자, 칸 in zip(글들, 폭칸):
        if not 글자:
            continue
        한줄글자 = max(6, int(칸 * 단위 / 2.05))
        줄 = 0
        for 조각 in str(글자).split("\n"):
            줄 += max(1, -(-len(조각) // 한줄글자))
        최대 = max(최대, 줄)
    return max(최소, 한줄 * 최대 + 8)


def 자리(spans):
    out, c = [], 1
    for sp in spans:
        out.append((c, c + sp - 1)); c += sp
    return out


