/**
 * 📑 G686 «캐드 물량 ↔ 원 내역» 대조 시험 — lib/골조변경.js 골조대조(설정.캐드줄) · 캐드짝후보 · 바꿀것 · 변경모형 · 변경시트들 + lib/캐드고름.js 캐드대조줄
 *   소장님 11-14 「캐드에서 물량 찾고, 그 물량이 엑셀로 나와야 해 … 원 내역과 비교해서」
 *   가상 예시 모델 · 가상 예시 내역서(실제 현장 아님) · web/node_modules(fflate) 를 씀 → 클라우드에서만(PC 올리기 시험 목록엔 안 넣음)
 * 쓰는 법: node tools/시험_캐드내역대조.mjs
 */
import fs from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'
import path from 'node:path'

const 뿌리 = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const 불러 = (f) => import(pathToFileURL(path.join(뿌리, 'web', 'src', 'lib', f)).href)
const { 작업예시모델, 모델셈 } = await 불러('골조모델.js')
const { 내역읽기 } = await 불러('내역대조.js')
const { readWorkbook } = await 불러('qtoxlsx.js')
const { 변경엑셀 } = await 불러('변경엑셀쓰기.js')
const V = await 불러('골조변경.js')
const C = await 불러('캐드고름.js')
const D = await 불러('캐드부재.js')

let 됨 = 0
const 틀 = []
const 봄 = (조건, 글, 값) => { if (조건) { 됨++; console.log('  ✓ ' + 글) } else { 틀.push(글); console.log('  ✗ ' + 글 + (값 !== undefined ? ' = ' + JSON.stringify(값).slice(0, 700) : '')) } }
const 가까 = (a, b, e = 1e-6) => Number.isFinite(a) && Number.isFinite(b) && Math.abs(a - b) <= e * Math.max(1, Math.abs(b))
const T = '\t'
const 머 = (적요) => ['KCMSEL', '1', 'C:\\가상\\시험.dwg', '4', 적요, '0', '24.3', 'AutoCAD'].join(T)
const 선 = (h, a, c) => ['LINE', 'A-미장', h, '0', '0', `${a[0]},${a[1]};${c[0]},${c[1]}`, '0,0', '', '']
const 폴 = (h, la, P) => ['LWPOLYLINE', la, h, '1', '0', P.map((p) => `${p[0]},${p[1]},0`).join(';'), '', '', '']
const 받기 = (캐드, 줄들, 적요, M) => {
  const 읽 = C.고름읽기([머(적요), ...줄들.map((c) => c.join(T))].join('\r\n'))
  const 풀 = C.적요풀기(읽.머리.적요, M.층)
  const r = C.줄만들기(읽, { 이름: '시험.dwg', 층: 풀.층, 있는핸들: C.있는핸들(캐드) })
  if (풀.부재) r.줄 = C.부재넣기(r.줄, () => true, 풀.부재, 풀, M.층).줄
  return C.묶음더하기(캐드, r).캐드
}

console.log('📑 G686 캐드 물량 ↔ 원 내역 대조 시험')
const M = 작업예시모델(), S = 모델셈(M)
const 예바 = new Uint8Array(fs.readFileSync(path.join(뿌리, 'web', 'public', 'jeoksan', '골조예시_내역서.xlsx')))
const 내 = V.시트고르기(내역읽기(예바, '골조예시_내역서.xlsx'))

/* 캐드 — 벽 미장(길이 × 높이) 96.6 m × 3 m = 289.8 ㎡ · 액체방수(면적) 26 ㎡ · 기둥(세움 — 빼야 함) */
let 캐드 = { 묶음: [], 줄: [] }
캐드 = 받기(캐드, [선('A1', [0, 0], [40000, 0]), 선('A2', [0, 3000], [40000, 3000]), 선('A3', [0, 6000], [16600, 6000])], '1층 모르타르바름 벽', M)
캐드 = { ...캐드, 줄: 캐드.줄.map((r) => ({ ...r, 갈래: '길이높이', 높이: '3' })) }
캐드 = 받기(캐드, [폴('B1', 'A-방수', [[0, 0], [5000, 0], [5000, 4000], [0, 4000]]), 폴('B2', 'A-방수', [[0, 0], [3000, 0], [3000, 2000], [0, 2000]])], '지붕층 액체방수', M)
캐드 = 받기(캐드, [폴('K1', 'S-COL', [[50000, 0], [50600, 0], [50600, 600], [50000, 600]])], '2층 기둥 C9', M)
const 결 = D.부재로세우기(캐드, M)
봄(결.세움 === 1, '기둥 C9 하나 세움(그 줄은 캐드 대조에서 빠져야 함)', D.세움글(결))
const 세운 = D.세운줄(결.M)
const 줄 = C.캐드대조줄(C.캐드셈(캐드, { 세운 }))
const 미 = 줄.find((d) => d.품명 === '모르타르바름 벽'), 방 = 줄.find((d) => d.품명 === '액체방수')
봄(줄.length === 2 && 미 && 방, '캐드 대조 줄 둘(«1층 · 지붕층» 층 말 뗌 · 세운 기둥 뺌)', 줄)
봄(가까(미.수량, 96.6 * 3, 1e-9) && 미.단위 === '㎡' && 가까(방.수량, 26, 1e-9), '수량 — 미장 289.8 ㎡ · 방수 26 ㎡', [미.수량, 방.수량])

console.log('① 내역 줄과 짝')
const 판0 = V.골조대조(M, S, 내)
const 판 = V.골조대조(M, S, 내, { 캐드줄: 줄 })
const 모 = 판.줄.find((x) => x.r.내역.품명 === '모르타르바름')
봄(모 && 모.r.도면 && 모.r.도면.key === 미.key && 모.믿음 === '확실', '«모르타르바름 | 벽» ↔ 캐드 «모르타르바름 벽» — 확실한 짝', 모 && [모.r.도면 && 모.r.도면.key, 모.믿음, 모.까닭])
봄(모 && 가까(모.모델, 289.8, 1e-9) && 가까(모.율, (289.8 - 300) / 300 * 100, 1e-9) && 모.판정 === '도면이 적음', '차이 −3.4 % · «도면이 적음»', 모 && [모.모델, 모.율, 모.판정])
봄(모 && 모.기본넣음 && 모.넣음 && 모.변경 === 289.8, '확실 · 30 % 안 → 처음부터 넣음(변경 289.8)', 모 && [모.기본넣음, 모.넣음, 모.변경])
봄(판.캐드남음.length === 1 && 판.캐드남음[0].key === 방.key, '내역에 짝 없는 캐드 물량 — 액체방수(26 ㎡) 하나', 판.캐드남음)
봄(판.셈.캐드 === 2 && 판.셈.캐드짝 === 1, '셈 — 캐드 2 · 짝 1', 판.셈)
const 골만 = (P) => P.줄.filter((x) => !(x.r.도면 && x.r.도면.캐드)).map((x) => x.열쇠 + '|' + (x.r.도면 ? x.r.도면.key : '') + '|' + x.변경 + '|' + x.넣음).join('\n')
봄(골만(판) === 골만(판0), '골조 줄 짝 · 변경은 캐드 줄을 넣어도 그대로(골조 대조가 안 바뀜)')
봄(!판0.줄.some((x) => x.r.내역.품명 === '모르타르바름'), '캐드 줄이 없으면 미장 줄은 안 나옴(예전 그대로)')

console.log('② 사람이 짝 고르기(내역 줄 고르기)')
const 후 = V.캐드짝후보(방, 내, 판)
봄(후.length >= 7 && 후.every((c) => /M2/i.test(c.n.단위)), '후보 — 단위가 같은(㎡) 내역 줄만 ' + 후.length + '줄', 후.map((c) => c.n.품명 + ' ' + c.n.단위))
봄(후[0].n.품명 === '방수턱 거푸집', '닮은 차례 — «방수턱 거푸집» 이 맨 앞(이름 닮음)', 후.slice(0, 3).map((c) => c.n.품명 + ' ' + c.점.toFixed(2)))
봄(후.findIndex((c) => c.있) === -1 || 후.findIndex((c) => c.있) > 후.findIndex((c) => !c.있), '이미 짝이 있는 줄은 뒤로')
const 방턱 = 내.줄.find((n) => n.품명 === '방수턱 거푸집')
const 판2 = V.골조대조(M, S, 내, { 캐드줄: 줄, 짝: { [V.줄열쇠(방턱)]: 방.key } })
const 고 = 판2.줄.find((x) => x.r.내역.id === 방턱.id)
봄(고 && 고.r.도면 && 고.r.도면.key === 방.key && 고.r.고친짝 && 고.믿음 === '확실', '고른 짝 — 방수턱 거푸집 ↔ 캐드 액체방수(사람이 고른 짝)', 고 && [고.r.도면 && 고.r.도면.key, 고.믿음])
봄(고 && 가까(고.모델, 26, 1e-9) && 가까(고.율, 30, 1e-9) && 고.기본넣음, '26 ↔ 20 = +30 %(경계 — «30 % 넘음» 아님) → 사람이 고른 확실한 짝이라 넣음', 고 && [고.모델, 고.율, 고.기본넣음])
const 판3 = V.골조대조(M, S, 내, { 캐드줄: [{ ...방, 수량: 27 }], 짝: { [V.줄열쇠(방턱)]: 방.key } })
const 고3 = 판3.줄.find((x) => x.r.내역.id === 방턱.id)
봄(고3 && 고3.큼 && !고3.기본넣음 && !고3.넣음, '27 ↔ 20 = +35 % — 30 % 넘게 다름 → 처음엔 안 넣음(사람이 ☑)', 고3 && [고3.율, 고3.큼, 고3.기본넣음])
봄(판2.캐드남음.length === 0, '짝을 고르면 «못 찾은 캐드 물량» 에서 빠짐')

console.log('③ 받기 — 내 내역서에 넣기 · 설계변경 엑셀')
const 바 = V.바꿀것(판)
const 미바 = 바.find((x) => x.품명 === '모르타르바름')
봄(미바 && 미바.값 === 289.8 && 미바.전 === 300 && /📏 캐드/.test(미바.근거), '내 내역서에 넣기 — 모르타르바름 300 → 289.8 · 근거 «📏 캐드 · 캐드 고름 …»', 미바)
const 책 = readWorkbook(예바)
const 형 = V.변경모형(책, 판, '골조예시_내역서.xlsx')
const 품 = 형.줄.filter((x) => x.꼴 === '품목')
봄(품.some((x) => x.이름 === '모르타르바름' && x.값[1].수량 === 289.8 && x.바뀜), '설계변경 모형 — 미장 줄 당초 300 · 변경 289.8', 품.filter((x) => x.이름 === '모르타르바름'))
const 시 = V.변경시트들(형, 판)
const 대 = 시.find((s) => s.이름 === '건설맵 대조')
봄(대 && /캐 드/.test(대.제목) && 대.줄.some((r) => r[3] === '모르타르바름' && /📏 캐드/.test(r[16] || '') === false && /캐드 고름/.test(r[16] || '')), '«건설맵 대조» 시트 — 제목에 캐드 · 미장 줄 근거 «캐드 고름 n줄»', 대 && [대.제목, 대.줄.filter((r) => r[3] === '모르타르바름')])
const 시0 = V.변경시트들(V.변경모형(책, 판0, '골조예시_내역서.xlsx'), 판0)
봄(시0.find((s) => s.이름 === '건설맵 대조').제목 === '건 설 맵   대 조 (골 조 모 델 ↔ 내 역 서)', '캐드 줄이 없으면 제목 예전 그대로')
const 바이트 = 변경엑셀(시)
봄(바이트 && 바이트.length > 3000 && 바이트[0] === 0x50 && 바이트[1] === 0x4b, '설계변경 엑셀 만들어짐(PK)', 바이트 && 바이트.length)
const 기 = V.변경기대(형)
봄(기.바뀐 >= 1 && 기.품목 === 품.length, '변경 기대 — 바뀐 줄 포함', 기)

console.log(틀.length ? `\n✗ ${틀.length}개 틀림 / ✓ ${됨}` : `\n✓ 모두 ${됨}개 통과`)
process.exit(틀.length ? 1 : 0)
