/**
 * 🧭 G274 계단 — lib/골조자동.js 계단일람찾기 · 계단판찾기 + lib/골조.js 계단 셈(판 수 · 복배근 · 단수 빈 칸 · QT 괄호)
 *   node tools/시험_계단.mjs
 * tools/계단_시험도면.py 로 그린 «가상» 도면: 계단 일람표(ST1 · ST2) + 일반사항 꼴 제목 + 평면 계단판 둘 + 개구부 X
 */
import fs from 'fs'
import { 도면읽기, 단위배율 } from '../web/src/lib/골조도면.js'
import { decodeBytes } from '../web/src/lib/dxf3d.js'
import { _준비, _계단일람찾기, _계단판찾기 } from '../web/src/lib/골조자동.js'
import { 셈, 새공사, 예시공사 } from '../web/src/lib/골조.js'

let bad = 0
const ok = (이름, c, got) => { if (!c) bad++; console.log((c ? '  ✓ ' : '  ✗ ') + 이름 + (got !== undefined && !c ? ' = ' + JSON.stringify(got) : '')) }
const near = (a, b, t = 0.0015) => Math.abs(a - b) <= t
const b = fs.readFileSync(new URL('./시험자료/계단_시험.dxf', import.meta.url))
const M = 도면읽기(decodeBytes(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength)))
const D = { ..._준비(M, 단위배율(M.units, M.box, M.ox, M.oy).k || 1, 0), 이름: '계단_시험.dxf' }

console.log('① 계단 일람표 → 기호마다 두께 · 철근 · 단')
const 일 = _계단일람찾기([D])
const a = 일.get('ST1') || {}
ok('ST1 두께 «THK = 160»', a.두께 === '160', a.두께)
ok('ST1 주근 = (B) HD13@150 · 위 주근 = (T) HD13@200 · 복배근', a.주근 === 'HD13@150' && a.상부주근 === 'HD13@200' && a.배근 === '복배근', [a.주근, a.상부주근, a.배근])
ok('ST1 배력근 = 가장 가는 (T&B) HD10@250 · 참 = 굵은 (T&B) HD13@150', a.배력근 === 'HD10@250' && a.참주근 === 'HD13@150' && a.참배력근 === 'HD13@150', [a.배력근, a.참주근])
ok('ST1 단면 그림 챌판 170 · 디딤 270', a.단높이 === '170' && a.단너비 === '270', [a.단높이, a.단너비])
const c = 일.get('ST2') || {}
ok('ST2 = 옆 칸 «HD16@200» 하나(ST1 글을 안 가져감) · 단배근', c.주근 === 'HD16@200' && c.배근 === '단배근' && !c.배력근, c)
ok('일반사항 꼴 제목(«8.3 계단배근 상세») 곁 SS9 는 일람 아님', !일.has('SS9'))

console.log('② 평면 계단판(네모 + 대각선 하나)')
const 글 = (s) => D.글자.filter((g) => g.s.trim() === s).sort((p, q) => q.x - p.x)[0]      // 평면 쪽(오른쪽) 글
const st = _계단판찾기(D, 글('ST1'))
ok('판 둘 · 폭 1,200 · 길이 (2,700 + 2,400) / 2 = 2,550', st && st.판.length === 2 && st.W === 1200 && st.L === 2550, st && [st.판.length, st.W, st.L])
ok('끝이 맞은 쪽(위) = 중간참 1,500 · 아래 = (1,000 + 1,300) / 2 = 1,150', st && st.상단참 === 1500 && st.하단참 === 1150, st && [st.상단참, st.하단참])
ok('개구부(대각선 둘 X) 곁 SS2 는 계단판 아님', _계단판찾기(D, 글('SS2')) === null)

console.log('③ 셈 — 판 수 · 복배근 · 빈 단수(층고 ÷ 판 수 ÷ 단 높이) · QT 2 는 식 전체에')
const P = 새공사()
P.층 = [{ 이름: 'FT', 층고: 0, 슬라브: 0 }, { 이름: '1', 층고: 3400, 슬라브: 150 }, { 이름: '2', 층고: 0, 슬라브: 0 }]
P.배근.계단 = [{ 기호: 'ST1', 두께: '160', 주근: 'HD13@150', 상부주근: 'HD13@200', 배력근: 'HD10@250', 참주근: 'HD13@150', 참배력근: 'HD13@150', 배근: '복배근', 단높이: '170' }]
P.동[0].주자료.계단 = [{ 층: '1', 기호: 'ST1', 단수: '', 길이: '2550', 폭: '1200', 하단참: '1150', 상단참: '1500', L정착: '0', W정착: '0', QT: '2', C: '', F: '', 챌판F: '', R: '', _판수: '2' }]
const R = 셈(P)
const 줄 = R.줄.filter((x) => x.부재 === '계단')
const 콘 = 줄.find((x) => x.항목 === '콘크리트')
// 한 판 1,700 오름 · 10단 · 빗길이 √(2.55² + 1.7²) = 3.0647 · 2×(1.2×0.16×3.065 + 1.2×10×0.255×0.17/2) + (1.15+1.5)×2×1.2×0.16 = 2.2770 + 1.0176 → × 2
const s = Math.sqrt(2.55 ** 2 + 1.7 ** 2)
const 콘기대 = Math.round((2 * (1.2 * 0.16 * +s.toFixed(3) + 1.2 * 10 * 0.255 * 0.17 / 2) + (1.15 + 1.5) * 2 * 1.2 * 0.16) * 2 * 1000) / 1000
ok('콘크리트 = (경사판 2 + 디딤 + 참) × QT 2 = ' + 콘기대, 콘 && near(콘.수량, 콘기대), 콘 && [콘.수량, 콘.식])
const 이름들 = 줄.filter((x) => x.항목 === '철근').map((x) => x.비고.split(' ')[0] + ' ' + (x.비고.split(' ')[1] || ''))
ok('철근 줄: 하부 주근 · 상부 주근 · 배력근 · 하단참 · 상단참', ['하부 주근', '상부 주근', '배력근', '하단참', '상단참'].every((k) => 줄.some((x) => x.항목 === '철근' && x.비고.includes(k))), 이름들)
const 하 = 줄.find((x) => x.항목 === '철근' && x.비고.includes('하부 주근'))
// 9개(⌈1200/150⌉+1) × 2판 × 빗길이 3.065 × 0.995 × 2
ok('하부 주근 9 × 2판 × 3.065 × 0.995 × QT 2', 하 && near(하.수량, Math.round(18 * 3.065 * 0.995 * 2 * 1000) / 1000, 0.01), 하 && [하.수량, 하.식])
const 배 = 줄.find((x) => x.항목 === '철근' && x.비고.startsWith('배력근'))
// (⌈3065/250⌉+1 = 14) × 2판 × 2겹 × 1.2 × 0.56 × 2
ok('배력근 14 × 2판 × 위아래 2겹 × 1.2 × 0.56 × QT 2', 배 && near(배.수량, Math.round(56 * 1.2 * 0.56 * 2 * 1000) / 1000, 0.01), 배 && [배.수량, 배.식])

console.log('④ 예시 공사 계단(단배근 · 판 수 비움)은 예전과 같음')
const E = 셈(예시공사())
const ec = E.줄.find((x) => x.부재 === '계단' && x.항목 === '콘크리트')
ok('예시 ST1 콘크리트 식 그대로(«2*(» 로 시작 · QT 1)', ec && /^2\*\(/.test(ec.식) && !/\*1$/.test(ec.식), ec && ec.식)

console.log(bad ? `\n✗ ${bad}건 틀림` : '\n✓ 모두 맞음')
process.exit(bad ? 1 : 0)
