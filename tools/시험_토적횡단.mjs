  ok('알림: 선으로 잰 면적은 어림 · 표 값 권함', G.알림.some((a) => /선으로 잰 면적은 잘게 나눈 칸으로 잰 어림/.test(a)), G.알림)
  const T = 토적셈({ 설정: { 간격: String(G.간격) }, 칸: G.칸.map((c) => (c.종 === '성' ? c : { ...c, C: '1' })), 줄: G.줄 })
  ok('토적셈: 오류 0 · 📏 거리 알림 없음 · 길이 500 m · 검산 맞음 · 터파기 > 0', !T.오류.length && !T.경고.some((w) => /📏/.test(w)) && T.합.길이 === 500 && T.검산.맞음 && T.합.칸[0] > 0, [T.오류, T.경고, T.합.길이])
