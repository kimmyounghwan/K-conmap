let bad = 0
const ok = (이름, c, got) => { if (!c) bad++; console.log((c ? '  ✓ ' : '  ✗ ') + 이름 + (got !== undefined ? ' = ' + JSON.stringify(got) : '')) }
const 같다 = (a, b, e = 1e-6) => Math.abs(a - b) < e

console.log('① 글자 도우미')
ok('측점 STA.0+020.000 → 20', A.측점값('STA.0+020.000') === 20)
ok('측점 STA. 1+250.5 → 1250.5', A.측점값('STA. 1+250.5') === 1250.5)
ok('측점 0-060.0000 → −60', A.측점값('STA.0-060.0000') === -60)
ok('측점 NO.5+10 → 110 · NO.7 → 140', A.측점값('NO.5+10') === 110 && A.측점값('NO.7') === 140)
ok('표 제목: 「철 근 재 료 표」 예 · 「범례」 아니오 · 「도면목록표」 아니오', A.표제목인가('철 근 재 료 표') && !A.표제목인가('범례') && !A.표제목인가('도면목록표'))
ok('칸 숫자: 「IP2 4.113」 → 4.113', A.칸숫자('IP2 4.113') === 4.113)

const buf = fs.readFileSync(new URL('../web/public/jeoksan/토목_예시.dxf', import.meta.url))
const M = 도면읽기(decodeBytes(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength)))

console.log('② 표')
const 표 = A.표찾기(M)
ok('표 2개 (철근 재료표 · 수량표)', 표.length === 2 && 표.some((t) => t.종류 === '철근') && 표.some((t) => t.종류 === '수량'), 표.map((t) => t.제목 + ':' + t.종류))
const 철표 = 표.find((t) => t.종류 === '철근')
ok('철근표 칸 뜻', JSON.stringify(철표.뜻) === JSON.stringify(['기호', '직경', '길이', '개수', '총길이', '단위무게', '총무게']), 철표.뜻)
ok('〃 → 위 칸 (B2 = H13)', 철표.줄[1][1] === 'H13', 철표.줄[1])
const R = A.철근모으기(표)
const kg = (d) => (R.합.find((a) => a.d === d) || {}).kg
ok('D13 = (1.2×20 + 2.5×10) × 0.995 = 48.755 kg', 같다(kg('D13'), 48.755), kg('D13'))
ok('D16 = (3.1×12 + 1.85×8) × 1.56 = 81.12 kg', 같다(kg('D16'), 81.12), kg('D16'))
ok('D22 = 4.2×6 × 3.04 = 76.608 kg', 같다(kg('D22'), 76.608), kg('D22'))
ok('소계 검산 걸린 것 없음', R.검산.length === 0, R.검산)
const Q = A.수량모으기(표)
ok('수량표 4품목 · 레미콘 18.4 m3', Q.합.length === 4 && Q.합.find((a) => a.품명 === '레미콘').수량 === 18.4, Q.합.map((a) => a.품명 + ' ' + a.수량))

console.log('③ 횡단면 토공')
const 노선 = A.노선묶기(A.측점찾기(M))
ok('노선 1개 · 측점 5개', 노선.length === 1 && 노선[0].점.length === 5)
const g = 노선[0]
const s = A.본측점고르기(g)
const 네모 = A.본네모짐작(M, s, g.점)
const 본 = A.본만들기(M, s, 네모, g.점)
const 이름들 = 본.칸.map((c) => c.이름)
ok('칸 이름 (지반고·계획고·토사·노체·표토제거·리핑암·노상·떼붙임·발파암)', ['지반고', '계획고', '토사', '노체', '표토제거', '리핑암', '노상', '발파암'].every((n) => 이름들.includes(n)) && 이름들.some((n) => /떼붙임/.test(n)), 이름들)
ok('지반고·계획고는 안 씀', 본.칸.filter((c) => !c.쓰기).map((c) => c.이름).sort().join() === '계획고,지반고')
const 결 = A.평균단면(A.본읽기(M, 본, g.점), 본.칸)
const 합 = (n) => 결.합[본.칸.findIndex((c) => c.이름 === n)]
ok('토사 = (12.4+15.8)/2×20 + (15.8+6.2)/2×20 + (6.2+0)/2×20 + (0+2.5)/2×20 = 589', 같다(합('토사'), 589), 합('토사'))
ok('노체 = 0 + (0+5.3)×10 + (5.3+18.6)×10 + (18.6+9.4)×10 = 572', 같다(합('노체'), 572), 합('노체'))
ok('발파암 = (0+0.8)×10 + (0.8+0)×10 = 16', 같다(합('발파암'), 16), 합('발파암'))
const 떼 = 본.칸.find((c) => /떼붙임/.test(c.이름))
ok('떼붙임(길이) 은 m 단위 → m²', 떼.단위 === 'm')

console.log('④ 세기')
const S = A.세기(M, { k: 1000 })
const 층 = (n) => S.층.find((a) => a.이름 === n)
ok('C-측구 선 2개 160 m', 층('C-측구').선수 === 2 && 같다(층('C-측구').길이m, 160), 층('C-측구').길이m)
ok('C-관로 30 + √404 + 14.5 m', 같다(층('C-관로').길이m, 30 + Math.sqrt(404) + 14.5, 1e-6), 층('C-관로').길이m)
ok('블록 집수정 4 · 가로등 3', S.블록.find((b) => b.이름 === '집수정').수 === 4 && S.블록.find((b) => b.이름 === '가로등').수 === 3)
const 네모세기 = A.세기(M, { k: 1000, 네모: [-40 - M.ox, -90 - M.oy, 0 - M.ox, -70 - M.oy] })
ok('네모(왼쪽 반) 안 집수정 2개', (네모세기.블록.find((b) => b.이름 === '집수정') || {}).수 === 2, 네모세기.블록)

console.log('⑤ 엑셀')
let 받은 = null
const 쓰기 = (sheets) => { 받은 = sheets; return new Uint8Array(1) }
const ST = { PLAIN: 0, BOX: 1, HEAD: 2, QTY: 3, GRAY: 4, RED: 5, INT: 6, DEC2: 7, PCT: 8, FILLIN: 9 }
A.자동엑셀({
  줄: [{ 구분: '토공', 품명: '토사', 단위: 'm³', 수량: 589, 토공: { t: 0, j: 0 } }, { 구분: '철근', 품명: '철근', 단위: 'kg', 수량: 48.755, 식: '(24+25)*0.995' }],
  철근줄: R.줄, 토공들: [{ 이름: '노선1', 칸: [{ 이름: '토사', 단위: '㎡' }], 점: 결.점.map((p) => ({ 글: p.글, 측: p.측, 값: [p.값[본.칸.findIndex((c) => c.이름 === '토사')]] })) }], 표들: 표,
}, 쓰기, ST)
ok('시트: 산출서 · 철근 재료표 · 토공 노선1 · 표 2장', 받은.map((x) => x.name).join('|') === '산출서|철근 재료표|토공 노선1|표 철근재료표|표 주요자재수량표', 받은.map((x) => x.name))
ok('산출서 토공 줄 → 토공 시트 합계 칸', 받은[0].rows[0][6].f === "ROUND('토공 노선1'!F7,3)", 받은[0].rows[0][6])
ok('토공 시트 평균·수량 식', 받은[2].rows[1][4].f === '(D3+D2)/2' && 받은[2].rows[1][5].f === 'ROUND(E3*C3,3)', 받은[2].rows[1])
console.log(bad ? '\n✗ 틀린 것 ' + bad + '개' : '\n✓ 모두 맞음')
process.exit(bad ? 1 : 0)
