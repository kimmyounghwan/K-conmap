def 기간(s):
    """«1. X (2025.1.1 ~ 2027.12.31) 2. X (2027.1.1 ~ …)» → 지금 판 · 다음 판"""
    ps = re.findall(r'\((\d{4})\.(\d{1,2})\.(\d{1,2})\s*~\s*(\d{4})\.(\d{1,2})\.(\d{1,2})\)', s)
    지금, 다음 = None, None
    for p in ps:
        a = tuple(int(x) for x in p[:3])
        b = tuple(int(x) for x in p[3:])
        if a <= TODAY <= b:
            지금 = (a, b)
        elif a > TODAY and (다음 is None or a < 다음[0]):
            다음 = (a, b)
    f = lambda t: f'{t[0]}. {t[1]}. {t[2]}.'   # noqa: E731
    out = f'{f(지금[0])} ~ {f(지금[1])}' if 지금 else ''
    if 다음:
        out += (' · ' if out else '') + f'다음 판 {f(다음[0])}부터'
    return out


def 실기꼴(s):
    if '복합형' in s or ('작업형' in s and '필답형' in s):
        return '복합형(필답 + 작업)'
    if '작업형' in s:
        return '작업형'
    if '필답형' in s:
        return '필답형'
    return s


def 회차글(s):
    xs = [re.sub(r'^2026년\s*', '', x.strip()).strip() for x in s.split('·') if x.strip()]
    if all(re.match(r'정기 기사 \d회', x) for x in xs):
        return '정기 기사 ' + ' · '.join(re.search(r'(\d)회', x).group(1) for x in xs) + '회'
    return ' · '.join(xs)


