def 날(s):
    """큐넷 날짜 칸 → «1. 12. ~ 1. 15.» (빈자리 접수는 아래 줄)"""
    s = (s or '').strip()
    if not s:
        return '—'
    빈 = ''
    m = re.search(r'\[?\s*빈자리접수\s*:\s*([\d.]+)\s*~\s*([\d.]+)\s*\]?', s)
    if m:
        빈 = m.group(0)
        s = s.replace(빈, '').strip()
    if '/' in s and re.match(r'^[\d.~ /]+$', s):     # 기술사 면접 접수 «3.3~3.6/3.30~4.2»(두 번)
        return ' · '.join(날(x) for x in s.split('/'))

    def 짧(x):
        mm = re.match(r'^(\d{4})\.(\d{1,2})\.(\d{1,2})$', x.strip())
        return f'{int(mm.group(2))}.\u00a0{int(mm.group(3))}.' if mm else x.strip()   # NBSP — 폰 좁은 칸에서 «1.» / «12.» 로 갈라지지 않게
    if not re.match(r'^[\d.~ ]+$', s):
        return s     # 글(특성화고 검정 등)은 그대로
    parts = [짧(x) for x in s.split('~')]
    out = ' ~ '.join(parts)
    if m:
        out += f'\n(빈자리 {짧(m.group(1))} ~ {짧(m.group(2))})'
    return out


def 평균(xs):
    """합격률(소수 한 자리) 평균 — 분수로 셈해 반올림(파이썬 3.11 · 3.12 의 float sum 차이로 25.9 / 26.0 이 갈리던 것 막음)"""
    from fractions import Fraction
    t = [Fraction(round(x * 10), 10) for x in xs]
    assert all(abs(float(a) - x) < 1e-9 for a, x in zip(t, xs)), xs
    v = int(sum(t) / len(t) * 10 + Fraction(1, 2))     # 0.05 는 올림
    return f'{v // 10}.{v % 10}'


