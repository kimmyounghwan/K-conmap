eq(옮김(옮1.새, 때에(12, 30)).인사, null, '그 뒤로 오후 안에서는 없음')
eq(옮김(null, 아침).인사, null, '저장된 것 없으면(처음 인사 전) 옮김으로는 안 띄움')
