eq([d.인사, d.새.n], [null, 2], '오전에 2시간 뒤 다시 → 방문은 2번째, 오전 인사는 이미 함')

console.log('3) 때가 바뀜 — 하루 세 번')
const e = 방문(d.새, 때에(13))
eq([e.인사, e.새.n, e.새.slot], ['다시', 3, '2026-09-29 오후'], '오후 1시 다시 → 오후 인사')
