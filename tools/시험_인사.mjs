eq([i.인사, i.새.day, i.새.slot], ['다시', '2026-09-30', '2026-09-30 오전'], '다음 날 아침 → 오전 인사')
const 셋 = [때에(9), 때에(13), 때에(19)].reduce((s, t) => { const r = 방문(s.v, t); return { v: r.새, n: s.n + (r.인사 ? 1 : 0) } }, { v: { n: 3, last: 0, day: '2026-09-28', slot: '2026-09-28 저녁' }, n: 0 })
