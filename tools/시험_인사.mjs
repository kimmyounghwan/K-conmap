let ok = 0, bad = 0
const eq = (got, want, what) => {
  const g = JSON.stringify(got), w = JSON.stringify(want)
  if (g === w) { ok++; console.log('  ✓', what) } else { bad++; console.log('  ✗', what, '— 나온 값', g, '· 바란 값', w) }
}
const 때에 = (h, m = 0, d = 29) => new Date(2026, 8, d, h, m).getTime()
const 아침 = 때에(9)
const 분 = 60 * 1000, 시간 = 60 * 분

console.log('1) 처음')
const a = 방문(null, 아침)
eq([a.인사, a.새.n, a.새.day, a.새.slot], ['처음', 1, '2026-09-29', '2026-09-29 오전'], '저장된 것 없음 → 반갑습니다(1번째) · 오전 칸 적음')
eq(방문({}, 아침).인사, '처음', '망가진 저장 → 처음으로')
eq([방문(null, 아침, { 전에옴: true }).인사, 방문(null, 아침, { 전에옴: true }).새.n], ['다시', 2], '이 기능 전부터 다녀가신 분(사이트 흔적 있음) → «다시»')

console.log('2) 같은 때(오전) 안')
