// 📋 G442 받기 전 검사(lib/받기전검사.js) — 통과 · 못 통과(셈 오류 · 합계 틀림 · 화면과 다름 · 시트 없음) · 숫자만 · 골조 예시 둘
//   node tools/시험_받기전검사.mjs
import { 받기전검사, 골조맞댈, 토목맞댈, 집계맞댈, 산출서맞댈, 넣은칸검사 } from '../web/src/lib/받기전검사.js'
import { 셀바꾸기 } from '../web/src/lib/내역채움.js'
import { writeWorkbook } from '../web/src/lib/qtoxlsx.js'
import { 엑셀읽기 } from '../web/src/lib/엑셀읽기.js'
import { ST } from '../web/src/lib/qtoxlsx.js'
import { 작업예시모델, 예시모델, 모델셈, 모델시트 } from '../web/src/lib/골조모델.js'
import { 엑셀 as 골조엑셀, 셈 as 골조셈, 예시공사 as 골조예시 } from '../web/src/lib/골조.js'
import { 엑셀 as 마감엑셀, 셈 as 마감셈, 예시공사 as 마감예시 } from '../web/src/lib/마감.js'
import { 자동엑셀 } from '../web/src/lib/도면자동.js'

let 맞 = 0, 틀 = 0
const ok = (말, c, 더 = '') => { if (c) 맞++; else 틀++; console.log(c ? '✓' : '✗', 말, c ? '' : 더) }
const 수식수 = (바이트) => { let n = 0; for (const s of 엑셀읽기(바이트).시트들) for (const [, x] of s.칸) if (x.f) n++; return n }

/* ① 맞는 시트 — 합계 식 · 화면 값 같음 → 통과 · 맨 앞 «검사 결과» · 식 0 */
const 시트 = () => [{ name: '집계', head: ['이름', '콘크리트(㎥)', '거푸집(㎡)'], rows: [['가', { v: 1.25, st: ST.QTY }, { v: 10, st: ST.QTY }], ['나', { v: 2.5, st: ST.QTY }, { v: 20.5, st: ST.QTY }], ['합계', { f: 'SUM(B2:B3)', st: ST.QTY }, { f: 'SUM(C2:C3)', st: ST.QTY }]] }]
let r = 받기전검사(시트(), [{ 이름: '콘크리트 합', 시트: '집계', 줄: '합계', 열: '콘크리트(㎥)', 값: 3.75, 단위: '㎥' }])
ok('① 맞는 시트 → 통과', r.통과, JSON.stringify(r.줄))
const 책 = 엑셀읽기(r.바이트)
ok('① 맨 앞 시트 = «검사 결과» · 그다음 원래 시트', 책.시트들[0].이름 === '검사 결과' && 책.시트들[1].이름 === '집계', 책.시트들.map((s) => s.이름).join(','))
ok('① 받는 파일에 식 칸 0(숫자만)', 수식수(r.바이트) === 0, 수식수(r.바이트))
ok('① 합계 칸이 셈한 값(3.75)', +책.시트들[1].칸.get('B4').v === 3.75, JSON.stringify(책.시트들[1].칸.get('B4')))
ok('① 화면 글에 «값만» · «수식 없음» 이라는 말 없음', r.줄.every((x) => !/값만|수식 없/.test(x.글)), r.줄.map((x) => x.글).join(' | '))

/* ② 화면과 다름 → 못 통과 · 그 줄이 ✗ */
r = 받기전검사(시트(), [{ 이름: '콘크리트 합', 시트: '집계', 줄: '합계', 열: '콘크리트(㎥)', 값: 3.9, 단위: '㎥' }])
ok('② 화면 3.9 ≠ 엑셀 3.75 → 못 통과', !r.통과 && r.줄.some((x) => !x.됨 && /≠ 화면 3\.90/.test(x.글)), JSON.stringify(r.줄))
ok('② 못 통과여도 파일은 만들어 둠(알고 받기)', r.바이트 && r.바이트.length > 1000)

/* ③ 합계가 위 줄 합과 다름(손으로 넣은 합계) → 못 통과 */
const 틀린합 = 시트(); 틀린합[0].rows[2][1] = { v: 4, st: ST.QTY }
r = 받기전검사(틀린합, [])
ok('③ 합계 4 ≠ 위 줄 합 3.75 → 못 통과', !r.통과 && r.줄.some((x) => !x.됨 && /합계가 위 줄 합과 다름/.test(x.글)), JSON.stringify(r.줄))

/* ④ 셈 오류(0 으로 나눔) → 못 통과 */
const 나눔 = 시트(); 나눔[0].rows.push(['비율', { f: 'B2/0' }, ''])
r = 받기전검사(나눔, [])
ok('④ 0 으로 나눔 → 셈 오류 · 못 통과', !r.통과 && r.줄.some((x) => !x.됨), JSON.stringify(r.줄))

/* ⑤ 시트 · 줄을 못 찾음 → 못 통과(조용히 넘기지 않음) */
r = 받기전검사(시트(), [{ 이름: '없는 시트', 시트: '토목 집계', 줄: '합계', 열: '콘크리트(㎥)', 값: 1 }, { 이름: '없는 줄', 시트: '집계', 줄: '다', 열: '콘크리트(㎥)', 값: 1 }])
ok('⑤ 시트 없음 · 줄 없음 → 둘 다 ✗', !r.통과 && r.줄.filter((x) => !x.됨).length === 2, JSON.stringify(r.줄))

/* ⑥ 줄합 — 첫 칸이 같은 줄을 모두 더함 */
const 부분 = [{ name: '구조물(부분별)', head: ['구조물', '부분', '콘크리트(㎥)'], rows: [['갑', '바닥', { v: 1.1 }], ['갑', '벽', { v: 2.2 }], ['을', '벽', { v: 5 }], ['합계', '', { v: 8.3 }]] }]
r = 받기전검사(부분, [{ 이름: '갑 합', 시트: '구조물(부분별)', 줄: '갑', 열: '콘크리트(㎥)', 값: 3.3, 줄합: true }])
ok('⑥ 줄합 갑 = 1.1 + 2.2 = 3.3 · 합계 8.3 = 위 줄 합', r.통과, JSON.stringify(r.줄))

/* ⑦ 골조 예시 둘 — 산출서 · 집계 · 부재별 · 모델 시트 → 통과 · 식 0 · 부재별 합계 = 화면 합 */
for (const [이름, M] of [['작업 예시', 작업예시모델()], ['예시', 예시모델()]]) {
  const S = 모델셈(M)
  const g = 받기전검사([...골조엑셀(S.공사, S.R, (s) => s, ST), ...모델시트(M, S, ST)], 골조맞댈(S))
  ok(`⑦ 골조 ${이름} — ${g.줄.length}가지 모두 통과 · 식 0`, g.통과 && 수식수(g.바이트) === 0, JSON.stringify(g.줄.filter((x) => !x.됨)))
}
/* ⑧ 맞댈 값 만들기 — 빈 것은 빈 목록 */
ok('⑧ 골조맞댈(null) · 토목맞댈(null) = []', 골조맞댈(null).length === 0 && 토목맞댈(null, null).length === 0)

/* ⑨ 🏢 골조 수량산출(골조.js 엑셀) — «집계» 시트 줄마다 = 화면 집계 · 식 0 (G444) */
{
  const 공 = 골조예시(), R = 골조셈(공)
  const g = 받기전검사(골조엑셀(공, R, (s) => s, ST), 집계맞댈(R.집계.합, '산출수량'))
  ok(`⑨ 골조 수량산출 예시 — ${g.줄.length}가지 모두 통과 · 집계 ${R.집계.합.length}줄 · 식 0`, g.통과 && 수식수(g.바이트) === 0 && g.줄.some((x) => /줄 모두 화면 셈과 같음/.test(x.글)), JSON.stringify(g.줄))
  const 틀린 = R.집계.합.map((x, i) => (i === 0 ? { ...x, 산출: x.산출 + 1 } : x))
  const h = 받기전검사(골조엑셀(공, R, (s) => s, ST), 집계맞댈(틀린, '산출수량'))
  ok('⑨ 화면 집계 한 줄이 다르면 → 못 통과 · 그 줄 이름', !h.통과 && h.줄.some((x) => !x.됨 && /다름 1 · 못 찾음 0/.test(x.글) && x.글.includes(R.집계.합[0].항목)), JSON.stringify(h.줄.filter((x) => !x.됨)))
}
/* ⑩ 🎨 마감 수량산출(마감.js 엑셀) — «집계» 시트 수량 = 화면 집계 */
{
  const 공 = 마감예시(), R = 마감셈(공)
  const g = 받기전검사(마감엑셀(공, R, (s) => s, ST), 집계맞댈(R.집계.합, '수량'))
  ok(`⑩ 마감 수량산출 예시 — ${g.줄.length}가지 모두 통과 · 집계 ${R.집계.합.length}줄 · 식 0`, g.통과 && 수식수(g.바이트) === 0 && R.집계.합.length > 3, JSON.stringify(g.줄.filter((x) => !x.됨)))
}
/* ⑪ 📐 도면 물량 자동(자동엑셀) — «산출서» 줄마다 수량 = 화면 · 토공 줄 = 토공 시트 합계 · «표 …»(도면 표) 합계는 안 봄 */
{
  const 토공들 = [{ 이름: '노선1', 칸: [{ 이름: '토사', 단위: '㎡' }], 점: [{ 글: 'NO.0', 측: 0, 값: [10.123] }, { 글: 'NO.1', 측: 20, 값: [12.456] }, { 글: 'NO.2', 측: 40, 값: [9.871] }] }]
  const 토사 = ((10.123 + 12.456) / 2) * 20 + ((12.456 + 9.871) / 2) * 20
  const 줄 = [{ 구분: '토공', 품명: '토사', 단위: 'm³', 수량: 토사, 토공: { t: 0, j: 0 } }, { 구분: '철근', 품명: '철근', 단위: 'kg', 수량: 48.755, 식: '(24+25)*0.995' }, { 구분: '세기', 품명: '집수정', 단위: '개', 수량: 4 }]
  const 표들 = [{ 제목: '수량표', 머리: ['품명', '수량'], 줄: [['가', '1'], ['나', '2'], ['합계', '4']] }]
  const sh = 자동엑셀({ 줄, 토공들, 표들 }, (s) => s, ST)
  const g = 받기전검사(sh, 산출서맞댈(줄, 토공들), { 합계안봄: /^표 / })
  ok('⑪ 도면 물량 자동 — 산출서 3줄 = 화면 · 토공 합계 · 식 0 · 도면 표 합계(4 ≠ 3)는 안 봄', g.통과 && 수식수(g.바이트) === 0, JSON.stringify(g.줄))
  const h = 받기전검사(sh, 산출서맞댈(줄.map((x, i) => (i === 1 ? { ...x, 수량: 50 } : x)), 토공들), { 합계안봄: /^표 / })
  ok('⑪ 화면 철근 50 ≠ 엑셀 48.755 → 못 통과', !h.통과 && h.줄.some((x) => !x.됨 && /2 엑셀 48\.755 ≠ 화면 50\.000/.test(x.글)), JSON.stringify(h.줄.filter((x) => !x.됨)))
  const k = 받기전검사(sh, 산출서맞댈(줄, 토공들))
  ok('⑪ (합계안봄 없이) 도면 표 합계 4 ≠ 3 → 못 통과(그래서 도면 표는 안 봄)', !k.통과, JSON.stringify(k.줄.filter((x) => !x.됨)))
}

/* ⑫ 📑 물량 넣은 내역서 — 다시 열어 넣은 칸 = 화면 값 · 소장님 내역서의 식(금액)은 그대로 */
{
  const 원 = writeWorkbook([{ name: '내역', head: ['품명', '규격', '단위', '수량', '단가', '금액'], rows: [['레미콘', '25-24-150', 'm3', '', { v: 80000 }, { f: 'D2*E2' }], ['거푸집', '합판 3회', 'm2', { v: 5 }, { v: 30000 }, { f: 'D3*E3' }]] }])
  const r = 셀바꾸기(원, [{ id: 1, 시트: '내역', 줄: 2, 칸: 3, 값: 12.345, 전: null, 품명: '레미콘', 규격: '25-24-150', 단위: 'm3' }, { id: 2, 시트: '내역', 줄: 3, 칸: 3, 값: 40.5, 전: 5, 품명: '거푸집', 규격: '합판 3회', 단위: 'm2' }], { 도면: '가상' })
  const g = 넣은칸검사(r.bytes, r.됨)
  ok('⑫ 물량 넣은 내역서 — 넣은 칸 2곳 = 화면 · 통과 · 금액 식은 그대로', g.통과 && r.됨.length === 2 && 수식수(g.바이트) === 2, JSON.stringify([g.줄, r.됨.length, 수식수(g.바이트)]))
  const h = 넣은칸검사(r.bytes, r.됨.map((x, i) => (i === 0 ? { ...x, 값: 13 } : x)))
  ok('⑫ 화면 13 ≠ 넣은 칸 12.345 → 못 통과', !h.통과 && /다름 1곳/.test(h.줄[1].글), JSON.stringify(h.줄))
  ok('⑫ 못 여는 파일 → 못 통과', !넣은칸검사(new Uint8Array([1, 2, 3]), []).통과)
}

console.log(`${맞 + 틀}개 중 맞음 ${맞} · 틀림 ${틀}`)
console.log(틀 ? '✗ 틀림 있음' : '✓ 모두 맞음')
process.exit(틀 ? 1 : 0)
