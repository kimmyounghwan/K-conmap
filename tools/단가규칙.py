"""단가를 «묶는 규칙» — 여기 한 곳에만 둡니다 (2026-09-16).

  왜 한 곳인가
    CLAUDE.md 9절 ⑤: 「묶는 규칙은 한 곳에만. 잘못 묶으면 중앙값이 통째로 헛것이 됩니다」
    — 「대유건설」 아홉 곳을 한 덩어리로 묶었던 것과 같은 사고를 막기 위한 것입니다.
    naeyeok_book.py(엑셀 책)와 단가사전.py(사전) 가 «둘 다» 이 파일을 씁니다.
    한쪽만 고치면 두 결과가 갈라집니다.

  무엇을 하나
    ① 시트 이름으로 «갈래» 를 가릅니다        - 규칙 ⑥ (설계/계약·관급을 섞지 않기 위한 첫걸음)
    ② 항목이 «아닌» 줄을 걷어냅니다           - 머리글 · 집계줄 · 파싱 오류
    ③ 일위대가 «안에서만» 뜻이 있는 줄을 뺍니다 - 공구손료 · 잡재료 처럼 %로 매번 달라지는 것
    ④ 노임 직종을 뺍니다                      - 표준노임단가는 «유료 자료» 입니다
    ⑤ 이름을 다듬어 열쇠를 만듭니다            - 좁게 묶습니다. 품명+규격+단위가 «정확히» 같은 것만

  ⚠️ 표준품셈 · 물가정보 · 노임단가를 싣는 것이 아닙니다.
     조달청이 공개한 내역서에 «적혀 있던 값» 의 분포입니다.
"""
import re

# ── ① 갈래 ────────────────────────────────────────────────────────────────
#    내역서 한 부에는 성격이 다른 시트가 섞여 있습니다. 섞어 놓고 중앙값을 내면
#    자재 시세와 일위대가 합성단가가 한 통에 들어가 분포가 뭉개집니다.
갈래설명 = {
    '자재': '자재단가·자재조서 — 물건 값입니다. 가장 «시세» 에 가깝습니다',
    '공종': '내역서·집계표 — 공종 한 줄의 단가입니다. 설계가 실제로 쓴 값입니다',
    '합성': '일위대가·단가산출 — 품과 재료를 합쳐 만든 값입니다. 조건이 붙습니다',
    '장비': '기계경비·중기 — 시간당 값입니다',
    '기타': '어느 쪽인지 못 가른 시트',
}


def 갈래(시트이름):
    """시트 이름으로 갈래를 정합니다. 싣지 않을 것은 None 을 돌려줍니다."""
    s = re.sub(r'\s+', '', str(시트이름 or ''))
    if re.search(r'노임', s):
        return None                      # 표준노임단가 — 유료 자료라 싣지 않습니다
    if re.search(r'표준시장단가|공사단가\(', s):
        return None                      # 정부 고시 단가 — «시세» 가 아닙니다
    if re.search(r'자재|조경수|단가조사|단가대비', s):
        return '자재'
    if re.search(r'기계경비|중기|건설기계|장비', s):
        return '장비'
    if re.search(r'일위대가|단가산출', s):
        return '합성'
    if re.search(r'내역|집계|총괄|예산|예측|공사설정|INITIAL|data', s):
        return '공종'
    return '기타'


# ── ② 항목이 아닌 줄 ───────────────────────────────────────────────────────
# 괄호로 싸 놓는 일이 흔합니다: <노무비> · [ 합 계 ] · '소 계'
_기호 = "\\s<>\\[\\]()（）「」【】·※■□○●◎◇◆★☆▲△▶▷▸→⇒☞☜✓√＃#'\"`~＊*\\-–—=+.,:;"
_벗김 = re.compile('^[' + _기호 + ']+|[' + _기호 + ']+$')
_항목아님 = re.compile(
    r'^(재료비|노무비|경비|합계|소계|총계|계|단가|금액|수량|규격|품명|공종|직접공사비|'
    r'순공사원가|공사원가|일위대가|비고|산출근거|적요|구분|호표|번호|계산|단위|소요량|'
    r'잡재료비|기계경비|장비비|직접노무비|간접노무비|공종별|집계|재료|노무|누계|이월|'
    r'공제|본사관리비|이윤|부가세|일반관리비|산출내역|내역)$'
    # 「단가/KG」·「금액/M」 처럼 머리글이 품명 자리로 밀려 들어온 것
    r'|^단가\s*[/／]|^금액\s*[/／]|^수량\s*[/／]|^단위\s*[/／]')

# ── ③ 일위대가 «안에서만» 뜻이 있는 줄 ─────────────────────────────────────
#    「공구손료 = 노무비의 3%」 는 단가가 아니라 «계산 결과» 입니다.
#    호표마다 달라지므로 분포를 내면 최저 4원 ~ 최고 21만원 같은 것이 나옵니다.
_비율항목 = re.compile(r'공구손료|^손료$|잡재료|소모잡자재|주연료|^잡품$|부속품비|^경비|기구손료|^설치비$')
_비율규격 = re.compile(r'(재료비|노무비|인력품|주연료비|주재료비|전선관|전선,|장비비|직접비|합계)\s*의'
                       r'|^\d+\s*%$|의\s*\d+(\.\d+)?\s*%')

# ── ④ 노임 직종 ───────────────────────────────────────────────────────────
#    표준노임단가는 유료 자료입니다. 내역서에 적혀 있어도 싣지 않습니다.
#    «공» 으로 끝난다고 다 직종은 아니라(예: 가공) 이름을 하나씩 적습니다.
_노임 = re.compile(
    r'인부$|운전사$|^작업반장$|^조력공$|^기능공$|'
    # 「내선전공」·「특고압전공」처럼 앞에 말이 붙는 직종이 많아 «전공으로 끝나면» 모두 봅니다.
    # (2026-09-16 — 「내선전공」 이 이 구멍으로 새어 사전에 들어갔었습니다)
    r'전공$|기사$|^기능사$|'
    r'^(비계|철근|형틀목|건축목|목|용접|배관|도장|미장|타일|방수|석|콘크리트|해체|보통|특별|'
    r'플랜트|plant|통신외선|통신내선|케이블|내선|외선|한식미장|한식목|한식|조적|견출|'
    r'창호|유리|덕트|보온|위생|수도|산업|특고압|저압|절연|계장|용접|제관|판금|주설|'
    r'광케이블|통신|전기)공(조공)?$|'
    r'^한식.*공(조공)?$|^벌목부$|^준설선원$|^잠수부$|^잠수사$|^해녀$|^작업선원$')

_숫자만 = re.compile(r'^[\d.,\s%㎡㎥mM]+$')


def 다듬기(x):
    return _벗김.sub('', re.sub(r'\s+', ' ', str(x if x is not None else ''))).strip()


def _붙임(x):
    """견줄 때만 쓰는 꼴 — 공백을 다 뗍니다.  「보 통 인 부」 == 「보통인부」"""
    return re.sub(r'\s+', '', str(x if x is not None else ''))


def _노임인가(품명, 규격, 단위):
    """노임(품) 줄인가.

    ⚠️ 직종 «이름» 을 일일이 적는 방식은 계속 샙니다 — 2026-09-16 에
       「내선전공」·「내장공」·「줄눈공」·「코킹공」 이 줄줄이 새어 사전에 들어갔습니다.
       그래서 이름 대신 «확실한 표시» 두 가지로 봅니다.
         ① 단위가 「인」  — 사람 하루치입니다. 물건에는 이 단위를 안 씁니다
         ② 규격에 「직종」 — 「일반공사 직종」·「문화재 직종」·「기타 직종」
       이름 목록은 이 둘로도 안 잡히는 것만 받는 «그물» 로 남겨 둡니다.
    """
    u = _붙임(다듬기(단위))
    if u in ('인', '人', '인일', '일'):
        return True
    if '직종' in _붙임(다듬기(규격)):
        return True
    return bool(_노임.search(_붙임(다듬기(품명))))


def 거를까(품명, 규격, 단가, 단위=''):
    """실을 수 없는 줄이면 «까닭» 을, 실어도 되면 None 을 돌려줍니다."""
    n = 다듬기(품명)
    t = _붙임(n)
    s = 다듬기(규격)
    ts = _붙임(s)
    if not n:
        return '품명 빈칸'
    if _항목아님.search(t):
        return '머리글·집계줄'
    if _숫자만.match(n):
        return '품명이 숫자(파싱오류)'
    if n.endswith(':') or n.endswith('：'):
        return '품명이 라벨(:)'
    if _비율항목.search(t):
        return '일위대가 %계산항목(품명)'
    if _비율규격.search(ts):
        return '일위대가 %계산항목(규격)'
    if _노임인가(품명, 규격, 단위):
        return '노임 직종(유료 자료)'
    if s and _숫자만.match(s):
        return '규격이 숫자(파싱오류)'
    try:
        p = float(str(단가).replace(',', ''))
    except (TypeError, ValueError):
        return '단가가 숫자 아님'
    if p <= 0:
        return '단가 0 이하'
    return None


def 열쇠(갈래이름, 품명, 규격, 단위):
    """묶는 열쇠.  «좁게» 묶습니다 — 갈래+품명+규격+단위가 정확히 같은 것만.

    ⚠️ 여기를 느슨하게 만들고 싶어질 것입니다(「아스콘 포장」과 「A.C 포장」을 합치고 싶어서).
       그 유혹을 참으십시오. 잘못 묶으면 «중앙값이 통째로 헛것» 이 됩니다.
       넓히려면 «넓힌 표를 따로 내고», 좁은 표와 견줘 본 뒤에 바꾸십시오.
    """
    return (갈래이름, _붙임(다듬기(품명)), _붙임(다듬기(규격)), _붙임(다듬기(단위)))


# ── 표본 등급 ──────────────────────────────────────────────────────────────
#    CLAUDE.md 9절 ③ : 30줄 이상 = 정식 · 10~29 = 「표본 적음」 · 10 미만 = 아예 안 냄
정식 = 30
적음 = 10


def 등급(표본수):
    if 표본수 >= 정식:
        return '정식'
    if 표본수 >= 적음:
        return '표본적음'
    return '자료부족'


def 사분위(값들, p):
    """엑셀 PERCENTILE 과 같은 방식(선형 보간)."""
    v = sorted(값들)
    if not v:
        return None
    k = (len(v) - 1) * p
    f = int(k)
    c = min(f + 1, len(v) - 1)
    return v[f] + (v[c] - v[f]) * (k - f)
