ok('레미콘 25-30-15 → 짝 없음 (강도 다름)', !줄('레미콘', '25-30-15').도면, 줄('레미콘', '25-30-15').까닭)
ok('레미콘 펌프차 타설 → 콘크리트 전체 · 할증 없이', 줄('레미콘 펌프차 타설').도면?.key === 'gzT:콘크리트' && 줄('레미콘 펌프차 타설').할증수량 === null && 줄('레미콘 펌프차 타설').믿음 === '확실')
ok('철근 SD400 HD10 → D10 · ton 그대로 · 할증 3%', 줄('철근', 'SD400 HD10').도면?.규격 === 'D10' && 같다(줄('철근', 'SD400 HD10').할증수량, R.집계.합.find((a) => a.규격 === 'D10').내역))
ok('철근 SHD22 → D22', 줄('철근', 'SHD22').도면?.규격 === 'D22')
ok('철근 HD25 → 짝 없음 (도면에 D25 없음)', !줄('철근', 'HD25').도면)
ok('철근가공조립 → 철근 전체 · 확실 · 할증 없이', 줄('철근가공조립').도면?.key === 'gzT:철근' && 줄('철근가공조립').믿음 === '확실' && 같다(줄('철근가공조립').도면수량, 철전))
ok('합판거푸집 3회 → 거푸집 줄이 하나 → 골조 거푸집 전체', 줄('합판거푸집').도면?.key === 'gzT:거푸집' && 줄('합판거푸집').믿음 === '확실')
ok('방수턱 거푸집 · 콘크리트 양생 → 골조 물량을 붙이지 않음', !(줄('방수턱 거푸집').도면 && 줄('방수턱 거푸집').도면.골) && !(줄('콘크리트 양생').도면 && 줄('콘크리트 양생').도면.골))
ok('먹매김 → 짝 없음', !줄('먹매김').도면)
ok('판정: 빈 줄 = «내역 수량 없음» · HD19 1.5 ↔ 도면 → 다름', 줄('철근', 'HD13').판정 === '내역 수량 없음' && /도면이/.test(줄('철근', 'HD19').판정), [줄('철근', 'HD13').판정, 줄('철근', 'HD19').판정])

