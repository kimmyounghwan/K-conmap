ok('부재 이름: 합판거푸집 슬라브 → 슬라브 · 보,기둥 → 기둥·보 · 보도블록 → 없음 · 합벽 → 없음', 부재들('합판거푸집 슬라브')[0] === '슬라브' && 부재들('거푸집 보,기둥').join() === '기둥,보' && !부재들('보도블록').length && !부재들('합벽거푸집 지하').length)
ok('갈래: 철근가공조립 → 가공조립 · 레미콘 펌프차 타설 → 타설 · 콘크리트 양생 → X · 방수턱 거푸집 → X · 먹매김 → 없음',
  골조갈래({ 품명: '철근가공조립', 단위: 'TON' }) === '가공조립' && 골조갈래({ 품명: '레미콘 펌프차 타설', 단위: 'M3' }) === '타설' && 골조갈래({ 품명: '콘크리트 양생', 단위: 'M3' }) === 'X' && 골조갈래({ 품명: '방수턱 거푸집', 단위: 'M2' }) === 'X' && 골조갈래({ 품명: '먹매김', 단위: 'M2' }) === '')

