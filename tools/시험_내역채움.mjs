ok('보탬: 콘크리트 전체 · 철근 전체 · 거푸집 전체 · 부재별 거푸집', ['gzT:콘크리트', 'gzT:철근', 'gzT:거푸집'].every((k) => 보탬.some((d) => d.key === k)) && 보탬.some((d) => d.key.startsWith('gzP:거푸집|')), 보탬.map((d) => d.key))
ok('철근 전체 = 지름별 합', 같다(보탬.find((d) => d.key === 'gzT:철근').수량, 철전))

console.log('③ 가상 공내역서 읽기 · 짝')
const 원본 = fs.readFileSync(new URL('./시험자료/내역채움_공내역.xlsx', import.meta.url))
