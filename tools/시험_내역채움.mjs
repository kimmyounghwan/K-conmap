ok('내역서 시트만 · 13줄 (빈 수량 줄도 읽음, 수식 칸은 값 없어 빈 줄로)', 내.줄.length === 13 && 내.줄.every((n) => n.시트 === '내역서'), 내.줄.length)
const 빈들 = 내.줄.filter((n) => n.빈).length
ok('빈 수량 줄 11 (HD19·먹매김 빼고)', 빈들 === 11, 빈들)
const 모든도면 = [...도면, ...보탬]
