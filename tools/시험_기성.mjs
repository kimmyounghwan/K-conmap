참(/name="_기성자료1"[^>]*state="hidden"/.test(wb), '자료 시트는 숨김')
const 내 = 책2['기성내역(1회)']
const 순행 = 내.findIndex((r) => r && String(r[1] || '').replace(/\s/g, '') === '순공사비')
eq([Number(내[순행][6]), Number(내[순행][12])], [결b.요약.순.계약, 결b.요약.순.누계], '기성내역 순공사비 계약 · 누계(미리 셈한 값)')
