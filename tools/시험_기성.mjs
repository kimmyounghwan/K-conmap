import * as K from '../web/src/lib/기성.js'

let ok = 0, bad = 0
const eq = (got, want, what) => {
  const g = JSON.stringify(got), w = JSON.stringify(want)
  if (g === w) { ok++; console.log('  ✓', what) } else { bad++; console.log('  ✗', what, '— 나온 값', g, '· 바란 값', w) }
}
const 참 = (c, what, 더 = '') => eq(!!c, true, what + (더 ? ' (' + 더 + ')' : ''))
const 버림 = (v) => Math.floor(v + 1e-7)

const 바이트 = new Uint8Array(readFileSync(new URL('./시험자료/원내역_예시.xlsx', import.meta.url)))
const 책 = readWorkbook(바이트)

console.log('① 읽기')
const 읽 = K.기성읽기(책, '원내역_예시.xlsx')
eq([읽.원읽은.고른, 읽.원읽은.모형.품목수, !!읽.원읽은.원가, 읽.지난], ['내역서', 12, true, null], '내역서 · 품목 12 · 원가계산서 있음 · 지난 기성 없음')
const 공 = (이름) => 읽.공종들.find((p) => p.이름.replace(/\s/g, '') === 이름)
참(공('토공') && 공('토공').품목들.length >= 2, '토공 공종 · 품목들', 공('토공') && 공('토공').품목들.length)
eq(new Set(읽.열쇠들.filter(Boolean)).size, 12, '품목 열쇠 12개 모두 다름')
const 편0 = K.새기성(읽)
eq([편0.회차, 편0.식], [1, '보고서'], '새 회차 = 1 · 엑셀은 보고서(원가는 값)')

console.log('② 0 % · 100 %')
const 결0 = K.기성셈(읽, 편0)
eq([결0.요약.금회, 결0.요약.누계, 결0.요약.전회], [0, 0, 0], '아무것도 안 넣으면 금회 · 누계 0')
const 편100 = { ...K.새기성(읽), 전체: 100 }
const 결100 = K.기성셈(읽, 편100)
eq(결100.줄.every((r) => r.누 === r.계 && (r.금액.누계.합계 || 0) === (r.금액.계약.합계 || 0)), true, '전체 100 % — 줄마다 누계 수량 · 금액 = 계약')
eq([결100.요약.누계, 결100.요약.계약, 결100.요약.무엇.replace(/\s/g, '')], [132764855, 132764855, '도급액'], '누계 도급액 = 계약 도급액 132,764,855')
eq(결100.원가.누계, 결100.원가.계약, '원가계산서 줄마다 누계 = 계약')

console.log('③ 공종 % · 줄 수량 — 원가를 처음부터 다시 셈한 것과 같나')
const 모형 = 읽.원읽은.모형
const 편 = K.새기성(읽)
편.공종률[공('토공').i] = 50
const 거i = 모형.줄.findIndex((x) => x.꼴 === '품목' && x.이름 === '거푸집')
편.수량[읽.열쇠들[거i]] = 300
편.전체 = 20
const 결 = K.기성셈(읽, 편)
/* 손 셈 — 품목마다 누계 수량 · 갈래 금액(버림) · 관급 따로 */
const 토공품목 = new Set(공('토공').품목들)
let 노 = 0, 재 = 0, 경 = 0, 관급 = 0, 관급중 = false
const 줄셈 = []
모형.줄.forEach((x, i) => {
  if (x.꼴 === '공종') { 관급중 = /관급/.test(x.이름.replace(/\s/g, '')); return }
  if (x.꼴 !== '품목') return
  const 계 = x.값[0].수량
  const q = i === 거i ? 300 : 토공품목.has(i) ? Math.round(계 * 0.5 * 1e6) / 1e6 : Math.round(계 * 0.2 * 1e6) / 1e6
  const g = x.값[0].g
  const a = { 노: 버림((g.노무비.단가 || 0) * q), 재: 버림((g.재료비.단가 || 0) * q), 경: 버림((g.경비.단가 || 0) * q) }
  줄셈.push([i, q, a.노 + a.재 + a.경])
  if (관급중) { 관급 += a.노 + a.재 + a.경; return }
  노 += a.노; 재 += a.재; 경 += a.경
})
const 결줄 = new Map(결.줄.map((r) => [r.i, r]))
eq(줄셈.every(([i, q, m]) => 결줄.get(i).누 === q && 결줄.get(i).금액.누계.합계 === m), true, '줄마다 누계 수량 · 금액 = 손 셈(수량 × 갈래 단가 버림의 합)')
eq(결줄.get(거i).근거, '줄 수량', '줄 수량이 공종 % · 전체 % 보다 먼저')
eq(결.요약.순.누계, 노 + 재 + 경, '누계 순공사비 = 손 셈')
const A = 재, n4 = 노, n5 = 버림(n4 * 0.146), B = n4 + n5, n6 = 경
const n7 = 버림(B * 0.0356), n8 = 버림(B * 0.0101), n9 = 버림(n4 * 0.03545), n10 = 버림(n4 * 0.045), n11 = 버림(n9 * 0.1295), n12 = 버림(n4 * 0.023)
const n13 = 버림((A + n4) * 0.0197), n14 = 버림((A + n4 + n6) * 0.008), n15 = 버림((A + B) * 0.0553)
const C = n6 + n7 + n8 + n9 + n10 + n11 + n12 + n13 + n14 + n15, D = A + B + C, E = 버림(D * 0.055), F = 버림((B + C + E) * 0.1135)
const Gg = D + E + F, H = 버림(Gg * 0.1), I = Gg + H, Kk = I + 관급
const 원줄 = 읽.원읽은.원가.줄
const 값 = (re) => 결.원가.누계[원줄.findIndex((x) => re.test(x.이름.replace(/\s/g, '')))]
eq([값(/^도급액/), 값(/총공사비/)], [I, Kk], `누계 도급액 ${I.toLocaleString()} · 총공사비 ${Kk.toLocaleString()} — 계약 원가계산서 식으로 처음부터 셈한 것과 같음`)
eq(결.요약.누계, I, '요약 누계 = 도급액')
eq(결.원가.금회.every((v, k) => v === null || v === (결.원가.누계[k] || 0) - (결.원가.전회[k] || 0)), true, '금회 = 누계 − 전회(줄마다)')

console.log('④ 엑셀 — 원본 시트 그대로 + 기성 시트 · 숨은 자료')
편.날짜 = '2026-10-31'; 편.기간 = '2026.10.01 ~ 2026.10.31'; 편.선금 = '30,000,000'
const 결b = K.기성셈(읽, 편)
const 엑 = await K.기성엑셀(바이트, 읽, 결b, 편, '2026-10-16')
eq(엑.붙임, true, '.xlsx 원본에 붙임')
const 책2 = readWorkbook(엑.바이트)
const 원시트들 = Object.keys(책)
eq(원시트들.every((n) => JSON.stringify(책2[n]) === JSON.stringify(책[n])), true, '원본 시트 한 칸도 안 바뀜')
eq(엑.시트이름들, ['기성내역(1회)', '기성원가(1회)', '부분기성(1회)', '기성검사원(1회)', '기성청구서(1회)', '기성검산(1회)', '_기성자료1'], '붙인 시트 일곱(서류 둘 포함)')
const z = unzipSync(엑.바이트)
