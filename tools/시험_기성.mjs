참(!책무['기성내역(1회)'].some((r) => r && String(r[0] || '') === K.아래글) && !책무['기성청구서(1회)'], '주소 · 서류를 끄면 안 넣음')

console.log('⑤ 다음 회차 — 받은 파일만 넣으면 전회 누계가 이어짐')
