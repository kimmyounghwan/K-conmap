eq(결b.요약.지급, 결b.요약.금회 - 결b.요약.선금.금회, '금회 지급 = 금회 기성 − 선금 정산')

const 청 = 책2['기성청구서(1회)']
const 칸값 = (t, 이름) => { const r = t.find((x) => x && String(x[0] || '').replace(/\s/g, '') === 이름.replace(/\s/g, '')); return r ? String(r[1] || '') : null }
참(/^일금 .+원정 \(₩[\d,]+\)$/.test(칸값(청, '금회 청구금액')) && 칸값(청, '금회 청구금액').includes(결b.요약.지급.toLocaleString('ko-KR')), '청구서 금회 청구금액 = 지급액 · 한글 금액', 칸값(청, '금회 청구금액'))
참(/노무비 구분/.test(칸값(청, '이 중 노무비') || '') && 결b.요약.노무비 > 0, '이 중 노무비(원가계산서 직접노무비 금회)', 결b.요약.노무비)
